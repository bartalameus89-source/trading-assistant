"""
Окупается ли ослабленный фильтр волатильности — по живым сделкам.

    python vol_learning.py

Подробности — в engine/volzones.py.
"""

from __future__ import annotations

from engine import variants, volzones


def главное() -> int:
    с = volzones.свод()
    print("ЗОНЫ ВОЛАТИЛЬНОСТИ — КОРОТКАЯ СИСТЕМА, ЖИВЫЕ СИГНАЛЫ\n")
    print(f"  {'зона':22} {'сигналов':>9} {'исполнено':>10} {'закрыто':>8} "
          f"{'итог R':>8} {'на сделку':>10} {'побед':>6}")
    for имя in volzones.ПОРЯДОК:
        з = с[имя]
        if not з["сигналов"]:
            continue
        на = "—" if з["на_сделку_R"] is None else f"{з['на_сделку_R']:+.3f}R"
        побед = "—" if not з["закрыто"] else f"{з['побед'] / з['закрыто'] * 100:.0f}%"
        print(f"  {имя:22} {з['сигналов']:9d} {з['исполнено']:10d} {з['закрыто']:8d} "
              f"{з['сумма_R']:+8.2f} {на:>10} {побед:>6}")
    print("\n  " + volzones.вывод(с))

    print("\n\nВАРИАНТЫ ФИЛЬТРА — ВСЕ ПОРОГИ ПАРАЛЛЕЛЬНО (state/variants.json)\n")
    print(f"  {'ослабление':>10} {'порог':>6} {'сигналов':>9} {'не исполн.':>10} {'в работе':>9} "
          f"{'закрыто':>8} {'итог R':>8} {'на сделку':>10} {'побед':>6}")
    строки = variants.свод()
    for в in строки:
        пор = "нет" if в["порог"] > 100 else f"{в['порог']:g}"
        на = "—" if в["на_сделку_R"] is None else f"{в['на_сделку_R']:+.3f}R"
        поб = "—" if not в["закрыто"] else f"{в['побед'] / в['закрыто'] * 100:.0f}%"
        метка = "  <- наш счёт" if в["ослабление"] == 50 else ""
        print(f"  {в['ослабление']:>9}% {пор:>6} {в['сигналов']:9d} {в['не_исполнилось']:10d} "
              f"{в['в_работе']:9d} {в['закрыто']:8d} {в['сумма_R']:+8.2f} {на:>10} {поб:>6}{метка}")
    print("\n  " + variants.вывод(строки))
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
