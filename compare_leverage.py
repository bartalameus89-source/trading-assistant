"""
Что даёт плечо: сравнение результатов при разном X и разном риске на сделку.

Здесь важно понять одну вещь, которая противоречит интуиции.

Когда размер позиции считается ОТ РИСКА (а не «на все деньги»), плечо почти
не влияет на результат. Потому что объём позиции определяется формулой
    объём = капитал * риск% / дистанция_до_стопа%
и в ней плеча нет вообще. Плечо задаёт только ПОТОЛОК объёма.

Поэтому плечо делает три вещи, и ни одна из них не «увеличивает доход»:
  1. снимает ограничение, из-за которого сделки с близким стопом урезались;
  2. добавляет цену ликвидации — принудительного закрытия с потерей маржи;
  3. добавляет плату за фондирование каждые 8 часов.

Доход меняет не плечо, а процент риска на сделку. Это разные ручки,
и их постоянно путают.

Запуск:  python compare_leverage.py
"""

from __future__ import annotations

import json
import os

from engine import risk
from experiments import Правила, СИГНАЛЫ, провести

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ЧАСОВ_В_БАРЕ = 4
СРЕДНЕЕ_УДЕРЖАНИЕ_БАРОВ = 12       # по факту бэктеста

ПРАВИЛО = Правила("рабочая цель 1.5R", цель_R=1.5)


def оценить(плечо: float, риск_пр: float, капитал: float) -> dict:
    """Прогоняет все сигналы при заданных плече и риске. Возвращает итог."""
    деньги = капитал
    пик = капитал
    просадка = 0.0
    сделок = 0
    урезано = 0
    ликвидаций = 0

    for сиг in sorted(СИГНАЛЫ, key=lambda с: (с["бар"], с["актив"])):
        r = провести(сиг, ПРАВИЛО)
        if r is None:
            continue

        стоп_отн = abs(сиг["вход"] - сиг["стоп"]) / сиг["вход"]
        if стоп_отн <= 0:
            continue

        # Сколько нужно объёма, чтобы риск составил заданный процент.
        нужный_объём = деньги * риск_пр / 100 / стоп_отн
        потолок = деньги * плечо
        фактический_объём = min(нужный_объём, потолок)
        if нужный_объём > потолок:
            урезано += 1

        # Фактический риск в деньгах — от реального объёма, а не от желаемого.
        риск_денег = фактический_объём * стоп_отн

        # Проверка: дошла бы цена до ликвидации раньше стопа?
        ликв = risk.цена_ликвидации(сиг["направление"], сиг["вход"], плечо)
        if ликв is not None:
            если_лонг = сиг["направление"] == "Long"
            стоп_за_ликвидацией = (сиг["стоп"] <= ликв) if если_лонг else (сиг["стоп"] >= ликв)
            if стоп_за_ликвидацией:
                # Позиция обнуляется до срабатывания стопа: теряем всю маржу.
                ликвидаций += 1
                деньги -= фактический_объём / плечо
                сделок += 1
                пик = max(пик, деньги)
                просадка = min(просадка, деньги / пик - 1)
                if деньги <= 0:
                    return {"итог": -100.0, "просадка": -100.0, "сделок": сделок,
                            "урезано": урезано, "ликвидаций": ликвидаций, "слив": True}
                continue

        прибыль = r * риск_денег

        # Фондирование — только при плече, только на фьючерсах.
        if плечо > 1:
            прибыль -= risk.стоимость_фондирования(
                фактический_объём, СРЕДНЕЕ_УДЕРЖАНИЕ_БАРОВ, ЧАСОВ_В_БАРЕ,
                CFG["риск"]["фондирование_за_8ч_пр"])

        деньги += прибыль
        сделок += 1
        пик = max(пик, деньги)
        просадка = min(просадка, деньги / пик - 1)
        if деньги <= 0:
            return {"итог": -100.0, "просадка": -100.0, "сделок": сделок,
                    "урезано": урезано, "ликвидаций": ликвидаций, "слив": True}

    return {"итог": (деньги / капитал - 1) * 100, "просадка": просадка * 100,
            "сделок": сделок, "урезано": урезано, "ликвидаций": ликвидаций,
            "слив": False}


def таблица(риск_пр: float, капитал: float) -> None:
    print(f"\n  РИСК НА СДЕЛКУ {риск_пр}%   капитал {капитал:.0f} $")
    print(f"  {'плечо':>6} {'итог':>9} {'просадка':>10} {'урезано':>9} "
          f"{'ликвидаций':>12}  ликвидация при движении")
    print("  " + "-" * 76)
    for L in (1, 2, 3, 5, 10, 20):
        о = оценить(L, риск_пр, капитал)
        ликв = risk.цена_ликвидации("Long", 100.0, L)
        расстояние = "—  (спот)" if ликв is None else f"против вас на {100 - ликв:.1f}%"
        итог = "СЛИВ" if о["слив"] else f"{о['итог']:+8.2f}%"
        print(f"  {L:5d}x {итог:>9} {о['просадка']:9.2f}% {о['урезано']:9d} "
              f"{о['ликвидаций']:12d}  {расстояние}")


if __name__ == "__main__":
    капитал = CFG["риск"]["депозит"] or 100
    print("=" * 80)
    print("  ВЛИЯНИЕ ПЛЕЧА НА РЕЗУЛЬТАТ")
    print("=" * 80)
    print("  «урезано» — сколько сделок пришлось уменьшить из-за потолка объёма.")
    print("  Именно это ограничение и снимает плечо — больше оно не делает ничего.")

    for риск in (0.5, 1.0, 2.0):
        таблица(риск, капитал)

    print("\n" + "=" * 80)
    print("  ВЫВОД")
    print("=" * 80)
    print("  Сравните строки внутри одной таблицы (меняется плечо) и между")
    print("  таблицами (меняется риск). Результат двигает второе, а не первое.")
    print("  Плечо при этом добавляет риск ликвидации, которого на споте нет.")
