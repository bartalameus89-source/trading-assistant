"""
Недельный отчёт в Telegram: что было за семь дней и что открыто сейчас.

Зачем. Сообщения приходят только по событиям — сигнал, доливка, закрытие.
Между событиями тишина, и по ней невозможно понять, идут дела или стоят.
Раз в неделю нужен связный итог: сколько закрылось, с каким результатом,
что осталось в работе и сколько это стоит на бумаге.

Отдельно показываем ХУДШИЙ случай — сколько останется, если завтра
сработают все стопы. Для трендовой системы это важнее текущей прибыли:
открытая прибыль может исчезнуть, а защищённая стопом уже нет.

    python weekly.py         напечатать отчёт
    python weekly.py --tg    напечатать и отправить в Telegram
"""

from __future__ import annotations

import json
import os
import sys
import time
from datetime import datetime, timezone

from engine import data, equity, pnl, volzones
from run import отправить_в_телеграм

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
НЕДЕЛЯ = 7 * 86400


def _цены() -> dict[str, float]:
    цены: dict[str, float] = {}
    for актив in CFG["активы"]:
        try:
            цены[актив] = data.загрузить(
                актив, "1d", лимит=3,
                источники=CFG["источник_данных"]).последняя_цена
        except Exception:
            continue
    return цены


def _дата(t: float | None) -> str:
    if not t:
        return "—"
    return datetime.fromtimestamp(t, tz=timezone.utc).strftime("%d.%m")


def собрать() -> dict:
    д = pnl.подсчитать(_цены())
    порог = time.time() - НЕДЕЛЯ
    за_неделю = [с for с in д["строки"] if (с.get("когда") or 0) >= порог]

    дни = equity.за_период(30)
    # Сравниваем наш счёт только с нашим же: снимки до 11.09 были общими
    # с тенью, и «изменение за неделю» смешало бы разные величины.
    было_неделю_назад = None
    for сн in дни:
        if сн["когда"] >= порог:
            break
        if сн.get("наш_итог") is not None:
            было_неделю_назад = сн["наш_итог"]

    return {"всё": д, "за_неделю": за_неделю, "было": было_неделю_назад,
            "дней_истории": len(дни)}


def d_знак(x: float) -> str:
    """Число со знаком: '+3.40' или '-1.20'. Знак важен — в отчёте
    несколько сумм подряд, и без него легко прочитать убыток как прибыль."""
    return f"{'+' if x >= 0 else ''}{x:.2f}"


def отчёт_текстом(с: dict) -> str:
    д = с["всё"]
    # Отчёт — про НАШ счёт, то есть рекомендации. Тень (сделки, которые
    # система отказалась брать) идёт отдельной строкой: раньше всё
    # складывалось в одно число, и минус отвергнутых сделок читался как наш.
    р = д["сводка_рекомендаций"]
    т = д["сводка_тени"]
    строки = ["📅 <b>ИТОГ НЕДЕЛИ</b>", ""]

    # --- что закрылось ---
    неделя = с["за_неделю"]
    if неделя:
        плюс = sum(1 for x in неделя if x["деньги"] > 0)
        минус = sum(1 for x in неделя if x["деньги"] < 0)
        ноль = len(неделя) - плюс - минус
        наши = [x for x in неделя if x["ветка"] == "рекомендации"]
        тени = [x for x in неделя if x["ветка"] != "рекомендации"]
        # Сделки в ноль считаем отдельно: они не убыток, и молча терять
        # их в подсчёте нечестно — безубыток это работа стопа, а не неудача.
        разбор = f"{плюс} в плюс, {минус} в минус"
        if ноль:
            разбор += f", {ноль} в ноль"
        строки.append(f"<b>Закрыто за неделю: {len(неделя)}</b> ({разбор})")
        строки.append(f"наш счёт: {len(наши)} — "
                      f"{d_знак(sum(x['деньги'] for x in наши))} $; "
                      f"тень: {len(тени)} — "
                      f"{d_знак(sum(x['деньги'] for x in тени))} $")
        for x in неделя[-8:]:
            знак = "✅" if x["деньги"] > 0 else ("➖" if x["деньги"] == 0 else "❌")
            метка = "" if x["ветка"] == "рекомендации" else " <i>(тень)</i>"
            строки.append(f"{знак} {_дата(x.get('когда'))} "
                          f"{x['актив'].replace('USDT', '')} — {x['исход']}, "
                          f"{x['r']:+.2f}R{метка}")
    else:
        строки.append("<b>За неделю ничего не закрылось.</b>")
        строки.append("<i>Для трендовой системы это обычно: сделки живут "
                      "неделями, и тишина между ними — не простой.</i>")
    строки.append("")

    # --- что открыто — только наш счёт ---
    строки.append(f"<b>В работе сейчас: {р['в_работе']} позиций</b>")
    строки.append(f"По рынку: {d_знак(р['открыто_итог'])} $")
    if р["защищено"]:
        строки.append(f"Из них у <b>{р['защищено']}</b> стоп уже выше "
                      f"входа — прибыль по ним закреплена.")
    строки.append("")

    # --- итог — наш счёт; тень одной строкой ---
    строки.append(f"<b>Наш счёт на бумаге: {d_знак(р['итог'])} $</b> "
                  f"от {CFG['риск']['депозит']} $")
    if с["было"] is not None:
        изм = р["итог"] - с["было"]
        строки.append(f"Неделю назад было {с['было']:+.2f} $, "
                      f"изменение {d_знак(изм)} $")
    строки.append(f"Если завтра сработают все стопы: "
                  f"{d_знак(р['закрыто_итог'] + д['открытые']['рекомендации']['худший'])} $")
    строки.append(f"<i>Тень — сделки, которые система отвергла, не наши деньги: "
                  f"закрыто {т['сделок']}, {d_знак(т['закрыто_итог'])} $, "
                  f"в работе {d_знак(т['открыто_итог'])} $.</i>")
    строки.append("")

    # --- опыт с фильтром волатильности (порог 80 -> 90 с 13.09.2026) ---
    зоны = volzones.свод()
    нов, спок = зоны["новая (80–90)"], зоны["спокойная (до 80)"]
    if нов["сигналов"] or спок["сигналов"]:
        def коротко(з: dict) -> str:
            if not з["закрыто"]:
                return f"сигналов {з['сигналов']}, закрытых нет"
            return (f"сигналов {з['сигналов']}, закрыто {з['закрыто']}, "
                    f"{з['на_сделку_R']:+.2f}R на сделку")
        строки.append("<b>Короткая система по волатильности</b>")
        строки.append(f"спокойная (до 80): {коротко(спок)}")
        строки.append(f"новая зона (80–90): {коротко(нов)}")
        строки.append(f"<i>{volzones.вывод(зоны)}</i>")
        строки.append("")

    # --- сколько до выводов ---
    # Выводы — по НАШЕМУ счёту. Раньше считались сделки вместе с тенью,
    # и отчёт писал «осталось 4», когда по рекомендациям было закрыто 3 из 30.
    осталось = max(0, 30 - р["сделок"])
    if осталось:
        строки.append(f"<i>Закрыто рекомендаций: {р['сделок']} из 30, нужных для первых "
                      f"выводов. Раньше статистика будет случайной.</i>")
    else:
        строки.append("<i>Закрытых сделок хватает для выводов — "
                      "статистика в кабинете.</i>")
    return "\n".join(строки)


def главное() -> int:
    с = собрать()
    текст = отчёт_текстом(с)
    print(текст.replace("<b>", "").replace("</b>", "")
              .replace("<i>", "").replace("</i>", ""))
    if "--tg" in sys.argv:
        if отправить_в_телеграм(текст):
            print("\nОтправлено в Telegram.")
        else:
            print("\nОтправить не удалось: нет токена или чата.")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
