"""
Проверка гипотез о том, почему стратегия убыточна.

Все варианты проверяются на ОДНИХ И ТЕХ ЖЕ входах — меняются только правила
выхода из сделки. Это изолирует эффект: если результат улучшился, дело именно
в управлении позицией, а не в том, что мы случайно набрали другие сделки.

Защита от самообмана (раздел 10 промта): сигналы делятся хронологически.
Первые 60% — «обучающая» часть, на ней смотрим, какая гипотеза выглядит лучше.
Последние 40% — «проверочная», её видим только один раз, для подтверждения.
Вариант, хороший на первой и плохой на второй, — это подгонка, а не находка.

Запуск:  python experiments.py
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass

БАЗА = os.path.dirname(os.path.abspath(__file__))
КЕШ = os.path.join(БАЗА, "cache")
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))

СВЕЧИ = json.load(open(os.path.join(КЕШ, "candles.json"), encoding="utf-8"))
СИГНАЛЫ = json.load(open(os.path.join(КЕШ, "signals.json"), encoding="utf-8"))


@dataclass
class Правила:
    имя: str
    множитель_стопа: float = 1.0      # во сколько раз шире исходного стопа
    цель_R: float | None = None       # цель как кратное риска; None = уровень из плана
    безубыток_после_R: float | None = None
    трейлинг_atr: float | None = None
    частичная_фиксация_R: float | None = None
    предел_баров: int = 60


def издержки_R(вход: float, стоп: float) -> float:
    и = CFG["издержки"]
    доля = (и["комиссия_вход_пр"] + и["комиссия_выход_пр"] + и["проскальзывание_пр"]) / 100
    отн = abs(вход - стоп) / вход
    return доля / отн if отн else 99.0


def провести(сиг: dict, пр: Правила) -> float | None:
    """Возвращает результат сделки в единицах риска после издержек,
    либо None если вход не состоялся."""
    c = СВЕЧИ[сиг["актив"]]
    highs, lows, opens, closes = c["highs"], c["lows"], c["opens"], c["closes"]
    n = len(closes)
    i = сиг["бар"]
    длинная = сиг["направление"] == "Long"
    ttl = CFG["сигналы"]["срок_жизни_сигнала_баров"]

    вход = сиг["вход"]
    базовый_риск = abs(вход - сиг["стоп"])
    риск = базовый_риск * пр.множитель_стопа
    if риск <= 0:
        return None
    стоп = вход - риск if длинная else вход + риск

    # --- вход ---
    if сиг["тип_ордера"] == "Market":
        бар_входа = i + 1
        if бар_входа >= n:
            return None
        вход = opens[бар_входа]
        стоп = вход - риск if длинная else вход + риск
    else:
        бар_входа = None
        for j in range(i + 1, min(i + 1 + ttl, n)):
            if lows[j] <= вход <= highs[j]:
                бар_входа = j
                break
        if бар_входа is None:
            return None

    # --- цель ---
    if пр.цель_R is not None:
        цель = вход + риск * пр.цель_R if длинная else вход - риск * пр.цель_R
    else:
        цель = сиг["цели"][0]

    # --- ведение позиции ---
    накоплено = 0.0          # результат уже зафиксированной части
    доля_открыта = 1.0
    предел = min(бар_входа + пр.предел_баров, n - 1)
    экстремум = highs[бар_входа] if длинная else lows[бар_входа]

    for j in range(бар_входа, предел + 1):
        h, l = highs[j], lows[j]
        экстремум = max(экстремум, h) if длинная else min(экстремум, l)
        прибыль_R = ((h - вход) if длинная else (вход - l)) / риск

        # Пессимизм: стоп проверяется раньше цели в пределах одной свечи.
        стоп_задет = (l <= стоп) if длинная else (h >= стоп)
        if стоп_задет:
            r = (стоп - вход) / риск if длинная else (вход - стоп) / риск
            накоплено += r * доля_открыта
            доля_открыта = 0.0
            break

        # Частичная фиксация половины позиции.
        if (пр.частичная_фиксация_R and доля_открыта == 1.0
                and прибыль_R >= пр.частичная_фиксация_R):
            накоплено += пр.частичная_фиксация_R * 0.5
            доля_открыта = 0.5

        # Перевод стопа в безубыток.
        if пр.безубыток_после_R and прибыль_R >= пр.безубыток_после_R:
            стоп = max(стоп, вход) if длинная else min(стоп, вход)

        # Трейлинг-стоп по ATR от достигнутого экстремума.
        if пр.трейлинг_atr:
            подтяжка = (экстремум - сиг["atr"] * пр.трейлинг_atr if длинная
                        else экстремум + сиг["atr"] * пр.трейлинг_atr)
            стоп = max(стоп, подтяжка) if длинная else min(стоп, подтяжка)

        цель_задета = (h >= цель) if длинная else (l <= цель)
        if цель_задета:
            r = (цель - вход) / риск if длинная else (вход - цель) / риск
            накоплено += r * доля_открыта
            доля_открыта = 0.0
            break
    else:
        j = предел

    if доля_открыта > 0:
        выход = closes[j]
        r = (выход - вход) / риск if длинная else (вход - выход) / риск
        накоплено += r * доля_открыта

    return накоплено - издержки_R(вход, стоп if стоп != вход else вход * 0.98)


def оценить(сигналы: list[dict], пр: Правила) -> dict:
    R = [провести(с, пр) for с in сигналы]
    R = [r for r in R if r is not None]
    if not R:
        return {"сделок": 0, "сумма": 0.0, "win": 0.0, "пф": 0.0, "просадка": 0.0}

    победы = [r for r in R if r > 0]
    убытки = [r for r in R if r <= 0]
    прибыль = sum(победы)
    потеря = abs(sum(убытки))
    накоп = пик = просадка = 0.0
    for r in R:
        накоп += r
        пик = max(пик, накоп)
        просадка = min(просадка, накоп - пик)
    return {
        "сделок": len(R), "сумма": sum(R), "win": len(победы) / len(R) * 100,
        "пф": прибыль / потеря if потеря else float("inf"),
        "просадка": просадка,
    }


ВАРИАНТЫ = [
    Правила("1. Базовый (как сейчас)"),
    Правила("2. Стоп в безубыток после +1R", безубыток_после_R=1.0),
    Правила("3. Цель ближе: 1.5R", цель_R=1.5),
    Правила("4. Цель 2R вместо уровня", цель_R=2.0),
    Правила("5. Стоп шире в 1.5 раза", множитель_стопа=1.5),
    Правила("6. Шире стоп + цель 2R", множитель_стопа=1.5, цель_R=2.0),
    Правила("7. Половина на 1R, стоп в безубыток",
            частичная_фиксация_R=1.0, безубыток_после_R=1.0),
    Правила("8. Трейлинг 2xATR", трейлинг_atr=2.0),
    Правила("9. Выход по времени через 20 баров", предел_баров=20),
    Правила("10. Цель 1.5R + половина на 1R", цель_R=1.5, частичная_фиксация_R=1.0),
]


def таблица(заголовок: str, сигналы: list[dict]) -> None:
    print(f"\n{'=' * 78}")
    print(f"  {заголовок}   (сигналов в выборке: {len(сигналы)})")
    print(f"{'=' * 78}")
    print(f"  {'вариант':38s} {'сделок':>7} {'побед':>7} {'итог R':>8} {'ПФ':>6} {'просадка':>9}")
    print(f"  {'-' * 74}")
    for пр in ВАРИАНТЫ:
        о = оценить(сигналы, пр)
        пф = "inf" if о["пф"] == float("inf") else f"{о['пф']:.2f}"
        print(f"  {пр.имя:38s} {о['сделок']:7d} {о['win']:6.1f}% "
              f"{о['сумма']:+8.2f} {пф:>6} {о['просадка']:9.2f}")


if __name__ == "__main__":
    сигналы = sorted(СИГНАЛЫ, key=lambda с: (с["бар"], с["актив"]))
    граница = int(len(сигналы) * 0.6)
    обучение, проверка = сигналы[:граница], сигналы[граница:]

    print(f"Всего сигналов: {len(сигналы)}")
    print(f"Обучающая часть: {len(обучение)}   Проверочная: {len(проверка)}")
    print("\nПФ — профит-фактор. Выше 1 = зарабатывает, ниже 1 = теряет.")

    таблица("ОБУЧАЮЩАЯ ЧАСТЬ — здесь подбираем", обучение)
    таблица("ПРОВЕРОЧНАЯ ЧАСТЬ — здесь подтверждаем", проверка)
    таблица("ВСЯ ВЫБОРКА (справочно)", сигналы)

    print("\nКак читать: вариант считается находкой, только если он хорош")
    print("в ОБЕИХ частях. Хорош в первой и плох во второй — это подгонка")
    print("под прошлое, на новых данных такой вариант работать не будет.")
