"""
Прорывы на глубокой истории — ТОЧНО по живым правилам, с датами и доливками.

Зачем отдельный прогон. Старая проверка test_breakout.py сравнивала окна
входа, но не знала ни о доливках, ни о датах сделок. А чтобы решить, сколько
ставить на прорывы относительно долгосрочной системы, нужно прогнать все
системы ВМЕСТЕ через общий портфель — для этого у каждой сделки должны быть
даты и риск на каждый день её жизни. У прорывов риск меняется: доливки его
поднимают, подтяжка стопа опускает, вплоть до нуля.

Порядок внутри дня тот же, что в breakouts.py (иначе живой журнал и замер
померяют разное):
  1. стоп в том виде, в каком он был с утра: минимум дня его задел — выход
     по цене стопа;
  2. доливка: максимум дня дошёл до входа + шаг·R·(n+1) — новая часть того же
     размера по этой цене, не больше макс_доливок;
  3. подтяжка стопа: минимум последних окно_выхода дней минус 0.2 ATR,
     только вверх.
День входа стопом не проверяется — его минимум мог случиться до входа.

Одно допущение строже живого: вход по закрытию дня пробоя (живой берёт
цену в момент прохода внутри этого дня). И одно честнее живого: комиссии
вычитаются с КАЖДОЙ части позиции, а живой журнал прорывов их не вычитает.

    python backtest_breakout.py        все монеты, сохраняет trades_breakout.json
"""

from __future__ import annotations

import json
import os
from datetime import datetime, timezone

from engine import data, indicators as ind, pyramid

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
# Имя переменной окружения — латиницей: кириллица не переживает оболочку.
ГЛУБИНА = int(os.environ.get("DEPTH", "3000"))


def _день(t: float) -> str:
    if t > 1e11:
        t /= 1000.0
    return datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%d")


def прогнать(свечи: data.Свечи, cfg: dict) -> list[dict]:
    п = cfg["прорывы"]
    вх = int(п["окно_входа"])
    вых = int(п["окно_выхода"])
    к_atr = float(п["стоп_atr"])
    шаг = float(п.get("доливка_шаг_R", 0.0))
    макс_д = int(п.get("макс_доливок", 0))
    и = cfg["издержки"]
    издержки = (и["комиссия_вход_пр"] + и["комиссия_выход_пр"]
                + и["проскальзывание_пр"]) / 100

    H, L, C, T = свечи.highs, свечи.lows, свечи.closes, свечи.времена
    atr = ind.atr(H, L, C, 14)
    объём_ср = ind.sma(свечи.volumes, 20)
    сделки: list[dict] = []
    занят_до = -1
    # Живой анализ требует не меньше окно_входа + 25 баров и готовые ATR и объём.
    начало = max(вх + 25, вых + 1, 30)

    for i in range(начало, len(C) - 1):
        if i <= занят_до:
            continue
        a = atr[i]
        if not a or not объём_ср[i]:
            continue
        # Пробой: закрытие выше максимума ПРЕДЫДУЩИХ окно_входа дней.
        if C[i] <= max(H[i - вх:i]):
            continue
        вход = C[i]
        стоп = вход - a * к_atr
        риск = вход - стоп
        if риск <= 0:
            continue

        части = pyramid.первая_часть(вход)
        путь = [[_день(T[i]), 1.0]]
        исход, выход, j = "открыта в конце истории", C[-1], len(C) - 1
        for j in range(i + 1, len(C)):
            if L[j] <= стоп:
                исход, выход = "стоп", стоп
                break
            сделано = len(части) - 1
            if шаг > 0 and сделано < макс_д:
                порог = pyramid.порог_доливки(вход, риск, шаг, сделано)
                if H[j] >= порог:
                    pyramid.долить(части, порог)
            # Как breakout.обновить_стоп по срезу до дня j включительно.
            минимум = min(L[max(0, j - вых + 1):j + 1])
            стоп = max(стоп, минимум - (atr[j] or 0) * 0.2)
            путь.append([_день(T[j]),
                         max(0.0, -pyramid.риск_сейчас_R(части, стоп, риск))])

        r = pyramid.результат_R(части, выход, риск)
        r -= sum(ч["доля"] * издержки * ч["цена"] / риск for ч in части)
        сделки.append({
            "актив": свечи.актив, "время_входа": T[i], "время_выхода": T[j],
            "вход": вход, "выход": выход, "исход": исход, "r": r,
            "долей": pyramid.размер_долей(части), "дней": j - i,
            "путь": путь,
        })
        занят_до = j
    return сделки


def главное() -> int:
    все: list[dict] = []
    for актив in CFG["активы"]:
        try:
            свечи = data.загрузить_глубоко(актив, "1d", баров=ГЛУБИНА,
                                           источники=CFG["источник_данных"])
        except Exception as e:
            print(f"  {актив:10s} ошибка -> {type(e).__name__}: {e}")
            continue
        с = прогнать(свечи, CFG)
        все.extend(с)
        print(f"  {актив:10s} с {_день(свечи.времена[0])}  сделок {len(с):3d}  "
              f"итог {sum(x['r'] for x in с):+8.2f}R")

    if not все:
        print("Сделок нет.")
        return 1
    все.sort(key=lambda x: x["время_входа"])
    R = [x["r"] for x in все]
    г = len(все) // 2
    print(f"\nВсего {len(R)} сделок, побед {sum(1 for r in R if r > 0) / len(R) * 100:.0f}%, "
          f"итог {sum(R):+.1f}R, на сделку {sum(R) / len(R):+.3f}R")
    print(f"половины по времени: {sum(R[:г]):+.1f}R / {sum(R[г:]):+.1f}R")
    print(f"с доливками: {sum(1 for x in все if x['долей'] > 1)} из {len(все)}")
    with open(os.path.join(БАЗА, "trades_breakout.json"), "w", encoding="utf-8") as f:
        json.dump(все, f, ensure_ascii=False)
    print("Сделки сохранены в trades_breakout.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
