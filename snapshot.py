"""
Снимок счёта за сегодня. Запускается в конце каждого прохода автоматики.

Считает три числа сразу — закрытое, открытое по рынку и худший случай —
и кладёт их в state/equity.json одной записью на сутки. Отдельным скриптом,
а не внутри торговых систем, потому что снимок должен учитывать ВСЕ
системы вместе, а каждая из них знает только про себя.

    python snapshot.py          посчитать и записать
    python snapshot.py --тихо   без вывода
"""

from __future__ import annotations

import json
import os
import sys

from engine import data, equity, pnl

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))


def текущие_цены() -> dict[str, float]:
    """Ошибка по одной монете не должна ронять весь снимок: такая позиция
    оценится по своему стопу, что честнее, чем пропустить её вовсе."""
    цены: dict[str, float] = {}
    for актив in CFG["активы"]:
        try:
            цены[актив] = data.загрузить(
                актив, "1d", лимит=3,
                источники=CFG["источник_данных"]).последняя_цена
        except Exception:
            continue
    return цены


def главное() -> int:
    д = pnl.подсчитать(текущие_цены())
    снимок = equity.записать(
        закрыто=д["всего_закрыто"],
        открыто=д["всего_открыто"],
        худший=д["худший_случай"],
        капитал=CFG["риск"]["депозит"],
        позиций=д["позиций_открыто"],
        сделок=sum(в["сделок"] for в in д["закрытые"].values()),
    )
    if "--тихо" not in sys.argv:
        с = equity.сводка()
        print(f"Снимок за {снимок['день']}: закрыто {снимок['закрыто']:+.2f} $, "
              f"открыто {снимок['открыто']:+.2f} $, итого {снимок['итог']:+.2f} $")
        print(f"  худший случай (все стопы): {снимок['худший']:+.2f} $")
        print(f"  в истории {с['дней']} дней, с {с['с']} по {с['по']}, "
              f"максимальная просадка {с['макс_просадка']:.2f} $")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
