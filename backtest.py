"""
Бэктест: доводим каждый сигнал до результата и считаем, зарабатывала бы система.

Правила симуляции выбраны ПЕССИМИСТИЧНО — лучше недооценить результат, чем
обмануться. Конкретно:

1. Вход по отложенному ордеру засчитывается, только если цена реально дошла
   до уровня в течение срока жизни сигнала. Не дошла — сделки не было.
2. Если внутри одной свечи задеты и стоп, и цель — считаем, что сработал СТОП.
   По часовым данным нельзя узнать, что случилось раньше, и это худший вариант.
3. Комиссии и проскальзывание вычитаются на входе и на выходе.
4. Сделка закрывается по первой цели (TP1) целиком. Частичных фиксаций нет.
5. Проверка на «заглядывание в будущее»: решение на баре i принимается только
   по данным до бара i включительно, исполнение — начиная с бара i+1.

Запуск:  python backtest.py              все монеты из конфига
         python backtest.py BTCUSDT      одна монета
"""

from __future__ import annotations

import json
import os
import sys
from dataclasses import dataclass, replace

from engine import data, signals
from engine.risk import LONG

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
РАЗОГРЕВ = 240
БАРОВ_НА_СДЕЛКУ = 60      # предел удержания: 60 баров по 4ч = 10 суток


@dataclass
class Сделка:
    актив: str
    направление: str
    бар_сигнала: int
    бар_входа: int
    бар_выхода: int
    вход: float
    стоп: float
    цель: float
    исход: str            # "цель" / "стоп" / "время"
    выход: float
    r_чистый: float       # результат в единицах риска, ПОСЛЕ издержек
    уверенность: str


def срез(свечи: data.Свечи, до: int) -> data.Свечи:
    return replace(
        свечи,
        времена=свечи.времена[:до + 1], opens=свечи.opens[:до + 1],
        highs=свечи.highs[:до + 1], lows=свечи.lows[:до + 1],
        closes=свечи.closes[:до + 1], volumes=свечи.volumes[:до + 1],
    )


def издержки_в_r(вход: float, стоп: float, cfg: dict) -> float:
    """Во сколько долей риска обходятся комиссии и проскальзывание.
    Считаем от объёма позиции: объём = риск / относительная_дистанция_стопа."""
    и = cfg["издержки"]
    доля = (и["комиссия_вход_пр"] + и["комиссия_выход_пр"] + и["проскальзывание_пр"]) / 100
    дистанция_отн = abs(вход - стоп) / вход
    return доля / дистанция_отн if дистанция_отн else 99.0


def провести_сделку(свечи: data.Свечи, i: int, план, cfg: dict) -> Сделка | None:
    """Проводит одну сделку вперёд по барам. i — бар, на котором дан сигнал."""
    ttl = cfg["сигналы"]["срок_жизни_сигнала_баров"]
    длинная = план.направление == LONG
    вход, стоп, цель = план.вход, план.стоп, план.цели[0]

    # --- Шаг 1: дождались ли входа ---
    бар_входа = None
    if план.тип_ордера == "Market":
        бар_входа = i + 1
        if бар_входа >= len(свечи):
            return None
        вход = свечи.opens[бар_входа]          # исполнение по открытию следующего бара
    else:
        for j in range(i + 1, min(i + 1 + ttl, len(свечи))):
            задет = (свечи.lows[j] <= вход <= свечи.highs[j])
            if задет:
                бар_входа = j
                break
    if бар_входа is None:
        return None                             # цена не пришла — сделки не было

    # Пересчёт уровней, если вход сместился (для Market).
    риск_ед = abs(вход - стоп)
    if риск_ед == 0:
        return None

    # --- Шаг 2: ведём позицию до стопа, цели или предела по времени ---
    исход, выход, бар_выхода = "время", свечи.closes[-1], len(свечи) - 1
    предел = min(бар_входа + БАРОВ_НА_СДЕЛКУ, len(свечи) - 1)

    for j in range(бар_входа, предел + 1):
        h, l = свечи.highs[j], свечи.lows[j]
        стоп_задет = (l <= стоп) if длинная else (h >= стоп)
        цель_задета = (h >= цель) if длинная else (l <= цель)

        # Пессимизм: если задеты оба уровня в одной свече — считаем стоп.
        if стоп_задет:
            исход, выход, бар_выхода = "стоп", стоп, j
            break
        if цель_задета:
            исход, выход, бар_выхода = "цель", цель, j
            break
    else:
        бар_выхода = предел
        выход = свечи.closes[предел]

    # --- Шаг 3: результат в единицах риска, за вычетом издержек ---
    движение = (выход - вход) if длинная else (вход - выход)
    r_грязный = движение / риск_ед
    r_чистый = r_грязный - издержки_в_r(вход, стоп, cfg)

    return Сделка(
        актив=свечи.актив, направление=план.направление, бар_сигнала=i,
        бар_входа=бар_входа, бар_выхода=бар_выхода, вход=вход, стоп=стоп,
        цель=цель, исход=исход, выход=выход, r_чистый=r_чистый,
        уверенность="",
    )


def прогнать(актив: str) -> list[Сделка]:
    свечи = data.загрузить(актив, CFG["таймфрейм"], лимит=1000,
                           источники=CFG["источник_данных"])
    сделки: list[Сделка] = []
    занят_до = -1                       # не открываем новую сделку, пока идёт прежняя

    for i in range(РАЗОГРЕВ, len(свечи) - 2):
        if i <= занят_до:
            continue
        а = signals.проанализировать(срез(свечи, i), CFG, флаги_данных=[],
                                     депозит=CFG["риск"]["депозит"],
                                     проверять_свежесть=False)
        if а.вывод != signals.СИГНАЛ:
            continue
        с = провести_сделку(свечи, i, а.план, CFG)
        if с:
            с.уверенность = а.уверенность
            сделки.append(с)
            занят_до = с.бар_выхода
    return сделки


def статистика(сделки: list[Сделка], имя: str) -> dict:
    if not сделки:
        print(f"\n{имя}: сделок не было.")
        return {}

    выигрыши = [с for с in сделки if с.r_чистый > 0]
    проигрыши = [с for с in сделки if с.r_чистый <= 0]
    сумма_r = sum(с.r_чистый for с in сделки)
    win = len(выигрыши) / len(сделки) * 100
    средний = сумма_r / len(сделки)

    прибыль = sum(с.r_чистый for с in выигрыши)
    убыток = abs(sum(с.r_чистый for с in проигрыши))
    пф = прибыль / убыток if убыток else float("inf")

    # Просадка по накопленной кривой в единицах риска.
    накоп, пик, просадка = 0.0, 0.0, 0.0
    for с in сделки:
        накоп += с.r_чистый
        пик = max(пик, накоп)
        просадка = min(просадка, накоп - пик)

    исходы: dict[str, int] = {}
    for с in сделки:
        исходы[с.исход] = исходы.get(с.исход, 0) + 1

    print(f"\n{'=' * 60}")
    print(f"  {имя}")
    print(f"{'=' * 60}")
    print(f"  Сделок:              {len(сделки)}")
    print(f"  Прибыльных:          {len(выигрыши)} ({win:.1f}%)")
    print(f"  Итог в риск-единицах: {сумма_r:+.2f}R  (среднее {средний:+.3f}R на сделку)")
    print(f"  Профит-фактор:       {пф:.2f}   (>1 — система зарабатывает)")
    print(f"  Макс. просадка:      {просадка:.2f}R")
    print(f"  Чем закрывались:     " + ", ".join(f"{к} — {v}" for к, v in исходы.items()))

    return {"сделок": len(сделки), "win": win, "сумма_r": сумма_r,
            "средний_r": средний, "пф": пф, "просадка": просадка}


