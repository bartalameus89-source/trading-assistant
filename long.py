"""
Долгосрочный обзор: что система думает о покупке на месяцы.

Запускать раз в сутки — чаще бессмысленно, дневная свеча меняется раз в день.
Это ОТДЕЛЬНАЯ система от короткой торговли: другие входы, другой горизонт,
другая статистика. Смешивать их выводы нельзя.

    python long.py          обзор в консоль
    python long.py --tg     то же + отправка в Telegram
"""

from __future__ import annotations

import json
import os
import sys

from engine import data, longterm
from engine.render import формат_цены
from run import отправить_в_телеграм

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))


def обзор() -> list[longterm.ДолгийВзгляд]:
    взгляды = []
    for актив in CFG["активы"]:
        try:
            свечи = data.загрузить(актив, "1d", лимит=400,
                                   источники=CFG["источник_данных"])
            взгляды.append(longterm.проанализировать_долгий(свечи, CFG))
        except Exception as e:
            print(f"  {актив}: ошибка {type(e).__name__}")
    return взгляды


def телеграм_текст(взгляды: list[longterm.ДолгийВзгляд]) -> str:
    есть = [в for в in взгляды if в.вывод == longterm.ЕСТЬ_ПОТЕНЦИАЛ]
    наблюдаем = [в for в in взгляды if в.вывод == longterm.НАБЛЮДАЕМ]

    т = ["📈 <b>ДОЛГОСРОЧНЫЙ ОБЗОР</b>",
         "<i>Отдельная система: покупка на месяцы, не путать с короткими сигналами.</i>", ""]

    if есть:
        for в in есть:
            монета = в.актив.replace("USDT", "")
            т.append(f"🟢 <b>{монета}</b> — есть потенциал для покупки вдолгую")
            т.append(f"Цена {формат_цены(в.цена)}, стоп {формат_цены(в.стоп)} "
                     f"({в.стоп_проц:.1f}% ниже)")
            т.append(f"Выход: {в.выход_по}")
            т.append(f"Горизонт: {в.горизонт}")
            т.append("")
    else:
        т.append("Активов для долгой покупки сейчас нет.")
        т.append("")

    if наблюдаем:
        т.append("<b>Близки к сигналу:</b>")
        for в in наблюдаем:
            монета = в.актив.replace("USDT", "")
            чего = "; ".join(п.replace("не выполнено: ", "") for п in в.причины)
            т.append(f"• {монета} — ждём: {чего}")
        т.append("")

    т.append("<i>Чего ждать от этой системы: примерно 18 побед из 100, "
             "но каждая победа в 13 раз крупнее убытка. Большую часть времени "
             "она теряет понемногу и редко ловит крупное движение. "
             "Проверено на 87 сделках за 2.7 года.</i>")
    return "\n".join(т)


def главное() -> int:
    взгляды = обзор()

    print("=" * 68)
    print("  ДОЛГОСРОЧНЫЙ ОБЗОР — покупка на месяцы (отдельно от коротких сделок)")
    print("=" * 68)
    print(f"  {'монета':8s} {'цена':>12s} {'вывод':<16s} {'условий':>8s}  комментарий")
    print("  " + "-" * 64)

    порядок = {longterm.ЕСТЬ_ПОТЕНЦИАЛ: 0, longterm.НАБЛЮДАЕМ: 1, longterm.НЕ_ВРЕМЯ: 2}
    for в in sorted(взгляды, key=lambda x: (порядок.get(x.вывод, 3), x.актив)):
        монета = в.актив.replace("USDT", "")
        print(f"  {монета:8s} {формат_цены(в.цена):>12s} {в.вывод:<16s} "
              f"{в.выполнено}/{len(в.условия):<6}  {longterm.словами(в)[:70]}")

    есть = [в for в in взгляды if в.вывод == longterm.ЕСТЬ_ПОТЕНЦИАЛ]
    if есть:
        print(f"\n{'=' * 68}")
        for в in есть:
            print(f"  {в.актив.replace('USDT','')} — ПОДРОБНО")
            for имя, ок, факт in в.условия:
                print(f"    [{'OK  ' if ок else 'НЕТ '}] {имя}: {факт}")
            риск_пр = CFG["долгосрочная"]["риск_на_позицию_пр"]
            депозит = CFG["риск"]["депозит"] or 100
            размер = депозит * риск_пр / 100 / (в.стоп_проц / 100)
            print(f"    Вход {формат_цены(в.цена)}, стоп {формат_цены(в.стоп)} ({в.стоп_проц:.1f}%)")
            print(f"    При капитале {депозит:.0f} $ и риске {риск_пр}%: "
                  f"позиция {размер:.2f} $, под риском {депозит * риск_пр / 100:.2f} $")
            print(f"    Выход: {в.выход_по}")

    print(f"\n  Итого: потенциал {len(есть)}, "
          f"наблюдаем {sum(1 for в in взгляды if в.вывод == longterm.НАБЛЮДАЕМ)}, "
          f"не время {sum(1 for в in взгляды if в.вывод == longterm.НЕ_ВРЕМЯ)}")

    if "--tg" in sys.argv:
        if отправить_в_телеграм(телеграм_текст(взгляды)):
            print("  Отправлено в Telegram.")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
