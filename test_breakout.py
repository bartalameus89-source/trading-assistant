"""
Прорывы: можно ли ловить движения вроде роста BTC на 24% за неделю.

Почему это отдельная проверка. Обе наши системы такое движение пропускают,
и обе по своей причине: короткая блокирует высокую волатильность, долгосрочная
ждёт отката в уже растущем тренде. Замер «в высокой волатильности убыточно»
проверял сигналы ВОЗВРАТА К СРЕДНЕМУ в такой фазе — это противоположный
по смыслу вход. Прорыв не проверялся ни разу.

Правило простое и старое (система «черепах», 1983 год):
  вход  — цена закрылась выше максимума за N баров;
  стоп  — под минимумом за M баров;
  выход — цена ушла ниже минимума за K баров, цели нет.

Цели нет намеренно: смысл прорыва в том, чтобы поймать движение целиком.
Проверяется на глубокой истории с делением на половины.

Запуск:  python test_breakout.py
"""

from __future__ import annotations

import json
import os

from engine import data, indicators as ind

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))

# Наборы параметров: (окно входа, окно выхода, множитель ATR для стопа)
ВАРИАНТЫ = [
    ("прорыв 20 баров, выход 10", 20, 10, 2.0),
    ("прорыв 20 баров, выход 20", 20, 20, 2.0),
    ("прорыв 55 баров, выход 20", 55, 20, 2.0),
    ("прорыв 30 баров, выход 15", 30, 15, 2.0),
    ("прорыв 20 + объём выше среднего", 20, 10, 2.0),
]
ПРЕДЕЛ_БАРОВ = 250


def прогнать(свечи: data.Свечи, вход_окно: int, выход_окно: int,
             стоп_atr: float, нужен_объём: bool) -> list[dict]:
    highs, lows, closes = свечи.highs, свечи.lows, свечи.closes
    atr_ряд = ind.atr(highs, lows, closes, 14)
    объём_ср = ind.sma(свечи.volumes, 20)

    сделки: list[dict] = []
    занят_до = -1
    начало = max(вход_окно, выход_окно, 30)

    for i in range(начало, len(свечи) - 2):
        if i <= занят_до:
            continue
        atr_ = atr_ряд[i]
        if atr_ is None or atr_ <= 0:
            continue

        # Прорыв: закрытие выше максимума предыдущих баров (сам бар не считаем).
        максимум = max(highs[i - вход_окно:i])
        if closes[i] <= максимум:
            continue
        if нужен_объём:
            ср = объём_ср[i]
            if not ср or свечи.volumes[i] < ср * 1.2:
                continue

        вход = свечи.opens[i + 1]           # покупаем на открытии следующего бара
        стоп = вход - atr_ * стоп_atr
        риск = вход - стоп
        if риск <= 0:
            continue

        исход, выход, j = "предел по времени", closes[-1], len(свечи) - 1
        предел = min(i + 1 + ПРЕДЕЛ_БАРОВ, len(свечи) - 1)
        for j in range(i + 1, предел + 1):
            if lows[j] <= стоп:
                исход, выход = "стоп", стоп
                break
            # Выход по прорыву вниз: цена ушла ниже минимума за выход_окно баров.
            минимум = min(lows[max(0, j - выход_окно):j])
            if closes[j] < минимум:
                исход, выход = "выход по слому", closes[j]
                break
            # Подтягиваем стоп за этим же минимумом — так работает трейлинг
            # у трендовых систем: не по ATR от цены, а по структуре рынка.
            стоп = max(стоп, минимум - atr_ * 0.2)
        else:
            j = предел
            выход = closes[предел]

        и = CFG["издержки"]
        издержки_отн = (и["комиссия_вход_пр"] + и["комиссия_выход_пр"]
                        + и["проскальзывание_пр"]) / 100
        r = (выход - вход) / риск - издержки_отн * вход / риск
        сделки.append({"актив": свечи.актив, "бар": i, "r": r,
                       "исход": исход, "баров": j - i,
                       "ход": (выход / вход - 1) * 100})
        занят_до = j
    return сделки


def свод(сделки: list[dict], подпись: str) -> None:
    if not сделки:
        print(f"  {подпись:34s} нет сделок")
        return
    R = [с["r"] for с in сделки]
    п = [r for r in R if r > 0]
    у = [r for r in R if r <= 0]
    пф = sum(п) / abs(sum(у)) if у else 99.0
    накоп = пик = прос = 0.0
    for r in R:
        накоп += r
        пик = max(пик, накоп)
        прос = min(прос, накоп - пик)
    print(f"  {подпись:34s}{len(R):6d}{len(п) / len(R) * 100:6.0f}%"
          f"{sum(R):+9.2f}{sum(R) / len(R):+9.3f}{пф:7.2f}{прос:9.1f}")


def главное() -> None:
    for имя, вх, вых, atr_м in ВАРИАНТЫ:
        нужен_объём = "объём" in имя
        все: list[dict] = []
        for актив in CFG["активы"]:
            try:
                свечи = data.загрузить_глубоко(актив, "1d", баров=3000,
                                               источники=CFG["источник_данных"])
            except Exception:
                continue
            все.extend(прогнать(свечи, вх, вых, atr_м, нужен_объём))

        if not все:
            print(f"\n{имя}: сделок нет")
            continue
        все.sort(key=lambda с: с["бар"])
        г = len(все) // 2
        print(f"\n{имя}")
        print(f"  {'часть':34s}{'сделок':>6}{'побед':>7}{'итог R':>9}"
              f"{'на сделку':>9}{'ПФ':>7}{'просадка':>9}")
        свод(все[:г], "первая половина истории")
        свод(все[г:], "вторая половина истории")
        свод(все, "ВСЯ ВЫБОРКА")
        лучшая = max(все, key=lambda с: с["ход"])
        print(f"  лучшая сделка: {лучшая['актив'].replace('USDT','')} "
              f"{лучшая['ход']:+.0f}% за {лучшая['баров']} дней")


if __name__ == "__main__":
    главное()
