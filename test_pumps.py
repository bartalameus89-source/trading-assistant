"""
Пампы: можно ли на них заработать, если входить после обнаружения.

Проблема пампа известна заранее: пока движение становится заметным, большая
его часть уже произошла. Вопрос не в том, как заметить — заметить просто.
Вопрос в том, что делает цена ПОСЛЕ обнаружения.

Метод. Ищем в истории все случаи резкого роста на аномальном объёме,
и смотрим, что было дальше на разных горизонтах. Без отбора, без условий —
чистая статистика по всем найденным пампам.

Отдельно считаем, что было бы при входе с обычным для нас риском: пампы
сопровождаются огромной волатильностью, и стоп приходится ставить далеко.

Запуск:  python test_pumps.py
"""

from __future__ import annotations

import json
import os
from collections import defaultdict

from engine import data, indicators as ind

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))

# Что считаем пампом: рост за окно + всплеск объёма
ОКНО_БАРОВ = 3           # за сколько баров смотрим рост
ПОРОГИ_РОСТА = (5.0, 10.0, 20.0)      # проценты
ПОРОГ_ОБЪЁМА = 3.0       # во сколько раз выше среднего
ГОРИЗОНТЫ = (1, 3, 6, 12, 24)         # через сколько баров смотрим результат


def найти_пампы(свечи: data.Свечи, порог: float) -> list[int]:
    """Индексы баров, на которых зафиксирован памп."""
    объём_ср = ind.sma(свечи.volumes, 20)
    найдено = []
    последний = -100
    for i in range(ОКНО_БАРОВ + 20, len(свечи) - max(ГОРИЗОНТЫ) - 1):
        if i - последний < 12:
            continue                      # не считаем один памп много раз
        было = свечи.closes[i - ОКНО_БАРОВ]
        стало = свечи.closes[i]
        рост = (стало / было - 1) * 100
        если_объём = объём_ср[i]
        if рост >= порог and если_объём and свечи.volumes[i] >= если_объём * ПОРОГ_ОБЪЁМА:
            найдено.append(i)
            последний = i
    return найдено


def главное() -> None:
    результаты: dict[tuple[float, int], list[float]] = defaultdict(list)
    просадки: dict[float, list[float]] = defaultdict(list)
    всего: dict[float, int] = defaultdict(int)

    for актив in CFG["активы"]:
        try:
            свечи = data.загрузить_глубоко(актив, "1h", баров=6000,
                                           источники=CFG["источник_данных"])
        except Exception as e:
            print(f"  {актив:10s} ошибка: {type(e).__name__}")
            continue

        for порог in ПОРОГИ_РОСТА:
            точки = найти_пампы(свечи, порог)
            всего[порог] += len(точки)
            for i in точки:
                вход = свечи.closes[i]
                for г in ГОРИЗОНТЫ:
                    результаты[(порог, г)].append(
                        (свечи.closes[i + г] / вход - 1) * 100)
                # Худшая просадка за 12 баров после входа — сколько нужно
                # выдержать, чтобы дождаться результата.
                дно = min(свечи.lows[i + 1:i + 13])
                просадки[порог].append((дно / вход - 1) * 100)
        print(f"  {актив:10s} пампов: " +
              ", ".join(f"{п:.0f}%={len(найти_пампы(свечи, п))}" for п in ПОРОГИ_РОСТА))

    print(f"\n{'=' * 78}")
    print("  ЧТО ДЕЛАЕТ ЦЕНА ПОСЛЕ ПАМПА (вход по закрытию бара обнаружения)")
    print(f"{'=' * 78}")
    print(f"  {'памп':>8} {'случаев':>9}" + "".join(f"{f'+{г}ч':>10}" for г in ГОРИЗОНТЫ)
          + f"{'просадка':>11}")
    print("  " + "-" * 74)
    for порог in ПОРОГИ_РОСТА:
        n = всего[порог]
        if not n:
            continue
        строка = f"  {порог:7.0f}% {n:9d}"
        for г in ГОРИЗОНТЫ:
            зн = результаты[(порог, г)]
            строка += f"{sum(зн) / len(зн):+9.2f}%" if зн else f"{'—':>10}"
        пр = просадки[порог]
        строка += f"{sum(пр) / len(пр):+10.2f}%"
        print(строка)

    print("  " + "-" * 74)
    print("  «просадка» — средний худший минус за 12 часов после входа.")
    print()
    print("  Доля случаев, когда цена была выше входа:")
    print(f"  {'памп':>8}" + "".join(f"{f'+{г}ч':>10}" for г in ГОРИЗОНТЫ))
    for порог in ПОРОГИ_РОСТА:
        строка = f"  {порог:7.0f}%"
        for г in ГОРИЗОНТЫ:
            зн = результаты[(порог, г)]
            строка += f"{sum(1 for x in зн if x > 0) / len(зн) * 100:9.1f}%" if зн else f"{'—':>10}"
        print(строка)

    print()
    print("  Как читать: чтобы вход после памп был выгоден, средний ход должен")
    print("  превышать издержки (0.25% за круг) с запасом, а доля успеха —")
    print("  быть заметно выше 50%. Иначе это подбрасывание монетки с комиссией.")


if __name__ == "__main__":
    главное()
