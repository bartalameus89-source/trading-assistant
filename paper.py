"""
Бумажная торговля: один проход по рынку.

Что делает за запуск:
  1. проводит уже открытые бумажные сделки по свежим свечам — сработал стоп?
     дошло до цели? истёк срок ожидания входа?
  2. ищет новые сигналы и записывает их в журнал;
  3. шлёт в Telegram только то, что изменилось.

Запускать раз в 4 часа (по закрытию бара). Реальные деньги не участвуют.

    python paper.py            один проход
    python paper.py --отчёт    только сводка, без изменений
"""

from __future__ import annotations

import json
import os
import sys
import time

from engine import data, decisions, journal, portfolio, render, shadow, signals
from run import отправить_в_телеграм

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ЧАСОВ_В_БАРЕ = {"1h": 1, "2h": 2, "4h": 4, "6h": 6, "12h": 12, "1d": 24}


def свежие_бары(активы: list[str], с_какого_времени: float) -> dict[str, list[dict]]:
    """Бары по каждому активу с указанного момента, СПИСКОМ.

    Раньше здесь возвращалось одно свёрнутое {high, low, close} на актив
    за общий период, и журналы сверяли уровни с ним. Две беды:
      - окно считалось от самой старой сделки, и свежая сделка проверялась
        по ценам, которых при ней не существовало;
      - high и low принадлежат РАЗНЫМ барам, а сравнивались как один момент,
        поэтому при недельном окне сделка видела и стоп, и цель сразу,
        и исход решал порядок проверок в коде, а не рынок.
    Теперь журнал идёт по барам по одному — как бэктест.
    """
    результат: dict[str, list[dict]] = {}
    for актив in активы:
        try:
            свечи = data.загрузить(актив, CFG["таймфрейм"], лимит=100,
                                   источники=CFG["источник_данных"])
        except Exception:
            continue
        порог = (с_какого_времени - 60) * 1000
        результат[актив] = [
            {"t": свечи.времена[i], "high": свечи.highs[i],
             "low": свечи.lows[i], "close": свечи.closes[i]}
            for i in range(len(свечи)) if свечи.времена[i] >= порог
        ]
    return результат


def сводка_текстом(ст: dict) -> str:
    if ст["закрыто"] == 0:
        return (f"📓 <b>Бумажный журнал</b>\n"
                f"Сделок всего: {ст['всего']} · ждут входа: {ст['ожидают']} · "
                f"в работе: {ст['открыты']}\n"
                f"Закрытых пока нет — статистики не будет, пока их не наберётся "
                f"хотя бы 30.")
    пф = ("∞" if ст["профит_фактор"] == float("inf")
          else f"{ст['профит_фактор']:.2f}")
    вердикт = ("зарабатывает" if ст["профит_фактор"] > 1 else "теряет")
    return (f"📓 <b>Бумажный журнал</b> — {ст['дней']:.0f} дней\n"
            f"Закрыто сделок: {ст['закрыто']} · побед: {ст['побед']} "
            f"({ст['доля_побед']:.0f}%)\n"
            f"Итог: {ст['сумма_R']:+.2f}R · профит-фактор {пф} — {вердикт}\n"
            f"Худшая просадка: {ст['просадка_R']:.2f}R\n"
            f"<i>Надёжные выводы — после 100+ сделок.</i>")


def сигнал_жизни(ст: dict, событий: int, новых: int) -> str:
    """Еженедельное подтверждение, что система жива.

    Без него молчание бота неотличимо от поломки — а сигналы приходят
    примерно раз в неделю, и естественная пауза выглядит как сбой.
    Уже дважды возникал вопрос «а точно ли работает».
    """
    строки = [
        "🫀 <b>Система работает</b>",
        "Проверка рынка идёт каждые 4 часа, сбоев нет.",
        "",
        f"За последний проход: событий {событий}, новых сигналов {новых}.",
        f"В журнале: ждут входа {ст['ожидают']}, в работе {ст['открыты']}, "
        f"закрыто {ст['закрыто']}.",
        "",
        "<i>Сигналы появляются примерно раз в неделю — молчание "
        "это нормальная работа, а не поломка.</i>",
    ]
    return "\n".join(строки)


def главное() -> int:
    if "--отчёт" in sys.argv:
        print(сводка_текстом(journal.статистика()).replace("<b>", "")
              .replace("</b>", "").replace("<i>", "").replace("</i>", ""))
        return 0

    часов = ЧАСОВ_В_БАРЕ.get(CFG["таймфрейм"], 4)
    активы = CFG["активы"]

    # --- 1. Провести существующие сделки ---
    открытые = [с for с in journal.все_сделки() if с.состояние != journal.ЗАКРЫТА]
    if открытые:
        самая_старая = min(с.открыта_в for с in открытые)
        бары = свежие_бары(sorted({с.актив for с in открытые}), самая_старая)
        события = journal.обновить(бары)
        for с, что in события:
            print(f"  {с.актив}: {что}")
            if с.состояние == journal.ЗАКРЫТА and с.исход != "истёк срок":
                знак = "✅" if (с.результат_R or 0) > 0 else "❌"
                прибыль = ""
                if с.риск_денег:
                    сумма = (с.результат_R or 0) * с.риск_денег
                    прибыль = f"\nНа бумаге: {сумма:+.2f} $ при риске {с.риск_денег:.2f} $"
                отправить_в_телеграм(
                    f"{знак} <b>{с.актив.replace('USDT','')}</b> — {что}\n"
                    f"Вход {с.цена_входа:,.4f} → выход {с.цена_выхода:,.4f}\n"
                    f"Результат: {с.результат_R:+.2f}R{прибыль}\n"
                    f"<i>Бумажная сделка, деньги не участвовали.</i>")
    else:
        события = []

    # --- 1б. Провести решения пользователя ---
    # Ведём и взятые, и пропущенные: без пропущенных не с чем сравнивать,
    # а весь смысл журнала решений — в этом сравнении.
    незакрытые = [р for р in decisions.все() if р.состояние != decisions.ЗАВЕРШЕНА]
    if незакрытые:
        бары_р = свежие_бары(sorted({р.актив for р in незакрытые}),
                             min(р.когда for р in незакрытые))
        for строка in decisions.провести(бары_р):
            print(f"  решение: {строка}")

    # --- 2. Искать новые сигналы ---
    новых = 0
    for актив in активы:
        try:
            свечи = data.загрузить(актив, CFG["таймфрейм"], лимит=400,
                                   источники=CFG["источник_данных"])
            флаги = data.проверить_качество(
                свечи, CFG["сигналы"]["макс_возраст_данных_баров"])
            а = signals.проанализировать(свечи, CFG, флаги,
                                         депозит=CFG["риск"]["депозит"])
        except Exception as e:
            print(f"  {актив}: ошибка {type(e).__name__}")
            continue

        if а.вывод != signals.СИГНАЛ:
            continue

        # Портфель имеет право вето: у короткой системы свой лимит позиций,
        # но он ничего не знает о прорывах и долгосрочных. Отсеянное здесь
        # уже лежит в тени — сигнал не теряется, он просто не рекомендуется.
        риск_сигнала = (а.план.риск_пр_депозита if а.план else 0.0) or 0.0
        можно, почему = portfolio.можно_открыть(CFG, актив, риск_сигнала)
        if not можно:
            print(f"  {актив}: сигнал есть, но портфель не пускает — {почему}")
            continue

        с = journal.добавить(а, CFG["риск"]["депозит"], часов,
                             CFG["сигналы"]["срок_жизни_сигнала_баров"],
                             порог_безубытка=CFG["риск"].get("безубыток_после_R", 0.0))
        if с is None:
            print(f"  {актив}: сигнал есть, но по активу уже идёт сделка")
            continue
        новых += 1
        print(f"  {актив}: НОВЫЙ СИГНАЛ записан в журнал")
        отправить_в_телеграм("📝 <b>Бумажная сделка</b>\n\n" + render.телеграм(а))

    # --- 2б. Теневой журнал: пишем и отсеянное тоже ---
    # Рекомендации от этого не меняются, в Telegram теневые записи не идут.
    # Смысл в том, чтобы через месяц сравнить отобранные сделки с отсеянными
    # и увидеть на живых данных, работают фильтры или мешают.
    теневые = [с for с in shadow.все() if с.состояние != shadow.ЗАКРЫТА]
    if теневые:
        бары_т = свежие_бары(sorted({с.актив for с in теневые}),
                                   min(с.создана for с in теневые))
        for строка in shadow.провести(бары_т):
            print(f"  тень: {строка}")

    новых_теней = 0
    for актив in активы:
        try:
            свечи = data.загрузить(актив, CFG["таймфрейм"], лимит=400,
                                   источники=CFG["источник_данных"])
            флаги = data.проверить_качество(
                свечи, CFG["сигналы"]["макс_возраст_данных_баров"])
            т = signals.проанализировать(свечи, CFG, флаги,
                                         депозит=CFG["риск"]["депозит"],
                                         теневой=True)
        except Exception:
            continue
        if т.вывод != signals.СИГНАЛ:
            continue
        если = shadow.добавить(т, часов, CFG["сигналы"]["срок_жизни_сигнала_баров"],
                               CFG["риск"].get("безубыток_после_R", 0.0))
        if если:
            новых_теней += 1

    # --- 3. Итог ---
    ст = journal.статистика()
    св = shadow.сводка()
    print(f"\nСобытий: {len(события)} · новых сигналов: {новых} "
          f"· новых теневых: {новых_теней}")
    print(f"Тень: рекомендованных {св['рекомендованные']['всего']}, "
          f"отсеянных {св['отсеянные']['всего']}, закрыто {св['все']['закрыто']}")
    print(f"В журнале: всего {ст['всего']}, ждут входа {ст['ожидают']}, "
          f"в работе {ст['открыты']}, закрыто {ст['закрыто']}")
    if ст["закрыто"]:
        print(f"Доля побед {ст['доля_побед']:.0f}%, итог {ст['сумма_R']:+.2f}R, "
              f"профит-фактор {ст['профит_фактор']:.2f}")

    # Раз в неделю — подтверждение, что система жива. Если за проход были
    # события, отдельный сигнал жизни не нужен: сообщения уже ушли.
    if "--жив" in sys.argv and not события and not новых:
        отправить_в_телеграм(сигнал_жизни(ст, len(события), новых))
        print("Отправлен сигнал жизни.")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
