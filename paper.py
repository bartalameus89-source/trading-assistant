"""
Бумажная торговля: один проход по рынку.

Что делает за запуск:
  1. проводит уже открытые бумажные сделки по свежим свечам — сработал стоп?
     дошло до цели? истёк срок ожидания входа?
  2. ищет новые сигналы и записывает их в журнал;
  3. шлёт в Telegram только то, что изменилось.

Запускать раз в 4 часа (по закрытию бара). Реальные деньги не участвуют.

    python paper.py            один проход
    python paper.py --отчёт    только сводка, без изменений
"""

from __future__ import annotations

import json
import os
import sys
import time

from engine import data, journal, render, signals
from run import отправить_в_телеграм

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ЧАСОВ_В_БАРЕ = {"1h": 1, "2h": 2, "4h": 4, "6h": 6, "12h": 12, "1d": 24}


def свежие_экстремумы(активы: list[str], с_какого_времени: float) -> dict:
    """Максимум, минимум и закрытие по каждому активу за прошедшее время.
    Берём все бары с прошлой проверки, чтобы не пропустить касание уровня
    внутри бара, который мы не видели."""
    результат = {}
    for актив in активы:
        try:
            свечи = data.загрузить(актив, CFG["таймфрейм"], лимит=30,
                                   источники=CFG["источник_данных"])
        except Exception:
            continue
        новые = [i for i, t in enumerate(свечи.времена)
                 if t / 1000 >= с_какого_времени - 60]
        if not новые:
            новые = [len(свечи) - 1]
        результат[актив] = {
            "high": max(свечи.highs[i] for i in новые),
            "low": min(свечи.lows[i] for i in новые),
            "close": свечи.closes[-1],
        }
    return результат


def сводка_текстом(ст: dict) -> str:
    if ст["закрыто"] == 0:
        return (f"📓 <b>Бумажный журнал</b>\n"
                f"Сделок всего: {ст['всего']} · ждут входа: {ст['ожидают']} · "
                f"в работе: {ст['открыты']}\n"
                f"Закрытых пока нет — статистики не будет, пока их не наберётся "
                f"хотя бы 30.")
    пф = ("∞" if ст["профит_фактор"] == float("inf")
          else f"{ст['профит_фактор']:.2f}")
    вердикт = ("зарабатывает" if ст["профит_фактор"] > 1 else "теряет")
    return (f"📓 <b>Бумажный журнал</b> — {ст['дней']:.0f} дней\n"
            f"Закрыто сделок: {ст['закрыто']} · побед: {ст['побед']} "
            f"({ст['доля_побед']:.0f}%)\n"
            f"Итог: {ст['сумма_R']:+.2f}R · профит-фактор {пф} — {вердикт}\n"
            f"Худшая просадка: {ст['просадка_R']:.2f}R\n"
            f"<i>Надёжные выводы — после 100+ сделок.</i>")


def главное() -> int:
    if "--отчёт" in sys.argv:
        print(сводка_текстом(journal.статистика()).replace("<b>", "")
              .replace("</b>", "").replace("<i>", "").replace("</i>", ""))
        return 0

    часов = ЧАСОВ_В_БАРЕ.get(CFG["таймфрейм"], 4)
    активы = CFG["активы"]

    # --- 1. Провести существующие сделки ---
    открытые = [с for с in journal.все_сделки() if с.состояние != journal.ЗАКРЫТА]
    if открытые:
        самая_старая = min(с.открыта_в for с in открытые)
        цены = свежие_экстремумы(sorted({с.актив for с in открытые}),
                                 max(самая_старая, time.time() - 7 * 86400))
        события = journal.обновить(цены)
        for с, что in события:
            print(f"  {с.актив}: {что}")
            if с.состояние == journal.ЗАКРЫТА and с.исход != "истёк срок":
                знак = "✅" if (с.результат_R or 0) > 0 else "❌"
                прибыль = ""
                if с.риск_денег:
                    сумма = (с.результат_R or 0) * с.риск_денег
                    прибыль = f"\nНа бумаге: {сумма:+.2f} $ при риске {с.риск_денег:.2f} $"
                отправить_в_телеграм(
                    f"{знак} <b>{с.актив.replace('USDT','')}</b> — {что}\n"
                    f"Вход {с.цена_входа:,.4f} → выход {с.цена_выхода:,.4f}\n"
                    f"Результат: {с.результат_R:+.2f}R{прибыль}\n"
                    f"<i>Бумажная сделка, деньги не участвовали.</i>")
    else:
        события = []

    # --- 2. Искать новые сигналы ---
    новых = 0
    for актив in активы:
        try:
            свечи = data.загрузить(актив, CFG["таймфрейм"], лимит=400,
                                   источники=CFG["источник_данных"])
            флаги = data.проверить_качество(
                свечи, CFG["сигналы"]["макс_возраст_данных_баров"])
            а = signals.проанализировать(свечи, CFG, флаги,
                                         депозит=CFG["риск"]["депозит"])
        except Exception as e:
            print(f"  {актив}: ошибка {type(e).__name__}")
            continue

        if а.вывод != signals.СИГНАЛ:
            continue
        с = journal.добавить(а, CFG["риск"]["депозит"], часов,
                             CFG["сигналы"]["срок_жизни_сигнала_баров"])
        if с is None:
            print(f"  {актив}: сигнал есть, но по активу уже идёт сделка")
            continue
        новых += 1
        print(f"  {актив}: НОВЫЙ СИГНАЛ записан в журнал")
        отправить_в_телеграм("📝 <b>Бумажная сделка</b>\n\n" + render.телеграм(а))

    # --- 3. Итог ---
    ст = journal.статистика()
    print(f"\nСобытий: {len(события)} · новых сигналов: {новых}")
    print(f"В журнале: всего {ст['всего']}, ждут входа {ст['ожидают']}, "
          f"в работе {ст['открыты']}, закрыто {ст['закрыто']}")
    if ст["закрыто"]:
        print(f"Доля побед {ст['доля_побед']:.0f}%, итог {ст['сумма_R']:+.2f}R, "
              f"профит-фактор {ст['профит_фактор']:.2f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
