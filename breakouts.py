"""
Система прорывов: поиск сигналов и ведение позиций.

Запускать раз в сутки после закрытия дневной свечи.

    python breakouts.py           обзор и ведение позиций
    python breakouts.py --tg      то же + сообщения в Telegram
    python breakouts.py --отчёт   только сводка

Позиций одновременно — не больше лимита из конфига. Когда прорывов больше,
чем мест, берутся самые свежие: прорыв, случившийся сегодня, надёжнее того,
что произошёл неделю назад и с тех пор топчется на месте.
"""

from __future__ import annotations

import json
import os
import sys
import time

from engine import breakout, data, portfolio
from engine.render import формат_цены
from run import отправить_в_телеграм

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ПАПКА = os.path.join(БАЗА, "state")
ФАЙЛ = os.path.join(ПАПКА, "breakouts.json")


def срез_до(свечи, i: int):
    """Свечи по i-й бар включительно. Нужно, чтобы подтягивать стоп
    только по тем данным, которые на тот день уже существовали."""
    from dataclasses import replace
    return replace(
        свечи,
        времена=свечи.времена[:i + 1], opens=свечи.opens[:i + 1],
        highs=свечи.highs[:i + 1], lows=свечи.lows[:i + 1],
        closes=свечи.closes[:i + 1], volumes=свечи.volumes[:i + 1],
    )


def читать() -> dict:
    if not os.path.exists(ФАЙЛ):
        return {"позиции": [], "создан": time.time()}
    with open(ФАЙЛ, encoding="utf-8") as f:
        return json.load(f)


def писать(с: dict) -> None:
    os.makedirs(ПАПКА, exist_ok=True)
    с["обновлён"] = time.time()
    with open(ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump(с, f, ensure_ascii=False, indent=1)


def статистика(позиции: list[dict], только_тень: bool | None = None) -> dict:
    """`только_тень`: None — все, False — только рекомендации, True — только тень."""
    if только_тень is not None:
        позиции = [п for п in позиции if bool(п.get("тень")) == только_тень]
    закрытые = [п for п in позиции if п["состояние"] == "закрыта"]
    итог = {"всего": len(позиции), "открыто": len(позиции) - len(закрытые),
            "закрыто": len(закрытые), "побед": 0, "доля_побед": 0.0,
            "сумма_R": 0.0, "профит_фактор": 0.0}
    if not закрытые:
        return итог
    R = [п["r"] for п in закрытые]
    победы = [r for r in R if r > 0]
    убытки = [r for r in R if r <= 0]
    итог.update({"побед": len(победы), "доля_побед": len(победы) / len(R) * 100,
                 "сумма_R": sum(R),
                 "профит_фактор": (sum(победы) / abs(sum(убытки))) if убытки
                 else float("inf")})
    return итог


def главное() -> int:
    состояние = читать()
    позиции = состояние["позиции"]
    п_конф = CFG["прорывы"]
    риск_пр = п_конф["риск_на_позицию_пр"]
    депозит = CFG["риск"]["депозит"] or 100
    # У прорывов свой лимит: они выстреливают гроздьями, когда рынок разворачивается,
    # и общий лимит в 3 отсекал бы две трети сигналов.
    предел = п_конф.get("макс_позиций", 5)

    if "--отчёт" in sys.argv:
        ст = статистика(позиции)
        print(f"Прорывы: открыто {ст['открыто']}, закрыто {ст['закрыто']}")
        if ст["закрыто"]:
            print(f"Побед {ст['доля_побед']:.0f}%, итог {ст['сумма_R']:+.2f}R, "
                  f"профит-фактор {ст['профит_фактор']:.2f}")
        return 0

    события: list[str] = []
    открытые = [п for п in позиции if п["состояние"] == "открыта"]
    # Тень ведём так же, как рекомендации: иначе сравнение окажется нечестным.

    # --- 1. Ведём открытые позиции ---
    for п in открытые:
        try:
            свечи = data.загрузить(п["актив"], "1d", лимит=60,
                                   источники=CFG["источник_данных"])
        except Exception:
            continue
        цена = свечи.последняя_цена

        # Идём по барам ПО ОДНОМУ, как в бэктесте. Две ошибки, которые
        # это лечит, обе подделывали результат:
        #
        # 1. Стоп сверялся с минимумом текущего, ещё не закрытого дня.
        #    Этот минимум мог случиться утром, ДО нашего входа днём.
        #    XRP закрыли по «стопу» 1.2588 в день, когда он вырос на +14.7%;
        #    AAVE — по 99.53 в день, когда он дошёл до 122.69.
        # 2. Подтянутый сегодня стоп сверялся с минимумами за все дни
        #    удержания. Стоп ползёт вверх — и рано или поздно оказывается
        #    выше какого-нибудь давнего минимума, после чего позиция
        #    закрывается задним числом. За один проход так закрылось 8 сделок.
        #
        # Правильный порядок внутри дня: сперва проверить стоп в том виде,
        # в каком он был с утра, и только потом подтягивать его по этому дню.
        начало = п.get("бар_входа_время") or (п["открыта_в"] * 1000)
        уже_проверено = п.get("проверен_до", начало)
        новые = [i for i, t in enumerate(свечи.времена) if t > уже_проверено]

        закрыта = False
        бар_закрытия = None
        for i in новые:
            if свечи.lows[i] <= п["стоп"]:
                закрыта, бар_закрытия = True, свечи.времена[i]
                break
            # Подтягиваем стоп по данным этого дня — для СЛЕДУЮЩЕГО дня.
            новый_стоп = breakout.обновить_стоп(п["стоп"], срез_до(свечи, i), CFG)
            if новый_стоп > п["стоп"]:
                п["стоп"] = новый_стоп
                события.append(
                    f"{п['актив']}: стоп подтянут до {формат_цены(новый_стоп)}")
            п["проверен_до"] = свечи.времена[i]

        if закрыта:
            риск = п["вход"] - п["стоп_начальный"]
            # Срок считаем по бару, на котором стоп пробит, а не по «сейчас».
            # Иначе сделка, закрывшаяся пять дней назад, записывается как
            # одиннадцатидневная, и статистика «сколько держатся убыточные»
            # врёт — а мы на неё опираемся в советах.
            когда = (бар_закрытия / 1000) if бар_закрытия else time.time()
            п.update({"состояние": "закрыта", "закрыта_в": когда,
                      "выход": п["стоп"], "исход": "стоп",
                      "r": (п["стоп"] - п["вход"]) / риск if риск else 0.0,
                      "ход_проц": (п["стоп"] / п["вход"] - 1) * 100,
                      "дней": max(1, round((когда - п["открыта_в"]) / 86400))})
            события.append(f"{п['актив']}: закрыта по стопу"
                             + (" (тень)" if п.get("тень") else ""))
            if п.get("тень"):
                continue          # теневые закрытия в Telegram не уходят
            знак = "✅" if п["r"] > 0 else "❌"
            отправить_в_телеграм(
                f"{знак} <b>{п['актив'].replace('USDT','')}</b> — прорыв закрыт\n"
                f"Вход {формат_цены(п['вход'])} → выход {формат_цены(п['выход'])} "
                f"({п['ход_проц']:+.1f}%)\n"
                f"Результат: {п['r']:+.2f}R за {п['дней']} дней\n"
                f"<i>Система прорывов, бумажная сделка.</i>")

    # Записываем ДО поиска новых. Портфельная проверка читает состояние
    # с диска, и если закрытия этого прохода ещё не сохранены, она считает
    # занятыми монеты, которые только что освободились: XRP закрылся по стопу
    # и тут же получил отказ «XRP уже занят».
    писать(состояние)

    # --- 2. Ищем новые прорывы ---
    занято = sum(1 for п in позиции
                 if п["состояние"] == "открыта" and not п.get("тень"))
    свободно = max(0, предел - занято)
    открыто_сейчас = 0
    кандидаты = []
    # Время открытия дневного бара, в котором мы входим. Нужно, чтобы потом
    # не сверять стоп с ценами, случившимися до входа.
    свечи_входа: dict[str, float] = {}

    for актив in CFG["активы"]:
        если_открыта = any(п["актив"] == актив and п["состояние"] == "открыта"
                           for п in позиции)
        if если_открыта:
            continue
        try:
            свечи = data.загрузить(актив, "1d", лимит=120,
                                   источники=CFG["источник_данных"])
            в = breakout.проанализировать_прорыв(свечи, CFG)
        except Exception:
            continue
        if в.вывод == breakout.ЕСТЬ_ПРОРЫВ:
            свечи_входа[актив] = свечи.времена[-1]
            # Насколько свежий прорыв: сколько дней назад цена впервые
            # превысила уровень. Чем свежее, тем лучше.
            свежесть = 0
            for i in range(len(свечи) - 1, max(0, len(свечи) - 15), -1):
                if свечи.closes[i] > в.максимум_окна:
                    свежесть += 1
                else:
                    break
            кандидаты.append((свежесть, в))

    кандидаты.sort(key=lambda п: п[0])          # самые свежие первыми

    # Сигналы сверх лимита записываются в тень: ведутся наравне с обычными,
    # но помечены и в Telegram не идут. Без этого нельзя узнать, дорого ли
    # обходится сам лимит — пропущенные сделки просто исчезали бы бесследно.
    for свежесть, в in кандидаты[свободно:]:
        уже = any(п["актив"] == в.актив and п["состояние"] == "открыта"
                  for п in позиции)
        if уже:
            continue
        размер_т = депозит * риск_пр / 100 / (в.стоп_проц / 100)
        позиции.append({
            "актив": в.актив, "открыта_в": time.time(), "состояние": "открыта",
            "вход": в.вход, "стоп": в.стоп, "стоп_начальный": в.стоп,
            "стоп_проц": в.стоп_проц, "уровень_выхода": в.уровень_выхода,
            "размер_usd": размер_т, "риск_usd": депозит * риск_пр / 100,
            "капитал": депозит, "свежесть_дней": свежесть,
            "бар_входа_время": свечи_входа.get(в.актив),
            "тень": True, "причина_тени": "сверх лимита позиций",
        })
        события.append(f"{в.актив}: записан в тень (сверх лимита)")

    for свежесть, в in кандидаты[:свободно]:
        # Последнее слово за портфелем: свой лимит система уже проверила,
        # но она не знает, что заняли другие. Отказ — не потеря сигнала,
        # он уходит в тень и будет измерен.
        можно, почему = portfolio.можно_открыть(CFG, в.актив, риск_пр)
        if not можно:
            размер_т = депозит * риск_пр / 100 / (в.стоп_проц / 100)
            позиции.append({
                "актив": в.актив, "открыта_в": time.time(), "состояние": "открыта",
                "вход": в.вход, "стоп": в.стоп, "стоп_начальный": в.стоп,
                "стоп_проц": в.стоп_проц, "уровень_выхода": в.уровень_выхода,
                "размер_usd": размер_т, "риск_usd": депозит * риск_пр / 100,
                "капитал": депозит, "свежесть_дней": свежесть,
                "бар_входа_время": свечи_входа.get(в.актив),
                "тень": True, "причина_тени": почему,
            })
            события.append(f"{в.актив}: в тень — {почему}")
            continue

        размер = депозит * риск_пр / 100 / (в.стоп_проц / 100)
        позиции.append({
            "актив": в.актив, "открыта_в": time.time(), "состояние": "открыта",
            "вход": в.вход, "стоп": в.стоп, "стоп_начальный": в.стоп,
            "стоп_проц": в.стоп_проц, "уровень_выхода": в.уровень_выхода,
            "размер_usd": размер, "риск_usd": депозит * риск_пр / 100,
            "капитал": депозит, "свежесть_дней": свежесть,
            "бар_входа_время": свечи_входа.get(в.актив),
            "тень": False,
        })
        события.append(f"{в.актив}: открыт прорыв")
        открыто_сейчас += 1

        риск_денег = депозит * риск_пр / 100
        # Пока цена не выросла, скользящий уровень выхода лежит НИЖЕ стопа,
        # и до него дело не дойдёт: стоп сработает раньше. Показывать его как
        # ориентир — вводить в заблуждение, поэтому берётся то, что сработает
        # первым, а про подъём уровня говорится отдельно.
        сработает_первым = max(в.стоп, в.уровень_выхода)
        # Суммы исходов — из замера на 1127 сделках, не из предположений.
        типичная_прибыль = 1.45 * риск_денег
        средняя_прибыль = 3.23 * риск_денег
        типичный_убыток = 0.76 * риск_денег

        отправить_в_телеграм(
            f"🟢 <b>ПОКУПКА · ПРОРЫВ · {в.актив.replace('USDT','')}</b>\n"
            f"<i>Ставка на РОСТ. Зарабатываете, если цена идёт вверх.</i>\n\n"
            f"<b>ЧТО СДЕЛАТЬ</b>\n"
            f"1. Купить на <b>{размер:,.2f} $</b> по цене ~<b>{формат_цены(в.вход)}</b>\n"
            f"2. Поставить стоп-лосс на <b>{формат_цены(в.стоп)}</b> — защита "
            f"на случай разворота, {в.стоп_проц:.1f}% ниже входа\n"
            f"3. <b>Цели нет — держим, пока растёт.</b> Выходим, когда цена "
            f"опустится до <b>{формат_цены(сработает_первым)}</b>. По мере роста "
            f"этот уровень поднимается, и прибыль закрепляется\n\n"
            f"<b>СКОЛЬКО НА КОНУ</b>\n"
            f"Потеряете, если развернётся: <b>−{риск_денег:,.2f} $</b> "
            f"(обычно чуть меньше: −{типичный_убыток:,.2f} $, "
            f"выход часто срабатывает раньше стопа)\n"
            f"Заработаете, если движение состоится: "
            f"обычно <b>+{типичная_прибыль:,.2f} $</b>, "
            f"в среднем <b>+{средняя_прибыль:,.2f} $</b> — среднее выше, потому что "
            f"редкие сделки дают в разы больше\n"
            f"Из капитала {депозит:,.0f} $ вложено {размер:,.2f} $\n\n"
            f"Цена пробила максимум за {CFG['прорывы']['окно_входа']} дней — "
            f"рост начался, входим по ходу движения.\n\n"
            f"<i>Проверено на 1127 сделках: прибыльны 33 из 100. "
            f"Убыточные закрываются за 10 дней, прибыльные держатся месяц. "
            f"В среднем по всем сделкам +{0.594 * риск_денег:,.2f} $. "
            f"Бумажная сделка.</i>")

    писать(состояние)
    ст = статистика(позиции)
    print(portfolio.словами(CFG))
    print(f"Событий: {len(события)}")
    for с in события:
        print(f"  {с}")
    рек = статистика(позиции, только_тень=False)
    тень = статистика(позиции, только_тень=True)
    print(f"Прорывов найдено: {len(кандидаты)}, открыто: {открыто_сейчас}, "
          f"в тень: {len(кандидаты) - открыто_сейчас} "
          f"(свой лимит {предел}, занято было {занято}; часть могло отсечь вето портфеля)")
    print(f"Рекомендации: открыто {рек['открыто']}, закрыто {рек['закрыто']}")
    print(f"Тень:         открыто {тень['открыто']}, закрыто {тень['закрыто']}")
    print(f"В журнале: открыто {ст['открыто']}, закрыто {ст['закрыто']}")
    if ст["закрыто"]:
        print(f"Побед {ст['доля_побед']:.0f}%, итог {ст['сумма_R']:+.2f}R, "
              f"профит-фактор {ст['профит_фактор']:.2f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
