"""
Система прорывов: поиск сигналов и ведение позиций.

Запускать раз в сутки после закрытия дневной свечи.

    python breakouts.py           обзор и ведение позиций
    python breakouts.py --tg      то же + сообщения в Telegram
    python breakouts.py --отчёт   только сводка

Позиций одновременно — не больше лимита из конфига. Когда прорывов больше,
чем мест, берутся самые свежие: прорыв, случившийся сегодня, надёжнее того,
что произошёл неделю назад и с тех пор топчется на месте.
"""

from __future__ import annotations

import json
import os
import sys
import time

from engine import breakout, data
from engine.render import формат_цены
from run import отправить_в_телеграм

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ПАПКА = os.path.join(БАЗА, "state")
ФАЙЛ = os.path.join(ПАПКА, "breakouts.json")


def читать() -> dict:
    if not os.path.exists(ФАЙЛ):
        return {"позиции": [], "создан": time.time()}
    with open(ФАЙЛ, encoding="utf-8") as f:
        return json.load(f)


def писать(с: dict) -> None:
    os.makedirs(ПАПКА, exist_ok=True)
    с["обновлён"] = time.time()
    with open(ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump(с, f, ensure_ascii=False, indent=1)


def статистика(позиции: list[dict]) -> dict:
    закрытые = [п for п in позиции if п["состояние"] == "закрыта"]
    итог = {"всего": len(позиции), "открыто": len(позиции) - len(закрытые),
            "закрыто": len(закрытые), "побед": 0, "доля_побед": 0.0,
            "сумма_R": 0.0, "профит_фактор": 0.0}
    if not закрытые:
        return итог
    R = [п["r"] for п in закрытые]
    победы = [r for r in R if r > 0]
    убытки = [r for r in R if r <= 0]
    итог.update({"побед": len(победы), "доля_побед": len(победы) / len(R) * 100,
                 "сумма_R": sum(R),
                 "профит_фактор": (sum(победы) / abs(sum(убытки))) if убытки
                 else float("inf")})
    return итог


def главное() -> int:
    состояние = читать()
    позиции = состояние["позиции"]
    п_конф = CFG["прорывы"]
    риск_пр = п_конф["риск_на_позицию_пр"]
    депозит = CFG["риск"]["депозит"] or 100
    # У прорывов свой лимит: они выстреливают гроздьями, когда рынок разворачивается,
    # и общий лимит в 3 отсекал бы две трети сигналов.
    предел = п_конф.get("макс_позиций", 5)

    if "--отчёт" in sys.argv:
        ст = статистика(позиции)
        print(f"Прорывы: открыто {ст['открыто']}, закрыто {ст['закрыто']}")
        if ст["закрыто"]:
            print(f"Побед {ст['доля_побед']:.0f}%, итог {ст['сумма_R']:+.2f}R, "
                  f"профит-фактор {ст['профит_фактор']:.2f}")
        return 0

    события: list[str] = []
    открытые = [п for п in позиции if п["состояние"] == "открыта"]

    # --- 1. Ведём открытые позиции ---
    for п in открытые:
        try:
            свечи = data.загрузить(п["актив"], "1d", лимит=60,
                                   источники=CFG["источник_данных"])
        except Exception:
            continue
        цена = свечи.последняя_цена
        новый_стоп = breakout.обновить_стоп(п["стоп"], свечи, CFG)
        if новый_стоп > п["стоп"]:
            п["стоп"] = новый_стоп
            события.append(f"{п['актив']}: стоп подтянут до {формат_цены(новый_стоп)}")

        if свечи.lows[-1] <= п["стоп"]:
            риск = п["вход"] - п["стоп_начальный"]
            п.update({"состояние": "закрыта", "закрыта_в": time.time(),
                      "выход": п["стоп"], "исход": "стоп",
                      "r": (п["стоп"] - п["вход"]) / риск if риск else 0.0,
                      "ход_проц": (п["стоп"] / п["вход"] - 1) * 100,
                      "дней": round((time.time() - п["открыта_в"]) / 86400)})
            события.append(f"{п['актив']}: закрыта по стопу")
            знак = "✅" if п["r"] > 0 else "❌"
            отправить_в_телеграм(
                f"{знак} <b>{п['актив'].replace('USDT','')}</b> — прорыв закрыт\n"
                f"Вход {формат_цены(п['вход'])} → выход {формат_цены(п['выход'])} "
                f"({п['ход_проц']:+.1f}%)\n"
                f"Результат: {п['r']:+.2f}R за {п['дней']} дней\n"
                f"<i>Система прорывов, бумажная сделка.</i>")

    # --- 2. Ищем новые прорывы ---
    занято = sum(1 for п in позиции if п["состояние"] == "открыта")
    свободно = max(0, предел - занято)
    кандидаты = []

    for актив in CFG["активы"]:
        если_открыта = any(п["актив"] == актив and п["состояние"] == "открыта"
                           for п in позиции)
        if если_открыта:
            continue
        try:
            свечи = data.загрузить(актив, "1d", лимит=120,
                                   источники=CFG["источник_данных"])
            в = breakout.проанализировать_прорыв(свечи, CFG)
        except Exception:
            continue
        if в.вывод == breakout.ЕСТЬ_ПРОРЫВ:
            # Насколько свежий прорыв: сколько дней назад цена впервые
            # превысила уровень. Чем свежее, тем лучше.
            свежесть = 0
            for i in range(len(свечи) - 1, max(0, len(свечи) - 15), -1):
                if свечи.closes[i] > в.максимум_окна:
                    свежесть += 1
                else:
                    break
            кандидаты.append((свежесть, в))

    кандидаты.sort(key=lambda п: п[0])          # самые свежие первыми
    for свежесть, в in кандидаты[:свободно]:
        размер = депозит * риск_пр / 100 / (в.стоп_проц / 100)
        позиции.append({
            "актив": в.актив, "открыта_в": time.time(), "состояние": "открыта",
            "вход": в.вход, "стоп": в.стоп, "стоп_начальный": в.стоп,
            "стоп_проц": в.стоп_проц, "уровень_выхода": в.уровень_выхода,
            "размер_usd": размер, "риск_usd": депозит * риск_пр / 100,
            "капитал": депозит, "свежесть_дней": свежесть,
        })
        события.append(f"{в.актив}: открыт прорыв")
        отправить_в_телеграм(
            f"🚀 <b>ПРОРЫВ · {в.актив.replace('USDT','')}</b>\n\n"
            f"<b>ЧТО СДЕЛАТЬ</b>\n"
            f"1. Купить на <b>{размер:,.2f} $</b> по цене ~<b>{формат_цены(в.вход)}</b>\n"
            f"2. Стоп-лосс на <b>{формат_цены(в.стоп)}</b> ({в.стоп_проц:.1f}% ниже)\n"
            f"3. <b>Цели нет.</b> Держать, пока цена не уйдёт ниже "
            f"{формат_цены(в.уровень_выхода)} — этот уровень будет подниматься "
            f"вслед за ценой\n\n"
            f"Под риском {депозит * риск_пр / 100:,.2f} $ из {депозит:,.0f} $.\n"
            f"Цена пробила максимум за {CFG['прорывы']['окно_входа']} дней — "
            f"движение началось.\n\n"
            f"<i>Система прорывов. Ожидание: 37 побед из 100, но убыточные "
            f"закрываются за 9 дней, а прибыльные держатся месяц и дают "
            f"в среднем +42%. Бумажная сделка.</i>")

    писать(состояние)
    ст = статистика(позиции)
    print(f"Событий: {len(события)}")
    for с in события:
        print(f"  {с}")
    print(f"Прорывов найдено: {len(кандидаты)}, взято: {min(len(кандидаты), свободно)} "
          f"(лимит позиций {предел}, занято было {занято})")
    print(f"В журнале: открыто {ст['открыто']}, закрыто {ст['закрыто']}")
    if ст["закрыто"]:
        print(f"Побед {ст['доля_побед']:.0f}%, итог {ст['сумма_R']:+.2f}R, "
              f"профит-фактор {ст['профит_фактор']:.2f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
