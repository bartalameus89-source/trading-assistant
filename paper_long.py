"""
Бумажная торговля долгосрочной системы. Отдельный журнал, отдельная статистика.

Почему отдельно от короткой: у них разные входы, разные горизонты и разные
профили результата. Короткая выигрывает каждую вторую сделку по чуть-чуть,
долгосрочная — каждую четвёртую, но помногу. Смешав их в одном журнале,
невозможно понять, какая работает.

Запускать раз в сутки — дневная свеча меняется раз в день.

    python paper_long.py            один проход
    python paper_long.py --отчёт    сводка без изменений
"""

from __future__ import annotations

import json
import os
import sys
import time

from engine import data, indicators as ind, longterm, portfolio
from engine.render import формат_цены
from run import отправить_в_телеграм

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ПАПКА = os.path.join(БАЗА, "state")
ФАЙЛ = os.path.join(ПАПКА, "paper_long.json")
ПРЕДЕЛ_ДНЕЙ = 250


def читать() -> dict:
    if not os.path.exists(ФАЙЛ):
        return {"позиции": [], "создан": time.time()}
    with open(ФАЙЛ, encoding="utf-8") as f:
        return json.load(f)


def писать(с: dict) -> None:
    os.makedirs(ПАПКА, exist_ok=True)
    с["обновлён"] = time.time()
    with open(ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump(с, f, ensure_ascii=False, indent=1)


def статистика(позиции: list[dict]) -> dict:
    закрытые = [п for п in позиции if п["состояние"] == "закрыта"]
    итог = {"всего": len(позиции),
            "открыты": sum(1 for п in позиции if п["состояние"] == "открыта"),
            "закрыто": len(закрытые), "побед": 0, "доля_побед": 0.0,
            "сумма_R": 0.0, "средний_R": 0.0, "профит_фактор": 0.0}
    if not закрытые:
        return итог
    R = [п["r"] for п in закрытые]
    победы = [r for r in R if r > 0]
    убытки = [r for r in R if r <= 0]
    итог.update({
        "побед": len(победы), "доля_побед": len(победы) / len(R) * 100,
        "сумма_R": sum(R), "средний_R": sum(R) / len(R),
        "профит_фактор": (sum(победы) / abs(sum(убытки))) if убытки else float("inf"),
    })
    return итог


def главное() -> int:
    состояние = читать()
    позиции = состояние["позиции"]

    if "--отчёт" in sys.argv:
        ст = статистика(позиции)
        print(f"Долгосрочный журнал: всего {ст['всего']}, открыто {ст['открыты']}, "
              f"закрыто {ст['закрыто']}")
        if ст["закрыто"]:
            print(f"Побед {ст['доля_побед']:.0f}%, итог {ст['сумма_R']:+.2f}R, "
                  f"профит-фактор {ст['профит_фактор']:.2f}")
        return 0

    события: list[str] = []
    риск_пр = CFG["долгосрочная"]["риск_на_позицию_пр"]
    депозит = CFG["риск"]["депозит"] or 100

    for актив in CFG["активы"]:
        try:
            свечи = data.загрузить(актив, "1d", лимит=400,
                                   источники=CFG["источник_данных"])
        except Exception:
            continue

        ma50, _ = ind.last_defined(ind.sma(свечи.closes, 50))
        цена = свечи.последняя_цена
        открытая = next((п for п in позиции
                         if п["актив"] == актив and п["состояние"] == "открыта"), None)

        # --- ведём открытую позицию ---
        if открытая:
            риск = открытая["вход"] - открытая["стоп"]
            дней = (time.time() - открытая["открыта_в"]) / 86400
            причина = None
            if свечи.lows[-1] <= открытая["стоп"]:
                причина, выход = "стоп", открытая["стоп"]
            elif ma50 is not None and цена < ma50:
                причина, выход = "слом тренда", цена
            elif дней > ПРЕДЕЛ_ДНЕЙ:
                причина, выход = "предел по времени", цена

            if причина:
                открытая.update({
                    "состояние": "закрыта", "закрыта_в": time.time(),
                    "выход": выход, "исход": причина,
                    "r": (выход - открытая["вход"]) / риск if риск else 0.0,
                    "рост_проц": (выход / открытая["вход"] - 1) * 100,
                    "дней": round(дней),
                })
                события.append(f"{актив}: закрыта — {причина}")
                знак = "✅" if открытая["r"] > 0 else "❌"
                отправить_в_телеграм(
                    f"{знак} <b>{актив.replace('USDT','')}</b> — долгая позиция закрыта\n"
                    f"Причина: {причина}\n"
                    f"Вход {формат_цены(открытая['вход'])} → выход {формат_цены(выход)} "
                    f"({открытая['рост_проц']:+.1f}%)\n"
                    f"Результат: {открытая['r']:+.2f}R за {открытая['дней']} дней\n"
                    f"<i>Долгосрочная система, бумажная сделка.</i>")
            continue

        # --- ищем новую ---
        в = longterm.проанализировать_долгий(свечи, CFG)
        if в.вывод != longterm.ЕСТЬ_ПОТЕНЦИАЛ:
            continue

        # У долгосрочной системы своего лимита позиций не было вообще —
        # она могла занять все 15 монет. Теперь предел общий с остальными.
        можно, почему = portfolio.можно_открыть(CFG, актив, риск_пр)
        if not можно:
            события.append(f"{актив}: потенциал есть, но портфель занят — {почему}")
            continue

        размер = депозит * риск_пр / 100 / (в.стоп_проц / 100)
        позиции.append({
            "актив": актив, "открыта_в": time.time(), "состояние": "открыта",
            "вход": в.цена, "стоп": в.стоп, "стоп_проц": в.стоп_проц,
            "размер_usd": размер, "риск_usd": депозит * риск_пр / 100,
            "капитал": депозит,
        })
        события.append(f"{актив}: открыта долгая позиция")

        риск_денег = депозит * риск_пр / 100
        # Числа из замера на 330 сделках за 8 лет, а не из предположений.
        типичная_прибыль = 0.64 * риск_денег
        средняя_прибыль = 4.33 * риск_денег
        типичный_убыток = 0.23 * риск_денег

        отправить_в_телеграм(
            f"🟢 <b>ПОКУПКА · НАДОЛГО · {актив.replace('USDT','')}</b>\n"
            f"<i>Ставка на РОСТ, горизонт месяцы.</i>\n\n"
            f"<b>ЧТО СДЕЛАТЬ</b>\n"
            f"1. Купить на <b>{размер:,.2f} $</b> по цене ~<b>{формат_цены(в.цена)}</b>\n"
            f"2. Стоп-лосс на <b>{формат_цены(в.стоп)}</b> — защита, "
            f"{в.стоп_проц:.1f}% ниже входа\n"
            f"3. Держать {в.горизонт}. Выход: {в.выход_по}\n\n"
            f"<b>СКОЛЬКО НА КОНУ</b>\n"
            f"Потеряете, если не пойдёт: <b>−{риск_денег:,.2f} $</b> "
            f"(обычно намного меньше: −{типичный_убыток:,.2f} $, "
            f"тренд ломается раньше стопа)\n"
            f"Заработаете, если движение состоится: "
            f"обычно <b>+{типичная_прибыль:,.2f} $</b>, "
            f"в среднем <b>+{средняя_прибыль:,.2f} $</b> — среднее втрое выше "
            f"типичного, потому что редкие сделки дают в десятки раз больше\n"
            f"Из капитала {депозит:,.0f} $ вложено {размер:,.2f} $\n\n"
            f"Цели нет намеренно — смысл в том, чтобы поймать движение целиком.\n\n"
            f"<i>Проверено на 330 сделках за 8 лет: прибыльны 26 из 100. "
            f"В среднем по всем сделкам +{0.905 * риск_денег:,.2f} $. "
            f"Бумажная сделка.</i>")

    писать(состояние)
    ст = статистика(позиции)
    print(f"Событий: {len(события)}")
    for с in события:
        print(f"  {с}")
    print(f"В журнале: открыто {ст['открыты']}, закрыто {ст['закрыто']}")
    if ст["закрыто"]:
        print(f"Побед {ст['доля_побед']:.0f}%, итог {ст['сумма_R']:+.2f}R, "
              f"профит-фактор {ст['профит_фактор']:.2f}")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
