"""
Записать нажатие «взял / пропустил», переданное ботом с компьютера владельца.

Зачем отдельный запуск. Бот на компьютере принимает нажатия мгновенно, но
журнал решений живёт в репозитории на GitHub — записывать его должна та же
автоматика, что ведёт остальные журналы, иначе два писателя затрут друг
друга. Поэтому бот не пишет сам, а запускает workflow «Решение из Telegram»
(.github/workflows/decision.yml) с нажатием во входных данных. Этот запуск
стоит в одной очереди с обычными проходами и коммитит журнал так же.

Нажатие приходит в переменной окружения TG_PAYLOAD (латиница — кириллица
в именах переменных окружения ломается молча). Поля проверяются: принимается
только решение t/s по сигналу из нашего чата. Всё прочее — отказ без записи.

    TG_PAYLOAD='{"решение":"t","сигнал":"BTCUSDT-1","чат":123}' python decide.py
    TG_PAYLOAD='{"проверка":true}' python decide.py      проверка пути, без записи
"""

from __future__ import annotations

import json
import os
import sys

from engine import tgbuttons


def разобрать(сырое: str, чат_владельца: str) -> tuple[dict | None, str]:
    """(нажатие, почему отказ). Отказ — если это не наше нажатие."""
    try:
        д = json.loads(сырое or "")
    except json.JSONDecodeError:
        return None, "входные данные не JSON"
    if not isinstance(д, dict):
        return None, "ожидался объект"
    if д.get("проверка"):
        return None, "проверка пути: запуск дошёл, запись не нужна"
    if д.get("решение") not in (tgbuttons.ВЗЯЛ, tgbuttons.ПРОПУСТИЛ):
        return None, f"неизвестное решение: {д.get('решение')!r}"
    сигнал = д.get("сигнал")
    if not isinstance(сигнал, str) or not сигнал or len(сигнал) > 64:
        return None, "нет идентификатора сигнала"
    if чат_владельца and str(д.get("чат")) != str(чат_владельца):
        return None, "нажатие не из чата владельца"
    return {
        "решение": д["решение"], "сигнал": сигнал,
        "когда": д.get("когда"), "чат": д.get("чат"),
        "сообщение": д.get("сообщение"), "id_нажатия": None,
    }, ""


def главное() -> int:
    нажатие, почему = разобрать(os.environ.get("TG_PAYLOAD", ""),
                                os.environ.get("TELEGRAM_CHAT_ID", ""))
    if нажатие is None:
        print(f"Решение не записано: {почему}")
        return 0 if почему.startswith("проверка") else 1
    import paper                     # тяжёлый импорт — только когда есть что писать
    записано = paper.обработать_нажатия([нажатие])
    print(f"Записано решений: {записано}")
    return 0 if записано else 1


if __name__ == "__main__":
    sys.exit(главное())
