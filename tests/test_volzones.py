"""
Зоны волатильности: опыт с ослабленным фильтром должен уметь дать ответ.

13.09.2026 порог высокой волатильности поднят с 80 до 90 по решению
владельца, без подтверждения замером. Ответ, окупилось ли это, даёт
engine/volzones.py по живым сигналам. Если он неверно делит сигналы на
зоны или считает неисполненные ордера сделками, мы получим ложный вывод
и либо зря откатим, либо зря оставим.

Запуск:  python tests/test_volzones.py
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from engine import volzones

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def сиг(п, r=None, исход=None, вол="нормальная", система="короткая") -> dict:
    з = {"система": система, "перцентиль_bbw": п, "волатильность": вол}
    if исход:
        з.update({"состояние": "закрыта", "исход": исход, "результат_R": r})
        if исход not in volzones.НЕ_ИСПОЛНЕНЫ:
            з["цена_входа"] = 1.0
    return з


def главное() -> int:
    print("ЗОНЫ ВОЛАТИЛЬНОСТИ\n")

    проверить("79.9 — спокойная", volzones.зона(сиг(79.9)) == "спокойная (до 80)")
    проверить("80 — уже новая зона", volzones.зона(сиг(80.0)) == "новая (80–90)")
    проверить("89.9 — ещё новая", volzones.зона(сиг(89.9)) == "новая (80–90)")
    проверить("90 — закрытая", volzones.зона(сиг(90.0)) == "закрытая (от 90)")
    проверить("старая запись без перцентиля с нормальной волатильностью",
              volzones.зона(сиг(None)) == "до 13.09: ниже 80")
    проверить("старая запись без перцентиля с высокой волатильностью",
              volzones.зона(сиг(None, вол="высокая")) == "до 13.09: 80 и выше")

    записи = ([сиг(50, 1.0, "цель"), сиг(50, -1.0, "стоп"), сиг(50, исход="не дошло")]
              + [сиг(85, 0.5, "цель"), сиг(85, исход="истёк срок")]
              + [сиг(85, 2.0, "цель", система="прорывы")])
    с = volzones.свод(записи)
    спок, нов = с["спокойная (до 80)"], с["новая (80–90)"]
    проверить("неисполненный ордер — сигнал, но не сделка",
              спок["сигналов"] == 3 and спок["закрыто"] == 2, str(спок))
    проверить("на сделку считается только по исполненным: (1 − 1) / 2 = 0",
              спок["на_сделку_R"] == 0.0, str(спок))
    проверить("чужая система в зоны не попадает",
              нов["сигналов"] == 2 and нов["закрыто"] == 1, str(нов))

    проверить("пока закрытых мало — вывода нет",
              volzones.вывод(с).startswith("Выводов пока нет"), volzones.вывод(с))

    хуже = ([сиг(50, 0.5, "цель") for _ in range(20)]
            + [сиг(85, -0.2, "стоп") for _ in range(20)])
    проверить("новая зона хуже спокойной — совет вернуть 80",
              "вернуть к 80" in volzones.вывод(volzones.свод(хуже)))
    лучше = ([сиг(50, 0.1, "цель") for _ in range(20)]
             + [сиг(85, 0.3, "цель") for _ in range(20)])
    проверить("новая зона не хуже — ослабление оправдано",
              "оправдано" in volzones.вывод(volzones.свод(лучше)))

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
