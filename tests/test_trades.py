"""
Список всех сделок: его итог обязан совпадать с итогом наверху кабинета.

Проверяемая беда. Главная жалоба владельца была «много цифр, мало понятно»,
и причина оказалась не в оформлении: одна страница давала разные ответы на
один вопрос — «Итого на бумаге 13,66» и «Сейчас на бумаге 13,79», позиций
16, 14 и 7. Новый список сделок при первой сборке добавил бы ещё один
ответ: 36 закрытых и −4,45 $ против 10 и −7,45 $ наверху. Три причины:
неисполненные ордера считались закрытыми сделками «в ноль», сделка без
записанного риска стоила 0 $ вместо 1 $, ждущие входа оценивались как
открытые. Последний цент расхождения давало округление каждой строки.

Здесь все три причины и округление проверяются на подменённых журналах,
а в конце — сверка с настоящими журналами: engine/trades.py и engine/pnl.py
должны давать один и тот же итог до цента.

Запуск:  python tests/test_trades.py
"""

from __future__ import annotations

import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from engine import pnl, trades

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def песочница(журналы: dict[str, dict]) -> str:
    п = tempfile.mkdtemp()
    for имя, содержимое in журналы.items():
        with open(os.path.join(п, имя), "w", encoding="utf-8") as f:
            json.dump(содержимое, f, ensure_ascii=False)
    trades.ПАПКА = п
    pnl.ПАПКА = п
    return п


def сверить(подпись: str, цены: dict | None = None) -> None:
    """Главное правило: список и кабинет считают одинаково."""
    св = trades.свод(trades.все(цены))
    п = pnl.подсчитать(цены)["сводка"]
    разные = [к for к in ("сделок", "в_плюс", "в_минус", "в_ноль", "заработано",
                         "потеряно", "закрыто_итог", "открыто_итог", "итог")
              if abs(float(св[к]) - float(п[к])) > 1e-9]
    проверить(подпись, not разные,
              "; ".join(f"{к}: список {св[к]}, кабинет {п[к]}" for к in разные))


def главное() -> int:
    print("СПИСОК ВСЕХ СДЕЛОК\n")
    исходные = trades.ПАПКА, pnl.ПАПКА

    # --- неисполненный ордер — не сделка ---
    песочница({"shadow.json": {"сделки": [
        {"актив": "BTCUSDT", "состояние": "закрыта", "исход": "не дошло",
         "результат_R": 0.0, "риск_денег": 1.0, "цена_входа": 100},
        {"актив": "ETHUSDT", "состояние": "закрыта", "исход": "истёк срок",
         "результат_R": 0.0, "риск_денег": 1.0, "цена_входа": 100},
        {"актив": "SOLUSDT", "состояние": "закрыта", "исход": "стоп",
         "результат_R": -1.0, "риск_денег": 1.0, "цена_входа": 100},
    ]}})
    с = trades.все()
    св = trades.свод(с)
    проверить("неисполненные ордера видны в списке", len(с) == 3, str(len(с)))
    проверить("но в итог не идут: закрыта одна сделка, а не три",
              св["сделок"] == 1 and св["в_ноль"] == 0, str(св))
    проверить("и помечены как неисполненные",
              sum(1 for x in с if not x["исполнена"]) == 2)
    сверить("со списком и кабинетом один итог — неисполненные")

    # --- риск без записи стоит 1 $, как в кабинете ---
    песочница({"shadow.json": {"сделки": [
        {"актив": "SOLUSDT", "состояние": "закрыта", "исход": "стоп",
         "результат_R": -1.0, "цена_входа": 100},
    ]}})
    св = trades.свод(trades.все())
    проверить("сделка без записанного риска теряет 1 $, а не 0",
              св["потеряно"] == -1.0 and св["в_минус"] == 1, str(св))
    сверить("один итог — риск без записи")

    # --- ждущая входа не оценивается как открытая ---
    песочница({"breakouts.json": {"позиции": [
        {"актив": "BTCUSDT", "состояние": "ждёт входа", "вход": 100,
         "стоп": 90, "стоп_начальный": 90, "риск_usd": 1.0},
        {"актив": "ETHUSDT", "состояние": "открыта", "вход": 100,
         "стоп": 90, "стоп_начальный": 90, "риск_usd": 1.0},
    ]}})
    цены = {"BTCUSDT": 80.0, "ETHUSDT": 110.0}
    с = trades.все(цены)
    ждёт = next(x for x in с if x["актив"] == "BTC")
    открыта = next(x for x in с if x["актив"] == "ETH")
    проверить("ждущая входа денег не имеет", ждёт["деньги"] is None, str(ждёт["деньги"]))
    проверить("открытая оценена по рынку: +10 при риске 10 — это +1 $",
              abs(открыта["деньги"] - 1.0) < 1e-9, str(открыта["деньги"]))
    проверить("у открытой видна текущая цена", открыта["цена_сейчас"] == 110.0)
    проверить("в работе одна позиция, а не две",
              trades.свод(с)["в_работе"] == 1, str(trades.свод(с)))
    сверить("один итог — ждущая входа", цены)

    # --- без цены биржи в колонке «сейчас» пусто, а не стоп ---
    с = trades.все({})
    открыта = next(x for x in с if x["актив"] == "ETH")
    проверить("без цены биржи «сейчас» пусто, стоп туда не подставляется",
              открыта["цена_сейчас"] is None, str(открыта["цена_сейчас"]))

    # --- округление не уводит сумму ---
    сделки = [{"актив": f"A{i}USDT", "состояние": "закрыта", "исход": "стоп",
               "результат_R": -1.0, "риск_денег": 0.333, "цена_входа": 1}
              for i in range(3)]
    песочница({"shadow.json": {"сделки": сделки}})
    сверить("три сделки по 0,333 $ дают один итог, а не разъезжаются на цент")

    # --- настоящие журналы ---
    trades.ПАПКА, pnl.ПАПКА = исходные
    сверить("на настоящих журналах список и кабинет совпадают до цента")

    # --- наш счёт и тень раздельно ---
    # Главная показывает наш счёт (рекомендации) отдельно от тени. Если
    # раздельные итоги разойдутся со списком сделок, на странице снова будет
    # два ответа на вопрос «сколько у нас», а именно это и путало владельца.
    п = pnl.подсчитать()
    все = trades.все()
    for ветка, ключ in (("рекомендация", "сводка_рекомендаций"),
                        ("тень", "сводка_тени")):
        св = trades.свод([x for x in все if x["ветка"] == ветка])
        разные = [к for к in ("сделок", "в_плюс", "в_минус", "в_ноль",
                             "заработано", "потеряно", "закрыто_итог",
                             "открыто_итог", "итог", "в_работе")
                  if abs(float(св[к]) - float(п[ключ][к])) > 1e-9]
        проверить(f"«{ветка}»: итог в кабинете совпадает со списком сделок",
                  not разные,
                  "; ".join(f"{к}: список {св[к]}, кабинет {п[ключ][к]}"
                            for к in разные))
    с = п["сводка_рекомендаций"]
    т = п["сводка_тени"]
    проверить("наш счёт плюс тень дают общий итог",
              abs(с["итог"] + т["итог"] - п["сводка"]["итог"]) < 0.011,
              f"{с['итог']} + {т['итог']} против {п['сводка']['итог']}")

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
