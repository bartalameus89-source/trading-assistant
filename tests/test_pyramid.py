"""
Доливка к выигрывающей позиции: считаем размер и риск честно.

Главная ловушка этой идеи — принять плечо за преимущество. Доливка
увеличивает размер позиции, и если считать результат в R от первоначального
риска, доход растёт сам собой. При замере это дало видимость учетверения
дохода. Честное сравнение с тем же средним размером БЕЗ доливок показало
рост доход/просадка с 45.9 до 60.3 — то есть преимущество есть, но втрое
меньше, чем казалось.

Здесь проверяется арифметика, на которой всё держится.

Запуск:  python tests/test_pyramid.py
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from engine import pyramid as пир

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def главное() -> int:
    print("ДОЛИВКА: РАЗМЕР И РИСК\n")
    ВХОД, СТОП = 100.0, 90.0
    РИСК = ВХОД - СТОП          # 10

    части = пир.первая_часть(ВХОД)
    проверить("вначале одна часть размером 1.0", пир.размер_долей(части) == 1.0)

    # --- пороги доливок ---
    проверить("первая доливка при +1R = 110",
              пир.порог_доливки(ВХОД, РИСК, 1.0, 0) == 110.0)
    проверить("вторая доливка при +2R = 120",
              пир.порог_доливки(ВХОД, РИСК, 1.0, 1) == 120.0)

    # --- добавляем две части ---
    пир.долить(части, 110.0)
    пир.долить(части, 120.0)
    проверить("после двух доливок размер 3.0", пир.размер_долей(части) == 3.0)
    проверить("средняя цена входа 110", abs(пир.средняя_цена(части) - 110.0) < 1e-9,
              f"{пир.средняя_цена(части)}")

    # --- результат складывается по частям, а не по средней ---
    r = пир.результат_R(части, 130.0, РИСК)
    ожидаемо = (130 - 100) / 10 + (130 - 110) / 10 + (130 - 120) / 10   # 3+2+1
    проверить("итог по частям = 6.0R", abs(r - ожидаемо) < 1e-9, f"{r}")
    проверить("это БОЛЬШЕ, чем одна часть дала бы (3.0R)", r > 3.0)

    # --- ГЛАВНОЕ: риск считается от цен ЧАСТЕЙ, а не от первой ---
    # Стоп ещё под первым входом: убыток по всем трём частям.
    риск_R = пир.риск_сейчас_R(части, 95.0, РИСК)
    ожидаемо = (95 - 100) / 10 + (95 - 110) / 10 + (95 - 120) / 10   # -0.5-1.5-2.5
    проверить("при стопе 95 теряем 4.5R, а не 1R",
              abs(риск_R - ожидаемо) < 1e-9, f"{риск_R}")
    проверить("то есть доливка ПОВЫШАЕТ риск, пока стоп низко", риск_R < -1.0)

    # Стоп подтянут выше первого входа: позиция уже не может дать убыток.
    риск_R = пир.риск_сейчас_R(части, 125.0, РИСК)
    проверить("при стопе 125 позиция гарантированно в плюсе", риск_R > 0,
              f"{риск_R}")

    # Стоп ровно на средней цене: итог ноль.
    риск_R = пир.риск_сейчас_R(части, 110.0, РИСК)
    проверить("стоп на средней цене даёт ровно ноль",
              abs(риск_R) < 1e-9, f"{риск_R}")

    # --- без доливок поведение прежнее ---
    одна = пир.первая_часть(ВХОД)
    проверить("одна часть: стоп на входе даёт ноль",
              abs(пир.риск_сейчас_R(одна, 100.0, РИСК)) < 1e-9)
    проверить("одна часть: стоп на 90 даёт ровно -1R",
              abs(пир.риск_сейчас_R(одна, 90.0, РИСК) + 1.0) < 1e-9)
    проверить("одна часть: выход 115 даёт 1.5R",
              abs(пир.результат_R(одна, 115.0, РИСК) - 1.5) < 1e-9)

    # --- итог после комиссий ---
    # Живой журнал прорывов раньше не вычитал комиссии, а бэктесты вычитают:
    # живые результаты выглядели лучше замеренных.
    изд = 0.0025
    проверить("одна часть: комиссия 0.25% от 100 при риске 10 — это 0.025R",
              abs(пир.результат_R_чистый(одна, 115.0, РИСК, изд) - (1.5 - 0.025)) < 1e-9,
              f"{пир.результат_R_чистый(одна, 115.0, РИСК, изд)}")
    три = пир.первая_часть(ВХОД)
    пир.долить(три, 110.0)
    пир.долить(три, 120.0)
    ожид = пир.результат_R(три, 130.0, РИСК) - изд * (100 + 110 + 120) / РИСК
    проверить("три части: каждая платит комиссию от своей цены",
              abs(пир.результат_R_чистый(три, 130.0, РИСК, изд) - ожид) < 1e-9,
              f"{пир.результат_R_чистый(три, 130.0, РИСК, изд)} против {ожид}")
    проверить("без комиссий совпадает со старым расчётом",
              abs(пир.результат_R_чистый(три, 130.0, РИСК, 0.0)
                  - пир.результат_R(три, 130.0, РИСК)) < 1e-9)

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
