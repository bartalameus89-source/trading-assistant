"""
Сравнение с «просто купил и держал»: чтобы вывод был честным в обе стороны.

Зачем эта проверка. Сравнение с удержанием — единственное, что отличает
«система зарабатывает» от «рынок вырос сам». Значит, ошибка именно здесь
опаснее всех прочих: она не ломает торговлю, она ломает СУЖДЕНИЕ о ней.
Ошибиться можно в две стороны, и обе проверяются ниже.

В нашу пользу: считать прибыль по портфелю, который система никогда бы
не набрала. Бэктесты гоняют каждую монету в одиночку и спокойно держат
15 позиций на 45% счёта под риском — в семь с половиной раз выше нашего
предела в 6%. Без соблюдения пределов итог получался +880% вместо +158%.

Против нас: сделка, которая открылась и закрылась в один календарный день
(у короткой системы шесть баров в сутки), занимала место в портфеле НАВСЕГДА
— её день закрытия уже прошёл, и освобождать было некому. Три таких
«вечных» держателя съедали весь предел, и до конца истории система не
открывала больше ничего: из 852 сделок бралось 8.

Запуск:  python tests/test_benchmark.py
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import benchmark

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def дни(сколько: int, с: int = 1) -> list[str]:
    return [f"2024-01-{д:02d}" for д in range(с, с + сколько)]


def подменить(сделки: list[dict], портфель: dict | None = None):
    """Подменяем источник сделок и пределы: проверяется логика отбора,
    а не содержимое реальных журналов."""
    benchmark._сделки = lambda файл: сделки if файл == "trades.json" else []
    benchmark.CFG = {
        "риск": {"депозит": 100, "стартовый_риск_на_сделку_пр": 2.0},
        "долгосрочная": {"риск_на_позицию_пр": 3.0},
        "портфель": портфель or {"макс_всего_позиций": 12,
                                 "макс_общий_риск_пр": 6.0,
                                 "макс_риск_быстрых_пр": 4.0,
                                 "макс_сделок_в_день": 0},
    }


def сделка(вход: str, выход: str, r: float) -> dict:
    """Время в файлах сделок — секунды; берём полдень, чтобы часовой пояс
    не сдвинул дату."""
    import datetime

    def т(д: str) -> float:
        г, м, ч = (int(x) for x in д.split("-"))
        return datetime.datetime(г, м, ч, 12, tzinfo=datetime.timezone.utc).timestamp()

    return {"время_входа": т(вход), "время_выхода": т(выход), "r": r}


def главное() -> int:
    print("СРАВНЕНИЕ С «КУПИЛ И ДЕРЖАЛ»\n")
    сохранённые = benchmark._сделки, benchmark.CFG

    # --- просадка ---
    проверить("ровная кривая — просадки нет",
              benchmark.просадка([100, 100, 100]) == 0.0)
    проверить("падение вдвое от пика — это -50%",
              abs(benchmark.просадка([100, 200, 100]) + 50.0) < 1e-9,
              str(benchmark.просадка([100, 200, 100])))
    проверить("просадка считается от ПИКА, а не от старта",
              abs(benchmark.просадка([100, 150, 120, 300]) + 20.0) < 1e-9,
              str(benchmark.просадка([100, 150, 120, 300])))
    проверить("итог считается от первого дня",
              abs(benchmark.итог_проц([100, 250]) - 150.0) < 1e-9)
    проверить("доход на единицу просадки = итог / просадку",
              abs(benchmark.на_единицу([100, 200, 150, 300]) - 8.0) < 1e-9,
              str(benchmark.на_единицу([100, 200, 150, 300])))

    # --- купил и держал ---
    д = дни(40)
    цены = {дн: 10.0 * (1 + и / 40) for и, дн in enumerate(д)}
    к = benchmark.кривая_монеты(цены, д, 100.0)
    проверить("удержание: старт равен капиталу", abs(к[0] - 100.0) < 1e-9)
    проверить("удержание: рост цены на 97.5% даёт те же 97.5% на счёте",
              abs(к[-1] - 197.5) < 0.01, str(к[-1]))
    проверить("слишком короткая история монеты не берётся",
              benchmark.кривая_монеты({д[0]: 1.0}, д, 100.0) is None)

    дырявые = {дн: 10.0 for дн in д[:35]}          # с 36-го дня цен нет
    к2 = benchmark.кривая_монеты(дырявые, д, 100.0)
    проверить("пропали цены — держим прежнюю оценку, а не ноль",
              к2 is not None and к2[-1] == к2[34] == 100.0,
              str(к2[-1] if к2 else None))

    # --- ГЛАВНОЕ 1: пределы портфеля соблюдаются ---
    # Быстрых пускают на 4% из общих 6%, сделка стоит 2% — значит две.
    # Именно быстрая квота срабатывает первой, и это правильно: короткие
    # сделки закрываются разом, поэтому им отведён отдельный, меньший угол.
    подменить([сделка("2024-01-02", "2024-01-20", 1.0) for _ in range(10)])
    _к, _п, вышло = benchmark.кривая_системы(дни(40), 100.0)
    проверить("быстрая квота 4% при риске 2% пускает ровно две сделки",
              вышло["взято"] == 2, str(вышло))
    проверить("остальные честно посчитаны отсеянными",
              вышло["отсеяно"] == 8, str(вышло))

    # Потолок медленных — отдельный от быстрых, как в живом портфеле
    # (engine/portfolio.py). Раньше здесь проверялось, что короткие сделки
    # упираются в ОБЩИЙ потолок 6% — это закрепляло ошибку: быстрые
    # и медленные системы место друг другу не занимают.
    подменить([], портфель={"макс_всего_позиций": 12, "макс_общий_риск_пр": 6.0,
                            "макс_риск_быстрых_пр": 4.0, "макс_сделок_в_день": 0})
    долгие = [сделка("2024-01-02", "2024-01-20", 1.0) for _ in range(5)]
    короткие = [сделка("2024-01-02", "2024-01-20", 1.0) for _ in range(5)]
    benchmark._сделки = lambda файл: {"trades_long.json": долгие,
                                      "trades.json": короткие}.get(файл, [])
    _к, _п, вышло = benchmark.кривая_системы(дни(40), 100.0)
    проверить("медленных по 3% в потолке 6% — две, и быстрые по 2% в своих 4% — ещё две",
              вышло["по_системам"] == {"долгосрочная": 2, "короткая": 2}, str(вышло))

    подменить([сделка("2024-01-02", "2024-01-20", 1.0) for _ in range(10)],
              портфель={"макс_всего_позиций": 2, "макс_общий_риск_пр": 100.0,
                        "макс_риск_быстрых_пр": 100.0, "макс_сделок_в_день": 0})
    _к, _п, вышло = benchmark.кривая_системы(дни(40), 100.0)
    проверить("предел по числу позиций тоже работает",
              вышло["взято"] == 2, str(вышло))

    подменить([сделка("2024-01-02", "2024-01-03", 1.0) for _ in range(10)],
              портфель={"макс_всего_позиций": 12, "макс_общий_риск_пр": 100.0,
                        "макс_риск_быстрых_пр": 100.0, "макс_сделок_в_день": 4})
    _к, _п, вышло = benchmark.кривая_системы(дни(40), 100.0)
    проверить("дневной предел сделок соблюдается",
              вышло["взято"] == 4, str(вышло))

    # --- ГЛАВНОЕ 2: сделка «вошёл и вышел в один день» освобождает место ---
    однодневные = [сделка(f"2024-01-{д:02d}", f"2024-01-{д:02d}", 1.0)
                   for д in range(2, 32)]
    подменить(однодневные)
    _к, _п, вышло = benchmark.кривая_системы(дни(40), 100.0)
    проверить("сделка входа и выхода в один день не занимает место навсегда",
              вышло["взято"] == 30, f"взято {вышло['взято']} из 30")

    # --- сложный процент ---
    подменить([сделка("2024-01-02", "2024-01-03", 1.0),
               сделка("2024-01-05", "2024-01-06", 1.0)])
    к3, _п, _в = benchmark.кривая_системы(дни(40), 100.0)
    # 100 -> +2% от 100 = 102 -> +2% от 102 = 104.04
    проверить("вторая сделка рискует процентом от ВЫРОСШЕГО счёта",
              abs(к3[-1] - 104.04) < 0.01, str(к3[-1]))

    # --- пессимистичная кривая не выше обычной ---
    подменить([сделка("2024-01-02", "2024-01-20", 2.0)])
    к4, п4, _в = benchmark.кривая_системы(дни(40), 100.0)
    проверить("пессимистичная кривая нигде не выше обычной",
              all(a <= b + 1e-9 for a, b in zip(п4, к4)))
    проверить("к концу, когда всё закрыто, обе кривые сходятся",
              abs(п4[-1] - к4[-1]) < 1e-9, f"{п4[-1]} против {к4[-1]}")

    # --- сделки вне окна не выдумываются ---
    подменить([сделка("2023-06-01", "2023-06-10", 5.0)])
    к5, _п, вышло = benchmark.кривая_системы(дни(40), 100.0)
    проверить("сделка вне окна не попадает в итог",
              вышло["взято"] == 0 and вышло["вне_окна"] == 1 and к5[-1] == 100.0,
              str(вышло))

    benchmark._сделки, benchmark.CFG = сохранённые

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
