def тест_13_индикаторы_вменяемы():
    print("\n13. Индикаторы в допустимых диапазонах")
    # Синтетический ряд: рост, затем падение.
    closes = [100 + i for i in range(60)] + [160 - i * 1.5 for i in range(60)]
    highs = [c + 1 for c in closes]
    lows = [c - 1 for c in closes]

    r = ind.rsi(closes, 14)
    r_опр = [v for v in r if v is not None]
    проверить("RSI в диапазоне 0..100", all(0 <= v <= 100 for v in r_опр))
    проверить("RSI не определён в начале", r[0] is None and r[13] is None)
    проверить("RSI на росте высокий", r[55] > 70, f"{r[55]}")

    a = ind.atr(highs, lows, closes, 14)
    проверить("ATR положительный", all(v > 0 for v in a if v is not None))

    adx_, pdi, mdi = ind.adx(highs, lows, closes, 14)
    adx_опр = [v for v in adx_ if v is not None]
    проверить("ADX в диапазоне 0..100", all(0 <= v <= 100 for v in adx_опр))
    проверить("ADX определён на длинной серии", len(adx_опр) > 0)

    up, mid, low, width = ind.bollinger(closes, 20, 2.0)
    проверить("верх > середина > низ",
              all(up[i] > mid[i] > low[i] for i in range(20, len(closes))))
    проверить("ширина положительна",
              all(v > 0 for v in width if v is not None))

    m_line, m_sig, m_hist = ind.macd(closes)
    проверить("гистограмма = линия - сигнал",
              all(abs(m_hist[i] - (m_line[i] - m_sig[i])) < 1e-9
                  for i in range(len(closes)) if m_hist[i] is not None))


