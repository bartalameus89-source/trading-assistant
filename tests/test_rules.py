ПРОВАЛЫ: list[str] = []
ВСЕГО = 0


def проверить(имя: str, условие: bool, подробности: str = "") -> None:
    global ВСЕГО
    ВСЕГО += 1
    if условие:
        print(f"  OK   {имя}")
    else:
        print(f"  ПРОВАЛ {имя}  {подробности}")
        ПРОВАЛЫ.append(имя)


def план(направление, вход, стоп, цели, цена=None, atr_=100.0) -> ПланСделки:
    return ПланСделки(
        актив="TESTUSDT", направление=направление, вход=вход, стоп=стоп,
        цели=цели, текущая_цена=цена if цена is not None else вход, atr=atr_,
    )


def правило(имя: str, p: ПланСделки) -> risk.Проверка | None:
    for пр in p.проверки:
        if пр.правило == имя:
            return пр
    return None


