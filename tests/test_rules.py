def тест_07d_мелкий_депозит_и_лимиты_биржи():
    """Мелкий счёт вскрывает то, чего не видно на крупном: биржа не примет
    слишком мелкую заявку, а количество округляется к её шагу."""
    print("\n7d. Ограничения биржи на мелком депозите")
    лимиты = {"мин_объём": 5.0, "шаг_количества": 0.001, "мин_количество": 0.001}

    # Депозит 10 $, стоп 2% -> объём 2.5 $, это НИЖЕ минимума биржи в 5 $.
    p = план(LONG, вход=100.0, стоп=98.0, цели=[103.0, 106.0], цена=100.0, atr_=2.0)
    p = risk.рассчитать(p, депозит=10.0, риск_пр=0.5, макс_плечо=1.0,
                        издержки_конфиг=CFG["издержки"], лимиты_биржи=лимиты)
    p = risk.проверить(p, CFG, 10.0)
    проверить("объём ниже минимума биржи распознан",
              правило("Минимальный объём биржи", p).ок is False,
              f"объём {p.notional}")

    # Депозит 100 $ — тот же расчёт проходит.
    g = план(LONG, вход=100.0, стоп=98.0, цели=[103.0, 106.0], цена=100.0, atr_=2.0)
    g = risk.рассчитать(g, депозит=100.0, риск_пр=0.5, макс_плечо=1.0,
                        издержки_конфиг=CFG["издержки"], лимиты_биржи=лимиты)
    g = risk.проверить(g, CFG, 100.0)
    проверить("на 100 $ объём проходит минимум",
              правило("Минимальный объём биржи", g).ок is True, f"объём {g.notional}")

    # Округление вниз к шагу: 0.25 при шаге 0.001 -> кратно шагу.
    проверить("количество кратно шагу биржи",
              abs(g.размер / 0.001 - round(g.размер / 0.001)) < 1e-6, f"{g.размер}")
    проверить("округление только вниз", g.размер <= 0.25 + 1e-9, f"{g.размер}")


