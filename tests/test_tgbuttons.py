"""
Кнопки «взял / пропустил» в Telegram: разбор нажатий и защита от повторов.

Зачем эта проверка. Журнал решений был пустым не потому, что решения
не принимаются, а потому что ради одной кнопки надо открыть кабинет.
Кнопка переехала в сообщение — но GitHub не может принимать вебхуки,
поэтому нажатия мы ОПРАШИВАЕМ сами. У опроса есть ловушка: если не двигать
смещение, Telegram отдаёт одни и те же нажатия снова и снова, и одно
нажатие превращается в шесть записей — по одной на каждый проход за сутки.

Сеть здесь подменена: проверяется логика, а не доступность Telegram.

Запуск:  python tests/test_tgbuttons.py
"""

from __future__ import annotations

import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from engine import tgbuttons

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


class Телеграм:
    """Подделка сети: помнит, что у неё спрашивали и с каким смещением."""

    def __init__(self, обновления: list[dict]) -> None:
        self.обновления = обновления
        self.вызовы: list[tuple[str, dict]] = []

    def __call__(self, метод: str, данные: dict) -> dict | None:
        self.вызовы.append((метод, данные))
        if метод != "getUpdates":
            return {"ok": True}
        смещение = int(данные.get("offset", 0))
        видимые = [о for о in self.обновления
                   if int(о["update_id"]) >= смещение]
        return {"ok": True, "result": видимые}


def нажатие(update_id: int, данные: str) -> dict:
    return {
        "update_id": update_id,
        "callback_query": {
            "id": f"cb{update_id}", "data": данные,
            "message": {"message_id": 100 + update_id, "date": 1700000000,
                        "chat": {"id": 555}},
        },
    }


def главное() -> int:
    print("КНОПКИ В TELEGRAM\n")
    папка = tempfile.mkdtemp()
    tgbuttons.ПАПКА = папка
    tgbuttons.ФАЙЛ_СМЕЩЕНИЯ = os.path.join(папка, "tg_offset.json")

    # --- клавиатура ---
    к = json.loads(tgbuttons.клавиатура("BTCUSDT-1700000000"))
    кнопки = к["inline_keyboard"][0]
    проверить("две кнопки в ряд", len(кнопки) == 2)
    проверить("первая — взял", кнопки[0]["callback_data"].startswith(tgbuttons.ВЗЯЛ + ":"))
    проверить("вторая — пропустил",
              кнопки[1]["callback_data"].startswith(tgbuttons.ПРОПУСТИЛ + ":"))
    проверить("данные кнопки влезают в лимит Telegram (64 байта)",
              all(len(b["callback_data"].encode()) <= 64 for b in кнопки),
              str([len(b["callback_data"].encode()) for b in кнопки]))

    # --- разбор нажатий ---
    сеть = Телеграм([нажатие(10, "t:BTC-1"), нажатие(11, "s:ETH-2")])
    tgbuttons._запрос = сеть
    н = tgbuttons.собрать_нажатия()
    проверить("прочитаны оба нажатия", len(н) == 2, f"{len(н)}")
    проверить("первое распознано как «взял»",
              н[0]["решение"] == tgbuttons.ВЗЯЛ and н[0]["сигнал"] == "BTC-1",
              str(н[0]))
    проверить("второе распознано как «пропустил»",
              н[1]["решение"] == tgbuttons.ПРОПУСТИЛ and н[1]["сигнал"] == "ETH-2")
    проверить("время берётся из сообщения, а не «сейчас»",
              н[0]["когда"] == 1700000000)

    # --- ГЛАВНОЕ: повторный опрос не должен вернуть то же самое ---
    повтор = tgbuttons.собрать_нажатия()
    проверить("повторный опрос не отдаёт те же нажатия ещё раз",
              повтор == [], f"вернулось {len(повтор)}")
    проверить("смещение сохранено на диск",
              os.path.exists(tgbuttons.ФАЙЛ_СМЕЩЕНИЯ))

    # --- новое нажатие после старых видно ---
    сеть.обновления.append(нажатие(12, "t:SOL-3"))
    ещё = tgbuttons.собрать_нажатия()
    проверить("новое нажатие приходит", len(ещё) == 1 and ещё[0]["сигнал"] == "SOL-3",
              str(ещё))

    # --- мусор игнорируется, а не роняет проход ---
    сеть.обновления.append(нажатие(13, "мусор"))
    сеть.обновления.append(нажатие(14, "x:нет-двоеточия-нет"))
    сеть.обновления.append({"update_id": 15})          # вовсе без нажатия
    мусор = tgbuttons.собрать_нажатия()
    проверить("непонятные данные пропускаются молча", мусор == [], str(мусор))
    проверить("смещение всё равно сдвинулось за мусором",
              tgbuttons._смещение() >= 16, str(tgbuttons._смещение()))

    # --- сеть недоступна: не падаем ---
    tgbuttons._запрос = lambda м, д: None
    проверить("при недоступном Telegram возвращается пустой список",
              tgbuttons.собрать_нажатия() == [])

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
