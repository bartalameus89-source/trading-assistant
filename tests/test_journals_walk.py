"""
Все три журнала идут по барам и не подделывают исходы.

Проверяемая ошибка встречалась в бою. Журналы получали одно свёрнутое
{high, low, close} за общий период, посчитанный от самой старой сделки.
Из этого следовали две подделки:

  1. Сделка, открытая сегодня, проверялась по ценам недельной давности.
     Так система прорывов закрыла XRP по «стопу» 1.2588 в день, когда он
     вырос на +14.7%: минимум был утром, до входа.

  2. high и low принадлежат РАЗНЫМ барам, а сравнивались как один момент.
     При недельном окне сделка видела и стоп, и цель одновременно,
     и исход решал порядок проверок в коде, а не рынок.

Запуск:  python tests/test_journals_walk.py
"""

from __future__ import annotations

import os
import shutil
import sys
import tempfile
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

ЧАС = 3600
провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def бар(t_сек: float, high: float, low: float, close: float) -> dict:
    return {"t": t_сек * 1000, "high": high, "low": low, "close": close}


def во_временной_папке(модуль):
    """Подменяет файл журнала на пустой временный."""
    папка = tempfile.mkdtemp()
    модуль.ПАПКА = папка
    модуль.ФАЙЛ = os.path.join(папка, "journal.json")
    return папка


def проверить_журнал(имя_журнала: str, подготовить, провести, состояние_из,
                     результат_из) -> None:
    """Один и тот же сценарий для всех трёх журналов."""
    print(f"\n{имя_журнала}")
    сейчас = time.time()

    # Сделка создана СЕЙЧАС. В истории есть провал ниже стопа, но он
    # случился ЧАС НАЗАД — до неё. Подделать убыток нельзя.
    запись = подготовить(создана=сейчас, вход=100.0, стоп=90.0, цель=115.0)
    бары = [
        бар(сейчас - 2 * ЧАС, 105, 85, 100),   # провал до 85 — ДО сделки
        бар(сейчас - 1 * ЧАС, 104, 88, 100),   # ещё один — тоже ДО
    ]
    провести({"TESTUSDT": бары})
    # Названия конечного состояния у журналов разные: "закрыта" и "завершена".
    ЗАКРЫТО = ("закрыта", "завершена")
    проверить("прошлый провал ниже стопа не закрывает сделку",
              состояние_из() not in ЗАКРЫТО, f"состояние {состояние_из()}")

    # Появился бар ПОСЛЕ сделки: вход исполнен, стоп не задет.
    бары.append(бар(сейчас + 1 * ЧАС, 103, 99, 102))
    провести({"TESTUSDT": бары})
    проверить("вход по бару после сделки исполняется",
              состояние_из() in ("в работе", "открыта"),
              f"состояние {состояние_из()}")

    # Теперь настоящее падение ниже стопа — должно сработать.
    бары.append(бар(сейчас + 2 * ЧАС, 101, 89, 90))
    провести({"TESTUSDT": бары})
    проверить("настоящее падение после входа закрывает по стопу",
              состояние_из() in ЗАКРЫТО, f"состояние {состояние_из()}")
    r = результат_из()
    проверить("результат отрицательный и близок к -1R",
              r is not None and -1.2 < r < -0.8, f"R = {r}")


def главное() -> int:
    print("ЖУРНАЛЫ ИДУТ ПО БАРАМ, А НЕ ПО СВЁРНУТОМУ ОКНУ")

    # ---------- тень ----------
    from engine import shadow
    во_временной_папке(shadow)
    shadow.ФАЙЛ = os.path.join(os.path.dirname(shadow.ФАЙЛ), "shadow.json")

    def подготовить_тень(создана, вход, стоп, цель):
        с = shadow.ТеневаяСделка(
            ид="t1", актив="TESTUSDT", система="короткая", направление="Long",
            создана=создана, вход=вход, стоп=стоп, цель=цель,
            тип_ордера="Limit", уверенность="средняя", режим="боковик",
            волатильность="обычная", срок_до=создана + 48 * ЧАС)
        shadow.сохранить([с])
        return с

    проверить_журнал(
        "ТЕНЬ (engine/shadow.py)", подготовить_тень,
        shadow.провести,
        lambda: shadow.все()[0].состояние,
        lambda: shadow.все()[0].результат_R)

    # ---------- журнал решений ----------
    from engine import decisions
    во_временной_папке(decisions)
    decisions.ФАЙЛ = os.path.join(os.path.dirname(decisions.ФАЙЛ), "decisions.json")

    def подготовить_решение(создана, вход, стоп, цель):
        р = decisions.Решение(
            ид="d1", актив="TESTUSDT", решение=decisions.ВЗЯЛ, когда=создана,
            направление="Long", вход=вход, стоп=стоп, цель=цель,
            тип_ордера="Limit", уверенность="средняя", режим="боковик",
            тег="тест", капитал=100.0, риск_проц=1.0, размер=10.0,
            риск_денег=10.0)
        decisions.сохранить([р])
        return р

    проверить_журнал(
        "РЕШЕНИЯ (engine/decisions.py)", подготовить_решение,
        decisions.провести,
        lambda: decisions.все()[0].состояние,
        lambda: decisions.все()[0].результат_R)

    # ---------- журнал рекомендаций ----------
    from engine import journal
    во_временной_папке(journal)
    journal.ФАЙЛ = os.path.join(os.path.dirname(journal.ФАЙЛ), "paper.json")

    def подготовить_сделку(создана, вход, стоп, цель):
        с = journal.БумажнаяСделка(
            ид="p1", актив="TESTUSDT", направление="Long", открыта_в=создана,
            вход=вход, стоп=стоп, цель=цель, тип_ордера="Limit", размер=10.0,
            риск_денег=10.0, капитал_на_момент=100.0, уверенность="средняя",
            тег="тест", режим="боковик", срок_до=создана + 48 * ЧАС)
        journal._записать([с])
        return с

    проверить_журнал(
        "РЕКОМЕНДАЦИИ (engine/journal.py)", подготовить_сделку,
        journal.обновить,
        lambda: journal.все_сделки()[0].состояние,
        lambda: journal.все_сделки()[0].результат_R)

    # ---------- мина безубытка ----------
    # Когда стоп переносится в безубыток, он становится равен цене входа.
    # Если риск считать от ТЕКУЩЕГО стопа, он обращается в ноль, и проверка
    # "if риск <= 0: continue" отсекает сделку навсегда: она не закрывается
    # и не попадает в статистику. Уцелевали только те, что успевали
    # закрыться в том же проходе, где сработал безубыток.
    print()
    print("МИНА БЕЗУБЫТКА: сделка не должна зависать между проходами")
    во_временной_папке(shadow)
    shadow.ФАЙЛ = os.path.join(os.path.dirname(shadow.ФАЙЛ), "shadow2.json")
    сейчас = time.time()
    с = shadow.ТеневаяСделка(
        ид="bu", актив="TESTUSDT", система="короткая", направление="Long",
        создана=сейчас, вход=100.0, стоп=90.0, стоп_начальный=90.0,
        цель=115.0, тип_ордера="Limit", уверенность="средняя",
        режим="боковик", волатильность="обычная",
        срок_до=сейчас + 48 * ЧАС, порог_безубытка=0.75)
    shadow.сохранить([с])

    # Проход 1: вход, затем рост до +0.75R — стоп уезжает в безубыток.
    бары = [бар(сейчас + 1 * ЧАС, 101, 99, 100),      # вход по 100
            бар(сейчас + 2 * ЧАС, 108, 100, 107)]     # +0.8R, безубыток
    shadow.провести({"TESTUSDT": бары})
    после1 = shadow.все()[0]
    проверить("стоп перенесён в безубыток", после1.стоп_в_безубытке,
              f"стоп {после1.стоп}")
    проверить("сделка ещё открыта", после1.состояние != shadow.ЗАКРЫТА)
    проверить("риск НЕ обнулился (иначе сделка зависнет)",
              после1.риск_на_единицу > 0,
              f"риск {после1.риск_на_единицу}")

    # Проход 2 (отдельный запуск): цена вернулась к входу — закрытие в ноль.
    бары.append(бар(сейчас + 3 * ЧАС, 103, 99, 100))
    shadow.провести({"TESTUSDT": бары})
    после2 = shadow.все()[0]
    проверить("на следующем проходе сделка закрывается, а не зависает",
              после2.состояние == shadow.ЗАКРЫТА, f"состояние {после2.состояние}")
    проверить("исход именно безубыток", после2.исход == "безубыток",
              f"исход {после2.исход}")
    проверить("результат около нуля",
              после2.результат_R is not None and abs(после2.результат_R) < 0.01,
              f"R = {после2.результат_R}")

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
