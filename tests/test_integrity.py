"""
Целостность журналов: порча должна останавливать работу, а не теряться.

Проверяемая беда. На битом файле журналы вели себя по-разному, и оба
поведения плохие: journal.py падал с JSONDecodeError и валил весь проход,
а equity, heartbeat, pnl и portfolio молча возвращали пустоту. Второе хуже:
повреждённый журнал становился неотличим от пустого, система спокойно
начинала с чистого листа, и вся история сделок пропадала без единого слова.

Отдельно проверяется главное правило копий: копия обновляется ТОЛЬКО
с целого файла. Иначе первая же порча затрёт последнюю здоровую копию.

Запуск:  python tests/test_integrity.py
"""

from __future__ import annotations

import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from engine import integrity

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def песочница() -> str:
    п = tempfile.mkdtemp()
    integrity.ПАПКА = п
    integrity.КОПИИ = os.path.join(п, "backup")
    return п


def записать(папка: str, имя: str, текст: str) -> None:
    with open(os.path.join(папка, имя), "w", encoding="utf-8") as f:
        f.write(текст)


def здоровый(папка: str) -> None:
    записать(папка, "breakouts.json",
             json.dumps({"позиции": [{"актив": "BTCUSDT"}]}, ensure_ascii=False))
    записать(папка, "paper.json", json.dumps({"сделки": []}))
    записать(папка, "shadow.json", json.dumps({"сделки": []}))
    записать(папка, "equity.json", json.dumps({"дни": []}))
    записать(папка, "heartbeat.json", json.dumps({"короткие": {"когда": 1}}))


def главное() -> int:
    print("ЦЕЛОСТНОСТЬ ЖУРНАЛОВ\n")

    # --- здоровое состояние ---
    п = песочница(); здоровый(п)
    беды, отчёт = integrity.проверить_все()
    проверить("на целых журналах бед нет", not беды, str(беды))
    проверить("копии созданы",
              os.path.exists(os.path.join(п, "backup", "breakouts.json")))
    проверить("отсутствующий файл — не беда",
              all("decisions" not in б for б in беды))

    # --- битый JSON ---
    п = песочница(); здоровый(п)
    integrity.сохранить_копию("breakouts.json")
    записать(п, "breakouts.json", "{битый файл")
    беды, _ = integrity.проверить_все()
    проверить("битый JSON замечен",
              any("breakouts" in б and "испорчен JSON" in б for б in беды), str(беды))
    проверить("сказано, что копия есть",
              any("целая копия есть" in б for б in беды), str(беды))

    # --- ГЛАВНОЕ: копия НЕ затирается битым файлом ---
    копия = os.path.join(п, "backup", "breakouts.json")
    with open(копия, encoding="utf-8") as f:
        внутри = json.load(f)
    проверить("копия осталась целой, её не затёрло битым файлом",
              внутри.get("позиции") == [{"актив": "BTCUSDT"}], str(внутри))

    # --- пустой файл (оборвалась запись) ---
    п = песочница(); здоровый(п)
    записать(п, "paper.json", "")
    беды, _ = integrity.проверить_все()
    проверить("пустой файл замечен",
              any("paper.json" in б and "пустой" in б for б in беды), str(беды))

    # --- правильный JSON, но не тот ---
    п = песочница(); здоровый(п)
    записать(п, "shadow.json", json.dumps([1, 2, 3]))
    беды, _ = integrity.проверить_все()
    проверить("список вместо объекта замечен",
              any("shadow" in б and "ожидался объект" in б for б in беды), str(беды))

    п = песочница(); здоровый(п)
    записать(п, "equity.json", json.dumps({"чтото": []}))
    беды, _ = integrity.проверить_все()
    проверить("пропавший ключ замечен",
              any("equity" in б and "нет ключа" in б for б in беды), str(беды))

    п = песочница(); здоровый(п)
    записать(п, "paper_long.json", json.dumps({"позиции": {"не": "список"}}))
    беды, _ = integrity.проверить_все()
    проверить("ключ не того типа замечен",
              any("paper_long" in б and "не список" in б for б in беды), str(беды))

    # --- убедиться() останавливает работу ---
    п = песочница(); здоровый(п)
    записать(п, "breakouts.json", "{битый")
    упало = False
    try:
        integrity.убедиться()
    except integrity.Повреждён as e:
        упало = "breakouts" in str(e)
    проверить("убедиться() останавливает проход на порче", упало)

    п = песочница(); здоровый(п)
    прошло = True
    try:
        integrity.убедиться()
    except integrity.Повреждён:
        прошло = False
    проверить("на здоровых журналах убедиться() пропускает", прошло)

    # --- копии нет, сказать честно ---
    п = песочница()
    записать(п, "breakouts.json", "{битый")
    беды, _ = integrity.проверить_все()
    проверить("если копии нет — так и сказано",
              any("восстанавливать нечем" in б for б in беды), str(беды))

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
