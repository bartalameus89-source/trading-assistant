"""
Движок портфеля для замеров: он обязан пускать ровно то, что пускает живой.

Зачем. На этом движке решается, сколько ставить на каждую систему. Если он
строже или мягче настоящего портфеля (engine/portfolio.py), замер выберет
распределение для портфеля, которого не существует. Так уже было: прогон
«купил и держал» складывал риск быстрой и медленных систем в один потолок
6%, а живой портфель держит их раздельно — 4% и 6%. Прогон пускал меньше
сделок, чем бывает в жизни.

Каждое правило живого портфеля проверяется здесь на подменённых сделках.

Запуск:  python tests/test_portsim.py
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from engine import portsim

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


ПРЕДЕЛЫ = {"медленных": 6.0, "быстрых": 4.0, "позиций": 12, "в_день": 0,
           "прорывов": 10}
СТАВКИ = {"короткая": 2.0, "долгосрочная": 3.0, "прорывы": 1.0}
ДНИ = [f"2024-01-{д:02d}" for д in range(1, 31)]


def сд(система: str, актив: str, вход: str, выход: str, r: float = 1.0,
       путь: dict | None = None, когда: float = 0.0) -> dict:
    return {"система": система, "актив": актив, "вход": вход, "выход": выход,
            "r": r, "путь": путь, "когда": когда}


def взято(итог: dict, система: str) -> int:
    return итог["взято"].get(система, 0)


def главное() -> int:
    print("ДВИЖОК ПОРТФЕЛЯ ПО ЖИВЫМ ПРАВИЛАМ\n")

    # --- быстрые и медленные не занимают место друг другу ---
    сделки = ([сд("долгосрочная", f"L{i}", "2024-01-02", "2024-01-20") for i in range(2)]
              + [сд("короткая", f"S{i}", "2024-01-03", "2024-01-20") for i in range(2)])
    итог = portsim.прогнать(сделки, ДНИ, СТАВКИ, ПРЕДЕЛЫ)
    проверить("две долгосрочные по 3% занимают весь потолок медленных 6%",
              взято(итог, "долгосрочная") == 2, str(итог["взято"]))
    проверить("и при этом две короткие по 2% всё равно проходят в свои 4%",
              взято(итог, "короткая") == 2, str(итог["взято"]))

    # --- у каждой группы свой потолок ---
    сделки = [сд("короткая", f"S{i}", "2024-01-02", "2024-01-20") for i in range(5)]
    итог = portsim.прогнать(сделки, ДНИ, СТАВКИ, ПРЕДЕЛЫ)
    проверить("быстрых по 2% при потолке 4% — ровно две",
              взято(итог, "короткая") == 2, str(итог["взято"]))
    сделки = [сд("долгосрочная", f"L{i}", "2024-01-02", "2024-01-20") for i in range(5)]
    итог = portsim.прогнать(сделки, ДНИ, СТАВКИ, ПРЕДЕЛЫ)
    проверить("медленных по 3% при потолке 6% — ровно две",
              взято(итог, "долгосрочная") == 2, str(итог["взято"]))

    # --- одна монета — одна система ---
    сделки = [сд("долгосрочная", "BTC", "2024-01-02", "2024-01-20"),
              сд("прорывы", "BTC", "2024-01-05", "2024-01-25")]
    итог = portsim.прогнать(сделки, ДНИ, СТАВКИ, ПРЕДЕЛЫ)
    проверить("монету, занятую долгосрочной, прорыв не берёт",
              взято(итог, "прорывы") == 0
              and итог["причины"].get("монета занята другой позицией") == 1,
              str(итог["причины"]))

    # --- риск прорыва текущий: подтянутый стоп освобождает место ---
    # Прорыв на 1% с путём риска: день входа 1R, дальше стоп выше входа — 0R.
    путь = {"2024-01-02": 1.0, "2024-01-03": 0.0}
    сделки = ([сд("прорывы", f"B{i}", "2024-01-02", "2024-01-25", путь=путь) for i in range(6)]
              + [сд("долгосрочная", "L", "2024-01-05", "2024-01-20")])
    итог = portsim.прогнать(сделки, ДНИ, СТАВКИ, ПРЕДЕЛЫ)
    проверить("шесть прорывов по 1% заняли потолок в день входа",
              взято(итог, "прорывы") == 6, str(итог["взято"]))
    проверить("когда их стопы ушли выше входа, место освободилось для долгосрочной",
              взято(итог, "долгосрочная") == 1, str(итог))

    # --- и наоборот: без подтяжки место не освобождается ---
    сделки = ([сд("прорывы", f"B{i}", "2024-01-02", "2024-01-25") for i in range(6)]
              + [сд("долгосрочная", "L", "2024-01-05", "2024-01-20")])
    итог = portsim.прогнать(сделки, ДНИ, СТАВКИ, ПРЕДЕЛЫ)
    проверить("без подтяжки стопа долгосрочной места нет",
              взято(итог, "долгосрочная") == 0, str(итог["взято"]))

    # --- доливка поднимает риск и занимает место ---
    путь = {"2024-01-02": 1.0, "2024-01-03": 3.0}
    сделки = ([сд("прорывы", "B1", "2024-01-02", "2024-01-25", путь=путь)]
              + [сд("долгосрочная", "L", "2024-01-05", "2024-01-20")])
    итог = portsim.прогнать(сделки, ДНИ, {**СТАВКИ, "прорывы": 1.0}, ПРЕДЕЛЫ)
    проверить("прорыв с доливками на 3% риска оставляет место долгосрочной (3+3=6)",
              взято(итог, "долгосрочная") == 1, str(итог["взято"]))
    путь = {"2024-01-02": 1.0, "2024-01-03": 4.0}
    сделки = ([сд("прорывы", "B1", "2024-01-02", "2024-01-25", путь=путь)]
              + [сд("долгосрочная", "L", "2024-01-05", "2024-01-20")])
    итог = portsim.прогнать(сделки, ДНИ, {**СТАВКИ, "прорывы": 1.0}, ПРЕДЕЛЫ)
    проверить("а на 4% уже не оставляет (4+3>6)",
              взято(итог, "долгосрочная") == 0, str(итог["взято"]))

    # --- пределы числа ---
    сделки = [сд("прорывы", f"B{i}", "2024-01-02", "2024-01-20") for i in range(15)]
    итог = portsim.прогнать(сделки, ДНИ, {"прорывы": 0.25}, ПРЕДЕЛЫ)
    проверить("прорывов не больше своего предела 10",
              взято(итог, "прорывы") == 10, str(итог["взято"]))
    итог = portsim.прогнать(сделки, ДНИ, {"прорывы": 0.25}, {**ПРЕДЕЛЫ, "в_день": 5})
    проверить("новых за день не больше 5",
              взято(итог, "прорывы") == 5, str(итог["взято"]))

    # --- вход и выход в один день не держат место вечно ---
    сделки = [сд("короткая", "S", f"2024-01-{д:02d}", f"2024-01-{д:02d}")
              for д in range(2, 28)]
    итог = portsim.прогнать(сделки, ДНИ, СТАВКИ, ПРЕДЕЛЫ)
    проверить("сделки на один день проходят каждый день",
              взято(итог, "короткая") == 26, str(итог["взято"]))

    # --- деньги: сложный процент и вклад по системам ---
    сделки = [сд("долгосрочная", "L1", "2024-01-02", "2024-01-03", r=1.0),
              сд("долгосрочная", "L2", "2024-01-05", "2024-01-06", r=1.0)]
    итог = portsim.прогнать(сделки, ДНИ, СТАВКИ, ПРЕДЕЛЫ)
    проверить("вторая сделка рискует 3% от выросшего счёта: 100 → 103 → 106.09",
              abs(итог["кривая"][-1] - 106.09) < 1e-6, str(итог["кривая"][-1]))
    проверить("вклад системы равен её прибыли",
              abs(итог["вклад"]["долгосрочная"] - 6.09) < 1e-6, str(итог["вклад"]))

    # --- пессимистичная кривая видит текущий риск прорыва ---
    путь = {"2024-01-02": 1.0, "2024-01-03": 2.0, "2024-01-04": 0.0}
    сделки = [сд("прорывы", "B", "2024-01-02", "2024-01-10", r=2.0, путь=путь)]
    итог = portsim.прогнать(сделки, ДНИ, {"прорывы": 1.0}, ПРЕДЕЛЫ)
    к, п = итог["кривая"], итог["песс"]
    проверить("в день с двумя частями под ударом 2% счёта",
              abs((к[2] - п[2]) - 2.0) < 1e-9, f"{к[2] - п[2]}")
    проверить("когда стоп выше входа, под ударом ничего",
              abs(к[3] - п[3]) < 1e-9, f"{к[3] - п[3]}")
    проверить("наибольший риск разом замечен",
              abs(итог["макс_разом_пр"] - 2.0) < 1e-9, str(итог["макс_разом_пр"]))

    # --- показатели ---
    пк = portsim.показатели([100, 120, 90, 150], [100, 120, 90, 150])
    проверить("просадка от лучшего счёта: 120 → 90 это −25%",
              abs(пк["просадка_пр"] + 25.0) < 1e-9, str(пк))
    проверить("доход на единицу просадки: 50 / 25 = 2",
              abs(пк["отношение"] - 2.0) < 1e-9, str(пк))

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
