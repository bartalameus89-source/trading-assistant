"""
Быстрая система не должна блокироваться медленными.

Проверяемая беда случилась в бою. Общий потолок риска считал все системы
одним счётом, и первый за 17 дней сигнал короткой системы по SUI не прошёл:
позиции прорывов и долгосрочная заняли 5% из 6%, а короткой нужно было 2%.

Это несправедливо по существу. Замер срока удержания на 857 сделках:
короткая система держит позицию ПОЛДНЯ, прорывы 13 дней, долгосрочная 7.
Плата за место в портфеле — 1.0 процент-день против 6.5 и 21.0. Позиция,
висящая месяц, отсекала сделку на полдня.

Потолки разделены: медленные и быстрая считаются отдельно. Но риск в момент
СОВПАДЕНИЯ всё равно складывается, поэтому квота быстрых мала и её нельзя
случайно потерять.

Запуск:  python tests/test_portfolio_quota.py
"""

from __future__ import annotations

import json
import os
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from engine import portfolio

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


CFG = {
    "риск": {"депозит": 100},
    "портфель": {"макс_общий_риск_пр": 6.0, "макс_всего_позиций": 12,
                 "макс_риск_быстрых_пр": 4.0},
}


def обстановка(медленных_риск: float, быстрых_риск: float) -> str:
    """Кладёт в журналы позиции на заданный риск и возвращает папку."""
    папка = tempfile.mkdtemp()
    portfolio.ПАПКА = папка

    def писать(имя, ключ, записи):
        with open(os.path.join(папка, имя), "w", encoding="utf-8") as f:
            json.dump({ключ: записи}, f, ensure_ascii=False)

    писать("breakouts.json", "позиции", [
        {"актив": f"МЕДЛ{i}USDT", "состояние": "открыта", "риск_usd": 1.0}
        for i in range(int(медленных_риск))])
    писать("paper.json", "сделки", [
        {"актив": f"БЫСТР{i}USDT", "состояние": "в работе", "риск_пр": 1.0}
        for i in range(int(быстрых_риск))])
    писать("paper_long.json", "позиции", [])
    return папка


def главное() -> int:
    print("БЫСТРАЯ СИСТЕМА НЕ БЛОКИРУЕТСЯ МЕДЛЕННЫМИ\n")

    # Ровно та обстановка, что была в бою: медленные заняли 5% из 6%.
    обстановка(медленных_риск=5, быстрых_риск=0)
    можно, почему = portfolio.можно_открыть(CFG, "SUIUSDT", 2.0, система="короткая")
    проверить("короткая проходит, когда медленные заняли 5 из 6%", можно, почему)

    можно, почему = portfolio.можно_открыть(CFG, "SUIUSDT", 2.0, система="прорывы")
    проверить("медленная в той же обстановке НЕ проходит", not можно, почему)

    # Своя квота тоже кончается.
    обстановка(медленных_риск=0, быстрых_риск=4)
    можно, почему = portfolio.можно_открыть(CFG, "SUIUSDT", 1.0, система="короткая")
    проверить("быстрая упирается в СВОЮ квоту 4%", not можно, почему)
    проверить("причина отказа называет быстрые системы",
              "быстр" in почему.lower(), почему)

    # Медленные при этом свободны — квоты не смешиваются.
    можно, почему = portfolio.можно_открыть(CFG, "SUIUSDT", 3.0, система="прорывы")
    проверить("медленная проходит, когда занята квота быстрых", можно, почему)

    # Один актив в двух системах по-прежнему не берём.
    обстановка(медленных_риск=1, быстрых_риск=0)
    можно, почему = portfolio.можно_открыть(CFG, "МЕДЛ0USDT", 1.0, система="короткая")
    проверить("занятый актив не берётся даже другой системой", not можно, почему)

    # Общий предел числа позиций работает поверх обеих квот.
    узкий = {**CFG, "портфель": {**CFG["портфель"], "макс_всего_позиций": 3}}
    обстановка(медленных_риск=3, быстрых_риск=0)
    можно, почему = portfolio.можно_открыть(узкий, "SUIUSDT", 0.5, система="короткая")
    проверить("общий предел числа позиций действует на обе квоты",
              not можно, почему)

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
