"""
Сторож обязан краснеть на молчаливых поломках.

Проверяемая беда случилась в бою: пять суток все 30 запусков автоматики
были зелёные, а система прорывов не выполнялась ни разу — шаг стоял
на условии по строке расписания cron, и GitHub молча помечал его skipped.
Отдельно оказалось, что paper_long.py не был в workflow вовсе.

Ни то, ни другое не даёт ошибки. Значит, ловить надо по следам: пульс
систем, движение дней в позициях, зависшие записи. Этот тест подделывает
каждую беду и требует, чтобы сторож её увидел.

Запуск:  python tests/test_health.py
"""

from __future__ import annotations

import json
import os
import shutil
import sys
import tempfile
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import health
from engine import heartbeat

ЧАС = 3600
СУТКИ = 86400
провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def подготовить(папка: str) -> None:
    """Здоровое состояние: пульс свежий, дни досчитаны, зависших нет."""
    health.ПАПКА = папка
    heartbeat.ПАПКА = папка
    heartbeat.ФАЙЛ = os.path.join(папка, "heartbeat.json")
    сейчас = time.time()
    писать(папка, "heartbeat.json", {
        с: {"когда": сейчас, "событий": 0}
        for с in ("короткие", "прорывы", "долгосрочная")})
    писать(папка, "breakouts.json", {"обновлён": сейчас, "создан": сейчас - 5 * СУТКИ,
        "позиции": [{"актив": "BTCUSDT", "состояние": "открыта",
                     "открыта_в": сейчас - 3 * СУТКИ, "проверен_до": (сейчас - ЧАС) * 1000,
                     "стоп": 110.0, "стоп_начальный": 100.0}]})
    писать(папка, "shadow.json", {"обновлён": сейчас, "создан": сейчас - 5 * СУТКИ,
                                  "сделки": []})
    писать(папка, "paper.json", {"обновлён": сейчас, "создан": сейчас - 5 * СУТКИ,
                                 "сделки": []})
    писать(папка, "paper_long.json", {"обновлён": сейчас, "создан": сейчас - 5 * СУТКИ,
                                      "позиции": []})


def писать(папка: str, имя: str, данные: dict) -> None:
    with open(os.path.join(папка, имя), "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False)


def читать(папка: str, имя: str) -> dict:
    with open(os.path.join(папка, имя), encoding="utf-8") as f:
        return json.load(f)


def главное() -> int:
    print("СТОРОЖ ЛОВИТ МОЛЧАЛИВЫЕ ПОЛОМКИ\n")
    сейчас = time.time()

    # --- здоровое состояние: сторож молчит ---
    папка = tempfile.mkdtemp()
    подготовить(папка)
    беды, _ = health.проверить()
    проверить("на здоровой системе бед нет", not беды, f"нашёл: {беды}")

    # --- беда 1: система перестала запускаться (та самая, что была) ---
    папка = tempfile.mkdtemp()
    подготовить(папка)
    п = читать(папка, "heartbeat.json")
    п["прорывы"]["когда"] = сейчас - 5 * СУТКИ      # молчит пять суток
    писать(папка, "heartbeat.json", п)
    беды, _ = health.проверить()
    проверить("видит систему, которая не запускается пять суток",
              any("прорывы" in б for б in беды), f"нашёл: {беды}")

    # --- беда 2: систему вообще ни разу не запускали (случай paper_long) ---
    папка = tempfile.mkdtemp()
    подготовить(папка)
    п = читать(папка, "heartbeat.json")
    del п["долгосрочная"]
    писать(папка, "heartbeat.json", п)
    беды, _ = health.проверить()
    проверить("видит систему, которой нет в автоматике вовсе",
              any("долгосрочная" in б for б in беды), f"нашёл: {беды}")

    # --- беда 2б: молчит ВСЯ автоматика (отличается от отставания одной) ---
    папка = tempfile.mkdtemp()
    подготовить(папка)
    п = читать(папка, "heartbeat.json")
    for с in п:
        п[с]["когда"] = сейчас - 2 * СУТКИ
    писать(папка, "heartbeat.json", п)
    беды, _ = health.проверить()
    проверить("отличает молчание всей автоматики от отставания одной системы",
              any("не запускается ни одна" in б for б in беды), f"нашёл: {беды}")

    # --- пороги молчания взяты замером реального расписания GitHub:
    #     фактический максимум простоя 13.2 часа, поэтому 13 часов —
    #     это норма, а 20 — уже беда. Порог в 8 часов, стоявший раньше,
    #     поднимал бы ложную тревогу примерно раз в сутки.
    for часов, ждём_тревогу in ((13, False), (20, True)):
        папка = tempfile.mkdtemp()
        подготовить(папка)
        п = читать(папка, "heartbeat.json")
        for с in п:
            п[с]["когда"] = сейчас - часов * ЧАС
        писать(папка, "heartbeat.json", п)
        беды, _ = health.проверить()
        есть = any("не запускается ни одна" in б for б in беды)
        проверить(f"простой {часов} ч: тревога {'нужна' if ждём_тревогу else 'не нужна'}",
                  есть == ждём_тревогу, f"нашёл: {беды}")

    # --- беда 3: проводка стоит, дни не досчитываются ---
    папка = tempfile.mkdtemp()
    подготовить(папка)
    б = читать(папка, "breakouts.json")
    б["позиции"][0]["проверен_до"] = (сейчас - 6 * СУТКИ) * 1000
    писать(папка, "breakouts.json", б)
    беды, _ = health.проверить()
    проверить("видит позицию, у которой дни не считаются",
              any("проводка стоит" in б for б in беды), f"нашёл: {беды}")

    # --- беда 4: запись висит с истёкшим сроком входа ---
    папка = tempfile.mkdtemp()
    подготовить(папка)
    писать(папка, "shadow.json", {"обновлён": сейчас, "создан": сейчас - 5 * СУТКИ,
        "сделки": [{"актив": "UNIUSDT", "состояние": "ждёт входа",
                    "срок_до": сейчас - 4 * СУТКИ}]})
    беды, _ = health.проверить()
    проверить("видит запись, зависшую после истечения срока",
              any("ждёт входа" in б for б in беды), f"нашёл: {беды}")

    # --- код возврата ---
    папка = tempfile.mkdtemp()
    подготовить(папка)
    п = читать(папка, "heartbeat.json")
    п["короткие"]["когда"] = сейчас - 3 * СУТКИ
    писать(папка, "heartbeat.json", п)
    sys.argv = ["health.py", "--тихо"]
    проверить("при беде возвращает код 1 — запуск краснеет",
              health.главное() == 1)

    папка = tempfile.mkdtemp()
    подготовить(папка)
    проверить("на здоровой системе возвращает 0", health.главное() == 0)

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
