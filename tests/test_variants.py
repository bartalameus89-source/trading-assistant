"""
Варианты фильтра волатильности: учатся параллельно и не трогают наш счёт.

Проверяемые беды. Варианты ведутся через теневой журнал с подменённым
файлом. Если подмена не вернётся на место, следующий проход запишет тень
в файл вариантов — и сравнение рекомендованных с отсеянными потеряется.
Если варианты окажутся в state/shadow.json, итоги кабинета смешают их
с тенью. И если позиции вариантов не раздельны, монета, занятая в одном
варианте, не даст сигналу в другом — варианты перестанут быть сравнимыми.

Запуск:  python tests/test_variants.py
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from types import SimpleNamespace

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from engine import shadow, signals, variants

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def анализ(актив: str, перцентиль: float, порог: float):
    """Подделка signals.проанализировать: сигнал есть, только если
    перцентиль ниже порога — ровно так работает фильтр."""
    план = SimpleNamespace(вход=100.0, стоп=95.0, atr=2.0, цели=[107.5],
                           тип_ордера="Limit")
    режим = SimpleNamespace(направление="боковик", волатильность="нормальная",
                            bbw_перцентиль=перцентиль)
    return SimpleNamespace(актив=актив, направление="Long", план=план, режим=режим,
                           уверенность="средняя", отсеяно_фильтрами=[],
                           вывод=signals.СИГНАЛ if перцентиль < порог else signals.НЕТ_СИГНАЛА)


def главное() -> int:
    print("ВАРИАНТЫ ФИЛЬТРА ВОЛАТИЛЬНОСТИ\n")

    ожид = {0: 80.0, 10: 82.0, 50: 90.0, 60: 92.0, 90: 98.0}
    проверить("ослабление X% сужает зону 20% пропорционально",
              all(abs(variants.порог(к) - v) < 1e-9 for к, v in ожид.items()),
              str({к: variants.порог(к) for к in ожид}))
    проверить("100% — фильтра нет", variants.порог(100) > 100)
    проверить("ведутся 11 вариантов: 0..100 через 10",
              variants.ОСЛАБЛЕНИЯ == list(range(0, 101, 10)))

    папка = tempfile.mkdtemp()
    исходный_файл = shadow.ФАЙЛ
    shadow.ФАЙЛ = os.path.join(папка, "shadow.json")
    variants.ФАЙЛ = os.path.join(папка, "variants.json")
    shadow.ПАПКА = папка

    перцентиль = {"BTCUSDT": 85.0}
    signals_оригинал = signals.проанализировать
    signals.проанализировать = lambda свечи, cfg, флаги, депозит: анализ(
        свечи, перцентиль[свечи], cfg["пороги"][variants.КЛЮЧ_ПОРОГА])
    cfg = {"пороги": {variants.КЛЮЧ_ПОРОГА: 90.0},
           "сигналы": {"срок_жизни_сигнала_баров": 4},
           "риск": {"депозит": 100, "безубыток_после_R": 0.75}}
    try:
        новых = variants.записать_сигналы("BTCUSDT", [], cfg, 4.0)
        # перцентиль 85: проходит при порогах 86, 88, 90 ... и без фильтра
        проверить("сигнал на 85-м перцентиле попал в варианты с порогом выше 85",
                  новых == 8, f"новых {новых}")
        имена = sorted(с.система for с in variants.все())
        проверить("и не попал в варианты 0–20% (пороги 80–84)",
                  not any(и in имена for и in ("ослабление-0", "ослабление-10", "ослабление-20")),
                  str(имена))
        проверить("у каждого варианта своя позиция по монете",
                  len(имена) == len(set(имена)) == 8, str(имена))

        повтор = variants.записать_сигналы("BTCUSDT", [], cfg, 4.0)
        проверить("повторный сигнал по той же монете не дублирует позицию", повтор == 0)

        проверить("в журнал теней ничего не записано",
                  not os.path.exists(shadow.ФАЙЛ), shadow.ФАЙЛ)
        проверить("после работы теневой журнал снова пишет в свой файл",
                  shadow.ФАЙЛ == os.path.join(папка, "shadow.json"), shadow.ФАЙЛ)
        with open(variants.ФАЙЛ, encoding="utf-8") as f:
            проверить("варианты лежат в своём файле", len(json.load(f)["сделки"]) == 8)

        с = {в["ослабление"]: в for в in variants.свод()}
        проверить("свод: у варианта 50% один сигнал, закрытых нет",
                  с[50]["сигналов"] == 1 and с[50]["закрыто"] == 0, str(с[50]))
        проверить("пока закрытых мало — вывода нет",
                  variants.вывод(variants.свод()).startswith("Выводов пока нет"))
    finally:
        signals.проанализировать = signals_оригинал
        shadow.ФАЙЛ = исходный_файл

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
