"""
Telegram-бот с меню: отвечает только владельцу, кнопки дают верные цифры,
нажатия «взял / пропустил» не теряются.

Проверяемые беды.
  * Бот ответил бы любому, кто найдёт его в Telegram, — показав счёт
    и позиции. Отвечать можно только чату владельца.
  * Бот забирает у Telegram все обновления, включая нажатия под сигналами.
    Если он не передаст нажатие на GitHub, решение пропадёт бесследно:
    проход автоматики его уже не увидит. При сбое передачи кнопки должны
    остаться, чтобы нажать ещё раз.
  * Цифры бота обязаны совпадать с кабинетом: итог считается теми же
    функциями и по тем же журналам, а журналы — скачанные с GitHub,
    не рабочая копия state/.
  * decide.py пишет в журнал решения из входных данных workflow — чужое
    или испорченное нажатие записываться не должно.

Сеть подменена: проверяется логика, а не доступность Telegram и GitHub.

Запуск:  python tests/test_bot.py
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
import time

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

import bot
import decide
from engine import botmenu, pnl, remote, trades

провалено = 0
ЧАТ = "555"


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


class Телеграм:
    def __init__(self):
        self.вызовы: list[tuple[str, dict]] = []

    def __call__(self, метод: str, поля: dict, таймаут: int = 30):
        self.вызовы.append((метод, поля))
        return {"ok": True, "result": []}

    def методы(self) -> list[str]:
        return [м for м, _ in self.вызовы]

    def тексты(self) -> list[str]:
        return [п.get("text", "") for м, п in self.вызовы if м == "sendMessage"]


def сообщение(текст: str, чат: str = ЧАТ) -> dict:
    return {"update_id": 1, "message": {"chat": {"id": int(чат)}, "text": текст}}


def нажатие(данные: str, чат: str = ЧАТ) -> dict:
    return {"update_id": 2, "callback_query": {
        "id": "cb1", "data": данные,
        "message": {"chat": {"id": int(чат)}, "message_id": 77, "date": 1700000000}}}


def сделать_бота(передача_успешна: bool = True):
    тг = Телеграм()
    переданы: list[dict] = []

    def запустить(н):
        переданы.append(н)
        return передача_успешна

    построено: list[str] = []

    def построить(кнопка):
        построено.append(кнопка)
        return f"ответ на {кнопка}"

    б = bot.Бот("токен", ЧАТ, "гитхаб", телеграм=тг, запустить_решение=запустить,
                запуски=lambda: [], скачать=lambda: {}, построить=построить)
    return б, тг, переданы, построено


def журналы(папка: str) -> None:
    теперь = time.time()

    def писать(имя, данные):
        with open(os.path.join(папка, имя), "w", encoding="utf-8") as f:
            json.dump(данные, f, ensure_ascii=False)

    писать("breakouts.json", {"позиции": [
        {"актив": "SOLUSDT", "состояние": "открыта", "вход": 100.0, "стоп": 90.0,
         "стоп_начальный": 90.0, "риск_usd": 0.5, "открыта_в": теперь - 86400},
        {"актив": "LTCUSDT", "состояние": "закрыта", "вход": 50.0, "стоп": 45.0,
         "стоп_начальный": 45.0, "риск_usd": 0.25, "r": -1.0, "исход": "стоп",
         "открыта_в": теперь - 5 * 86400, "закрыта_в": теперь - 2 * 86400},
        {"актив": "ETHUSDT", "состояние": "открыта", "тень": True, "вход": 10.0,
         "стоп": 9.0, "стоп_начальный": 9.0, "риск_usd": 1.0, "открыта_в": теперь},
    ]})
    писать("paper.json", {"сделки": []})
    писать("paper_long.json", {"позиции": []})
    писать("shadow.json", {"сделки": []})
    писать("equity.json", {"дни": []})
    писать("heartbeat.json", {"прорывы": {"когда": теперь - 3600, "событий": 0,
                                          "ошибок_данных": 0}})


def главное() -> int:
    print("TELEGRAM-БОТ С МЕНЮ\n")

    # --- только владелец ---
    б, тг, _, построено = сделать_бота()
    б.обработать(сообщение(botmenu.ИТОГ, чат="999"))
    проверить("чужому чату бот не отвечает ничего", not тг.вызовы and not построено,
              str(тг.вызовы))
    б.обработать(нажатие("t:BTCUSDT-1", чат="999"))
    проверить("чужое нажатие не передаётся и не подтверждается", not тг.вызовы)

    # --- кнопки меню ---
    б, тг, _, построено = сделать_бота()
    б.обработать(сообщение(botmenu.ИТОГ))
    проверить("кнопка «Итог» строит ответ «Итог»", построено == [botmenu.ИТОГ], str(построено))
    проверить("ответ отправлен владельцу с меню",
              тг.вызовы and тг.вызовы[-1][1]["chat_id"] == ЧАТ
              and "reply_markup" in тг.вызовы[-1][1], str(тг.вызовы))
    б, тг, _, построено = сделать_бота()
    б.обработать(сообщение(botmenu.СИГНАЛЫ))
    проверить("долгая кнопка сначала говорит «считаю», потом отвечает",
              len(тг.тексты()) == 2 and тг.тексты()[0].startswith("⏳"), str(тг.тексты()))
    б, тг, _, построено = сделать_бота()
    б.обработать(сообщение("/start"))
    проверить("на /start и любой текст — меню и помощь, без расчётов",
              not построено and "Меню" in тг.тексты()[0], str(тг.тексты()))
    клав = json.loads(botmenu.клавиатура())
    проверить("в меню все семь кнопок",
              sum(len(р) for р in клав["keyboard"]) == 7, str(клав))

    # --- ошибка расчёта не роняет бота ---
    б, тг, _, _ = сделать_бота()
    б.построить = lambda к: 1 / 0
    б.обработать(сообщение(botmenu.ИТОГ))
    проверить("если расчёт упал, владелец получает понятное сообщение",
              тг.тексты() and "Не получилось" in тг.тексты()[-1], str(тг.тексты()))

    # --- нажатия «взял / пропустил» ---
    б, тг, переданы, _ = сделать_бота(передача_успешна=True)
    б.обработать(нажатие("t:BTCUSDT-1700"))
    проверить("нажатие передано на GitHub с решением и сигналом",
              переданы and переданы[0]["решение"] == "t"
              and переданы[0]["сигнал"] == "BTCUSDT-1700"
              and переданы[0]["сообщение"] == 77, str(переданы))
    проверить("владелец видит подтверждение и отметку в сообщении",
              "answerCallbackQuery" in тг.методы() and "editMessageReplyMarkup" in тг.методы(),
              str(тг.методы()))
    б, тг, переданы, _ = сделать_бота(передача_успешна=False)
    б.обработать(нажатие("s:BTCUSDT-1700"))
    проверить("при сбое передачи кнопки НЕ заменяются — можно нажать снова",
              "editMessageReplyMarkup" not in тг.методы(), str(тг.методы()))
    проверить("и владелец предупреждён", any(
        "Не удалось" in п.get("text", "") for м, п in тг.вызовы if м == "answerCallbackQuery"))
    б, тг, переданы, _ = сделать_бота()
    б.обработать(нажатие("x"))
    проверить("повторное нажатие на отметку ничего не передаёт", not переданы)

    # --- смещение ---
    б, тг, _, _ = сделать_бота()
    б.телеграм = lambda м, п, таймаут=30: {"ok": True, "result": [
        {"update_id": 41, "message": {"chat": {"id": 999}, "text": "x"}},
        {"update_id": 42, "message": {"chat": {"id": 999}, "text": "y"}}]}
    б.шаг()
    проверить("после опроса смещение за последним обновлением", б.смещение == 43, str(б.смещение))

    # --- decide.py: что можно записывать ---
    н, _ = decide.разобрать(json.dumps({"решение": "t", "сигнал": "BTCUSDT-1", "чат": 555}), "555")
    проверить("decide: нормальное нажатие принимается", н and н["сигнал"] == "BTCUSDT-1")
    н, почему = decide.разобрать(json.dumps({"решение": "t", "сигнал": "BTCUSDT-1", "чат": 9}), "555")
    проверить("decide: нажатие из чужого чата отвергается", н is None and "чата" in почему, почему)
    н, почему = decide.разобрать(json.dumps({"решение": "buy", "сигнал": "X"}), "555")
    проверить("decide: неизвестное решение отвергается", н is None, почему)
    н, почему = decide.разобрать("{битое", "555")
    проверить("decide: испорченные данные отвергаются", н is None, почему)
    н, почему = decide.разобрать(json.dumps({"проверка": True}), "555")
    проверить("decide: проверка пути не пишет ничего", н is None and почему.startswith("проверка"))

    # --- цифры бота = цифры кабинета, по скачанным журналам ---
    папка = tempfile.mkdtemp()
    журналы(папка)
    исходная = pnl.ПАПКА
    цены = {"SOLUSDT": 110.0, "ETHUSDT": 12.0}
    with remote.журналы_из(папка):
        текст = botmenu.итог(цены)
        р = pnl.подсчитать(цены)["сводка_рекомендаций"]
        позиции = botmenu.позиции(цены)
        сделки = botmenu.сделки(цены)
        обучение = botmenu.обучение()
        состояние = botmenu.состояние([{"created_at": "2026-09-13T10:00:00Z",
                                        "status": "completed", "conclusion": "success"}], {})
    проверить("после блока модули снова смотрят в state/", pnl.ПАПКА == исходная, pnl.ПАПКА)
    # SOL: вход 100, стоп 90, сейчас 110 — +1R по 0.5 $ = +0.50; LTC закрыта −1R по 0.25 = −0.25
    проверить("итог бота считан по скачанным журналам: +0.50 − 0.25 = +0.25 $",
              abs(р["итог"] - 0.25) < 1e-9 and "+0,25 $" in текст, f"{р['итог']} | {текст}")
    проверить("тень в итог нашего счёта не попала (ETH — теневая)",
              "ETH" not in позиции, позиции)
    проверить("позиции показывают SOL с текущей ценой и результатом",
              "SOL" in позиции and "+0,50 $" in позиции, позиции)
    проверить("закрытые сделки показывают LTC по стопу",
              "LTC" in сделки and "стоп" in сделки, сделки)
    проверить("обучение показывает все 11 вариантов",
              обучение.count("%:") == 11, обучение)
    проверить("состояние показывает проход прорывов и запуск GitHub",
              "прорывы" in состояние and "успешно" in состояние, состояние)
    for имя, т in (("итог", текст), ("позиции", позиции), ("сделки", сделки),
                   ("обучение", обучение), ("состояние", состояние)):
        проверить(f"«{имя}» влезает в одно сообщение Telegram", len(т) < 4000, str(len(т)))

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
