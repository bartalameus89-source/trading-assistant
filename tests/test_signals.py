ПРОВАЛЫ: list[str] = []
ВСЕГО = 0


def проверить(имя: str, условие: bool, подробности: str = "") -> None:
    global ВСЕГО
    ВСЕГО += 1
    if условие:
        print(f"  OK   {имя}")
    else:
        print(f"  ПРОВАЛ {имя}  {подробности}")
        ПРОВАЛЫ.append(имя)


def свечи_из(закрытия: list[float], объёмы: list[float] | None = None) -> Свечи:
    n = len(закрытия)
    шаг = ДЛИТЕЛЬНОСТЬ_БАРА_МИН[CFG["таймфрейм"]] * 60 * 1000
    конец = int(datetime.now(timezone.utc).timestamp() * 1000)
    конец -= конец % шаг
    return Свечи(
        актив="TESTUSDT", таймфрейм=CFG["таймфрейм"], источник="тест",
        времена=[конец - (n - 1 - i) * шаг for i in range(n)],
        opens=[c - 0.2 for c in закрытия],
        highs=[c + 1.0 for c in закрытия],
        lows=[c - 1.0 for c in закрытия],
        closes=закрытия,
        volumes=объёмы or [1000.0] * n,
    )


def ряд(наклон: float, амплитуда: float, период: float, n: int = 400,
        зерно: int = 7) -> list[float]:
    состояние = зерно
    def шум() -> float:
        nonlocal состояние
        состояние = (состояние * 1103515245 + 12345) % (2 ** 31)
        return состояние / (2 ** 31) - 0.5
    return [100 + i * наклон + math.sin(i / период) * амплитуда + шум() * 1.1
            for i in range(n)]


