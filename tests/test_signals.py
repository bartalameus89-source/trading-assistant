def тест_направление_следует_режиму():
    """Главный дефект, найденный на реальных данных BTC: система выдала Long
    при режиме «тренд вниз», опираясь только на моментум и объём."""
    print("\n1. Направление сделки не противоречит режиму рынка")

    # Нисходящий тренд, но последний бар — резкий рост на большом объёме,
    # то есть моментум и объём кричат «покупай».
    закр = ряд(наклон=-0.30, амплитуда=7.5, период=26)
    закр[-1] = закр[-1] + 6.0
    объёмы = [1000.0] * (len(закр) - 1) + [3000.0]

    а = signals.проанализировать(свечи_из(закр, объёмы), CFG, флаги_данных=[],
                                 депозит=10000.0)
    проверить(f"режим определён как тренд вниз ({а.режим.направление})",
              а.режим.направление == "тренд вниз", а.режим.пояснение)
    проверить("Long в нисходящем тренде не выдан",
              а.направление != "Long", f"направление={а.направление}")

    # Зеркально: восходящий тренд, резкое падение последнего бара.
    закр2 = ряд(наклон=0.30, амплитуда=7.5, период=26, зерно=11)
    закр2[-1] = закр2[-1] - 6.0
    а2 = signals.проанализировать(свечи_из(закр2, объёмы), CFG, флаги_данных=[],
                                  депозит=10000.0)
    проверить(f"режим определён как тренд вверх ({а2.режим.направление})",
              а2.режим.направление == "тренд вверх", а2.режим.пояснение)
    проверить("Short в восходящем тренде не выдан",
              а2.направление != "Short", f"направление={а2.направление}")


def тест_тег_соответствует_режиму():
    print("\n2. Тег стратегии не противоречит режиму")
    закр = ряд(наклон=0.30, амплитуда=7.5, период=26)
    а = signals.проанализировать(свечи_из(закр), CFG, флаги_данных=[], депозит=10000.0)
    if а.тег_стратегии:
        если_вверх = а.режим.направление == "тренд вверх"
        проверить("тег согласован с режимом",
                  ("_up_" in а.тег_стратегии) == если_вверх or "range" in а.тег_стратегии,
                  f"режим={а.режим.направление}, тег={а.тег_стратегии}")
    else:
        проверить("тег отсутствует, потому что сигнала нет", а.вывод != signals.СИГНАЛ)


def тест_высокая_волатильность_блокирует():
    print("\n3. Высокая волатильность останавливает генерацию сигналов")
    # Резко расширяющийся диапазон в конце ряда.
    закр = ряд(наклон=0.05, амплитуда=1.0, период=30)
    for i in range(len(закр) - 30, len(закр)):
        закр[i] += math.sin(i * 1.7) * 18
    а = signals.проанализировать(свечи_из(закр), CFG, флаги_данных=[], депозит=10000.0)
    if а.режим.волатильность == "высокая":
        проверить("вывод — риск-предупреждение", а.вывод == signals.РИСК_ПРЕДУПРЕЖДЕНИЕ)
        проверить("сигнал на вход не выдан", а.направление is None)
    else:
        проверить("волатильность не поднялась до порога — тест неинформативен",
                  True, f"перцентиль {а.режим.bbw_перцентиль:.0f}")


def тест_флаги_данных_блокируют():
    print("\n4. Флаг качества данных останавливает анализ")
    закр = ряд(наклон=0.30, амплитуда=7.5, период=26)
    а = signals.проанализировать(свечи_из(закр), CFG,
                                 флаги_данных=["разрывы в истории: 4 промежутка"],
                                 депозит=10000.0)
    проверить("вывод — риск-предупреждение", а.вывод == signals.РИСК_ПРЕДУПРЕЖДЕНИЕ)
    проверить("причина названа", any("качество данных" in п for п in а.причины_отказа))


def тест_группы_считаются_раздельно():
    print("\n5. Два подтверждения из одной группы не заменяют двух групп")
    закр = ряд(наклон=0.30, амплитуда=7.5, период=26)
    а = signals.проанализировать(свечи_из(закр), CFG, флаги_данных=[], депозит=10000.0)
    if а.подтверждения:
        группы = [п.группа for п in а.подтверждения]
        проверить("в каждой группе не более одного подтверждения",
                  len(группы) == len(set(группы)), f"{группы}")
    if а.вывод == signals.СИГНАЛ:
        проверить("задействовано групп не меньше минимума",
                  len(а.группы) >= CFG["сигналы"]["мин_подтверждений"], f"{а.группы}")
    else:
        проверить("сигнала нет — проверять нечего", True)


def тест_лимиты_риска_блокируют_до_анализа():
    print("\n6. Исчерпанный лимит убытка останавливает до расчётов")
    закр = ряд(наклон=0.30, амплитуда=7.5, период=26)
    а = signals.проанализировать(свечи_из(закр), CFG, флаги_данных=[], депозит=10000.0,
                                 лимит_убытка_исчерпан=True)
    проверить("вывод — риск-предупреждение", а.вывод == signals.РИСК_ПРЕДУПРЕЖДЕНИЕ)
    проверить("план не строился", а.план is None)

    б = signals.проанализировать(свечи_из(закр), CFG, флаги_данных=[], депозит=10000.0,
                                 серия_убытков=3)
    проверить("серия убытков тоже останавливает", б.вывод == signals.РИСК_ПРЕДУПРЕЖДЕНИЕ)


