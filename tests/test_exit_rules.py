"""
Частичная фиксация: часть прибыли берём на цели, остаток едет дальше.

Правило появилось из вопроса владельца: зачем закрывать сделку на 1.5R,
если цена идёт выше. Простое "убрать цель и вести стопом" замерилось хуже
(+0.082R против +0.145R, а на первой половине истории ПФ 0.96 — убыток),
потому что короткая система ставит на ВОЗВРАТ цены к среднему: когда цель
достигнута, повода держать позицию больше нет.

Работает середина: 70% забрать на цели, остаток отпустить с плотным стопом
в 1.0 ATR. Замер: +0.151R против +0.145R, ПФ 1.36 против 1.35, и потолок
сделки поднимается с 1.5R до 3.1R.

Запуск:  python tests/test_exit_rules.py
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from engine import exit_rules as пр

провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def позиция(**правки) -> пр.Состояние:
    """Лонг: вход 100, стоп 90 (риск 10), цель 115 (1.5R)."""
    осн = dict(направление="Long", цена_входа=100.0, стоп=90.0,
               стоп_начальный=90.0, цель=115.0, atr=5.0,
               порог_безубытка=0.75, доля_на_цели=0.7, трейлинг_atr=1.0)
    осн.update(правки)
    return пр.Состояние(**осн)


def главное() -> int:
    print("ЧАСТИЧНАЯ ФИКСАЦИЯ И ВЕДЕНИЕ ОСТАТКА\n")

    # --- обычный ход: стоп ---
    с = позиция()
    ш = пр.провести_бар(с, high=101, low=89)
    проверить("стоп закрывает всю позицию", ш.состояние == пр.ЗАКРЫТА)
    проверить("результат ровно -1R", abs(ш.результат_R + 1.0) < 1e-9,
              f"R={ш.результат_R}")

    # --- цель: забираем часть, остаток остаётся ---
    с = позиция()
    ш = пр.провести_бар(с, high=116, low=99)
    проверить("на цели позиция НЕ закрывается целиком",
              ш.состояние == пр.ДЕРЖИМ, f"{ш.состояние}")
    проверить("зафиксировано 70% от 1.5R = 1.05R",
              abs(с.взято_R - 1.05) < 1e-9, f"взято {с.взято_R}")
    проверить("в рынке остаётся 30%", abs(с.осталось - 0.3) < 1e-9)
    проверить("стоп остатка переставлен на цену входа", с.стоп == 100.0)
    проверить("событие объясняет, что произошло",
              ш.событие and "остаток" in ш.событие, str(ш.событие))

    # --- остаток едет: стоп ползёт за ценой ---
    пр.провести_бар(с, high=130, low=120)
    проверить("стоп подтянулся за ценой (130 - 1 ATR = 125)",
              abs(с.стоп - 125.0) < 1e-9, f"стоп {с.стоп}")
    прежний = с.стоп
    пр.провести_бар(с, high=126, low=124)
    проверить("стоп не опускается обратно", с.стоп == прежний, f"стоп {с.стоп}")

    # --- остаток закрылся: считаем ОБЕ части ---
    ш = пр.провести_бар(с, high=126, low=120)
    проверить("остаток закрыт по подтянутому стопу", ш.состояние == пр.ЗАКРЫТА)
    ожидаемо = 1.05 + 0.3 * ((125.0 - 100.0) / 10.0)
    проверить("итог складывает зафиксированное и остаток",
              abs(ш.результат_R - ожидаемо) < 1e-9,
              f"получили {ш.результат_R}, ждали {ожидаемо}")
    проверить("итог БОЛЬШЕ старого потолка 1.5R", ш.результат_R > 1.5,
              f"{ш.результат_R}")
    проверить("исход назван отдельно", ш.исход == "остаток закрыт", str(ш.исход))

    # --- разворот сразу после фиксации: хуже взятого не будет ---
    с = позиция()
    пр.провести_бар(с, high=116, low=99)
    ш = пр.провести_бар(с, high=101, low=95)
    проверить("разворот после фиксации: закрылись по безубытку",
              ш.состояние == пр.ЗАКРЫТА and abs(ш.результат_R - 1.05) < 1e-9,
              f"R={ш.результат_R}")

    # --- старое поведение сохранено, если доля не задана ---
    с = позиция(доля_на_цели=0.0)
    ш = пр.провести_бар(с, high=116, low=99)
    проверить("без доли цель закрывает всё, как раньше",
              ш.состояние == пр.ЗАКРЫТА and abs(ш.результат_R - 1.5) < 1e-9,
              f"R={ш.результат_R}")

    # --- перенос в безубыток ДО цели ---
    с = позиция()
    ш = пр.провести_бар(с, high=108, low=99)   # +0.8R
    проверить("до цели стоп уходит в безубыток", с.стоп == 100.0)
    проверить("но позиция остаётся открытой", ш.состояние == пр.ДЕРЖИМ)
    проверить("это НЕ трейлинг: дальше стоп не ползёт",
              (пр.провести_бар(с, high=112, low=105), с.стоп == 100.0)[1],
              f"стоп {с.стоп}")

    # --- шорт зеркально ---
    с = позиция(направление="Short", цена_входа=100.0, стоп=110.0,
                стоп_начальный=110.0, цель=85.0)
    ш = пр.провести_бар(с, high=101, low=84)
    проверить("шорт: на цели тоже фиксируется часть",
              ш.состояние == пр.ДЕРЖИМ and abs(с.взято_R - 1.05) < 1e-9,
              f"взято {с.взято_R}")
    пр.провести_бар(с, high=80, low=70)
    проверить("шорт: стоп ползёт ВНИЗ (70 + 1 ATR = 75)",
              abs(с.стоп - 75.0) < 1e-9, f"стоп {с.стоп}")

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
