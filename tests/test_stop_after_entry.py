"""
Стоп нельзя проверять по ценам, случившимся ДО входа.

Ошибка, которую ловит этот тест, встречалась в бою и подделывала результаты.
Дневная свеча ещё не закрыта: утром цена упала, потом выросла, и мы вошли
днём по высокой цене. Система сверяла стоп с минимумом ВСЕГО дня — то есть
с утренним провалом, которого при нашей позиции не существовало.

Реальный случай 21.08: XRP открылся 1.2681, упал до 1.2588, вырос до 1.4544.
Вход был по 1.3763, стоп 1.25884. Позицию закрыли по стопу в день,
когда монета выросла на +14.7%. AAVE в тот же день закрыли по 99.53,
а он дошёл до 122.69 и через десять дней стоил 126.

Хуже одной сделки: место освобождалось, тут же открывалась новая позиция
по той же монете, и на следующем проходе всё повторялось — цикл,
печатающий -1R на ровном месте.

Запуск:  python tests/test_stop_after_entry.py
"""

from __future__ import annotations

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

ЧАС = 3600 * 1000
провалено = 0


def проверить(имя: str, условие: bool, факт: str = "") -> None:
    global провалено
    if условие:
        print(f"  OK   {имя}")
    else:
        провалено += 1
        print(f"  НЕТ  {имя}  {факт}")


def минимум_после_входа(времена: list[int], lows: list[float],
                        начало_входа: float) -> float | None:
    """Та же логика, что в breakouts.py и paper_long.py."""
    после = [i for i, t in enumerate(времена) if t > начало_входа]
    return min((lows[i] for i in после), default=None)


def главное() -> int:
    print("СТОП ПРОВЕРЯЕТСЯ ТОЛЬКО ПО ЦЕНАМ ПОСЛЕ ВХОДА\n")

    # Случай XRP 21.08, числа настоящие.
    времена = [1_000 * ЧАС, 1_024 * ЧАС]       # вчерашний день и сегодняшний
    lows = [1.0879, 1.2588]                     # минимум сегодня — утренний
    вход, стоп = 1.3763, 1.25884

    # Вошли ВНУТРИ сегодняшнего бара: время входа больше времени его открытия.
    начало_входа = 1_024 * ЧАС
    м = минимум_после_входа(времена, lows, начало_входа)
    проверить("день входа не учитывается — закрытых баров после входа нет",
              м is None, f"получили {м}")
    проверить("значит стоп в этот день не срабатывает",
              not (м is not None and м <= стоп))

    # Наступил следующий день, и он тоже не падал ниже стопа.
    времена.append(1_048 * ЧАС)
    lows.append(1.3780)
    м = минимум_после_входа(времена, lows, начало_входа)
    проверить("на следующий день смотрим только его минимум",
              abs(м - 1.3780) < 1e-9, f"получили {м}")
    проверить("стоп по-прежнему не задет (1.3780 > 1.25884)", м > стоп)

    # А вот теперь цена действительно провалилась ниже стопа.
    времена.append(1_072 * ЧАС)
    lows.append(1.2000)
    м = минимум_после_входа(времена, lows, начало_входа)
    проверить("настоящее падение ниже стопа — срабатывает", м <= стоп,
              f"минимум {м}, стоп {стоп}")

    # Утренний провал НЕ должен попадать в расчёт даже задним числом.
    проверить("утренний минимум 1.2588 не участвует в решении",
              1.2588 not in [lows[i] for i, t in enumerate(времена)
                             if t > начало_входа])

    print("\nЛОВУШКА AAVE: вход выше дневного минимума")
    времена2 = [2_000 * ЧАС]
    lows2 = [98.53]            # минимум дня, случился до входа
    вход2, стоп2 = 109.49, 99.528
    м2 = минимум_после_входа(времена2, lows2, 2_000 * ЧАС)
    проверить("позиция, открытая внутри дня, не закрывается этим же днём",
              м2 is None or м2 > стоп2, f"минимум после входа {м2}")

    print("\nСТАРЫЕ ЗАПИСИ БЕЗ ПОЛЯ бар_входа_время")
    # Откат: если поля нет, берём время открытия позиции — оно тоже
    # внутри бара, значит бар входа так же исключается.
    открыта_в = 2_000 * ЧАС / 1000 + 3600      # через час после открытия бара
    м3 = минимум_после_входа(времена2, lows2, открыта_в * 1000)
    проверить("откат на открыта_в работает так же", м3 is None,
              f"получили {м3}")

    print()
    if провалено:
        print(f"ПРОВАЛЕНО ПРОВЕРОК: {провалено}")
        return 1
    print("ВСЕ ПРОВЕРКИ ПРОЙДЕНЫ")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
