"""
Порог высокой волатильности для короткой системы: замер ряда значений.

Повод. Вживую фильтр высокой волатильности отсёк больше всего сигналов
короткой системы — 24 из 47 теневых за три недели, и сделок почти нет.
Владелец предложил ослабить фильтр на 60%. Сейчас волатильность считается
высокой, если ширина полос Боллинджера на 80-м перцентиле или выше за 90
баров, то есть фильтр закрывает самые беспокойные 20% времени. Ослабить
на 60% — сузить эту зону до 8%: порог 92.

Одно значение не мерим: смотрим ряд, чтобы видеть, монотонна ли
зависимость. Немонотонная — шум, а не закономерность.

Как. Бэктест короткой системы (backtest.провести_сделку, та же логика)
на одних и тех же свечах для каждого порога, параллельно на всех ядрах.
Потом каждый вариант — через общий портфель вместе с прорывами и
долгосрочной (engine/portsim.py), по обеим половинам истории. Монеты,
которые короткая система не торгует, в замер не идут.

    python vol_threshold.py
"""

from __future__ import annotations

import copy
import json
import os
import pickle
import sys
from concurrent.futures import ProcessPoolExecutor

import backtest
from engine import data, portsim, signals

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ПОРОГИ = [80.0, 85.0, 88.0, 92.0, 95.0, 101.0]      # 101 — фильтра нет
КЛЮЧ = "bbw_высокая_волатильность_перцентиль"
ПАПКА = os.path.join(БАЗА, "export", "vol_threshold")


def раздел_порога(cfg: dict) -> str:
    return next(к for к, v in cfg.items() if isinstance(v, dict) and КЛЮЧ in v)


def прогнать(задание: tuple[float, str]) -> tuple[float, str, list[dict]]:
    порог, актив = задание
    with open(os.path.join(ПАПКА, f"{актив}.pkl"), "rb") as f:
        свечи = pickle.load(f)
    cfg = copy.deepcopy(CFG)
    cfg[раздел_порога(cfg)][КЛЮЧ] = порог
    сделки: list[dict] = []
    занят_до = -1
    for i in range(backtest.РАЗОГРЕВ, len(свечи) - 2):
        if i <= занят_до:
            continue
        а = signals.проанализировать(backtest.срез(свечи, i), cfg, флаги_данных=[],
                                     депозит=cfg["риск"]["депозит"],
                                     проверять_свежесть=False)
        if а.вывод != signals.СИГНАЛ:
            continue
        с = backtest.провести_сделку(свечи, i, а.план, cfg)
        if с:
            сделки.append({"актив": с.актив, "направление": с.направление,
                           "время_входа": с.время_входа, "время_выхода": с.время_выхода,
                           "исход": с.исход, "r": с.r_чистый})
            занят_до = с.бар_выхода
    return порог, актив, сделки


def главное() -> int:
    os.makedirs(ПАПКА, exist_ok=True)
    исключить = set(CFG["сигналы"].get("исключить_из_короткой", []))
    активы = [а for а in CFG["активы"] if а not in исключить]

    # Свечи тянем один раз, чтобы все пороги мерились на одних данных.
    for а in активы:
        п = os.path.join(ПАПКА, f"{а}.pkl")
        if os.path.exists(п):
            continue
        свечи = data.загрузить_глубоко(а, CFG["таймфрейм"], баров=backtest.ГЛУБИНА,
                                       источники=CFG["источник_данных"])
        with open(п, "wb") as f:
            pickle.dump(свечи, f)
        print(f"  свечи {а}: {len(свечи)}", flush=True)

    задания = [(п, а) for п in ПОРОГИ for а in активы]
    по_порогу: dict[float, list[dict]] = {п: [] for п in ПОРОГИ}
    with ProcessPoolExecutor(max_workers=max(1, (os.cpu_count() or 2) - 1)) as пул:
        for готово, (порог, актив, сделки) in enumerate(пул.map(прогнать, задания), 1):
            по_порогу[порог].extend(сделки)
            print(f"  [{готово}/{len(задания)}] порог {порог:g} {актив}: {len(сделки)}",
                  flush=True)

    with open(os.path.join(ПАПКА, "итог.json"), "w", encoding="utf-8") as f:
        json.dump({str(k): v for k, v in по_порогу.items()}, f, ensure_ascii=False)

    п = CFG["портфель"]
    пределы = {"медленных": п["макс_общий_риск_пр"], "быстрых": п["макс_риск_быстрых_пр"],
               "позиций": п["макс_всего_позиций"], "в_день": п.get("макс_сделок_в_день", 0),
               "прорывов": CFG["прорывы"].get("макс_позиций", 10)}
    ставки = {"короткая": CFG["риск"]["стартовый_риск_на_сделку_пр"],
              "долгосрочная": CFG["долгосрочная"]["риск_на_позицию_пр"],
              "прорывы": CFG["прорывы"]["риск_на_позицию_пр"]}
    медленные = portsim.загрузить({"долгосрочная", "прорывы"})

    дни = None
    строки = []
    for порог in ПОРОГИ:
        сырые = sorted(по_порогу[порог], key=lambda x: x["время_входа"])
        R = [x["r"] for x in сырые]
        г = len(R) // 2
        короткие = [{"система": "короткая", "актив": x["актив"], "когда": float(x["время_входа"]),
                     "вход": portsim.день(x["время_входа"]), "выход": portsim.день(x["время_выхода"]),
                     "r": float(x["r"]), "путь": None} for x in сырые]
        if дни is None:
            дни = portsim.календарь(короткие)
        все = sorted(медленные + короткие, key=lambda с: (с["когда"], с["система"], с["актив"]))
        for раздельно in (False, True):
            и = portsim.прогнать(все, дни, ставки, {**пределы, "монеты_раздельно": раздельно})
            в = portsim.показатели(и["кривая"], и["песс"])
            п1, п2 = portsim.по_половинам(и)
            строки.append((порог, раздельно, len(R), sum(R) / len(R) if R else 0,
                           sum(R[:г]), sum(R[г:]), в, п1, п2, и))

    print("\n  порог  монеты     сделок  R/сделку  половины R        годовых  просадка  отношение  половины       вклад корот.  риск разом")
    for порог, раздельно, n, ср, h1, h2, в, п1, п2, и in строки:
        имя = "без фильтра" if порог > 100 else f"{порог:g}"
        print(f"  {имя:>11} {'раздельно' if раздельно else 'как сейчас':10} {n:5d} {ср:+8.3f}  {h1:+7.1f} / {h2:+6.1f}"
              f"   {в['годовых_пр']:+6.1f}% {в['просадка_пр']:7.1f}%  {в['отношение']:8.2f}  "
              f"{п1['отношение']:5.2f} / {п2['отношение']:5.2f}   {и['вклад'].get('короткая', 0):+7.0f}$   "
              f"{и['макс_разом_пр']:5.1f}%")
    return 0


if __name__ == "__main__":
    sys.exit(главное())
