"""
Прогон правил по реальной истории: на каждом баре прошлого задаём вопрос
«что сказала бы система, если бы стояла здесь?» — и смотрим, где она дала вход.

Это ЕЩЁ НЕ бэктест: здесь нет проверки, чем закончилась сделка, нет комиссий
по факту исполнения и нет walk-forward разбиения (раздел 10 промта). Задача
проще и честнее — понять, как часто правила вообще пропускают сделку,
и увидеть настоящую карточку сигнала на настоящих данных.

Запуск:  python scan_history.py            все активы из конфига
         python scan_history.py BTCUSDT    один актив
"""

from __future__ import annotations

import json
import os
import sys
from dataclasses import replace

from engine import data, render, signals

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))

# Сколько баров нужно индикаторам, прежде чем их значения вообще определены.
РАЗОГРЕВ = 240


def срез(свечи: data.Свечи, до: int) -> data.Свечи:
    """Свечи по индекс `до` включительно — то, что было видно на том баре.
    Ни одного значения из будущего здесь быть не должно."""
    return replace(
        свечи,
        времена=свечи.времена[:до + 1],
        opens=свечи.opens[:до + 1],
        highs=свечи.highs[:до + 1],
        lows=свечи.lows[:до + 1],
        closes=свечи.closes[:до + 1],
        volumes=свечи.volumes[:до + 1],
    )


def прогнать(актив: str) -> None:
    свечи = data.загрузить(актив, CFG["таймфрейм"], лимит=1000,
                           источники=CFG["источник_данных"])

    всего = 0
    статистика: dict[str, int] = {}
    сигналы: list[tuple[int, signals.Анализ]] = []

    for i in range(РАЗОГРЕВ, len(свечи)):
        всего += 1
        а = signals.проанализировать(
            срез(свечи, i), CFG, флаги_данных=[],
            депозит=10000.0,              # условный депозит только для расчёта размера
            проверять_свежесть=False,
        )
        if а.вывод == signals.СИГНАЛ:
            сигналы.append((i, а))
            ключ = "СИГНАЛ"
        elif а.план and а.план.нарушения:
            # Группируем по НАЗВАНИЮ правила, а не по конкретным числам, —
            # иначе каждое значение R:R становится отдельной строкой статистики.
            ключ = "не прошло правило: " + а.план.нарушения[0].правило
        elif а.причины_отказа:
            ключ = а.причины_отказа[0].split(":")[0][:48]
        else:
            ключ = а.вывод
        статистика[ключ] = статистика.get(ключ, 0) + 1

    период = (f"{свечи.время_последнего_бара:%Y-%m-%d}")
    print("\n" + "=" * 62)
    print(f"  {актив} {CFG['таймфрейм']} — прогон по {всего} барам "
          f"(история до {период})")
    print("=" * 62)
    print(f"  Сигналов на вход: {len(сигналы)}  "
          f"({len(сигналы) / всего * 100:.1f}% баров)")
    print()
    print("  Что останавливало систему чаще всего:")
    for ключ, n in sorted(статистика.items(), key=lambda kv: -kv[1]):
        доля = n / всего * 100
        print(f"    {n:5d}  ({доля:5.1f}%)  {ключ}")

    if сигналы:
        индекс, лучший = max(
            сигналы,
            key=lambda п: (п[1].уверенность == "высокая",
                           п[1].план.rr_по_целям[0] if п[1].план else 0),
        )
        когда = свечи.времена[индекс]
        from datetime import datetime, timezone
        дата = datetime.fromtimestamp(когда / 1000, tz=timezone.utc)
        print()
        print("  " + "-" * 58)
        print(f"  ПРИМЕР РЕАЛЬНОГО СИГНАЛА — бар от {дата:%Y-%m-%d %H:%M} UTC")
        print("  Депозит для расчёта размера взят условный: 10 000")
        print("  " + "-" * 58)
        print(render.консоль(лучший, валидатор_есть=True))


if __name__ == "__main__":
    активы = sys.argv[1:] or CFG["активы"]
    for актив in активы:
        try:
            прогнать(актив)
        except Exception as e:
            print(f"\n{актив}: ОШИБКА -> {type(e).__name__}: {e}")
