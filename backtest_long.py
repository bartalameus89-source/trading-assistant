"""
Бэктест долгосрочной стратегии. Отдельно от короткой — это разные системы,
и смешивать их результаты нельзя.

Отличия симуляции от короткого бэктеста:
  - дневные свечи, история до 1000 дней (около 2.7 лет);
  - выход не по цели, а по слому тренда (закрытие дня ниже MA50)
    либо по стопу;
  - предел удержания 250 дней — иначе позиция висит до конца истории
    и результат зависит от того, где закончились данные;
  - издержки берутся один раз за круг: долгая позиция не платит комиссию
    каждый день, в отличие от частой торговли.

Запуск:  python backtest_long.py
"""

from __future__ import annotations

import json
import os
from dataclasses import replace

from engine import data, indicators as ind, longterm

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
РАЗОГРЕВ = 210          # MA200 плюс запас
ПРЕДЕЛ_ДНЕЙ = 250


def срез(свечи: data.Свечи, до: int) -> data.Свечи:
    от = max(0, до + 1 - 400)      # глубже MA200 анализ не смотрит
    return replace(
        свечи,
        времена=свечи.времена[от:до + 1], opens=свечи.opens[от:до + 1],
        highs=свечи.highs[от:до + 1], lows=свечи.lows[от:до + 1],
        closes=свечи.closes[от:до + 1], volumes=свечи.volumes[от:до + 1],
    )


def прогнать(актив: str) -> list[dict]:
    свечи = data.загрузить_глубоко(актив, "1d", баров=3000,
                                   источники=CFG["источник_данных"])
    if len(свечи) < РАЗОГРЕВ + 30:
        return []

    ma50_ряд = ind.sma(свечи.closes, 50)
    сделки: list[dict] = []
    занят_до = -1

    for i in range(РАЗОГРЕВ, len(свечи) - 2):
        if i <= занят_до:
            continue
        в = longterm.проанализировать_долгий(срез(свечи, i), CFG)
        if в.вывод != longterm.ЕСТЬ_ПОТЕНЦИАЛ:
            continue

        вход = свечи.opens[i + 1]          # покупаем на открытии следующего дня
        стоп = в.стоп
        риск = вход - стоп
        if риск <= 0:
            continue

        исход, выход, j = "конец истории", свечи.closes[-1], len(свечи) - 1
        предел = min(i + 1 + ПРЕДЕЛ_ДНЕЙ, len(свечи) - 1)
        for j in range(i + 1, предел + 1):
            if свечи.lows[j] <= стоп:
                исход, выход = "стоп", стоп
                break
            # Слом тренда: закрытие дня ниже MA50. Выходим по закрытию.
            if ma50_ряд[j] is not None and свечи.closes[j] < ma50_ряд[j]:
                исход, выход = "слом тренда", свечи.closes[j]
                break
        else:
            j = предел
            исход, выход = "предел по времени", свечи.closes[предел]

        и = CFG["издержки"]
        издержки_отн = (и["комиссия_вход_пр"] + и["комиссия_выход_пр"]
                        + и["проскальзывание_пр"]) / 100
        r = (выход - вход) / риск - издержки_отн * вход / риск
        сделки.append({
            "актив": актив, "бар": i, "вход": вход, "стоп": стоп,
            "выход": выход, "исход": исход, "r": r,
            "дней": j - i, "рост_проц": (выход / вход - 1) * 100,
        })
        занят_до = j
    return сделки


def главное() -> None:
    все: list[dict] = []
    for актив in CFG["активы"]:
        try:
            с = прогнать(актив)
        except Exception as e:
            print(f"  {актив:10s} ошибка: {type(e).__name__}")
            continue
        все.extend(с)
        итог = sum(x["r"] for x in с)
        побед = sum(1 for x in с if x["r"] > 0)
        print(f"  {актив:10s} сделок {len(с):3d}  побед {побед:3d}  итог {итог:+7.2f}R")

    if not все:
        print("\nСделок не нашлось.")
        return

    R = [x["r"] for x in все]
    победы = [r for r in R if r > 0]
    убытки = [r for r in R if r <= 0]
    накоп = пик = просадка = 0.0
    for r in R:
        накоп += r
        пик = max(пик, накоп)
        просадка = min(просадка, накоп - пик)

    исходы: dict[str, int] = {}
    for x in все:
        исходы[x["исход"]] = исходы.get(x["исход"], 0) + 1

    print(f"\n{'=' * 62}")
    print("  ДОЛГОСРОЧНАЯ СТРАТЕГИЯ")
    print(f"{'=' * 62}")
    print(f"  Сделок:            {len(R)}")
    print(f"  Прибыльных:        {len(победы)} ({len(победы) / len(R) * 100:.1f}%)")
    print(f"  Итог:              {sum(R):+.2f}R  (среднее {sum(R) / len(R):+.3f}R)")
    пф = sum(победы) / abs(sum(убытки)) if убытки else float("inf")
    print(f"  Профит-фактор:     {пф:.2f}")
    print(f"  Макс. просадка:    {просадка:.2f}R")
    print(f"  Средний срок:      {sum(x['дней'] for x in все) / len(все):.0f} дней")
    print(f"  Средний ход цены:  {sum(x['рост_проц'] for x in все) / len(все):+.1f}%")
    лучшая = max(все, key=lambda x: x["рост_проц"])
    print(f"  Лучшая сделка:     {лучшая['актив'].replace('USDT','')} "
          f"{лучшая['рост_проц']:+.1f}% за {лучшая['дней']} дней")
    print(f"  Чем закрывались:   " + ", ".join(f"{к} — {v}" for к, v in исходы.items()))

    # Проверка на подгонку: делим хронологически пополам.
    все.sort(key=lambda x: x["бар"])
    г = len(все) // 2
    for имя, часть in (("первая половина", все[:г]), ("вторая половина", все[г:])):
        r2 = [x["r"] for x in часть]
        п2 = [r for r in r2 if r > 0]
        у2 = [r for r in r2 if r <= 0]
        пф2 = sum(п2) / abs(sum(у2)) if у2 else float("inf")
        print(f"  {имя}: {len(r2)} сделок, {len(п2) / len(r2) * 100:.0f}% побед, "
              f"итог {sum(r2):+.2f}R, ПФ {пф2:.2f}")

    with open(os.path.join(БАЗА, "trades_long.json"), "w", encoding="utf-8") as f:
        json.dump(все, f, ensure_ascii=False, indent=1)
    print(f"\n  Сделки сохранены в trades_long.json")


if __name__ == "__main__":
    главное()
