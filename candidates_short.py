"""
Больше монет для короткой системы: отбор ТОЛЬКО по ликвидности.

Зачем. Короткая система зарабатывает количеством сделок, а не размером:
+0.17R на сделку, и вход по рынку вместо ожидания цены убивает преимущество
до нуля. Значит, больше её сделок можно получить только одним способом —
дать ей больше монет, не опуская планку для каждой сделки.

Почему отбор по ликвидности, а не по результату. Прошлая попытка брала
монеты со слабой связью с биткоином — они оказались неликвидными (оборот
3–17 млн $ в день), и система на них работала втрое слабее. А выбирать
монеты по тому, как система на них сработала в прошлом, — подгонка: на тех
же данных любая выборка «лучших» выглядит хорошо. Поэтому правило отбора
задаётся ДО прогона и от результата не зависит:

  * пара к USDT, не стейблкоин, не обёртка, не золото, не плечевой токен;
  * самые оборотистые за сутки, кроме тех 15, что уже торгуются;
  * история на четырёхчасовых не короче двух лет — иначе не с чем делить
    выборку на половины.

Решение о приёме принимается по ВСЕЙ группе сразу, через портфель,
по обеим половинам истории — а не монета за монетой.

    python candidates_short.py [сколько]     по умолчанию 10 кандидатов
    сохраняет trades_candidates.json в формате trades.json
"""

from __future__ import annotations

import json
import os
import sys

import backtest
import scan_universe
from engine import data

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))

# Сверх исключений scan_universe: обёртки и привязанные к активам токены —
# их цена повторяет другой актив, самостоятельного движения у них нет.
НЕ_МОНЕТЫ = {"WBTCUSDT", "WBETHUSDT", "PAXGUSDT", "XAUTUSDT", "USD1USDT",
             "RLUSDUSDT", "BFUSDUSDT", "USDEUSDT", "AEURUSDT", "EURIUSDT"}
МИН_БАРОВ = 2 * 365 * 6          # два года четырёхчасовых баров


def список_по_обороту() -> list[str]:
    """Сначала живой список биржи; если она недоступна — сохранённый
    список рынка (он тоже упорядочен по обороту)."""
    try:
        return scan_universe.топ_пары(80)
    except Exception as e:
        print(f"Биржа не отдала список ({type(e).__name__}) — беру cache/universe.json")
        with open(os.path.join(БАЗА, "cache", "universe.json"), encoding="utf-8") as f:
            return json.load(f)


def главное() -> int:
    сколько = int(sys.argv[1]) if len(sys.argv) > 1 else 10
    уже = set(CFG["активы"])
    кандидаты: list[str] = []
    for п in список_по_обороту():
        if п in уже or п in НЕ_МОНЕТЫ or п in scan_universe.ИСКЛЮЧИТЬ:
            continue
        if п.endswith(scan_universe.ПЛЕЧЕВЫЕ):
            continue
        try:
            свечи = data.загрузить_глубоко(п, CFG["таймфрейм"], баров=backtest.ГЛУБИНА,
                                           источники=CFG["источник_данных"])
        except Exception as e:
            print(f"  {п:12s} нет истории: {type(e).__name__}")
            continue
        if len(свечи) < МИН_БАРОВ:
            print(f"  {п:12s} история {len(свечи)} баров — меньше двух лет, пропуск")
            continue
        кандидаты.append(п)
        print(f"  {п:12s} в группу ({len(свечи)} баров)")
        if len(кандидаты) >= сколько:
            break

    print(f"\nГруппа кандидатов ({len(кандидаты)}): "
          f"{', '.join(к.replace('USDT', '') for к in кандидаты)}\n")
    все = []
    for п in кандидаты:
        с = backtest.прогнать(п)
        все.extend(с)
        print(f"  {п:12s} сделок {len(с):3d}  итог {sum(x.r_чистый for x in с):+7.2f}R")

    все.sort(key=lambda с: (с.время_входа, с.актив))
    with open(os.path.join(БАЗА, "trades_candidates.json"), "w", encoding="utf-8") as f:
        json.dump([{
            "актив": с.актив, "направление": с.направление,
            "бар_входа": с.бар_входа, "бар_выхода": с.бар_выхода,
            "время_входа": с.время_входа, "время_выхода": с.время_выхода,
            "исход": с.исход, "r": round(с.r_чистый, 4), "уверенность": с.уверенность,
        } for с in все], f, ensure_ascii=False, indent=1)
    print(f"\nСделок кандидатов: {len(все)}, сохранены в trades_candidates.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
