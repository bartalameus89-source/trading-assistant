"""
Сторож: ловит МОЛЧАЛИВЫЕ поломки — когда всё зелёное, а система стоит.

Зачем понадобился. Пять суток подряд все 30 запусков автоматики были
успешными, и при этом система прорывов не выполнялась ни разу: шаг стоял
на условии по строке расписания cron, оно перестало совпадать, и GitHub
молча помечал шаг как skipped. Успешным считался запуск, который ничего
не сделал. Отдельно выяснилось, что paper_long.py не был в workflow вовсе —
долгосрочная система не торговала на бумаге ни одного дня.

Ни одна из этих поломок не даёт ошибки. Их видно только по тому, что
СОСТОЯНИЕ НЕ ДВИГАЕТСЯ. Поэтому сторож смотрит не на код, а на следы:
кто когда последний раз что-то записал, не завис ли кто, идут ли дни.

Возвращает код 1, если нашёл беду, — и тогда запуск автоматики краснеет.
Лучше красный запуск, чем зелёный, за которым ничего нет.

    python health.py            проверить и напечатать
    python health.py --тихо     только код возврата
"""

from __future__ import annotations

import json
import os
import sys
import time

from engine import heartbeat

БАЗА = os.path.dirname(os.path.abspath(__file__))
ПАПКА = os.path.join(БАЗА, "state")
ЧАС = 3600
СУТКИ = 86400


def _журнал(имя: str) -> dict:
    п = os.path.join(ПАПКА, имя)
    if not os.path.exists(п):
        return {}
    try:
        with open(п, encoding="utf-8") as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError):
        return {}


def проверить() -> tuple[list[str], list[str]]:
    """Возвращает (беды, замечания). Беды красят запуск, замечания — нет."""
    беды: list[str] = []
    замечания: list[str] = []
    сейчас = time.time()

    # --- 1. Каждая система должна отмечаться пульсом. Смотрим именно
    #        на пульс, а не на время правки журнала: журнал коротких сделок
    #        пуст, его никто не трогает, и он выглядит заброшенным, хотя
    #        система исправно ходит. А журнал прорывов выглядел живым,
    #        потому что его обновлял чужой шаг, — при том что сами прорывы
    #        пять суток не выполнялись.
    пульс = heartbeat.прочитать()
    ожидаем = {"короткие": 8 * ЧАС, "прорывы": 8 * ЧАС, "долгосрочная": 8 * ЧАС}
    for система, предел in ожидаем.items():
        отметка = пульс.get(система)
        if not отметка:
            беды.append(f"система «{система}» ни разу не отмечалась — "
                        f"её вообще не запускают")
            continue
        возраст = сейчас - отметка.get("когда", 0)
        if возраст > предел:
            беды.append(f"система «{система}» не запускалась "
                        f"{возраст / ЧАС:.0f} часов (предел {предел / ЧАС:.0f})")

    # --- 2. Позиции прорывов должны досчитываться по дням. Если проверен_до
    #        отстаёт больше чем на двое суток, проводка не идёт.
    for п in _журнал("breakouts.json").get("позиции", []):
        if п.get("состояние") != "открыта":
            continue
        пд = п.get("проверен_до")
        if not пд:
            замечания.append(f"{п['актив']}: нет отметки проверен_до")
            continue
        отставание = (сейчас - пд / 1000) / СУТКИ
        if отставание > 2.5:
            беды.append(f"{п['актив']}: последний посчитанный день "
                        f"{отставание:.1f} суток назад — проводка стоит")

    # --- 3. Никто не должен висеть с истёкшим сроком входа.
    for имя, ключ, поле in (("shadow.json", "сделки", "срок_до"),
                            ("paper.json", "сделки", "срок_до"),
                            ("decisions.json", "решения", None)):
        for з in _журнал(имя).get(ключ, []):
            if з.get("состояние") not in ("ждёт входа", "ожидает входа"):
                continue
            срок = з.get(поле) if поле else None
            if срок and сейчас > срок + 12 * ЧАС:
                беды.append(f"{имя}: {з.get('актив')} ждёт входа, "
                            f"хотя срок вышел {(сейчас - срок) / ЧАС:.0f} часов назад")

    # --- 4. Открытая позиция без движения стопа дольше двух недель
    #        подозрительна: трейлинг должен хоть раз сработать.
    for п in _журнал("breakouts.json").get("позиции", []):
        if п.get("состояние") != "открыта":
            continue
        дней = (сейчас - п.get("открыта_в", сейчас)) / СУТКИ
        сдвинут = п.get("стоп", 0) > (п.get("стоп_начальный") or 0)
        if дней > 14 and not сдвинут:
            замечания.append(f"{п['актив']}: открыта {дней:.0f} дней, "
                             f"стоп ни разу не подтянулся")

    # --- 5. Хоть что-то должно закрываться. Если за две недели работы
    #        нет ни одной закрытой сделки, торговли не происходит.
    закрытых = 0
    for имя, ключ in (("breakouts.json", "позиции"), ("shadow.json", "сделки"),
                      ("paper.json", "сделки"), ("paper_long.json", "позиции")):
        for з in _журнал(имя).get(ключ, []):
            if з.get("состояние") in ("закрыта", "завершена"):
                закрытых += 1
    самый_старый = min([(_журнал(и).get("создан") or сейчас)
                        for и in ("breakouts.json", "shadow.json",
                                  "paper.json", "paper_long.json")] or [сейчас])
    если_давно = (сейчас - самый_старый) / СУТКИ
    if если_давно > 14 and закрытых == 0:
        беды.append(f"работаем {если_давно:.0f} дней, закрытых сделок ноль — "
                    f"похоже, проводка не работает")

    return беды, замечания


def тревога_в_телеграм(беды: list[str]) -> bool:
    """Сообщение владельцу. Пишется здесь, а не в workflow: вложенный
    heredoc внутри YAML разъезжается по отступам, и проверить его можно
    только запуском. Здесь это обычный код, который проверяется тестом."""
    import urllib.parse
    import urllib.request

    токен = os.environ.get("TELEGRAM_BOT_TOKEN")
    чат = os.environ.get("TELEGRAM_CHAT_ID")
    if not токен or not чат:
        return False
    строки = ["⚠️ <b>СИСТЕМА СТОИТ</b>", ""]
    строки += ["• " + б for б in беды]
    строки += ["", "<i>Запуски зелёные, но работа не идёт. "
                   "Нужно вмешаться.</i>"]
    данные = urllib.parse.urlencode({
        "chat_id": чат, "text": "\n".join(строки), "parse_mode": "HTML",
    }).encode()
    try:
        urllib.request.urlopen(
            f"https://api.telegram.org/bot{токен}/sendMessage",
            данные, timeout=20)
        return True
    except Exception:
        return False


def главное() -> int:
    беды, замечания = проверить()
    тихо = "--тихо" in sys.argv

    if not тихо:
        print("=" * 64)
        print("  СТОРОЖ: не стоит ли система молча")
        print("=" * 64)
        for з in замечания:
            print(f"  . {з}")
        for б in беды:
            print(f"  ! {б}")
        if not беды and not замечания:
            print("  Всё движется: журналы свежие, дни досчитываются, "
                  "зависших записей нет.")
        elif not беды:
            print("\n  Бед нет, только замечания выше.")

    if беды:
        if not тихо:
            print(f"\n  НАЙДЕНО БЕД: {len(беды)}")
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
