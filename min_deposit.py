"""
С каким капиталом какие монеты вообще доступны.

Отвечает на вопрос: «хочу торговать с 10-100 $ — что из этого получится».
Считает по реальным ограничениям биржи и реальной волатильности каждой монеты.

Запуск:  python min_deposit.py
"""

from __future__ import annotations

import json
import os

from engine import data, exchange, indicators as ind

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
П = CFG["пороги"]


def типичный_стоп_проц(актив: str) -> tuple[float, float]:
    """Насколько далеко обычно оказывается стоп у этой монеты, в процентах
    от цены. Считается по нашему же правилу: 1.05 x ATR."""
    свечи = data.загрузить(актив, CFG["таймфрейм"], лимит=250,
                           источники=CFG["источник_данных"])
    atr_, _ = ind.last_defined(
        ind.atr(свечи.highs, свечи.lows, свечи.closes, П["atr_период"]))
    цена = свечи.последняя_цена
    return atr_ * CFG["риск"]["мин_стоп_atr"] * 1.05 / цена * 100, цена


def главное() -> None:
    активы = CFG["активы"]
    лимиты = exchange.загрузить_лимиты(активы)
    риск_проц = CFG["риск"]["стартовый_риск_на_сделку_пр"]

    print(f"Риск на сделку: {риск_проц}% от капитала (текущая настройка)\n")
    print(f"{'монета':10s} {'цена':>11s} {'типич. стоп':>12s} {'мин. сделка':>12s} "
          f"{'нужен капитал':>14s}")
    print("-" * 64)

    строки = []
    for актив in активы:
        try:
            стоп_проц, цена = типичный_стоп_проц(актив)
        except Exception as e:
            print(f"{актив:10s} ошибка: {type(e).__name__}")
            continue
        мин_объём = лимиты.get(актив, {}).get("мин_объём", 5.0)
        нужно = exchange.минимальный_депозит(мин_объём, стоп_проц, риск_проц)
        строки.append((актив, нужно))
        print(f"{актив:10s} {цена:11,.4f} {стоп_проц:11.2f}% {мин_объём:11.2f} $ "
              f"{нужно:13.0f} $")

    print()
    print("=" * 64)
    print("  СКОЛЬКО МОНЕТ ДОСТУПНО ПРИ РАЗНОМ КАПИТАЛЕ")
    print("=" * 64)
    for капитал in (10, 25, 50, 100, 250, 500):
        доступно = [а for а, н in строки if н <= капитал]
        сколько = len(доступно)
        рискуем = капитал * риск_проц / 100
        пометка = "" if сколько else "   <- торговать нельзя"
        print(f"  {капитал:4d} $   доступно монет: {сколько:2d} из {len(строки)}   "
              f"риск на сделку {рискуем:5.2f} ${пометка}")

    print()
    print("=" * 64)
    print("  ТО ЖЕ САМОЕ ПРИ РИСКЕ 1% ВМЕСТО 0.5%")
    print("=" * 64)
    for капитал in (10, 25, 50, 100):
        доступно = [а for а, н in строки if н / 2 <= капитал]
        print(f"  {капитал:4d} $   доступно монет: {len(доступно):2d} из {len(строки)}   "
              f"риск на сделку {капитал * 0.01:5.2f} $")


if __name__ == "__main__":
    главное()
