"""
Пробои вниз: зеркало прорыва, вход в шорт.

Крипта растёт и падает несимметрично: падения обычно резче и короче,
рост — дольше и с откатами. Поэтому нельзя просто перевернуть правила
и считать, что шорт заработает столько же. Нужен отдельный замер.

Правило зеркальное:
  вход  — цена закрылась ниже минимума за N баров;
  стоп  — выше на несколько ATR;
  выход — цена ушла выше максимума за K баров.

Запуск:  python test_breakdown.py
"""

from __future__ import annotations

import json
import os

from engine import data, indicators as ind

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ПРЕДЕЛ_БАРОВ = 250


def прогнать_шорт(свечи: data.Свечи, вход_окно: int, выход_окно: int,
                  стоп_atr: float) -> list[dict]:
    highs, lows, closes = свечи.highs, свечи.lows, свечи.closes
    atr_ряд = ind.atr(highs, lows, closes, 14)
    сделки: list[dict] = []
    занят_до = -1
    начало = max(вход_окно, выход_окно, 30)

    for i in range(начало, len(свечи) - 2):
        if i <= занят_до:
            continue
        atr_ = atr_ряд[i]
        if atr_ is None or atr_ <= 0:
            continue

        минимум = min(lows[i - вход_окно:i])
        if closes[i] >= минимум:
            continue

        вход = свечи.opens[i + 1]
        стоп = вход + atr_ * стоп_atr
        риск = стоп - вход
        if риск <= 0:
            continue

        исход, выход, j = "предел по времени", closes[-1], len(свечи) - 1
        предел = min(i + 1 + ПРЕДЕЛ_БАРОВ, len(свечи) - 1)
        for j in range(i + 1, предел + 1):
            if highs[j] >= стоп:
                исход, выход = "стоп", стоп
                break
            максимум = max(highs[max(0, j - выход_окно):j])
            if closes[j] > максимум:
                исход, выход = "выход по слому", closes[j]
                break
            стоп = min(стоп, максимум + atr_ * 0.2)
        else:
            j = предел
            выход = closes[предел]

        и = CFG["издержки"]
        издержки_отн = (и["комиссия_вход_пр"] + и["комиссия_выход_пр"]
                        + и["проскальзывание_пр"]) / 100
        r = (вход - выход) / риск - издержки_отн * вход / риск
        сделки.append({"актив": свечи.актив, "бар": i, "r": r,
                       "исход": исход, "баров": j - i,
                       "ход": (1 - выход / вход) * 100})
        занят_до = j
    return сделки


def свод(сделки: list[dict], подпись: str) -> None:
    if not сделки:
        print(f"  {подпись:30s} нет сделок")
        return
    R = [с["r"] for с in сделки]
    п = [r for r in R if r > 0]
    у = [r for r in R if r <= 0]
    пф = sum(п) / abs(sum(у)) if у else 99.0
    print(f"  {подпись:30s}{len(R):6d}{len(п) / len(R) * 100:6.0f}%"
          f"{sum(R):+9.2f}{sum(R) / len(R):+9.3f}{пф:7.2f}")


def главное() -> None:
    for имя, вх, вых in (("пробой вниз 20, выход 10", 20, 10),
                         ("пробой вниз 20, выход 20", 20, 20),
                         ("пробой вниз 55, выход 20", 55, 20)):
        все: list[dict] = []
        for актив in CFG["активы"]:
            try:
                с = data.загрузить_глубоко(актив, "1d", баров=3000,
                                           источники=CFG["источник_данных"])
            except Exception:
                continue
            все.extend(прогнать_шорт(с, вх, вых, 2.0))
        if not все:
            continue
        все.sort(key=lambda с: с["бар"])
        г = len(все) // 2
        print(f"\n{имя}")
        print(f"  {'часть':30s}{'сделок':>6}{'побед':>7}{'итог R':>9}"
              f"{'на сделку':>9}{'ПФ':>7}")
        свод(все[:г], "первая половина")
        свод(все[г:], "вторая половина")
        свод(все, "ВСЯ ВЫБОРКА")


if __name__ == "__main__":
    главное()
