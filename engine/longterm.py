"""
Долгосрочная стратегия: участие в больших движениях.

Зачем она нужна рядом с короткой. Короткая система фиксирует прибыль на 1.5R
(около 3.5% хода) и в дальнейшем росте не участвует. Замер показал, что снятие
этого ограничения на коротком таймфрейме даёт лотерею: 13 убытков подряд на
одной половине данных и +29R на другой. Значит удержание требует не отмены
цели, а ДРУГИХ входов и другого горизонта.

Чем отличается от короткой системы:

  короткая                        долгосрочная
  ------------------------------  ------------------------------
  таймфрейм 4 часа                таймфрейм 1 день
  торгует боковик                 торгует тренд
  выход по цели 1.5R              выход по слому тренда
  держит часы-дни                 держит недели-месяцы
  лонг и шорт                     только лонг
  стоп ~2.3% от цены              стоп ~3 ATR, то есть 8-15%

Почему только лонг: удержание шорта неделями означает постоянную плату
за фондирование и убыток без ограничения сверху. Для долгого горизонта
это несопоставимо с риском покупки.

Это ОТДЕЛЬНАЯ система. Её сигналы не смешиваются с короткими ни в выводе,
ни в журнале, ни в статистике — иначе невозможно понять, какая из двух работает.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from . import indicators as ind
from .render import формат_цены
from .data import Свечи

ЕСТЬ_ПОТЕНЦИАЛ = "ЕСТЬ ПОТЕНЦИАЛ"
НАБЛЮДАЕМ = "НАБЛЮДАЕМ"
НЕ_ВРЕМЯ = "НЕ ВРЕМЯ"


@dataclass
class ДолгийВзгляд:
    актив: str
    цена: float
    вывод: str = НЕ_ВРЕМЯ

    # картина рынка
    выше_ma200: bool = False
    ma50_выше_ma200: bool = False
    adx: float = 0.0
    rsi: float = 50.0
    расстояние_до_ma50_atr: float = 99.0
    просадка_от_максимума: float = 0.0

    # план, если есть потенциал
    вход: float | None = None
    стоп: float | None = None
    стоп_проц: float | None = None
    выход_по: str | None = None
    горизонт: str = ""

    условия: list[tuple[str, bool, str]] = field(default_factory=list)
    причины: list[str] = field(default_factory=list)

    @property
    def выполнено(self) -> int:
        return sum(1 for _, ок, _ in self.условия if ок)


def проанализировать_долгий(свечи: Свечи, cfg: dict) -> ДолгийВзгляд:
    """Свечи должны быть ДНЕВНЫЕ. Минимум 220 баров — иначе MA200 не определена."""
    закр, макс, мин = свечи.closes, свечи.highs, свечи.lows
    цена = свечи.последняя_цена
    д = cfg.get("долгосрочная", {})

    ma50, _ = ind.last_defined(ind.sma(закр, 50))
    ma200, _ = ind.last_defined(ind.sma(закр, 200))
    atr_, _ = ind.last_defined(ind.atr(макс, мин, закр, 14))
    rsi_, _ = ind.last_defined(ind.rsi(закр, 14))
    adx_ряд, _, _ = ind.adx(макс, мин, закр, 14)
    adx_, _ = ind.last_defined(adx_ряд)

    в = ДолгийВзгляд(актив=свечи.актив, цена=цена)
    if None in (ma50, ma200, atr_, rsi_, adx_):
        в.причины.append("недостаточно истории: для MA200 нужно 200 дневных свечей")
        return в

    максимум = max(закр[-260:])
    в.выше_ma200 = цена > ma200
    в.ma50_выше_ma200 = ma50 > ma200
    в.adx = adx_
    в.rsi = rsi_
    в.расстояние_до_ma50_atr = abs(цена - ma50) / atr_
    в.просадка_от_максимума = (цена / максимум - 1) * 100

    # --- условия входа в долгую позицию ---
    # Смысл: покупаем сильный актив на откате, а не на пике и не на дне обвала.
    порог_adx = д.get("мин_adx", 20.0)
    порог_отката = д.get("макс_расстояние_до_ma50_atr", 1.5)
    порог_rsi = д.get("макс_rsi", 65.0)

    в.условия = [
        ("Цена выше MA200 — долгосрочный тренд вверх", в.выше_ma200,
         f"цена {формат_цены(цена)}, MA200 {формат_цены(ma200)}"),
        ("MA50 выше MA200 — тренд подтверждён", в.ma50_выше_ma200,
         f"MA50 {формат_цены(ma50)} против MA200 {формат_цены(ma200)}"),
        (f"Тренд выражен (ADX ≥ {порог_adx:g})", adx_ >= порог_adx,
         f"ADX {adx_:.1f}"),
        (f"Цена откатилась к MA50 (ближе {порог_отката:g} ATR)",
         в.расстояние_до_ma50_atr <= порог_отката,
         f"{в.расстояние_до_ma50_atr:.2f} ATR до MA50"),
        (f"Не перегрето (RSI ≤ {порог_rsi:g})", rsi_ <= порог_rsi,
         f"RSI {rsi_:.1f}"),
        ("Цена выше MA50 — среднесрочно не сломано", цена > ma50,
         f"цена {'выше' if цена > ma50 else 'ниже'} MA50"),
    ]

    выполнено = в.выполнено
    if выполнено == len(в.условия):
        в.вывод = ЕСТЬ_ПОТЕНЦИАЛ
        # Стоп широкий: долгую позицию нельзя держать на коротком стопе,
        # обычные колебания выбьют её задолго до того, как идея реализуется.
        множитель = д.get("стоп_atr", 3.0)
        в.вход = цена
        в.стоп = min(цена - atr_ * множитель, ma50 - atr_ * 0.5)
        в.стоп_проц = (цена - в.стоп) / цена * 100
        в.выход_по = "закрытие дня ниже MA50 — тренд сломан"
        в.горизонт = "недели-месяцы"
    elif выполнено >= len(в.условия) - 2:
        в.вывод = НАБЛЮДАЕМ
        в.причины = [f"не выполнено: {имя}" for имя, ок, _ in в.условия if not ок]
    else:
        в.вывод = НЕ_ВРЕМЯ
        в.причины = [f"не выполнено: {имя}" for имя, ок, _ in в.условия if not ок]

    return в


def словами(в: ДолгийВзгляд) -> str:
    """Короткое объяснение для человека."""
    if в.вывод == ЕСТЬ_ПОТЕНЦИАЛ:
        return (f"Актив в долгосрочном росте и откатился к поддержке — "
                f"исторически подходящий момент для покупки на месяцы. "
                f"Риск на позицию {в.стоп_проц:.1f}% от цены.")
    if в.вывод == НАБЛЮДАЕМ:
        return ("Почти сложились условия для долгой покупки. "
                "Осталось дождаться: " + "; ".join(
                    п.replace("не выполнено: ", "") for п in в.причины))
    if not в.выше_ma200:
        return ("Актив ниже своей годовой средней — это нисходящий рынок. "
                "Покупать вдолгую здесь значит ловить падающий нож.")
    return ("Условия для долгой покупки не сложились: "
            + "; ".join(п.replace("не выполнено: ", "") for п in в.причины[:2]))
