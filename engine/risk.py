"""
Риск-менеджмент и расчёт размера позиции. Раздел 8 и 7.1 промта.

Это и есть тот «код-валидатор», которого требует раздел 14: он пересчитывает
условия заново и блокирует сделку, если правило нарушено — независимо от того,
насколько убедительно звучит текстовое обоснование.

ЗДЕСЬ ЖИВУТ ДВА БАГА ИЗ ПЕРВОЙ ВЕРСИИ ПРОМТА, ИСПРАВЛЕННЫЕ:
  1) модуль в знаменателе  -> шорт больше не даёт отрицательный размер;
  2) ограничение по плечу  -> узкий стоп больше не создаёт скрытое кредитное плечо.
Оба закрыты тестами в tests/test_rules.py.
"""

from __future__ import annotations
from dataclasses import dataclass, field


LONG = "Long"
SHORT = "Short"


@dataclass
class Проверка:
    """Результат одной проверки. `ок=False` означает: сделка не выдаётся."""
    правило: str
    ок: bool
    факт: str
    требование: str

    def строкой(self) -> str:
        знак = "OK  " if self.ок else "СТОП"
        return f"[{знак}] {self.правило}: {self.факт} (требуется: {self.требование})"


@dataclass
class ПланСделки:
    актив: str
    направление: str
    вход: float
    стоп: float
    цели: list[float]
    текущая_цена: float
    atr: float

    # заполняется расчётом
    размер: float | None = None
    notional: float | None = None
    риск_валюта: float | None = None
    риск_пр_депозита: float | None = None
    дистанция_абс: float | None = None
    дистанция_пр: float | None = None
    дистанция_atr: float | None = None
    rr_по_целям: list[float] = field(default_factory=list)
    издержки: float | None = None
    издержки_пр_риска: float | None = None
    урезан_плечом: bool = False
    тип_ордера: str | None = None
    мин_объём_биржи: float | None = None

    проверки: list[Проверка] = field(default_factory=list)

    @property
    def допущена(self) -> bool:
        return all(p.ок for p in self.проверки)

    @property
    def нарушения(self) -> list[Проверка]:
        return [p for p in self.проверки if not p.ок]


# --------------------------------------------------------------- арифметика

def дистанция_до_стопа(вход: float, стоп: float) -> float:
    """МОДУЛЬ ОБЯЗАТЕЛЕН. Без него шорт (стоп выше входа) даёт отрицательную
    дистанцию и, следом, отрицательный размер позиции. Ровно этот баг был
    в первой версии промта: вход 100, стоп 105 -> 100/(100-105) = -20."""
    return abs(вход - стоп)


def риск_reward(вход: float, стоп: float, цель: float) -> float:
    """Во сколько раз потенциальная прибыль больше риска. Считается по каждой цели
    отдельно; решение принимается по первой (самой близкой, самой достижимой)."""
    риск = дистанция_до_стопа(вход, стоп)
    if риск == 0:
        return 0.0
    return abs(цель - вход) / риск


def тип_ордера(направление: str, вход: float, текущая: float,
               допуск_пр: float = 0.05) -> str:
    """Limit — вход выгоднее текущей цены (ждём отката к нам).
    Stop  — вход хуже текущей цены (входим по пробою, подтверждая движение).
    Market — вход практически на текущей цене."""
    отклонение = (вход - текущая) / текущая * 100.0
    if abs(отклонение) < допуск_пр:
        return "Market"
    if направление == LONG:
        return "Limit" if вход < текущая else "Stop"
    return "Limit" if вход > текущая else "Stop"


# ------------------------------------------------------------ размер позиции

def рассчитать(план: ПланСделки, депозит: float | None, риск_пр: float,
               макс_плечо: float, издержки_конфиг: dict,
               лимиты_биржи: dict | None = None) -> ПланСделки:
    """Раздел 8.1 промта. Если депозит не задан — размер не считаем и не выдумываем."""

    план.дистанция_абс = дистанция_до_стопа(план.вход, план.стоп)
    план.дистанция_пр = план.дистанция_абс / план.вход * 100.0 if план.вход else 0.0
    план.дистанция_atr = план.дистанция_абс / план.atr if план.atr else 0.0
    план.rr_по_целям = [риск_reward(план.вход, план.стоп, ц) for ц in план.цели]
    план.тип_ордера = тип_ордера(план.направление, план.вход, план.текущая_цена)

    if депозит is None or депозит <= 0:
        return план  # размер не рассчитывается — так требует раздел 8.1

    if план.дистанция_абс == 0:
        return план  # защита от деления на ноль; инвариант поймает это ниже

    план.риск_валюта = депозит * риск_пр / 100.0
    план.размер = план.риск_валюта / план.дистанция_абс
    план.notional = план.размер * план.вход

    # --- ОГРАНИЧЕНИЕ ПЛЕЧОМ ---
    # Формула размера сама по себе плечо не ограничивает. При узком стопе она
    # выдаёт объём в разы больше депозита: вход 3000, стоп 2997, депозит 10000,
    # риск 1% -> notional 100 000, то есть 10x плечо при лимите 1x.
    предел = депозит * макс_плечо
    if план.notional > предел:
        план.размер = предел / план.вход
        план.notional = предел
        план.риск_валюта = план.размер * план.дистанция_абс
        план.урезан_плечом = True
        # Фактический риск стал НИЖЕ заданного — это безопасная сторона,
        # но пользователь должен это видеть, а не узнать постфактум.

    # --- ОКРУГЛЕНИЕ ПОД БИРЖУ ---
    # Биржа принимает только количество, кратное своему шагу. На счёте в
    # тысячи долларов разница незаметна, на счёте в 10-100 $ она меняет
    # и размер позиции, и фактический риск. Округляем ВНИЗ: превысить
    # заданный риск нельзя, недобрать — можно.
    if лимиты_биржи:
        шаг = лимиты_биржи.get("шаг_количества", 0)
        if шаг > 0:
            шагов = int(план.размер / шаг + 1e-9)
            план.размер = round(шагов * шаг, 12)
            план.notional = план.размер * план.вход
            план.риск_валюта = план.размер * план.дистанция_абс
        план.мин_объём_биржи = лимиты_биржи.get("мин_объём", 0.0)

    план.риск_пр_депозита = план.риск_валюта / депозит * 100.0

    # --- ИЗДЕРЖКИ ---
    комиссии = план.notional * (
        издержки_конфиг["комиссия_вход_пр"] + издержки_конфиг["комиссия_выход_пр"]
    ) / 100.0
    проскальзывание = план.notional * издержки_конфиг["проскальзывание_пр"] / 100.0
    план.издержки = комиссии + проскальзывание
    план.издержки_пр_риска = (
        план.издержки / план.риск_валюта * 100.0 if план.риск_валюта else 0.0
    )
    return план


# --------------------------------------------------- обязательные проверки 7.1

def проверить(план: ПланСделки, cfg: dict, депозит: float | None,
              риск_кластера_текущий_пр: float = 0.0,
              открытых_позиций: int = 0,
              лимит_убытка_исчерпан: bool = False,
              серия_убытков: int = 0,
              занятый_объём: float = 0.0) -> ПланСделки:
    """Раздел 7.1 + раздел 8. Любая непройденная проверка = сделка не выдаётся."""
    r = cfg["риск"]
    и = cfg["издержки"]
    проверки: list[Проверка] = []

    # 1. Порядок уровней. Для Long: стоп < вход < цели. Для Short: наоборот.
    # Проверяется СТОРОНА уровней, а не их порядок между собой: цели[0] — рабочая,
    # цели[-1] — структурный уровень, и они выполняют разные роли. Их взаимное
    # расположение контролирует отдельная проверка «Запас до сопротивления».
    if план.направление == LONG:
        порядок_ок = план.стоп < план.вход and all(ц > план.вход for ц in план.цели)
    else:
        порядок_ок = план.стоп > план.вход and all(ц < план.вход for ц in план.цели)
    проверки.append(Проверка(
        "Порядок уровней", порядок_ок,
        f"{план.направление}: стоп {план.стоп:g}, вход {план.вход:g}, цели {план.цели}",
        "Long: стоп<вход<цели по возрастанию; Short: зеркально",
    ))

    # 1b. Стоп относительно ТЕКУЩЕЙ цены, а не только относительно входа.
    # Без этой проверки возможен абсурд: для покупки стоп оказывается выше рынка,
    # то есть сделка убыточна ещё до открытия. Сравнения «стоп < вход» для этого
    # недостаточно — вход может быть выше текущей цены (стоп-ордер на пробой).
    if план.направление == LONG:
        стоп_ок = план.стоп < план.текущая_цена
        требование = "стоп ниже текущей цены"
    else:
        стоп_ок = план.стоп > план.текущая_цена
        требование = "стоп выше текущей цены"
    проверки.append(Проверка(
        "Стоп относительно рынка", стоп_ок,
        f"стоп {план.стоп:g}, рынок {план.текущая_цена:g}", требование,
    ))

    # 2. Стоп обязателен и не нулевой.
    проверки.append(Проверка(
        "Наличие стоп-лосса", план.дистанция_абс > 0,
        f"дистанция {план.дистанция_абс:g}", "больше нуля",
    ))

    # 2b. Вход не должен быть оторван от текущей цены.
    # Лимитка в 4% от рынка — это не план сделки, а ставка на то, что рынок
    # соизволит прийти. За время ожидания меняется и режим, и уровни, а R:R,
    # посчитанный от такого входа, ничего не описывает.
    отрыв_atr = abs(план.вход - план.текущая_цена) / план.atr if план.atr else 99.0
    проверки.append(Проверка(
        "Близость входа к рынку", отрыв_atr <= r.get("макс_отрыв_входа_atr", 1.5),
        f"{отрыв_atr:.2f} x ATR от текущей цены",
        f"<= {r.get('макс_отрыв_входа_atr', 1.5)} x ATR",
    ))

    # 3. Стоп не внутри шума.
    проверки.append(Проверка(
        "Дистанция до стопа в ATR", план.дистанция_atr >= r["мин_стоп_atr"],
        f"{план.дистанция_atr:.2f} x ATR", f">= {r['мин_стоп_atr']} x ATR",
    ))

    # 4. Две разные проверки вместо одной, потому что это два разных вопроса.
    #
    #    (а) Рабочая цель — где мы РЕАЛЬНО фиксируем прибыль. Она должна окупать
    #        риск и издержки. При цели 1.5R порог безубыточности — 45% побед.
    #    (б) Запас до сопротивления — есть ли вообще куда идти. Проверяется по
    #        ПОСЛЕДНЕЙ цели (структурный уровень). Если до ближайшего реального
    #        уровня тесно, цена упрётся в него раньше нашей цели.
    #
    #    Раньше это была одна проверка, и она заставляла ставить цель на дальний
    #    уровень — что и делало стратегию убыточной.
    rr_рабочая = план.rr_по_целям[0] if план.rr_по_целям else 0.0
    rr_запас = план.rr_по_целям[-1] if план.rr_по_целям else 0.0

    проверки.append(Проверка(
        "Рабочая цель окупает риск", rr_рабочая >= r["рабочая_цель_R"] - 1e-9,
        f"1:{rr_рабочая:.2f}", f">= 1:{r['рабочая_цель_R']}",
    ))
    проверки.append(Проверка(
        "Запас до сопротивления", rr_запас >= r["мин_запас_до_сопротивления_R"] - 1e-9,
        f"1:{rr_запас:.2f} до ближайшего уровня",
        f">= 1:{r['мин_запас_до_сопротивления_R']}",
    ))

    # Проверки ниже требуют рассчитанного размера. Он отсутствует, если депозит
    # не задан ИЛИ если расчёт прервался на вырожденных данных (нулевая дистанция).
    # Во втором случае сделку уже блокирует проверка №2 — молча пропустить
    # остальные корректнее, чем упасть на форматировании пустого поля.
    размер_посчитан = (
        депозит is not None and депозит > 0
        and план.риск_пр_депозита is not None
        and план.notional is not None
    )

    if размер_посчитан:
        # 5. Риск на депозит в пределах лимита.
        проверки.append(Проверка(
            "Риск на сделку", (план.риск_пр_депозита or 0) <= r["макс_риск_на_сделку_пр"] + 1e-9,
            f"{план.риск_пр_депозита:.3f}% депозита",
            f"<= {r['макс_риск_на_сделку_пр']}%",
        ))
        # 6. Плечо по этой сделке.
        плечо_факт = (план.notional or 0) / депозит
        проверки.append(Проверка(
            "Плечо", плечо_факт <= r["макс_плечо"] + 1e-9,
            f"{плечо_факт:.2f}x (объём {план.notional:.2f})",
            f"<= {r['макс_плечо']}x",
        ))

        # 6b. Плечо по ВСЕМУ портфелю.
        # Проверки каждой сделки по отдельности недостаточно: три позиции
        # по 8 $ на счёте в 10 $ — это 2.4 плеча, хотя каждая в лимит проходит.
        # На крупном счёте такое почти не встречается, на мелком — постоянно.
        всего = занятый_объём + (план.notional or 0)
        проверки.append(Проверка(
            "Плечо по портфелю", всего <= депозит * r["макс_плечо"] + 1e-9,
            f"занято {занятый_объём:.2f} + новая {план.notional:.2f} = {всего:.2f}",
            f"<= {депозит * r['макс_плечо']:.2f} (капитал x {r['макс_плечо']})",
        ))

        # 6c. Минимальный размер заявки на бирже.
        if план.мин_объём_биржи:
            проверки.append(Проверка(
                "Минимальный объём биржи",
                (план.notional or 0) >= план.мин_объём_биржи - 1e-9,
                f"объём {план.notional:.2f}",
                f">= {план.мин_объём_биржи:.2f} (биржа меньше не примет)",
            ))
        if план.размер is not None and план.размер <= 0:
            проверки.append(Проверка(
                "Размер после округления", False,
                "0 после округления к шагу биржи",
                "больше нуля — увеличьте капитал или риск на сделку",
            ))
        # 7. Риск кластера.
        кластер_после = риск_кластера_текущий_пр + (план.риск_пр_депозита or 0)
        проверки.append(Проверка(
            "Риск кластера", кластер_после <= r["макс_риск_кластера_пр"] + 1e-9,
            f"{риск_кластера_текущий_пр:.2f}% + {план.риск_пр_депозита:.2f}% = {кластер_после:.2f}%",
            f"<= {r['макс_риск_кластера_пр']}%",
        ))
        # 8. Издержки не съедают риск.
        проверки.append(Проверка(
            "Издержки к риску", (план.издержки_пр_риска or 0) <= и["предел_издержек_от_риска_пр"],
            f"{план.издержки_пр_риска:.1f}% от риска",
            f"<= {и['предел_издержек_от_риска_пр']}%",
        ))

    # 9. Лимит открытых позиций.
    проверки.append(Проверка(
        "Открытых позиций", открытых_позиций < r["макс_открытых_позиций"],
        f"{открытых_позиций}", f"< {r['макс_открытых_позиций']}",
    ))

    # 10. Дневной/недельный лимит убытка.
    проверки.append(Проверка(
        "Лимит убытка", not лимит_убытка_исчерпан,
        "исчерпан" if лимит_убытка_исчерпан else "не исчерпан", "не исчерпан",
    ))

    # 11. Cooldown после серии убытков.
    проверки.append(Проверка(
        "Серия убытков", серия_убытков < r["серия_убытков_до_паузы"],
        f"{серия_убытков} подряд", f"< {r['серия_убытков_до_паузы']}",
    ))

    план.проверки = проверки
    return план
