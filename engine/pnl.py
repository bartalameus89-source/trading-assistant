"""
Деньги: сколько заработано и потеряно на самом деле.

Зачем отдельно. Кабинет показывал СЧЁТ сделок — открыто столько, закрыто
столько. По нему картина выходила безрадостная: восемь закрытых, семь
в минус. И это была половина правды: все двенадцать открытых позиций
стояли в плюсе, а прибыль по ним нигде не считалась.

Для трендовой системы это не мелочь, а суть. Убыточные сделки закрываются
быстро и мелко, прибыльные держатся месяц и продолжают идти. Судить по
одним закрытым — значит систематически видеть только убытки и не видеть
прибыль, ради которой всё затевалось.

Здесь считается и то, и другое, в долларах:
  реализованное — по закрытым сделкам, это уже история;
  нереализованное — по открытым, по текущей цене, это ещё может измениться;
  худший случай — если все стопы сработают завтра. Он важнее прочего:
  показывает, сколько из нынешней прибыли уже защищено подтянутым стопом.
"""

from __future__ import annotations

import json
import os

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")


def _чит(файл: str, ключ: str) -> list[dict]:
    п = os.path.join(ПАПКА, файл)
    if not os.path.exists(п):
        return []
    try:
        with open(п, encoding="utf-8") as f:
            return json.load(f).get(ключ, []) or []
    except (json.JSONDecodeError, OSError):
        return []


def _пусто() -> dict:
    return {"сделок": 0, "прибыльных": 0, "убыточных": 0, "в_ноль": 0,
            "заработано": 0.0, "потеряно": 0.0, "итог": 0.0}


def _добавить(св: dict, деньги: float) -> None:
    св["сделок"] += 1
    св["итог"] += деньги
    if деньги > 0:
        св["прибыльных"] += 1
        св["заработано"] += деньги
    elif деньги < 0:
        св["убыточных"] += 1
        св["потеряно"] += деньги
    else:
        св["в_ноль"] += 1


def подсчитать(цены: dict[str, float] | None = None) -> dict:
    """`цены` — текущая цена по активу. Без них открытые позиции
    оцениваются по подтянутому стопу, то есть по защищённой прибыли."""
    цены = цены or {}
    закрытые = {"рекомендации": _пусто(), "тень": _пусто()}
    открытые = {"рекомендации": {"позиций": 0, "сейчас": 0.0, "худший": 0.0,
                                 "защищено": 0},
                "тень": {"позиций": 0, "сейчас": 0.0, "худший": 0.0,
                         "защищено": 0}}
    строки: list[dict] = []

    def обработать(з: dict, система: str, r_поле: str, риск_поле: str) -> None:
        ветка = "тень" if з.get("тень") else "рекомендации"
        риск_денег = float(з.get(риск_поле) or 1.0)

        if з.get("состояние") in ("закрыта", "завершена"):
            r = з.get(r_поле)
            if r is None or з.get("исход") in ("не дошло", "истёк срок"):
                return
            деньги = r * риск_денег
            _добавить(закрытые[ветка], деньги)
            строки.append({"система": система, "ветка": ветка,
                           "актив": з.get("актив", "?"), "исход": з.get("исход"),
                           "r": round(r, 2), "деньги": round(деньги, 2),
                           "дней": з.get("дней", 0), "когда": з.get("закрыта_в")})
            return

        if з.get("состояние") != "открыта":
            return
        вход = з.get("вход")
        стоп_нач = з.get("стоп_начальный") or з.get("стоп")
        if not вход or not стоп_нач:
            return
        риск = вход - стоп_нач
        if риск <= 0:
            return
        цена = цены.get(з["актив"], з.get("стоп", вход))
        открытые[ветка]["позиций"] += 1
        открытые[ветка]["сейчас"] += (цена - вход) / риск * риск_денег
        стоп = з.get("стоп", стоп_нач)
        открытые[ветка]["худший"] += (стоп - вход) / риск * риск_денег
        # Позиция, у которой стоп уже выше входа, хуже нуля закрыться
        # не может: прибыль по ней закреплена. Считать это по СУММЕ нельзя —
        # общий худший случай может быть отрицательным, когда часть позиций
        # уже защищена, а часть ещё нет.
        if стоп > вход:
            открытые[ветка]["защищено"] += 1

    for з in _чит("breakouts.json", "позиции"):
        обработать(з, "Прорывы", "r", "риск_usd")
    for з in _чит("paper_long.json", "позиции"):
        обработать(з, "Долгосрочная", "r", "риск_usd")
    for з in _чит("shadow.json", "сделки"):
        обработать({**з, "тень": True, "состояние": з.get("состояние"),
                    "вход": з.get("цена_входа") or з.get("вход")},
                   "Короткие", "результат_R", "риск_денег")
    for з in _чит("paper.json", "сделки"):
        обработать({**з, "вход": з.get("цена_входа") or з.get("вход")},
                   "Короткие", "результат_R", "риск_денег")

    строки.sort(key=lambda с: с.get("когда") or 0)
    всего_закрыто = sum(в["итог"] for в in закрытые.values())
    всего_открыто = sum(в["сейчас"] for в in открытые.values())
    рек_итог = закрытые["рекомендации"]["итог"] + открытые["рекомендации"]["сейчас"]

    return {
        "закрытые": закрытые, "открытые": открытые, "строки": строки,
        "всего_закрыто": round(всего_закрыто, 2),
        "всего_открыто": round(всего_открыто, 2),
        "худший_случай": round(sum(в["худший"] for в in открытые.values()), 2),
        "итог": round(всего_закрыто + всего_открыто, 2),
        "итог_рекомендаций": round(рек_итог, 2),
        "позиций_открыто": sum(в["позиций"] for в in открытые.values()),
        "позиций_защищено": sum(в["защищено"] for в in открытые.values()),
    }
