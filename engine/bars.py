"""
Проход по барам для журналов сделок.

Зачем отдельный модуль. Все три журнала — рекомендации, тень и решения
пользователя — получали цены в виде одного свёрнутого {high, low, close}
за общий период. У этого две беды, и обе подделывают результат.

Первая. Окно было ОБЩЕЕ для всех сделок и считалось от самой старой
из них (или за неделю назад — что позже). Сделка, открытая сегодня,
проверялась по ценам, которых при ней не существовало. Ровно так система
прорывов закрыла XRP по «стопу» 1.2588 в день, когда он вырос на +14.7%:
минимум был утром, до входа.

Вторая. Свёрнутые high и low принадлежат РАЗНЫМ барам, а сравниваются
с уровнями так, будто это один момент. При недельном окне сделка почти
наверняка увидит и свой стоп, и свою цель одновременно — и результат
решит порядок проверок в коде, а не рынок.

Здесь бары отдаются списком, и каждый журнал идёт по ним по одному,
начиная от СВОЕГО времени. Это то же самое, что делает бэктест, и только
так живой журнал и бэктест меряют одно и то же.
"""

from __future__ import annotations


def бары_после(бары: list[dict], время_с: float) -> list[dict]:
    """Бары, начавшиеся строго позже указанного момента (в секундах).

    Бар, внутри которого сделка появилась, исключается целиком: неизвестно,
    случился его минимум до нашего входа или после. Пропустить настоящий
    стоп на день — терпимо, выдумать несуществующий — нет.
    """
    порог = время_с * 1000
    return [б for б in бары if б["t"] > порог]


def первое_касание(бары: list[dict], уровень: float) -> dict | None:
    """Первый бар, внутри которого цена дотянулась до уровня."""
    for б in бары:
        if б["low"] <= уровень <= б["high"]:
            return б
    return None
