"""
Версии настроек: под какими правилами была заключена каждая сделка.

Зачем. За две недели мы поменяли десяток параметров: сняли фильтр ADX,
понизили предел издержек, ввели доливку, частичную фиксацию, изменили срок
ожидания ордера. Все сделки лежат в одном журнале вперемешку. Через месяц
статистика смешает результаты РАЗНЫХ правил и покажет среднее по ним —
число, которого никогда не существовало ни в одной версии системы.

Что записываем. Отпечаток — короткая подпись значимых для торговли
настроек. Он кладётся в каждую новую сделку, и потом статистику можно
разложить по версиям: вот 40 сделок на старых правилах, вот 12 на новых.

Отдельно ведётся журнал самих изменений: когда отпечаток сменился и что
именно поменялось. Это то, чем подписываются отметки на кривой счёта —
«здесь сняли ADX», «здесь добавили доливку».

Что НЕ входит в отпечаток: депозит и текущий риск. Их владелец меняет
свободно, они не меняют правил игры, и подпись от них дёргаться не должна.
"""

from __future__ import annotations

import hashlib
import json
import os
import time

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")
ФАЙЛ = os.path.join(ПАПКА, "settings_log.json")
КОНФИГ = os.path.join(БАЗА, "config.json")

# Что считается «правилами игры». Порядок важен: он задаёт порядок сравнения.
ЗНАЧИМЫЕ = [
    ("сигналы", "мин_подтверждений"),
    # Какие монеты короткая система не торгует — тоже правило игры: без него
    # сделки после исключения LTC и ADA получили бы подпись прежней версии.
    ("сигналы", "исключить_из_короткой"),
    ("сигналы", "мин_уверенность"),
    ("сигналы", "срок_жизни_сигнала_баров"),
    ("сигналы", "торговать_в_высокой_волатильности"),
    ("риск", "рабочая_цель_R"),
    ("риск", "мин_запас_до_сопротивления_R"),
    ("риск", "макс_отрыв_входа_atr"),
    ("риск", "безубыток_после_R"),
    ("риск", "доля_фиксации_на_цели"),
    ("риск", "трейлинг_остатка_atr"),
    ("издержки", "предел_издержек_от_риска_пр"),
    ("прорывы", "окно_входа"),
    ("прорывы", "окно_выхода"),
    ("прорывы", "стоп_atr"),
    ("прорывы", "риск_на_позицию_пр"),
    ("прорывы", "доливка_шаг_R"),
    ("прорывы", "макс_доливок"),
    ("долгосрочная", "мин_adx"),
    ("долгосрочная", "макс_расстояние_до_ma50_atr"),
    ("долгосрочная", "макс_rsi"),
    ("долгосрочная", "риск_на_позицию_пр"),
    ("портфель", "макс_общий_риск_пр"),
    ("портфель", "макс_всего_позиций"),
    ("портфель", "макс_риск_быстрых_пр"),
]


def _значения(cfg: dict | None = None) -> dict:
    if cfg is None:
        try:
            with open(КОНФИГ, encoding="utf-8") as f:
                cfg = json.load(f)
        except (json.JSONDecodeError, OSError):
            return {}
    из = {}
    for раздел, ключ in ЗНАЧИМЫЕ:
        из[f"{раздел}.{ключ}"] = (cfg.get(раздел) or {}).get(ключ)
    return из


def отпечаток(cfg: dict | None = None) -> str:
    """Восемь знаков — достаточно, чтобы различать версии, и коротко
    настолько, чтобы влезать в каждую запись журнала без раздувания."""
    з = _значения(cfg)
    строка = json.dumps(з, ensure_ascii=False, sort_keys=True)
    return hashlib.sha256(строка.encode()).hexdigest()[:8]


def _читать() -> list[dict]:
    if not os.path.exists(ФАЙЛ):
        return []
    try:
        with open(ФАЙЛ, encoding="utf-8") as f:
            return json.load(f).get("версии", []) or []
    except (json.JSONDecodeError, OSError):
        return []


def что_изменилось(было: dict, стало: dict) -> list[str]:
    из = []
    for ключ in sorted(set(было) | set(стало)):
        a, b = было.get(ключ), стало.get(ключ)
        if a != b:
            из.append(f"{ключ}: {a} → {b}")
    return из


def отметить(cfg: dict | None = None) -> dict:
    """Вызывается каждый проход. Пишет запись ТОЛЬКО если отпечаток
    изменился — иначе журнал версий за месяц раздуется до тысяч
    одинаковых строк и станет нечитаемым."""
    текущий = отпечаток(cfg)
    версии = _читать()
    if версии and версии[-1].get("отпечаток") == текущий:
        return версии[-1]

    значения = _значения(cfg)
    запись = {
        "отпечаток": текущий,
        "когда": time.time(),
        "значения": значения,
        "изменения": (что_изменилось(версии[-1].get("значения", {}), значения)
                      if версии else ["первая записанная версия"]),
    }
    версии.append(запись)
    os.makedirs(ПАПКА, exist_ok=True)
    with open(ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump({"версии": версии, "обновлён": time.time()}, f,
                  ensure_ascii=False, indent=1)
    return запись


def все_версии() -> list[dict]:
    return _читать()


def описание(отп: str) -> str:
    """Человеку: чем эта версия отличалась от предыдущей."""
    for в in _читать():
        if в.get("отпечаток") == отп:
            изм = в.get("изменения") or []
            return "; ".join(изм[:4]) or "без изменений"
    return "версия неизвестна"
