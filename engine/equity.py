"""
Снимок счёта: сколько денег было на каждый день.

Зачем. До сих пор мы знали только «сейчас». Число «+13.82 $» ничего
не говорит о том, ровно мы росли или скакали, и невозможно проверить,
помогло ли изменение настроек — сравнивать не с чем. История терялась
безвозвратно: каждый проход пересчитывал текущее состояние и забывал
предыдущее.

Что записываем. Один снимок в сутки, по последнему проходу за день:
реализованная прибыль по закрытым сделкам, нереализованная по открытым
и худший случай, если все стопы сработают завтра. Три числа, а не одно,
потому что у трендовой системы они расходятся сильно: закрытые могут
быть в минусе, пока открытые растут.

Почему по суткам, а не по каждому проходу. Проходов шесть в день,
и они дают шум, а не сведения. Кривая по дням читается, кривая
по проходам — нет.
"""

from __future__ import annotations

import json
import os
import time
from datetime import datetime, timezone

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")
ФАЙЛ = os.path.join(ПАПКА, "equity.json")


def _день(когда: float | None = None) -> str:
    т = datetime.fromtimestamp(когда or time.time(), tz=timezone.utc)
    return т.strftime("%Y-%m-%d")


def прочитать() -> list[dict]:
    if not os.path.exists(ФАЙЛ):
        return []
    try:
        with open(ФАЙЛ, encoding="utf-8") as f:
            return json.load(f).get("дни", []) or []
    except (json.JSONDecodeError, OSError):
        return []


def записать(закрыто: float, открыто: float, худший: float,
             капитал: float, позиций: int = 0, сделок: int = 0) -> dict:
    """Кладёт снимок за сегодня. Повторный вызов в тот же день ЗАМЕНЯЕТ
    запись, а не добавляет вторую: за день остаётся последнее известное
    состояние."""
    дни = прочитать()
    сегодня = _день()
    снимок = {
        "день": сегодня,
        "когда": time.time(),
        "закрыто": round(закрыто, 4),
        "открыто": round(открыто, 4),
        "итог": round(закрыто + открыто, 4),
        "худший": round(закрыто + худший, 4),
        "капитал": капитал,
        "позиций": позиций,
        "закрытых_сделок": сделок,
    }
    дни = [д for д in дни if д.get("день") != сегодня]
    дни.append(снимок)
    дни.sort(key=lambda д: д["день"])

    os.makedirs(ПАПКА, exist_ok=True)
    with open(ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump({"дни": дни, "обновлён": time.time()}, f,
                  ensure_ascii=False, indent=1)
    return снимок


def за_период(дней: int = 0) -> list[dict]:
    дни = прочитать()
    return дни[-дней:] if дней > 0 else дни


def сводка() -> dict:
    """Что показать рядом с кривой."""
    дни = прочитать()
    if not дни:
        return {"дней": 0}
    первый, последний = дни[0], дни[-1]
    итоги = [д["итог"] for д in дни]
    пик = пров = 0.0
    for и in итоги:
        пик = max(пик, и)
        пров = min(пров, и - пик)
    лучший = max(дни, key=lambda д: д["итог"])
    худший_день = min(дни, key=lambda д: д["итог"])
    return {
        "дней": len(дни),
        "с": первый["день"], "по": последний["день"],
        "итог": последний["итог"],
        "капитал": последний.get("капитал", 100),
        "макс_просадка": round(пров, 2),
        "лучший_день": лучший["день"], "лучший_итог": лучший["итог"],
        "худший_день": худший_день["день"], "худший_итог": худший_день["итог"],
    }
