"""
Целостность журналов: заметить порчу до того, как она станет потерей.

Зачем. Проверка показала, что журналы ведут себя по-разному на битом файле,
и оба поведения плохие. journal.py падает с JSONDecodeError и валит весь
проход. equity, heartbeat, pnl и portfolio молча возвращают пустоту —
повреждённый журнал становится неотличим от пустого, и система спокойно
начинает с чистого листа, потеряв всю историю сделок.

Второе хуже первого. Падение видно сразу, тихая потеря — нет.

Что делает этот модуль. Перед работой проверяет каждый журнал: читается ли
он вообще, тот ли внутри тип, есть ли ожидаемый ключ, не выглядит ли
внезапно пустым. Если файл цел — рядом кладётся копия. Если сломан —
проход останавливается с понятным сообщением, а последняя целая копия
остаётся на месте, чтобы было чем чинить.

Копия обновляется ТОЛЬКО когда файл прошёл проверку. Иначе первая же
порча затрёт последнюю здоровую копию, и спасать будет нечего.
"""

from __future__ import annotations

import json
import os
import shutil
import time

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")
КОПИИ = os.path.join(ПАПКА, "backup")

# файл -> (ключ со списком, можно ли ему быть пустым)
ЖУРНАЛЫ = {
    "breakouts.json": ("позиции", True),
    "paper.json": ("сделки", True),
    "paper_long.json": ("позиции", True),
    "shadow.json": ("сделки", True),
    "decisions.json": ("решения", True),
    "equity.json": ("дни", True),
    "heartbeat.json": (None, True),
}


class Повреждён(Exception):
    """Журнал непригоден. Поднимается вместо тихого возврата пустоты."""


def _путь(имя: str) -> str:
    return os.path.join(ПАПКА, имя)


def проверить_файл(имя: str) -> tuple[bool, str]:
    """(цел, что не так). Отсутствующий файл считается целым: система
    имеет право начинаться с нуля, это не порча."""
    п = _путь(имя)
    if not os.path.exists(п):
        return True, "файла нет — это нормально для нового журнала"

    ключ, пустой_ок = ЖУРНАЛЫ.get(имя, (None, True))
    try:
        сырое = open(п, encoding="utf-8").read()
    except OSError as e:
        return False, f"не читается: {type(e).__name__}: {e}"

    if not сырое.strip():
        return False, "файл пустой — вероятно, запись оборвалась"

    try:
        данные = json.loads(сырое)
    except json.JSONDecodeError as e:
        return False, f"испорчен JSON: {e}"

    if not isinstance(данные, dict):
        return False, f"внутри {type(данные).__name__}, а ожидался объект"

    if ключ is not None:
        if ключ not in данные:
            return False, f"нет ключа «{ключ}»"
        if not isinstance(данные[ключ], list):
            return False, f"ключ «{ключ}» не список"

    return True, "цел"


def размер_записей(имя: str) -> int:
    ключ, _ = ЖУРНАЛЫ.get(имя, (None, True))
    п = _путь(имя)
    if not os.path.exists(п) or ключ is None:
        return 0
    try:
        with open(п, encoding="utf-8") as f:
            return len(json.load(f).get(ключ, []) or [])
    except (json.JSONDecodeError, OSError):
        return 0


def сохранить_копию(имя: str) -> None:
    """Копия делается ТОЛЬКО с целого файла. Иначе первая же порча
    затрёт последнюю здоровую копию, и чинить будет нечем."""
    п = _путь(имя)
    if not os.path.exists(п):
        return
    os.makedirs(КОПИИ, exist_ok=True)
    shutil.copy2(п, os.path.join(КОПИИ, имя))


def проверить_все(делать_копии: bool = True) -> tuple[list[str], list[str]]:
    """(беды, что проверено). Беда — повод остановить проход."""
    беды: list[str] = []
    отчёт: list[str] = []
    for имя in ЖУРНАЛЫ:
        цел, почему = проверить_файл(имя)
        if цел:
            отчёт.append(f"{имя}: {почему}"
                         + (f", записей {размер_записей(имя)}"
                            if размер_записей(имя) else ""))
            if делать_копии:
                сохранить_копию(имя)
        else:
            беды.append(f"{имя}: {почему}")
            копия = os.path.join(КОПИИ, имя)
            if os.path.exists(копия):
                когда = time.strftime("%d.%m %H:%M",
                                      time.gmtime(os.path.getmtime(копия)))
                беды.append(f"    целая копия есть: state/backup/{имя} от {когда}")
            else:
                беды.append(f"    копии нет — восстанавливать нечем")
    return беды, отчёт


def убедиться() -> None:
    """Вызывается в начале каждого прохода. Если журнал повреждён,
    останавливаем работу: писать в сломанный журнал — значит добить его."""
    беды, _ = проверить_все()
    if беды:
        raise Повреждён("Журналы повреждены, работа остановлена:\n  "
                        + "\n  ".join(беды))
