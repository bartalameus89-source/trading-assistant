"""
Журнал ВАШИХ решений: что вы взяли, что пропустили и чем это кончилось.

Отличие от бумажного журнала. Бумажный записывает всё, что предложила система,
и показывает, как работала бы стратегия целиком. Этот — записывает, что сделали
ВЫ. Разница между ними и есть ответ на вопрос из раздела 11 промта: помогают
ваши ручные решения результату или вредят.

Пропущенные сделки тоже доводятся до результата. Иначе невозможно понять,
удачно ли вы их пропустили: сравнивать нужно с тем, что было бы.

Хранится в state/decisions.json.
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import asdict, dataclass, field

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")
ФАЙЛ = os.path.join(ПАПКА, "decisions.json")

ВЗЯЛ = "взял"
ПРОПУСТИЛ = "пропустил"

ЖДЁТ_ВХОДА = "ждёт входа"
В_РАБОТЕ = "в работе"
ЗАВЕРШЕНА = "завершена"


@dataclass
class Решение:
    ид: str
    актив: str
    решение: str              # ВЗЯЛ или ПРОПУСТИЛ
    когда: float              # unix-время нажатия кнопки

    направление: str
    вход: float
    стоп: float
    цель: float
    тип_ордера: str
    уверенность: str
    режим: str
    тег: str

    капитал: float            # какой капитал был выбран в кабинете
    риск_проц: float
    размер: float
    риск_денег: float
    порог_безубытка: float = 0.0

    состояние: str = ЖДЁТ_ВХОДА
    цена_входа: float | None = None
    вошли_в: float | None = None
    стоп_в_безубытке: bool = False
    закрыта_в: float | None = None
    цена_выхода: float | None = None
    исход: str | None = None      # "цель" / "стоп" / "безубыток" / "не дошло"
    результат_R: float | None = None
    результат_денег: float | None = None
    заметка: str = ""

    @property
    def риск_на_единицу(self) -> float:
        база = self.цена_входа if self.цена_входа else self.вход
        return abs(база - self.стоп)


def _читать() -> dict:
    if not os.path.exists(ФАЙЛ):
        return {"решения": [], "создан": time.time()}
    with open(ФАЙЛ, encoding="utf-8") as f:
        return json.load(f)


def _писать(данные: dict) -> None:
    os.makedirs(ПАПКА, exist_ok=True)
    данные["обновлён"] = time.time()
    with open(ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump(данные, f, ensure_ascii=False, indent=1)


def все() -> list[Решение]:
    return [Решение(**р) for р in _читать()["решения"]]


def сохранить(решения: list[Решение]) -> None:
    д = _читать()
    д["решения"] = [asdict(р) for р in решения]
    _писать(д)


# Ключи, приходящие по HTTP, — латиницей. Кириллица в именах полей не переживает
# путь через оболочку и разные кодировки клиентов: ровно на этом уже споткнулись
# имя cookie и переменная окружения. Внутри программы поля остаются русскими,
# перевод происходит здесь, в одной точке.
ПОЛЯ = {
    "id": "ид", "asset": "актив", "choice": "решение", "side": "направление",
    "entry": "вход", "stop": "стоп", "target": "цель", "order": "тип_ордера",
    "confidence": "уверенность", "regime": "режим", "tag": "тег",
    "capital": "капитал", "riskPct": "риск_проц", "size": "размер",
    "riskMoney": "риск_денег", "breakeven": "порог_безубытка",
}


# Значение выбора тоже латиницей: это поле, по которому режется вся статистика,
# и оно не должно зависеть от того, как клиент закодировал русский текст.
ВЫБОР = {"taken": ВЗЯЛ, "skipped": ПРОПУСТИЛ}


def из_запроса(сырое: dict) -> dict:
    """Латинские ключи и значения запроса -> русские имена полей."""
    готово = {ПОЛЯ[к]: v for к, v in сырое.items() if к in ПОЛЯ}
    выбор = сырое.get("choice")
    if выбор not in ВЫБОР:
        raise ValueError(f"неизвестное решение: {выбор!r}, ожидается taken или skipped")
    готово["решение"] = ВЫБОР[выбор]
    return готово


def записать(данные: dict) -> Решение | None:
    """Регистрирует решение из кабинета. Повторное нажатие по тому же
    сигналу перезаписывает выбор, а не плодит дубли."""
    решения = все()
    ид = данные["ид"]

    существующее = next((р for р in решения if р.ид == ид), None)
    if существующее:
        if существующее.состояние != ЖДЁТ_ВХОДА:
            return существующее          # сделка уже пошла, менять поздно
        существующее.решение = данные["решение"]
        существующее.когда = time.time()
        сохранить(решения)
        return существующее

    р = Решение(
        ид=ид, актив=данные["актив"], решение=данные["решение"], когда=time.time(),
        направление=данные["направление"], вход=float(данные["вход"]),
        стоп=float(данные["стоп"]), цель=float(данные["цель"]),
        тип_ордера=данные.get("тип_ордера", "Limit"),
        уверенность=данные.get("уверенность", ""), режим=данные.get("режим", ""),
        тег=данные.get("тег", ""),
        капитал=float(данные.get("капитал", 0)),
        риск_проц=float(данные.get("риск_проц", 0)),
        размер=float(данные.get("размер", 0)),
        риск_денег=float(данные.get("риск_денег", 0)),
        порог_безубытка=float(данные.get("порог_безубытка", 0)),
    )
    решения.append(р)
    сохранить(решения)
    return р


def провести(цены: dict[str, dict], срок_входа_часов: float = 12.0) -> list[str]:
    """Двигает все незавершённые решения по свежим ценам.

    `цены[актив]` = {"high", "low", "close"} за прошедший период.
    Пропущенные сделки ведутся наравне со взятыми — иначе не с чем сравнивать.
    """
    решения = все()
    события: list[str] = []
    сейчас = time.time()

    for р in решения:
        if р.состояние == ЗАВЕРШЕНА:
            continue
        ц = цены.get(р.актив)
        if not ц:
            continue
        high, low, close = ц["high"], ц["low"], ц["close"]
        длинная = р.направление == "Long"

        if р.состояние == ЖДЁТ_ВХОДА:
            if р.тип_ордера == "Market":
                р.состояние, р.цена_входа, р.вошли_в = В_РАБОТЕ, close, сейчас
                события.append(f"{р.актив}: вход исполнен")
            elif low <= р.вход <= high:
                р.состояние, р.цена_входа, р.вошли_в = В_РАБОТЕ, р.вход, сейчас
                события.append(f"{р.актив}: вход исполнен")
            elif сейчас - р.когда > срок_входа_часов * 3600:
                р.состояние, р.исход = ЗАВЕРШЕНА, "не дошло"
                р.закрыта_в, р.результат_R, р.результат_денег = сейчас, 0.0, 0.0
                события.append(f"{р.актив}: цена не дошла, сделки не было")
            continue

        риск = р.риск_на_единицу
        if риск <= 0:
            continue

        стоп_задет = (low <= р.стоп) if длинная else (high >= р.стоп)
        цель_задета = (high >= р.цель) if длинная else (low <= р.цель)

        if стоп_задет:
            р.состояние = ЗАВЕРШЕНА
            р.исход = "безубыток" if р.стоп_в_безубытке else "стоп"
            р.цена_выхода, р.закрыта_в = р.стоп, сейчас
            движение = (р.стоп - р.цена_входа) if длинная else (р.цена_входа - р.стоп)
            р.результат_R = движение / риск
            р.результат_денег = р.результат_R * р.риск_денег
            события.append(f"{р.актив}: закрыта — {р.исход}")
        elif цель_задета:
            р.состояние, р.исход = ЗАВЕРШЕНА, "цель"
            р.цена_выхода, р.закрыта_в = р.цель, сейчас
            движение = (р.цель - р.цена_входа) if длинная else (р.цена_входа - р.цель)
            р.результат_R = движение / риск
            р.результат_денег = р.результат_R * р.риск_денег
            события.append(f"{р.актив}: закрыта — цель достигнута")
        elif not р.стоп_в_безубытке and р.порог_безубытка > 0:
            # Перенос стопа — после проверок текущей свечи, со следующей.
            прибыль_R = ((high - р.цена_входа) if длинная
                         else (р.цена_входа - low)) / риск
            if прибыль_R >= р.порог_безубытка:
                р.стоп = р.цена_входа
                р.стоп_в_безубытке = True
                события.append(f"{р.актив}: стоп перенесён в безубыток")

    сохранить(решения)
    return события


def учебное(р: Решение) -> bool:
    """Решение по учебному примеру. Ведётся как настоящее, чтобы показать
    жизненный цикл сделки, но в статистику не входит — иначе тренировка
    испортит цифры, ради которых журнал и заведён."""
    return р.ид.startswith("DEMO-")


def статистика(решения: list[Решение], издержки_R: float = 0.125) -> dict:
    """Сводка. Считается отдельно по взятым и по пропущенным —
    ради сравнения, ради которого журнал и существует.
    Учебные записи исключаются."""
    решения = [р for р in решения if not учебное(р)]
    def посчитать(набор: list[Решение]) -> dict:
        завершённые = [р for р in набор if р.состояние == ЗАВЕРШЕНА
                       and р.результат_R is not None and р.исход != "не дошло"]
        итог = {"всего": len(набор), "завершено": len(завершённые),
                "в_работе": sum(1 for р in набор if р.состояние == В_РАБОТЕ),
                "ждут": sum(1 for р in набор if р.состояние == ЖДЁТ_ВХОДА),
                "побед": 0, "доля_побед": 0.0, "сумма_R": 0.0,
                "сумма_денег": 0.0, "профит_фактор": 0.0, "просадка_денег": 0.0}
        if not завершённые:
            return итог
        R = [р.результат_R - издержки_R for р in завершённые]
        деньги = [(р.результат_R - издержки_R) * р.риск_денег for р in завершённые]
        победы = [x for x in R if x > 0]
        убытки = [x for x in R if x <= 0]
        накоп = пик = просадка = 0.0
        for д in деньги:
            накоп += д
            пик = max(пик, накоп)
            просадка = min(просадка, накоп - пик)
        итог.update({
            "побед": len(победы), "доля_побед": len(победы) / len(R) * 100,
            "сумма_R": sum(R), "сумма_денег": sum(деньги),
            "профит_фактор": (sum(победы) / abs(sum(убытки))) if убытки else float("inf"),
            "просадка_денег": просадка,
        })
        return итог

    взятые = [р for р in решения if р.решение == ВЗЯЛ]
    пропущенные = [р for р in решения if р.решение == ПРОПУСТИЛ]
    return {"взятые": посчитать(взятые), "пропущенные": посчитать(пропущенные),
            "все": посчитать(решения)}
