"""
Теневой журнал: записываем ВСЁ, включая отсеянное фильтрами.

Зачем. Рекомендации проходят через фильтры, и их остаётся мало — около
5 сделок в месяц. Чтобы понять, работает ли система, нужно 30 закрытых
сделок, то есть почти два месяца ожидания. А главный вопрос — правильно ли
фильтры отсеивают — по одним рекомендациям вообще не проверить: отсеянных
сделок в журнале нет, сравнивать не с чем.

Тень пишет обе части. Через месяц становится видно:
  если отсеянные в среднем хуже — фильтры работают, оставляем;
  если лучше — фильтры мешают, и это надо знать до того, как они съедят год.

Рекомендации от этого не меняются. Теневые записи помечены, в советы
не идут и в Telegram не отправляются. Их единственная задача — накопить
материал для сравнения.

Хранится в state/shadow.json.
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import asdict, dataclass, field

from . import bars

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")
ФАЙЛ = os.path.join(ПАПКА, "shadow.json")

ЖДЁТ = "ждёт входа"
В_РАБОТЕ = "в работе"
ЗАКРЫТА = "закрыта"


@dataclass
class ТеневаяСделка:
    ид: str
    актив: str
    система: str              # "короткая" — пока только она
    направление: str
    создана: float

    вход: float
    стоп: float
    цель: float
    тип_ордера: str
    уверенность: str
    режим: str
    волатильность: str

    # Пустой список = сигнал прошёл все фильтры и был рекомендован.
    отсеяно: list[str] = field(default_factory=list)
    порог_безубытка: float = 0.0
    срок_до: float = 0.0

    состояние: str = ЖДЁТ
    цена_входа: float | None = None
    вошли_в: float | None = None
    стоп_начальный: float | None = None   # для расчёта риска
    стоп_в_безубытке: bool = False
    цена_выхода: float | None = None
    закрыта_в: float | None = None
    исход: str | None = None
    результат_R: float | None = None

    @property
    def рекомендована(self) -> bool:
        return not self.отсеяно

    @property
    def риск_на_единицу(self) -> float:
        """Риск считается от ПЕРВОНАЧАЛЬНОГО стопа.

        Раньше брался текущий, и это была мина: когда стоп переносится
        в безубыток, он становится равен цене входа, риск обращается
        в ноль, и на следующем проходе сделка отсекается проверкой
        "if риск <= 0: continue" — то есть зависает навсегда, не закрывшись
        и не попав в статистику. Уцелевали только те, что успевали
        закрыться в том же проходе, где сработал безубыток.
        """
        база = self.цена_входа if self.цена_входа else self.вход
        опорный = self.стоп_начальный if self.стоп_начальный else self.стоп
        return abs(база - опорный)


def _читать() -> dict:
    if not os.path.exists(ФАЙЛ):
        return {"сделки": [], "создан": time.time()}
    with open(ФАЙЛ, encoding="utf-8") as f:
        return json.load(f)


def _писать(д: dict) -> None:
    os.makedirs(ПАПКА, exist_ok=True)
    д["обновлён"] = time.time()
    with open(ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump(д, f, ensure_ascii=False, indent=1)


def все() -> list[ТеневаяСделка]:
    return [ТеневаяСделка(**с) for с in _читать()["сделки"]]


def сохранить(сделки: list[ТеневаяСделка]) -> None:
    д = _читать()
    д["сделки"] = [asdict(с) for с in сделки]
    _писать(д)


def добавить(анализ, часов_в_баре: float, срок_баров: int,
             порог_безубытка: float, система: str = "короткая") -> ТеневаяСделка | None:
    """Записывает сигнал в тень. По одному активу одновременно только одна
    запись — иначе журнал наполнится дублями одного движения."""
    сделки = все()
    if any(с.актив == анализ.актив and с.система == система
           and с.состояние != ЗАКРЫТА for с in сделки):
        return None

    p = анализ.план
    if p is None:
        return None

    с = ТеневаяСделка(
        ид=f"{система}-{анализ.актив}-{int(time.time())}",
        актив=анализ.актив, система=система,
        направление=анализ.направление, создана=time.time(),
        вход=p.вход, стоп=p.стоп, стоп_начальный=p.стоп, цель=p.цели[0],
        тип_ордера=p.тип_ордера, уверенность=анализ.уверенность,
        режим=анализ.режим.направление,
        волатильность=анализ.режим.волатильность,
        отсеяно=list(анализ.отсеяно_фильтрами),
        порог_безубытка=порог_безубытка,
        срок_до=time.time() + срок_баров * часов_в_баре * 3600,
    )
    сделки.append(с)
    сохранить(сделки)
    return с


def провести(бары_по_активам: dict[str, list[dict]]) -> list[str]:
    """Двигает незакрытые записи ПО БАРАМ. Логика та же, что в основном
    журнале: иначе сравнение рекомендаций с отсеянными окажется нечестным."""
    сделки = все()
    события: list[str] = []
    сейчас = time.time()

    for с in сделки:
        if с.состояние == ЗАКРЫТА:
            continue
        все_бары = бары_по_активам.get(с.актив)
        if not все_бары:
            continue
        длинная = с.направление == "Long"

        if с.состояние == ЖДЁТ:
            свежие = bars.бары_после(все_бары, с.создана)
            if not свежие:
                continue
            if с.тип_ордера == "Market":
                вошли_на = свежие[0]
                с.цена_входа = вошли_на["close"]
            else:
                вошли_на = bars.первое_касание(свежие, с.вход)
                с.цена_входа = с.вход if вошли_на else None
            if вошли_на is None:
                if сейчас > с.срок_до:
                    с.состояние, с.исход = ЗАКРЫТА, "не дошло"
                    с.закрыта_в, с.результат_R = сейчас, 0.0
                    события.append(f"{с.актив}: вход не состоялся")
                continue
            с.состояние = В_РАБОТЕ
            с.вошли_в = вошли_на["t"] / 1000

        риск = с.риск_на_единицу
        if риск <= 0:
            continue

        for б in bars.бары_после(все_бары, с.вошли_в or с.создана):
            high, low = б["high"], б["low"]
            стоп_задет = (low <= с.стоп) if длинная else (high >= с.стоп)
            цель_задета = (high >= с.цель) if длинная else (low <= с.цель)

            if стоп_задет:
                с.состояние = ЗАКРЫТА
                с.исход = "безубыток" if с.стоп_в_безубытке else "стоп"
                с.цена_выхода, с.закрыта_в = с.стоп, б["t"] / 1000
                движение = ((с.стоп - с.цена_входа) if длинная
                            else (с.цена_входа - с.стоп))
                с.результат_R = движение / риск
                события.append(f"{с.актив}: {с.исход}")
                break
            if цель_задета:
                с.состояние, с.исход = ЗАКРЫТА, "цель"
                с.цена_выхода, с.закрыта_в = с.цель, б["t"] / 1000
                движение = ((с.цель - с.цена_входа) if длинная
                            else (с.цена_входа - с.цель))
                с.результат_R = движение / риск
                события.append(f"{с.актив}: цель")
                break

            if not с.стоп_в_безубытке and с.порог_безубытка > 0:
                прибыль_R = ((high - с.цена_входа) if длинная
                             else (с.цена_входа - low)) / риск
                if прибыль_R >= с.порог_безубытка:
                    с.стоп = с.цена_входа
                    с.стоп_в_безубытке = True

    сохранить(сделки)
    return события


def сводка(издержки_R: float = 0.125) -> dict:
    """Сравнение рекомендованных и отсеянных — ради чего тень и заведена."""
    сделки = все()

    def посчитать(набор: list[ТеневаяСделка]) -> dict:
        закрытые = [с for с in набор if с.состояние == ЗАКРЫТА
                    and с.результат_R is not None and с.исход != "не дошло"]
        итог = {"всего": len(набор), "закрыто": len(закрытые),
                "в_работе": sum(1 for с in набор if с.состояние == В_РАБОТЕ),
                "ждут": sum(1 for с in набор if с.состояние == ЖДЁТ),
                "доля_побед": 0.0, "средний_R": 0.0, "профит_фактор": 0.0}
        if not закрытые:
            return итог
        R = [с.результат_R - издержки_R for с in закрытые]
        победы = [r for r in R if r > 0]
        убытки = [r for r in R if r <= 0]
        итог.update({
            "доля_побед": len(победы) / len(R) * 100,
            "средний_R": sum(R) / len(R),
            "сумма_R": sum(R),
            "профит_фактор": (sum(победы) / abs(sum(убытки))) if убытки
            else float("inf"),
        })
        return итог

    рекомендованные = [с for с in сделки if с.рекомендована]
    отсеянные = [с for с in сделки if not с.рекомендована]

    # По каждому фильтру отдельно: какие сделки он отсеял и чем они кончились.
    по_фильтрам: dict[str, list[ТеневаяСделка]] = {}
    for с in отсеянные:
        for ф in с.отсеяно:
            по_фильтрам.setdefault(ф, []).append(с)

    return {
        "рекомендованные": посчитать(рекомендованные),
        "отсеянные": посчитать(отсеянные),
        "все": посчитать(сделки),
        "по_фильтрам": {ф: посчитать(н) for ф, н in по_фильтрам.items()},
    }
