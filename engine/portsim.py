"""
Портфель по ЖИВЫМ правилам — для замеров, а не для торговли.

Зачем. Каждая система меряется своим бэктестом в одиночку, а деньги
зарабатываются портфелем: системы делят общий риск, одну монету может
держать только одна из них, в день открывается не больше пяти позиций.
Замер «в одиночку» уже однажды обманул нас в разы: бэктест держал 15
позиций на 45% счёта, при нашем пределе 6%. Решать, сколько ставить на
каждую систему, можно только прогоном через портфель, который допускает
ровно то, что допускает настоящий (engine/portfolio.py):

  * у быстрой системы (короткая) свой потолок риска, у медленных
    (прорывы и долгосрочная) — свой, общий на двоих; друг другу они
    место НЕ занимают;
  * позиций всего не больше предела, новых за день не больше предела;
  * одну монету держит одна система;
  * у прорывов ещё свой предел числа позиций;
  * риск прорыва считается ТЕКУЩИЙ: с доливками он растёт, с подтяжкой
    стопа падает до нуля — так портфелю его сообщает живой журнал.

Счёт растёт сложным процентом: ставка берётся от счёта на день входа.
Пессимистичная кривая вычитает весь текущий риск открытых позиций — это
«если все стопы сработают сегодня».
"""

from __future__ import annotations

import json
import os
from datetime import date, datetime, timedelta, timezone

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ФАЙЛЫ = (("trades.json", "короткая"),
         ("trades_long.json", "долгосрочная"),
         ("trades_breakout.json", "прорывы"))
БЫСТРЫЕ = {"короткая"}


def день(t: float) -> str:
    if t > 1e11:
        t /= 1000.0
    return datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%d")


def загрузить(системы: set[str] | None = None, база: str = БАЗА,
              исключить: dict[str, set[str]] | None = None) -> list[dict]:
    """Сделки всех систем в одном виде, по времени входа.

    `исключить` — монеты, которые система вживую не торгует, например
    {'короткая': {'LTCUSDT', 'ADAUSDT'}}. Их сделки из бэктеста не берутся:
    иначе замер считал бы деньги, которых в жизни не будет."""
    исключить = исключить or {}
    из: list[dict] = []
    for файл, система in ФАЙЛЫ:
        if системы and система not in системы:
            continue
        п = os.path.join(база, файл)
        if not os.path.exists(п):
            continue
        with open(п, encoding="utf-8") as f:
            сырые = json.load(f)
        for с in сырые:
            вх, вых, r = с.get("время_входа"), с.get("время_выхода"), с.get("r")
            if вх is None or вых is None or not isinstance(r, (int, float)):
                continue
            if с.get("актив") in исключить.get(система, ()):
                continue
            путь = ({д: float(x) for д, x in с["путь"]} if с.get("путь") else None)
            из.append({"система": система, "актив": с.get("актив", "?"),
                       "когда": float(вх), "вход": день(вх), "выход": день(вых),
                       "r": float(r), "путь": путь})
    из.sort(key=lambda с: (с["когда"], с["система"], с["актив"]))
    return из


def календарь(сделки: list[dict]) -> list[str]:
    if not сделки:
        return []
    с = date.fromisoformat(min(x["вход"] for x in сделки))
    по = date.fromisoformat(max(x["выход"] for x in сделки))
    return [(с + timedelta(days=i)).isoformat() for i in range((по - с).days + 1)]


def прогнать(сделки: list[dict], дни: list[str], ставки: dict[str, float],
             пределы: dict, капитал: float = 100.0) -> dict:
    """ставки — процент счёта на позицию по системам, например
    {'короткая': 2.0, 'долгосрочная': 3.0, 'прорывы': 0.25}.
    пределы — {'медленных', 'быстрых', 'позиций', 'в_день', 'прорывов'}."""
    if not дни:
        return {"кривая": [], "песс": [], "дни": []}
    первый, последний = дни[0], дни[-1]
    по_дню: dict[str, list[dict]] = {}
    вне_окна = 0
    for с in сделки:
        if с["система"] not in ставки:
            continue
        if с["вход"] < первый or с["выход"] > последний:
            вне_окна += 1
            continue
        по_дню.setdefault(с["вход"], []).append(с)

    п_мед = float(пределы.get("медленных", 6.0))
    п_быстр = float(пределы.get("быстрых", 4.0))
    п_поз = int(пределы.get("позиций", 12))
    п_день = int(пределы.get("в_день", 0))
    п_прорывов = int(пределы.get("прорывов", 10))

    счёт = капитал
    открытые: list[dict] = []
    закрыть: dict[str, list[dict]] = {}
    кривая: list[float] = []
    песс: list[float] = []
    взято: dict[str, int] = {}
    отсеяно: dict[str, int] = {}
    причины: dict[str, int] = {}
    вклад: dict[str, float] = {}
    макс_разом = 0.0

    def закрыть_позицию(поз: dict) -> None:
        nonlocal счёт
        прибыль = поз["r"] * поз["деньги"]
        счёт += прибыль
        вклад[поз["система"]] = вклад.get(поз["система"], 0.0) + прибыль
        открытые.remove(поз)

    def отказ(система: str, почему: str) -> None:
        отсеяно[система] = отсеяно.get(система, 0) + 1
        причины[почему] = причины.get(почему, 0) + 1

    for д in дни:
        for поз in закрыть.pop(д, []):
            закрыть_позицию(поз)

        сегодня = 0
        for к in по_дню.get(д, []):
            система = к["система"]
            ставка = float(ставки[система])
            if any(о["актив"] == к["актив"] for о in открытые):
                отказ(система, "монета занята другой позицией")
                continue
            if len(открытые) >= п_поз:
                отказ(система, "предел числа позиций")
                continue
            if п_день and сегодня >= п_день:
                отказ(система, "предел новых позиций в день")
                continue
            if (система == "прорывы" and
                    sum(1 for о in открытые if о["система"] == "прорывы") >= п_прорывов):
                отказ(система, "предел числа прорывов")
                continue
            быстрая = система in БЫСТРЫЕ
            свой = sum(о["ставка"] * о["R"] for о in открытые
                       if (о["система"] in БЫСТРЫЕ) == быстрая)
            if свой + ставка > (п_быстр if быстрая else п_мед) + 1e-9:
                отказ(система, "потолок риска " + ("быстрых" if быстрая else "медленных"))
                continue
            поз = dict(к, ставка=ставка, R=1.0, деньги=счёт * ставка / 100)
            открытые.append(поз)
            закрыть.setdefault(к["выход"], []).append(поз)
            сегодня += 1
            взято[система] = взято.get(система, 0) + 1

        # Вход и выход в один календарный день (у короткой системы шесть
        # баров в сутки): без этого прохода позиция занимала бы место вечно.
        for поз in закрыть.pop(д, []):
            закрыть_позицию(поз)

        # Текущий риск прорывов на конец дня — им портфель будет судить завтра.
        for о in открытые:
            if о["путь"] and д in о["путь"]:
                о["R"] = о["путь"][д]

        под_риском = sum(о["деньги"] * о["R"] for о in открытые)
        кривая.append(счёт)
        песс.append(счёт - под_риском)
        if счёт > 0:
            макс_разом = max(макс_разом, под_риском / счёт * 100)

    return {"дни": дни, "кривая": кривая, "песс": песс, "взято": взято,
            "отсеяно": отсеяно, "причины": причины, "вклад": вклад,
            "макс_разом_пр": макс_разом, "вне_окна": вне_окна}


# --------------------------------------------------------------- показатели

def показатели(кривая: list[float], песс: list[float]) -> dict:
    """Доход по кривой, просадка — от лучшего достигнутого счёта до
    пессимистичной отметки (если бы все стопы сработали в тот день)."""
    if not кривая or кривая[0] <= 0:
        return {"итог_пр": 0.0, "просадка_пр": 0.0, "отношение": 0.0,
                "годовых_пр": 0.0}
    итог = (кривая[-1] / кривая[0] - 1) * 100
    пик, худшая = кривая[0], 0.0
    for к, п in zip(кривая, песс):
        пик = max(пик, к)
        худшая = min(худшая, (п - пик) / пик * 100)
    лет = max(len(кривая), 1) / 365.0
    годовых = ((кривая[-1] / кривая[0]) ** (1 / лет) - 1) * 100 if кривая[-1] > 0 else -100.0
    отношение = итог / abs(худшая) if худшая < -1e-9 else float("inf")
    return {"итог_пр": итог, "просадка_пр": худшая, "отношение": отношение,
            "годовых_пр": годовых}


def по_половинам(итог: dict) -> tuple[dict, dict]:
    к, п = итог["кривая"], итог["песс"]
    г = len(к) // 2
    return показатели(к[:г], п[:г]), показатели(к[г:], п[г:])
