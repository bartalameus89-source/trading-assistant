def итог(ц: dict[str, float]) -> str:
    д = pnl.подсчитать(ц)
    р, т = д["сводка_рекомендаций"], д["сводка_тени"]
    дни = equity.прочитать()
    наши = [x for x in дни if x.get("наш_итог") is not None]
    строки = [
        "💰 <b>НАШ СЧЁТ</b> — рекомендации системы",
        "",
        f"<b>Итого на бумаге: {_д(р['итог'])} $</b> от {конфиг()['риск']['депозит']} $",
        f"закрытые {_д(р['закрыто_итог'])} $ · в работе {_д(р['открыто_итог'])} $",
        "",
        f"Закрыто сделок: {р['сделок']} (в плюс {р['в_плюс']}, в минус {р['в_минус']}, "
        f"в ноль {р['в_ноль']})",
        f"Заработали {_д(р['заработано'])} $ · потеряли {_д(р['потеряно'])} $",
        f"В работе: {р['в_работе']} позиций"
        + (f", у {р['защищено']} прибыль уже закреплена стопом" if р["защищено"] else ""),
    ]
    if len(наши) >= 2:
        строки.append(f"С {_дата(наши[0]['когда'])}: {_д(наши[0]['наш_итог'])} → "
                      f"{_д(наши[-1]['наш_итог'])} $ по снимкам на конец дня")
    строки += [
        "",
        f"<i>Тень — сделки, которые система отвергла, не наши деньги: закрыто "
        f"{т['сделок']}, {_д(т['закрыто_итог'])} $, в работе {_д(т['открыто_итог'])} $.</i>",
        f"<i>До первых выводов нужно 30 закрытых рекомендаций, сейчас {р['сделок']}.</i>",
    ]
    return "\n".join(строки)


ИМЯ_СИСТЕМЫ = {"короткая": "короткая", "прорывы": "прорыв", "долгосрочная": "долгосрочная"}


def позиции(ц: dict[str, float]) -> str:
    все = [x for x in trades.все(ц) if x["ветка"] == "рекомендация"]
    открытые = [x for x in все if x["состояние"] == "открыта"]
    ждут = [x for x in все if not x["закрыта_ли"] and x["состояние"] != "открыта"]
    строки = ["📂 <b>ПОЗИЦИИ НАШЕГО СЧЁТА</b>", ""]
    if not открытые and not ждут:
        строки.append("Открытых позиций нет.")
    for x in sorted(открытые, key=lambda x: -(x["деньги"] or 0)):
        знак = "🟢" if (x["деньги"] or 0) >= 0 else "🔴"
        сейчас = _цена(x["цена_сейчас"]) if x["цена_сейчас"] else "нет цены"
        строки.append(f"{знак} <b>{x['актив']}</b> · {ИМЯ_СИСТЕМЫ.get(x['система'], x['система'])}")
        строки.append(f"   вход {_цена(x['вход'])} → сейчас {сейчас} · стоп {_цена(x['стоп'])}")
        строки.append(f"   {_д(x['r'])}R = <b>{_д(x['деньги'])} $</b> · с {_дата(x['открыта'])}")
    if ждут:
        строки += ["", "<b>Ждут входа</b> (лимитный ордер):"]
        for x in ждут:
            строки.append(f"⏳ {x['актив']} · вход {_цена(x['вход'])} · стоп {_цена(x['стоп'])}")
    if открытые:
        строки += ["", f"Всего в работе: <b>{_д(sum(x['деньги'] or 0 for x in открытые))} $</b>"]
    return "\n".join(строки)


def сделки(ц: dict[str, float], сколько: int = 12) -> str:
    закрытые = [x for x in trades.все(ц)
                if x["ветка"] == "рекомендация" and x["закрыта_ли"]]
    строки = ["📜 <b>ЗАКРЫТЫЕ СДЕЛКИ НАШЕГО СЧЁТА</b>", ""]
    if not закрытые:
        строки.append("Закрытых сделок пока нет.")
    for x in закрытые[:сколько]:
        if not x["исполнена"]:
            строки.append(f"⚪ {_дата(x['закрыта'] or x['открыта'])} {x['актив']} — ордер не исполнился")
            continue
        знак = "✅" if x["деньги"] > 0 else ("➖" if x["деньги"] == 0 else "❌")
        строки.append(f"{знак} {_дата(x['закрыта'])} <b>{x['актив']}</b> "
                      f"({ИМЯ_СИСТЕМЫ.get(x['система'], x['система'])}) — {x['исход']}, "
                      f"{_д(x['r'])}R = {_д(x['деньги'])} $")
    св = trades.свод([x for x in закрытые])
    if св["сделок"]:
        строки += ["", f"Итог закрытых: <b>{_д(св['закрыто_итог'])} $</b> · "
                       f"сделок: {св['сделок']} · побед {св['доля_побед']:.0f}%"]
    return "\n".join(строки)


def сигналы_сейчас(cfg: dict | None = None) -> str:
    """Живой разбор рынка — считается прямо сейчас, 20–40 секунд."""
    cfg = cfg or конфиг()
    исключить = set(cfg["сигналы"].get("исключить_из_короткой", []))
    короткие, почему_нет, ошибок = [], {}, 0
    прорывы_есть, прорывы_близко = [], []
    for актив in cfg["активы"]:
        try:
            свечи = data.загрузить(актив, cfg["таймфрейм"], лимит=400,
                                   источники=cfg["источник_данных"])
            флаги = data.проверить_качество(свечи, cfg["сигналы"]["макс_возраст_данных_баров"])
            а = signals.проанализировать(свечи, cfg, флаги, депозит=cfg["риск"]["депозит"])
            if а.вывод == signals.СИГНАЛ and а.план and актив not in исключить:
                короткие.append(а)
            elif а.причины_отказа:
                к = а.причины_отказа[0].split(":")[0][:40]
                почему_нет[к] = почему_нет.get(к, 0) + 1
            дн = data.загрузить(актив, "1d", лимит=120, источники=cfg["источник_данных"])
            п = breakout.проанализировать_прорыв(дн, cfg)
            if п.вывод == breakout.ЕСТЬ_ПРОРЫВ:
                прорывы_есть.append(п)
            elif п.вывод == breakout.БЛИЗКО:
                прорывы_близко.append(п)
        except Exception:
            ошибок += 1
    строки = ["🔔 <b>СИГНАЛЫ ПРЯМО СЕЙЧАС</b>", "", "<b>Короткая система</b>"]
    if короткие:
        for а in короткие:
            p = а.план
            строки.append(f"🟢 <b>{_монета(а.актив)}</b> {'покупка' if а.направление == 'Long' else 'шорт'} · "
                          f"вход {_цена(p.вход)} · стоп {_цена(p.стоп)} · цель {_цена(p.цели[0])}")
    else:
        строки.append("Сигналов нет.")
        if почему_нет:
            главные = sorted(почему_нет.items(), key=lambda kv: -kv[1])[:3]
            строки.append("<i>Чаще всего мешает: "
                          + "; ".join(f"{к.lower()} ({v})" for к, v in главные) + "</i>")
    строки += ["", "<b>Прорывы</b>"]
    if прорывы_есть:
        строки.append("🚀 Пробой сейчас: " + ", ".join(_монета(п.актив) for п in прорывы_есть))
    if прорывы_близко:
        строки.append("👀 Близко к пробою: " + ", ".join(
            f"{_монета(п.актив)} (ещё {п.до_прорыва_проц:.1f}%)".replace(".", ",") for п in
            sorted(прорывы_близко, key=lambda п: п.до_прорыва_проц)))
    if not прорывы_есть and not прорывы_близко:
        строки.append("Рядом с пробоем монет нет.")
    строки += ["", "<i>Это разбор на сейчас. Рекомендацию система выдаёт в проходе автоматики "
                   "раз в 4 часа — с учётом лимитов портфеля; она придёт отдельным сообщением.</i>"]
    if ошибок:
        строки.append(f"<i>Не удалось получить данные по {ошибок} монетам.</i>")
    return "\n".join(строки)


def обучение() -> str:
    строки_вар = variants.свод()
    строки = ["🧪 <b>ОБУЧЕНИЕ</b>", "", "<b>Фильтр волатильности — варианты</b>",
              "<i>ослабление: сигналов / закрыто / итог</i>"]
    for в in строки_вар:
        итог = f"{_д(в['сумма_R'])}R" if в["закрыто"] else "—"
        метка = " ← наш счёт" if в["ослабление"] == 50 else ""
        строки.append(f"{в['ослабление']:>3}%: {в['сигналов']} / {в['закрыто']} / {итог}{метка}")
    строки.append(f"<i>{variants.вывод(строки_вар)}</i>")
    зоны = volzones.свод()
    нов, спок = зоны["новая (80–90)"], зоны["спокойная (до 80)"]
    строки += ["", "<b>Зоны волатильности нашей короткой системы</b>",
               f"спокойная (до 80): сигналов {спок['сигналов']}, закрыто {спок['закрыто']}",
               f"новая (80–90): сигналов {нов['сигналов']}, закрыто {нов['закрыто']}",
               f"<i>{volzones.вывод(зоны)}</i>"]
    р = pnl.подсчитать()["сводка_рекомендаций"]
    строки += ["", f"<b>Статистика нашего счёта:</b> закрыто {р['сделок']} из 30, "
                   f"нужных для первых выводов."]
    return "\n".join(строки)


ИМЕНА_СИСТЕМ = {"короткие": "короткая", "прорывы": "прорывы", "долгосрочная": "долгосрочная"}


def состояние(запуски: list[dict] | None, скачивание: dict | None) -> str:
    """запуски — последние запуски автоматики с GitHub (или None, если
    их не удалось получить); скачивание — итог engine.remote.скачать."""
    строки = ["🩺 <b>СОСТОЯНИЕ СИСТЕМЫ</b>", ""]
    пульс = heartbeat.прочитать()
    строки.append("<b>Последний проход по системам</b>")
    for ключ, имя in ИМЕНА_СИСТЕМ.items():
        з = пульс.get(ключ) or {}
        часов = (time.time() - з["когда"]) / 3600 if з.get("когда") else None
        знак = "🟢" if часов is not None and часов < 8 else "🔴"
        ошибки = f", ошибок данных {з.get('ошибок_данных')}" if з.get("ошибок_данных") else ""
        строки.append(f"{знак} {имя}: {_часов_назад(з.get('когда'))}{ошибки}")
    строки.append("")
    if запуски is None:
        строки.append("⚠️ Не удалось узнать запуски на GitHub.")
    elif запуски:
        последний = запуски[0]
        зелёных = sum(1 for з in запуски if з.get("conclusion") == "success")
        строки.append(f"<b>Автоматика на GitHub</b>: последний запуск "
                      f"{_часов_назад(_из_iso(последний.get('created_at')))}, "
                      f"{_итог_запуска(последний)}")
        строки.append(f"успешных {зелёных} из последних {len(запуски)}")
    if скачивание and скачивание.get("ошибки"):
        строки.append("⚠️ Часть журналов не скачалась: " + ", ".join(скачивание["ошибки"]))
    else:
        строки.append("Данные в боте — свежие, с GitHub.")
    return "\n".join(строки)


def _из_iso(s: str | None) -> float | None:
    if not s:
        return None
    return datetime.fromisoformat(s.replace("Z", "+00:00")).timestamp()


def _итог_запуска(з: dict) -> str:
    if з.get("status") != "completed":
        return "идёт сейчас ⏳"
    return {"success": "успешно ✅", "failure": "с ошибкой ❌",
            "cancelled": "отменён"}.get(з.get("conclusion"), str(з.get("conclusion")))


