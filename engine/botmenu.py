"""
Тексты кнопок меню Telegram-бота.

Каждая кнопка — одна функция, возвращающая готовое сообщение (HTML Telegram).
Считают те же функции, что кабинет и недельный отчёт: наш счёт — engine/pnl,
сделки — engine/trades, варианты — engine/variants. Своих подсчётов здесь
нет намеренно — иначе бот и кабинет разошлись бы в цифрах, как это уже
случалось между блоками одной страницы.

Функции читают журналы из модулей движка как есть. Бот перед вызовом
перенаправляет модули на свежие журналы с GitHub (engine/remote.py),
проверки — на подменённые.
"""

