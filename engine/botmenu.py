def конфиг() -> dict:
    with open(os.path.join(БАЗА, "config.json"), encoding="utf-8") as f:
        return json.load(f)


def клавиатура() -> str:
    """Постоянные кнопки внизу чата — не нужно ничего набирать."""
    return json.dumps({
        "keyboard": [[{"text": к} for к in ряд] for ряд in РАСКЛАДКА],
        "resize_keyboard": True, "is_persistent": True,
    }, ensure_ascii=False)


# ------------------------------------------------------------------ помощники

def _д(x: float | None, знаков: int = 2) -> str:
    if x is None:
        return "—"
    return f"{x:+,.{знаков}f}".replace(",", " ").replace(".", ",")


def _монета(актив: str) -> str:
    return (актив or "?").replace("USDT", "")


def _цена(x: float | None) -> str:
    if not x:
        return "—"
    if x >= 100:
        return f"{x:,.0f}".replace(",", " ")
    if x >= 1:
        return f"{x:,.2f}".replace(",", " ").replace(".", ",")
    return f"{x:.4f}".replace(".", ",")


def _дата(t: float | None) -> str:
    if not t:
        return "—"
    return datetime.fromtimestamp(t, timezone.utc).strftime("%d.%m")


def _часов_назад(t: float | None) -> str:
    if not t:
        return "нет данных"
    ч = (time.time() - t) / 3600
    return f"{ч * 60:.0f} мин назад" if ч < 1 else f"{ч:.1f} ч назад"


_кеш_цен: dict = {"когда": 0.0, "цены": {}}


def цены(cfg: dict | None = None) -> dict[str, float]:
    """Текущие цены с бирж, не чаще раза в минуту. Монета, по которой цена
    не пришла, оценивается по своему стопу — так же, как в кабинете."""
    if time.time() - _кеш_цен["когда"] < 60 and _кеш_цен["цены"]:
        return _кеш_цен["цены"]
    cfg = cfg or конфиг()
    из: dict[str, float] = {}
    for актив in cfg["активы"]:
        try:
            из[актив] = data.загрузить(актив, "1d", лимит=3,
                                       источники=cfg["источник_данных"]).последняя_цена
        except Exception:
            continue
    _кеш_цен.update(когда=time.time(), цены=из)
    return из


