"""
Общий взгляд на риск: сколько денег под ударом ПО ВСЕМ системам сразу.

Зачем понадобилось. Каждая система вела свой счёт позиций и не знала
о других: у коротких лимит 3, у прорывов 5, у долгосрочной его не было
вовсе. Проверка состояния показала, что 10 монет из 15 одновременно заняты
двумя системами. Формально лимиты соблюдены, фактически это одна ставка
в тройном размере.

Почему это не мелочь. Замер корреляции дневных движений по нашим 15 монетам
за 799 дней: средняя связь с биткоином 0.67, у эфира 0.83. В 23% дней
падают 14 монет из 15 разом; худший день — все 15, в среднем -17.8%.
Стоп стоит в двух ATR, то есть в такой день срабатывают почти все стопы
одновременно. «Пять независимых позиций по 1%» — это не 1% пять раз,
это 5% один раз, и дневной лимит убытка в 3% не успевает вмешаться:
стопы срабатывают вместе, а не по очереди.

Отсюда правило: суммарный риск по всем системам ограничен сверху, и лимит
общий. Кто первый открылся, тот и занял место. Система, которой места
не хватило, записывает сигнал в тень — так видно, дорого ли обходится
сам лимит, и через месяц-другой его можно двигать по замеру, а не на глаз.
"""

from __future__ import annotations

import json
import os

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")

# Где что лежит: файл, ключ со списком, как называется система,
# и какие состояния считаются «деньги под ударом».
ИСТОЧНИКИ = [
    ("breakouts.json", "позиции", "прорывы", {"открыта"}),
    ("paper.json", "сделки", "короткая", {"в работе"}),
    ("paper_long.json", "позиции", "долгосрочная", {"открыта"}),
]


def _читать(имя: str, ключ: str) -> list[dict]:
    п = os.path.join(ПАПКА, имя)
    if not os.path.exists(п):
        return []
    try:
        with open(п, encoding="utf-8") as f:
            return json.load(f).get(ключ, []) or []
    except (json.JSONDecodeError, OSError):
        return []


def занятость(cfg: dict) -> dict:
    """Что открыто прямо сейчас по всем системам вместе.

    Теневые записи не считаются: они существуют только для сравнения
    и никаких денег не занимают."""
    депозит = cfg["риск"]["депозит"] or 100
    позиции: list[dict] = []

    for имя, ключ, система, живые in ИСТОЧНИКИ:
        for з in _читать(имя, ключ):
            if з.get("состояние") not in живые or з.get("тень"):
                continue
            риск = з.get("риск_usd")
            if риск is None:
                # У коротких сделок риск хранится в процентах капитала.
                риск = депозит * float(з.get("риск_пр", 0) or 0) / 100
            позиции.append({
                "актив": з.get("актив", "?"),
                "система": система,
                "риск_usd": float(риск or 0),
                "риск_пр": float(риск or 0) / депозит * 100 if депозит else 0.0,
            })

    активы: dict[str, list[str]] = {}
    for п in позиции:
        активы.setdefault(п["актив"], []).append(п["система"])

    return {
        "позиции": позиции,
        "всего_позиций": len(позиции),
        "риск_пр": sum(п["риск_пр"] for п in позиции),
        "риск_usd": sum(п["риск_usd"] for п in позиции),
        "по_активам": активы,
        "пересечения": {а: с for а, с in активы.items() if len(с) > 1},
    }


def лимиты(cfg: dict) -> tuple[float, int]:
    п = cfg.get("портфель", {})
    return (float(п.get("макс_общий_риск_пр", 6.0)),
            int(п.get("макс_всего_позиций", 6)))


def можно_открыть(cfg: dict, актив: str, риск_пр: float) -> tuple[bool, str]:
    """Разрешение на новую позицию с точки зрения всего портфеля.

    Возвращает (можно, причина отказа). Причина написана словами,
    чтобы её можно было показать в кабинете и записать в тень."""
    макс_риск, макс_поз = лимиты(cfg)
    з = занятость(cfg)

    if актив in з["по_активам"]:
        кто = ", ".join(з["по_активам"][актив])
        return False, f"{актив.replace('USDT', '')} уже занят ({кто})"

    if з["всего_позиций"] >= макс_поз:
        return False, (f"занято {з['всего_позиций']} позиций из {макс_поз} "
                       f"по всем системам вместе")

    станет = з["риск_пр"] + риск_пр
    if станет > макс_риск + 1e-9:
        return False, (f"общий риск стал бы {станет:.1f}% при пределе "
                       f"{макс_риск:.1f}% (сейчас под ударом {з['риск_пр']:.1f}%)")

    return True, ""


def словами(cfg: dict) -> str:
    з = занятость(cfg)
    макс_риск, макс_поз = лимиты(cfg)
    if not з["позиции"]:
        return "Открытых позиций нет — под ударом 0 $."
    строки = [f"Открыто {з['всего_позиций']} из {макс_поз} позиций, "
              f"под ударом {з['риск_usd']:,.2f} $ "
              f"({з['риск_пр']:.1f}% из {макс_риск:.1f}% разрешённых)."]
    if з["пересечения"]:
        строки.append("Один актив в нескольких системах: "
                      + "; ".join(f"{а.replace('USDT', '')} — {', '.join(с)}"
                                  for а, с in з["пересечения"].items()))
    строки.append("Монеты ходят вместе (связь с биткоином 0.67): в плохой день "
                  "стопы срабатывают не по очереди, а разом.")
    return " ".join(строки)
