"""
Журнал бумажной торговли: сделки без денег, но по всем правилам.

Зачем это нужно. Бэктест показал профит-фактор 0.93 на 36 сделках — то есть
преимущества не видно, но и доказать его отсутствие такая выборка не позволяет.
Разрешить спор может только новая история, которой ещё не существует.
Журнал её накапливает: сигналы отрабатываются на реальном рынке в реальном
времени, а капитал не участвует.

Отличие от бэктеста принципиальное: здесь нет и не может быть подглядывания
в будущее. Решение принимается до того, как рынок пошёл дальше.

Состояние хранится в state/paper.json.
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import asdict, dataclass, field

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")
ФАЙЛ = os.path.join(ПАПКА, "paper.json")

ОЖИДАЕТ_ВХОДА = "ожидает входа"
ОТКРЫТА = "открыта"
ЗАКРЫТА = "закрыта"


@dataclass
class БумажнаяСделка:
    ид: str
    актив: str
    направление: str
    открыта_в: float              # время создания сигнала, unix
    вход: float
    стоп: float
    цель: float
    тип_ордера: str
    размер: float | None
    риск_денег: float | None
    капитал_на_момент: float | None
    уверенность: str
    тег: str
    режим: str
    срок_до: float                # до какого времени ждём входа

    состояние: str = ОЖИДАЕТ_ВХОДА
    вошли_в: float | None = None
    цена_входа: float | None = None
    закрыта_в: float | None = None
    цена_выхода: float | None = None
    исход: str | None = None      # "цель" / "стоп" / "истёк срок" / "время"
    результат_R: float | None = None
    заметка: str = ""

    @property
    def риск_на_единицу(self) -> float:
        база = self.цена_входа if self.цена_входа else self.вход
        return abs(база - self.стоп)


def _загрузить() -> dict:
    if not os.path.exists(ФАЙЛ):
        return {"сделки": [], "создан": time.time()}
    with open(ФАЙЛ, encoding="utf-8") as f:
        return json.load(f)


def _сохранить(состояние: dict) -> None:
    os.makedirs(ПАПКА, exist_ok=True)
    with open(ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump(состояние, f, ensure_ascii=False, indent=1)


def все_сделки() -> list[БумажнаяСделка]:
    return [БумажнаяСделка(**с) for с in _загрузить()["сделки"]]


def _записать(сделки: list[БумажнаяСделка]) -> None:
    состояние = _загрузить()
    состояние["сделки"] = [asdict(с) for с in сделки]
    состояние["обновлён"] = time.time()
    _сохранить(состояние)


def уже_есть(актив: str, бар_времени: float, сделки: list[БумажнаяСделка]) -> bool:
    """Не заводим второй сигнал по активу, пока прежний не закрыт.
    Иначе журнал наполнится дублями одного и того же движения."""
    return any(с.актив == актив and с.состояние != ЗАКРЫТА for с in сделки)


def добавить(анализ, капитал: float | None, часов_в_баре: float,
             срок_баров: int) -> БумажнаяСделка | None:
    """Регистрирует новый сигнал. Возвращает сделку либо None, если такой
    актив уже в работе."""
    сделки = все_сделки()
    if уже_есть(анализ.актив, time.time(), сделки):
        return None

    p = анализ.план
    с = БумажнаяСделка(
        ид=f"{анализ.актив}-{int(time.time())}",
        актив=анализ.актив, направление=анализ.направление,
        открыта_в=time.time(), вход=p.вход, стоп=p.стоп, цель=p.цели[0],
        тип_ордера=p.тип_ордера, размер=p.размер, риск_денег=p.риск_валюта,
        капитал_на_момент=капитал, уверенность=анализ.уверенность,
        тег=анализ.тег_стратегии or "", режим=анализ.режим.направление,
        срок_до=time.time() + срок_баров * часов_в_баре * 3600,
    )
    сделки.append(с)
    _записать(сделки)
    return с


def обновить(свежие_цены: dict[str, dict]) -> list[tuple[БумажнаяСделка, str]]:
    """Проводит все незакрытые сделки по свежим свечам.

    `свежие_цены[актив]` = {"high": .., "low": .., "close": ..} — экстремумы
    с момента прошлой проверки. Возвращает список (сделка, что_произошло)
    для тех, чьё состояние изменилось.
    """
    сделки = все_сделки()
    события: list[tuple[БумажнаяСделка, str]] = []
    сейчас = time.time()

    for с in сделки:
        if с.состояние == ЗАКРЫТА:
            continue
        цены = свежие_цены.get(с.актив)
        if not цены:
            continue
        high, low, close = цены["high"], цены["low"], цены["close"]
        длинная = с.направление == "Long"

        # --- ждём входа ---
        if с.состояние == ОЖИДАЕТ_ВХОДА:
            if с.тип_ордера == "Market":
                с.состояние, с.вошли_в, с.цена_входа = ОТКРЫТА, сейчас, close
                события.append((с, "вход исполнен"))
            elif low <= с.вход <= high:
                с.состояние, с.вошли_в, с.цена_входа = ОТКРЫТА, сейчас, с.вход
                события.append((с, "вход исполнен"))
            elif сейчас > с.срок_до:
                с.состояние, с.исход, с.закрыта_в = ЗАКРЫТА, "истёк срок", сейчас
                с.результат_R = 0.0
                события.append((с, "сигнал истёк, входа не было"))
            continue

        # --- ведём открытую позицию ---
        риск = с.риск_на_единицу
        if риск <= 0:
            continue
        стоп_задет = (low <= с.стоп) if длинная else (high >= с.стоп)
        цель_задета = (high >= с.цель) if длинная else (low <= с.цель)

        # Тот же пессимизм, что и в бэктесте: при обоих уровнях в одной
        # свече считаем, что сработал стоп. Иначе журнал будет добрее рынка.
        if стоп_задет:
            с.состояние, с.исход = ЗАКРЫТА, "стоп"
            с.цена_выхода, с.закрыта_в = с.стоп, сейчас
            с.результат_R = -1.0
            события.append((с, "закрыта по стопу"))
        elif цель_задета:
            с.состояние, с.исход = ЗАКРЫТА, "цель"
            с.цена_выхода, с.закрыта_в = с.цель, сейчас
            движение = (с.цель - с.цена_входа) if длинная else (с.цена_входа - с.цель)
            с.результат_R = движение / риск
            события.append((с, "закрыта по цели"))

    _записать(сделки)
    return события


def статистика(издержки_R: float = 0.125) -> dict:
    """Сводка по журналу. `издержки_R` вычитается из каждой закрытой сделки —
    комиссии и проскальзывание существуют и на бумаге тоже."""
    сделки = все_сделки()
    закрытые = [с for с in сделки if с.состояние == ЗАКРЫТА
                and с.результат_R is not None and с.исход != "истёк срок"]

    итог = {
        "всего": len(сделки),
        "ожидают": sum(1 for с in сделки if с.состояние == ОЖИДАЕТ_ВХОДА),
        "открыты": sum(1 for с in сделки if с.состояние == ОТКРЫТА),
        "закрыто": len(закрытые),
        "истекло": sum(1 for с in сделки if с.исход == "истёк срок"),
        "побед": 0, "доля_побед": 0.0, "сумма_R": 0.0,
        "средний_R": 0.0, "профит_фактор": 0.0, "просадка_R": 0.0,
        "дней": 0.0,
    }
    if not закрытые:
        состояние = _загрузить()
        итог["дней"] = (time.time() - состояние.get("создан", time.time())) / 86400
        return итог

    R = [с.результат_R - издержки_R for с in закрытые]
    победы = [r for r in R if r > 0]
    убытки = [r for r in R if r <= 0]
    накоп = пик = просадка = 0.0
    for r in R:
        накоп += r
        пик = max(пик, накоп)
        просадка = min(просадка, накоп - пик)

    итог.update({
        "побед": len(победы),
        "доля_побед": len(победы) / len(R) * 100,
        "сумма_R": sum(R),
        "средний_R": sum(R) / len(R),
        "профит_фактор": (sum(победы) / abs(sum(убытки))) if убытки else float("inf"),
        "просадка_R": просадка,
        "дней": (time.time() - _загрузить().get("создан", time.time())) / 86400,
    })
    return итог
