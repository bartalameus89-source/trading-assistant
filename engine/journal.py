"""
Журнал бумажной торговли: сделки без денег, но по всем правилам.

Зачем это нужно. Бэктест показал профит-фактор 0.93 на 36 сделках — то есть
преимущества не видно, но и доказать его отсутствие такая выборка не позволяет.
Разрешить спор может только новая история, которой ещё не существует.
Журнал её накапливает: сигналы отрабатываются на реальном рынке в реальном
времени, а капитал не участвует.

Отличие от бэктеста принципиальное: здесь нет и не может быть подглядывания
в будущее. Решение принимается до того, как рынок пошёл дальше.

Состояние хранится в state/paper.json.
"""

from __future__ import annotations

import json
import os
import time

from . import bars, exit_rules
from dataclasses import asdict, dataclass, field

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")
ФАЙЛ = os.path.join(ПАПКА, "paper.json")


# Правила выхода берутся из конфига: сколько фиксировать на цели и насколько
# плотно вести стоп остатка. Замеры — в engine/exit_rules.py и в config.json.
def _правила_выхода() -> tuple[float, float]:
    п = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                     "config.json")
    try:
        with open(п, encoding="utf-8") as f:
            р = json.load(f).get("риск", {})
        return (float(р.get("доля_фиксации_на_цели", 0.0)),
                float(р.get("трейлинг_остатка_atr", 1.0)))
    except (json.JSONDecodeError, OSError, ValueError):
        return 0.0, 1.0


ДОЛЯ_НА_ЦЕЛИ, ТРЕЙЛИНГ_ОСТАТКА = _правила_выхода()

ОЖИДАЕТ_ВХОДА = "ожидает входа"
ОТКРЫТА = "открыта"
ЗАКРЫТА = "закрыта"


@dataclass
class БумажнаяСделка:
    ид: str
    актив: str
    направление: str
    открыта_в: float              # время создания сигнала, unix
    вход: float
    стоп: float
    цель: float
    тип_ордера: str
    размер: float | None
    риск_денег: float | None
    капитал_на_момент: float | None
    уверенность: str
    тег: str
    режим: str
    срок_до: float                # до какого времени ждём входа

    состояние: str = ОЖИДАЕТ_ВХОДА
    вошли_в: float | None = None
    цена_входа: float | None = None
    закрыта_в: float | None = None
    цена_выхода: float | None = None
    исход: str | None = None      # "цель" / "стоп" / "истёк срок" / "время"
    результат_R: float | None = None
    заметка: str = ""
    порог_безубытка: float = 0.0     # при скольких R стоп идёт на вход
    стоп_начальный: float | None = None   # для расчёта риска
    настройки: str = ""            # отпечаток версии правил, см. engine/settings_log.py
    # Частичная фиксация: часть прибыли берётся на цели, остаток едет
    # дальше с плотным стопом. Подробности и замеры — в engine/exit_rules.py.
    atr: float = 0.0
    часть_взята: bool = False
    взято_R: float = 0.0
    осталось: float = 1.0
    экстремум: float = 0.0
    стоп_в_безубытке: bool = False

    @property
    def риск_на_единицу(self) -> float:
        """Риск считается от ПЕРВОНАЧАЛЬНОГО стопа.

        Раньше брался текущий, и это была мина: когда стоп переносится
        в безубыток, он становится равен цене входа, риск обращается
        в ноль, и на следующем проходе сделка отсекается проверкой
        "if риск <= 0: continue" — то есть зависает навсегда, не закрывшись
        и не попав в статистику. Уцелевали только те, что успевали
        закрыться в том же проходе, где сработал безубыток.
        """
        база = self.цена_входа if self.цена_входа else self.вход
        опорный = self.стоп_начальный if self.стоп_начальный else self.стоп
        return abs(база - опорный)


def _загрузить() -> dict:
    if not os.path.exists(ФАЙЛ):
        return {"сделки": [], "создан": time.time()}
    with open(ФАЙЛ, encoding="utf-8") as f:
        return json.load(f)


def _сохранить(состояние: dict) -> None:
    os.makedirs(ПАПКА, exist_ok=True)
    with open(ФАЙЛ, "w", encoding="utf-8") as f:
        json.dump(состояние, f, ensure_ascii=False, indent=1)


def все_сделки() -> list[БумажнаяСделка]:
    return [БумажнаяСделка(**с) for с in _загрузить()["сделки"]]


def _записать(сделки: list[БумажнаяСделка]) -> None:
    состояние = _загрузить()
    состояние["сделки"] = [asdict(с) for с in сделки]
    состояние["обновлён"] = time.time()
    _сохранить(состояние)


def уже_есть(актив: str, бар_времени: float, сделки: list[БумажнаяСделка]) -> bool:
    """Не заводим второй сигнал по активу, пока прежний не закрыт.
    Иначе журнал наполнится дублями одного и того же движения."""
    return any(с.актив == актив and с.состояние != ЗАКРЫТА for с in сделки)


def добавить(анализ, капитал: float | None, часов_в_баре: float,
             срок_баров: int, порог_безубытка: float = 0.0) -> БумажнаяСделка | None:
    """Регистрирует новый сигнал. Возвращает сделку либо None, если такой
    актив уже в работе."""
    сделки = все_сделки()
    if уже_есть(анализ.актив, time.time(), сделки):
        return None

    p = анализ.план
    с = БумажнаяСделка(
        ид=f"{анализ.актив}-{int(time.time())}",
        актив=анализ.актив, направление=анализ.направление,
        открыта_в=time.time(), вход=p.вход, стоп=p.стоп, стоп_начальный=p.стоп, atr=p.atr or 0.0,
        настройки=settings_log.отпечаток(),
        цель=p.цели[0],
        тип_ордера=p.тип_ордера, размер=p.размер, риск_денег=p.риск_валюта,
        капитал_на_момент=капитал, уверенность=анализ.уверенность,
        тег=анализ.тег_стратегии or "", режим=анализ.режим.направление,
        срок_до=time.time() + срок_баров * часов_в_баре * 3600,
        порог_безубытка=порог_безубытка,
    )
    сделки.append(с)
    _записать(сделки)
    return с


def обновить(бары_по_активам: dict[str, list[dict]]) -> list[tuple[БумажнаяСделка, str]]:
    """Проводит все незакрытые сделки ПО БАРАМ, по одному.

    `бары_по_активам[актив]` = список {"t", "high", "low", "close"} по
    возрастанию времени. Каждая сделка идёт от СВОЕГО момента: раньше окно
    было общим и считалось от самой старой сделки, и свежая сделка
    проверялась по ценам, которых при ней не было. Подробности — в engine/bars.py.
    """
    сделки = все_сделки()
    события: list[tuple[БумажнаяСделка, str]] = []
    сейчас = time.time()

    for с in сделки:
        if с.состояние == ЗАКРЫТА:
            continue
        все_бары = бары_по_активам.get(с.актив)
        if not все_бары:
            continue
        длинная = с.направление == "Long"

        # --- ждём входа ---
        if с.состояние == ОЖИДАЕТ_ВХОДА:
            свежие = bars.бары_после(все_бары, с.открыта_в)
            if not свежие:
                continue
            if с.тип_ордера == "Market":
                вошли_на = свежие[0]
                с.цена_входа = вошли_на["close"]
            else:
                вошли_на = bars.первое_касание(свежие, с.вход)
                с.цена_входа = с.вход if вошли_на else None
            if вошли_на is None:
                if сейчас > с.срок_до:
                    с.состояние, с.исход = ЗАКРЫТА, "истёк срок"
                    с.закрыта_в, с.результат_R = сейчас, 0.0
                    события.append((с, "сигнал истёк, входа не было"))
                continue
            с.состояние, с.вошли_в = ОТКРЫТА, вошли_на["t"] / 1000
            события.append((с, "вход исполнен"))

        # --- ведём открытую позицию ---
        риск = с.риск_на_единицу
        if риск <= 0:
            continue

        # Бар входа исключаем: порядок событий внутри него неизвестен,
        # и его минимум мог случиться до нашего входа.
        # Ведение позиции вынесено в engine/exit_rules.py: одна логика
        # на все три журнала, проверяется отдельным тестом. Раньше она была
        # переписана в каждом журнале по-своему, и расхождения искать
        # приходилось глазами.
        сост = exit_rules.Состояние(
            направление=с.направление, цена_входа=с.цена_входа,
            стоп=с.стоп, стоп_начальный=с.стоп_начальный or с.стоп,
            цель=с.цель, atr=с.atr, порог_безубытка=с.порог_безубытка,
            доля_на_цели=ДОЛЯ_НА_ЦЕЛИ, трейлинг_atr=ТРЕЙЛИНГ_ОСТАТКА,
            стоп_в_безубытке=с.стоп_в_безубытке, часть_взята=с.часть_взята,
            взято_R=с.взято_R, осталось=с.осталось, экстремум=с.экстремум)

        for б in bars.бары_после(все_бары, с.вошли_в or с.открыта_в):
            шаг = exit_rules.провести_бар(сост, б["high"], б["low"])
            с.стоп = сост.стоп
            с.стоп_в_безубытке = сост.стоп_в_безубытке
            с.часть_взята = сост.часть_взята
            с.взято_R = сост.взято_R
            с.осталось = сост.осталось
            с.экстремум = сост.экстремум
            if шаг.событие:
                события.append((с, шаг.событие))
            if шаг.состояние == exit_rules.ЗАКРЫТА:
                с.состояние = ЗАКРЫТА
                с.исход = шаг.исход
                с.цена_выхода = шаг.цена_выхода
                с.закрыта_в = б["t"] / 1000
                с.результат_R = шаг.результат_R
                события.append((с, f"закрыта — {шаг.исход}"))
                break

    _записать(сделки)
    return события


def статистика(издержки_R: float = 0.125) -> dict:
    """Сводка по журналу. `издержки_R` вычитается из каждой закрытой сделки —
    комиссии и проскальзывание существуют и на бумаге тоже."""
    сделки = все_сделки()
    закрытые = [с for с in сделки if с.состояние == ЗАКРЫТА
                and с.результат_R is not None and с.исход != "истёк срок"]

    итог = {
        "всего": len(сделки),
        "ожидают": sum(1 for с in сделки if с.состояние == ОЖИДАЕТ_ВХОДА),
        "открыты": sum(1 for с in сделки if с.состояние == ОТКРЫТА),
        "закрыто": len(закрытые),
        "истекло": sum(1 for с in сделки if с.исход == "истёк срок"),
        "побед": 0, "доля_побед": 0.0, "сумма_R": 0.0,
        "средний_R": 0.0, "профит_фактор": 0.0, "просадка_R": 0.0,
        "дней": 0.0,
    }
    if not закрытые:
        состояние = _загрузить()
        итог["дней"] = (time.time() - состояние.get("создан", time.time())) / 86400
        return итог

    R = [с.результат_R - издержки_R for с in закрытые]
    победы = [r for r in R if r > 0]
    убытки = [r for r in R if r <= 0]
    накоп = пик = просадка = 0.0
    for r in R:
        накоп += r
        пик = max(пик, накоп)
        просадка = min(просадка, накоп - пик)

    итог.update({
        "побед": len(победы),
        "доля_побед": len(победы) / len(R) * 100,
        "сумма_R": sum(R),
        "средний_R": sum(R) / len(R),
        "профит_фактор": (sum(победы) / abs(sum(убытки))) if убытки else float("inf"),
        "просадка_R": просадка,
        "дней": (time.time() - _загрузить().get("создан", time.time())) / 86400,
    })
    return итог
