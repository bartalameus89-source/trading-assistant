"""
Доливка к выигрывающей позиции: добавляем размер там, где движение подтвердилось.

Идея старая (система «черепах» её использовала), у нас не проверялась ни разу.
Прорывы держат сделку около двух недель и ловят движения на десятки процентов.
Если по ходу движения добавлять, крупная сделка даёт кратно больше, а мелкие
убыточные остаются мелкими: доливки в них просто не происходит.

ЗАМЕР на 1126 сделках за 8 лет. Сырые числа выглядели как учетверение дохода,
и верить им было нельзя: доливка увеличивает размер позиции, а результат
считался в R от ПЕРВОНАЧАЛЬНОГО риска. Половина роста оказалась бы просто
плечом. Честное сравнение — доход на единицу просадки, против того же
среднего размера позиции БЕЗ доливок:

    без доливок                    +693R,  просадка -15R,  доход/просадка 45.9
    доливка через 1.0R, до 2 раз  +1945R,  просадка -32R,  доход/просадка 60.3
    то же плечо, но без доливок   +1189R,  просадка -26R,  доход/просадка 45.9

При одинаковой экспозиции доливка даёт на 31% больше дохода на единицу
просадки. Это преимущество, а не плечо: добавленные деньги идут только
в сделки, где движение уже состоялось.

Прочие проверенные варианты (доход/просадка): шаг 2.0R до 1 раза — 59.8,
шаг 0.5R до 3 раз — 56.3. Выбран шаг 1.0R до 2 доливок как лучший.

ВАЖНО ПРО РИСК. Доливка входит по цене ВЫШЕ первой, а стоп к тому моменту
уже подтянут вверх. Поэтому добавленная часть рискует меньше, чем первая,
и суммарный риск позиции растёт медленнее, чем её размер. Именно суммарный
риск и надо показывать портфелю — иначе потолок будет считать позицию
опаснее, чем она есть.
"""

from __future__ import annotations


def первая_часть(вход: float) -> list[dict]:
    return [{"цена": вход, "доля": 1.0}]


def порог_доливки(вход: float, риск: float, шаг_R: float, сделано: int) -> float:
    """Цена, при достижении которой делается следующая доливка."""
    return вход + риск * шаг_R * (сделано + 1)


def долить(части: list[dict], цена: float, доля: float = 1.0) -> None:
    части.append({"цена": цена, "доля": доля})


def размер_долей(части: list[dict]) -> float:
    return sum(ч["доля"] for ч in части)


def результат_R(части: list[dict], выход: float, риск: float) -> float:
    """Итог всей позиции в единицах ПЕРВОНАЧАЛЬНОГО риска."""
    if риск <= 0:
        return 0.0
    return sum(ч["доля"] * (выход - ч["цена"]) / риск for ч in части)


def результат_R_чистый(части: list[dict], выход: float, риск: float,
                       издержки_отн: float) -> float:
    """Итог после комиссий: каждая часть платит вход и выход от своего
    объёма. Живой журнал прорывов раньше их не вычитал, а бэктесты
    вычитают — и живые результаты прорывов выглядели лучше замеренных
    на пару сотых R на часть."""
    if риск <= 0:
        return 0.0
    return (результат_R(части, выход, риск)
            - sum(ч["доля"] * издержки_отн * ч["цена"] / риск for ч in части))


def риск_сейчас_R(части: list[dict], стоп: float, риск: float) -> float:
    """Сколько потеряем, если стоп сработает прямо сейчас, в единицах риска.

    Считается по КАЖДОЙ части от её собственной цены входа. Когда стоп
    подтянут выше цены первой части, число становится положительным:
    позиция уже не может закрыться в убыток."""
    if риск <= 0:
        return 0.0
    return sum(ч["доля"] * (стоп - ч["цена"]) / риск for ч in части)


def средняя_цена(части: list[dict]) -> float:
    всего = размер_долей(части)
    if всего <= 0:
        return 0.0
    return sum(ч["доля"] * ч["цена"] for ч in части) / всего
