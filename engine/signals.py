"""
Логика формирования сигнала. Разделы 2, 3 и 7 промта.

Ключевой принцип раздела 3.1: подтверждения считаются ПО ГРУППАМ.
RSI, MACD и Bollinger — все производные одного ценового ряда, их совпадение
почти не добавляет информации. Поэтому из каждой группы засчитывается
максимум одно подтверждение, и нужны подтверждения из разных групп.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from . import indicators as ind
from . import risk
from .data import Свечи
from .risk import LONG, SHORT, ПланСделки

# Вывод
СИГНАЛ = "СИГНАЛ"
НЕТ_СИГНАЛА = "НЕТ СИГНАЛА"
РИСК_ПРЕДУПРЕЖДЕНИЕ = "РИСК-ПРЕДУПРЕЖДЕНИЕ"

# Уверенность
НИЗКАЯ, СРЕДНЯЯ, ВЫСОКАЯ = "низкая", "средняя", "высокая"


@dataclass
class Подтверждение:
    группа: str          # A, B, C или D
    название: str
    факт: str            # измеренное значение — это факт
    интерпретация: str   # что это может значить — это уже интерпретация
    направление: str     # LONG или SHORT


@dataclass
class Режим:
    направление: str     # "тренд вверх" / "тренд вниз" / "боковик" / "переходный"
    волатильность: str   # "нормальная" / "высокая"
    adx: float
    bbw_перцентиль: float
    пояснение: str

    @property
    def трендовый(self) -> bool:
        return self.направление.startswith("тренд")

    @property
    def боковик(self) -> bool:
        return self.направление == "боковик"


@dataclass
class Анализ:
    актив: str
    таймфрейм: str
    источник: str
    цена: float
    время_бара: str
    возраст_баров: float

    режим: Режим
    показатели: dict
    флаги_данных: list[str]

    вывод: str = НЕТ_СИГНАЛА
    уверенность: str = НИЗКАЯ
    направление: str | None = None
    тег_стратегии: str | None = None
    срок_жизни_баров: int = 3

    подтверждения: list[Подтверждение] = field(default_factory=list)
    противоречия: list[str] = field(default_factory=list)
    причины_отказа: list[str] = field(default_factory=list)
    отягчающие: list[str] = field(default_factory=list)

    план: ПланСделки | None = None
    инвалидация: str | None = None

    @property
    def группы(self) -> set[str]:
        return {п.группа for п in self.подтверждения}


# ------------------------------------------------------- вспомогательное

def свинги(highs: list[float], lows: list[float], слева: int = 2, справа: int = 2):
    """Локальные экстремумы («свинги») — те самые уровни, от которых рынок
    разворачивался. Стоп ставится за них, а не на круглое число."""
    вершины: list[tuple[int, float]] = []
    впадины: list[tuple[int, float]] = []
    for i in range(слева, len(highs) - справа):
        окно_в = highs[i - слева:i + справа + 1]
        окно_н = lows[i - слева:i + справа + 1]
        if highs[i] == max(окно_в):
            вершины.append((i, highs[i]))
        if lows[i] == min(окно_н):
            впадины.append((i, lows[i]))
    return вершины, впадины


def определить_режим(показ: dict, П: dict) -> Режим:
    """Раздел 2: две независимые оси, а не одно значение."""
    adx = показ["adx"]
    перц = показ["bbw_перцентиль"]

    if adx >= П["adx_тренд"]:
        направление = "тренд вверх" if показ["ma50"] > показ["ma200"] else "тренд вниз"
        пояснение = (
            f"ADX {adx:.1f} выше порога {П['adx_тренд']}, "
            f"MA50 {'выше' if показ['ma50'] > показ['ma200'] else 'ниже'} MA200"
        )
    elif adx <= П["adx_боковик"]:
        направление = "боковик"
        пояснение = f"ADX {adx:.1f} ниже порога {П['adx_боковик']} — направленного движения нет"
    else:
        направление = "переходный"
        пояснение = (
            f"ADX {adx:.1f} между порогами {П['adx_боковик']} и {П['adx_тренд']} — "
            f"режим не определён"
        )

    волатильность = ("высокая" if перц >= П["bbw_высокая_волатильность_перцентиль"]
                     else "нормальная")
    return Режим(направление, волатильность, adx, перц, пояснение)


# ------------------------------------------------------- подтверждения

def собрать_подтверждения(показ: dict, свечи: Свечи, режим: Режим,
                          П: dict) -> list[Подтверждение]:
    """Максимум одно подтверждение на группу — раздел 3.1."""
    найдено: list[Подтверждение] = []

    # --- Группа A: тренд и структура ---
    a: Подтверждение | None = None
    if режим.трендовый:
        # Раздел 2 промта: тренд определяют ADX (сила) и MA50 vs MA200 (направление).
        # Мгновенное соотношение +DI/-DI здесь НЕ требуется: вход на откате по
        # определению происходит тогда, когда краткосрочное движение идёт против
        # тренда. Требовать согласия DI означало бы никогда не входить на откате.
        напр = LONG if режим.направление == "тренд вверх" else SHORT
        di_согласен = ((напр == LONG and показ["pdi"] > показ["mdi"])
                       or (напр == SHORT and показ["mdi"] > показ["pdi"]))
        a = Подтверждение(
            "A", "Направленный тренд",
            f"ADX {показ['adx']:.1f}, MA50 {показ['ma50']:,.2f} "
            f"{'выше' if показ['ma50'] > показ['ma200'] else 'ниже'} "
            f"MA200 {показ['ma200']:,.2f}; +DI {показ['pdi']:.1f} / -DI {показ['mdi']:.1f}",
            "тренд выражен по силе и направлению"
            + ("; краткосрочное движение с ним согласовано" if di_согласен
               else "; краткосрочно идёт откат против тренда — это и есть момент входа"),
            напр,
        )
    elif режим.боковик:
        # В боковике структурное подтверждение — цена у границы диапазона.
        if показ["цена"] <= показ["bb_низ"]:
            a = Подтверждение(
                "A", "Цена у нижней границы диапазона",
                f"цена {показ['цена']:,.2f} на уровне нижней полосы {показ['bb_низ']:,.2f}",
                "в боковике границы диапазона исторически чаще отрабатывают как отбой",
                LONG,
            )
        elif показ["цена"] >= показ["bb_верх"]:
            a = Подтверждение(
                "A", "Цена у верхней границы диапазона",
                f"цена {показ['цена']:,.2f} на уровне верхней полосы {показ['bb_верх']:,.2f}",
                "в боковике границы диапазона исторически чаще отрабатывают как отбой",
                SHORT,
            )
    if a:
        найдено.append(a)

    # --- Группа B: моментум ---
    b: Подтверждение | None = None
    rsi_ = показ["rsi"]
    гист = показ["macd"] - показ["macd_сигнал"]
    if режим.боковик:
        if rsi_ <= П["rsi_перепроданность"]:
            b = Подтверждение("B", "RSI в зоне перепроданности",
                              f"RSI {rsi_:.1f} (порог {П['rsi_перепроданность']})",
                              "возможна перепроданность — в боковике это аргумент за отбой вверх",
                              LONG)
        elif rsi_ >= П["rsi_перекупленность"]:
            b = Подтверждение("B", "RSI в зоне перекупленности",
                              f"RSI {rsi_:.1f} (порог {П['rsi_перекупленность']})",
                              "возможна перекупленность — в боковике это аргумент за откат вниз",
                              SHORT)
    else:
        # В тренде моментум подтверждается знаком гистограммы MACD. Положение цены
        # относительно EMA20 идёт как контекст, а не как условие: во время отката
        # цена уходит за EMA20, и это нормальная часть трендовой стратегии.
        где = "выше" if показ["цена"] > показ["ema20"] else "ниже"
        if гист > 0:
            b = Подтверждение("B", "Моментум вверх",
                              f"гистограмма MACD {гист:+.2f}; цена {где} EMA20 "
                              f"({показ['ema20']:,.2f})",
                              "импульс роста сохраняется", LONG)
        elif гист < 0:
            b = Подтверждение("B", "Моментум вниз",
                              f"гистограмма MACD {гист:+.2f}; цена {где} EMA20 "
                              f"({показ['ema20']:,.2f})",
                              "импульс снижения сохраняется", SHORT)
    if b:
        найдено.append(b)

    # --- Группа C: объём ---
    объёмы = свечи.volumes
    средний = sum(объёмы[-20:]) / 20
    последний = объёмы[-1]
    движение_вверх = свечи.closes[-1] > свечи.opens[-1]
    if последний > средний * 1.3:
        найдено.append(Подтверждение(
            "C", "Повышенный объём",
            f"объём последнего бара {последний:,.0f} против среднего {средний:,.0f} "
            f"за 20 баров (+{(последний / средний - 1) * 100:.0f}%)",
            "движение подкреплено участием, а не проходит на тонком рынке",
            LONG if движение_вверх else SHORT,
        ))

    # --- Группа D: ончейн ---
    # Источник не подключён. Пустая группа — это честно; выдумывать нечего.

    return найдено


# ------------------------------------------------------- построение плана

def построить_план(актив: str, направление: str, показ: dict, свечи: Свечи,
                   режим: Режим, П: dict,
                   рабочая_R: float = 1.5) -> tuple[ПланСделки | None, str]:
    """Возвращает (план, тег стратегии). Уровни берутся от реальных свингов
    и полос, а не от круглых чисел.

    В `цели` кладутся ДВЕ РАЗНЫЕ по смыслу величины:
      цели[0]  — рабочая цель, где реально фиксируется прибыль (`рабочая_R` риска);
      цели[-1] — ближайший структурный уровень, мера свободного хода.
    Второе не цель, а условие входа: если до уровня тесно, сделка не берётся."""
    цена = показ["цена"]
    atr_ = показ["atr"]
    вершины, впадины = свинги(свечи.highs[-120:], свечи.lows[-120:])

    посл_вершины = sorted([ц for _, ц in вершины[-12:]], reverse=True)
    посл_впадины = sorted([ц for _, ц in впадины[-12:]])

    if режим.боковик:
        тег = f"range_mean_reversion_{'long' if направление == LONG else 'short'}"
        if направление == LONG:
            вход = min(показ["bb_низ"], цена)
            ориентир = min(вход, цена)
            опора = min(посл_впадины) if посл_впадины else ориентир - atr_
            стоп = min(опора - atr_ * 0.3, ориентир - atr_ * 1.05)
            риск_ед = вход - стоп
            цели = [вход + рабочая_R * риск_ед, показ["bb_верх"]]
        else:
            вход = max(показ["bb_верх"], цена)
            ориентир = max(вход, цена)
            опора = max(посл_вершины) if посл_вершины else ориентир + atr_
            стоп = max(опора + atr_ * 0.3, ориентир + atr_ * 1.05)
            риск_ед = стоп - вход
            цели = [вход - рабочая_R * риск_ед, показ["bb_низ"]]
    else:
        # Тег берётся от РЕЖИМА, а не от направления: если они разойдутся,
        # это должно быть видно в журнале, а не замаскировано названием.
        куда = "up" if режим.направление == "тренд вверх" else "down"
        тег = f"trend_{куда}_pullback_{'long' if направление == LONG else 'short'}"
        if направление == LONG:
            # Если цена уже ушла ниже EMA20, откат УЖЕ идёт — ждать его бессмысленно,
            # входим по рынку. Если цена выше — ставим лимитку на откат к EMA20.
            вход = min(показ["ema20"], цена)
            ориентир = min(вход, цена)
            опора = max([ц for ц in посл_впадины if ц < ориентир],
                        default=ориентир - 2 * atr_)
            # Стоп — за дальней из двух границ: структурной опоры и границы шума.
            # Стоп внутри шума будет выбит случайным движением, а не опровержением идеи.
            стоп = min(опора - atr_ * 0.3, ориентир - atr_ * 1.05)
            риск_ед = вход - стоп
            # Первая цель — БЛИЖАЙШЕЕ сопротивление, каким бы близким оно ни было:
            # именно там движение с наибольшей вероятностью упрётся. Если до него
            # слишком мало хода, сделка не окупает риск и будет отклонена проверкой
            # R:R — это правильный исход, а не повод искать цель подальше.
            # Сопротивлением считается только то, что ВЫШЕ РЫНКА. Вершина, которую
            # цена уже прошла, ничего не сдерживает — брать её за цель означало бы
            # мерить прибыль до уровня, оставшегося позади.
            выше = [ц for ц in посл_вершины if ц > max(вход, цена)]
            структурная = min(выше) if выше else вход + 3 * риск_ед
            # Первая цель — рабочая, где реально фиксируем. Вторая — структурный
            # уровень: он не цель, а мера того, есть ли куда идти (проверка входа).
            цели = [вход + рабочая_R * риск_ед, структурная]
        else:
            вход = max(показ["ema20"], цена)
            ориентир = max(вход, цена)
            опора = min([ц for ц in посл_вершины if ц > ориентир],
                        default=ориентир + 2 * atr_)
            стоп = max(опора + atr_ * 0.3, ориентир + atr_ * 1.05)
            риск_ед = стоп - вход
            # Зеркально: поддержкой для шорта служит только то, что НИЖЕ РЫНКА.
            ниже = [ц for ц in посл_впадины if ц < min(вход, цена)]
            структурная = max(ниже) if ниже else вход - 3 * риск_ед
            цели = [вход - рабочая_R * риск_ед, структурная]

    # Сортировать НЕЛЬЗЯ: порядок здесь смысловой (рабочая цель, затем уровень),
    # а не по возрастанию. Если структурный уровень окажется ближе рабочей цели,
    # это не повод их менять местами — это повод отклонить сделку, что и сделает
    # проверка «Запас до сопротивления».
    план = ПланСделки(
        актив=актив, направление=направление, вход=round(вход, 8),
        стоп=round(стоп, 8), цели=[round(ц, 8) for ц in цели],
        текущая_цена=цена, atr=atr_,
    )
    return план, тег


# ------------------------------------------------------- главный проход

def проанализировать(свечи: Свечи, cfg: dict, флаги_данных: list[str],
                     депозит: float | None = None,
                     риск_кластера_текущий_пр: float = 0.0,
                     открытых_позиций: int = 0,
                     лимит_убытка_исчерпан: bool = False,
                     серия_убытков: int = 0,
                     проверять_свежесть: bool = True) -> Анализ:
    П = cfg["пороги"]
    С = cfg["сигналы"]
    закр, макс, мин = свечи.closes, свечи.highs, свечи.lows

    adx_р, pdi_р, mdi_р = ind.adx(макс, мин, закр, П["adx_период"])
    верх, серед, низ, ширина = ind.bollinger(закр, П["bb_период"], П["bb_отклонений"])
    линия, сигнал_л, _ = ind.macd(закр)
    окно = [v for v in ширина[-П["bbw_окно_баров"]:] if v is not None]
    bbw = ind.last_defined(ширина)[0]

    показ = {
        "цена": свечи.последняя_цена,
        "rsi": ind.last_defined(ind.rsi(закр, П["rsi_период"]))[0],
        "atr": ind.last_defined(ind.atr(макс, мин, закр, П["atr_период"]))[0],
        "ma50": ind.last_defined(ind.sma(закр, П["ma_быстрая"]))[0],
        "ma200": ind.last_defined(ind.sma(закр, П["ma_медленная"]))[0],
        "ema20": ind.last_defined(ind.ema(закр, П["ema_быстрая"]))[0],
        "adx": ind.last_defined(adx_р)[0],
        "pdi": ind.last_defined(pdi_р)[0],
        "mdi": ind.last_defined(mdi_р)[0],
        "macd": ind.last_defined(линия)[0],
        "macd_сигнал": ind.last_defined(сигнал_л)[0],
        "bb_верх": верх[-1], "bb_середина": серед[-1], "bb_низ": низ[-1],
        "bbw": bbw,
        "bbw_перцентиль": ind.percentile_rank(окно, bbw),
    }

    режим = определить_режим(показ, П)

    анализ = Анализ(
        актив=свечи.актив, таймфрейм=свечи.таймфрейм, источник=свечи.источник,
        цена=показ["цена"],
        время_бара=f"{свечи.время_последнего_бара:%Y-%m-%d %H:%M} UTC",
        возраст_баров=свечи.возраст_в_барах(),
        режим=режим, показатели=показ, флаги_данных=флаги_данных,
        срок_жизни_баров=С["срок_жизни_сигнала_баров"],
    )

    # --- Жёсткие блокировки до всякого анализа ---
    if флаги_данных:
        анализ.вывод = РИСК_ПРЕДУПРЕЖДЕНИЕ
        анализ.причины_отказа.append(
            "качество данных под вопросом: " + "; ".join(флаги_данных)
        )
        return анализ

    # При прогоне по истории проверка свежести отключается намеренно: там каждый
    # бар «устарел» по определению. В боевом режиме она обязательна.
    if проверять_свежесть and анализ.возраст_баров > С["макс_возраст_данных_баров"]:
        анализ.вывод = РИСК_ПРЕДУПРЕЖДЕНИЕ
        анализ.причины_отказа.append(
            f"данные устарели: последний бар {анализ.возраст_баров:.1f} баров назад"
        )
        return анализ

    if режим.волатильность == "высокая" and not С.get("торговать_в_высокой_волатильности"):
        анализ.вывод = РИСК_ПРЕДУПРЕЖДЕНИЕ
        анализ.причины_отказа.append(
            f"высокая волатильность: ширина Bollinger на {режим.bbw_перцентиль:.0f}-м "
            f"перцентиле за {len(окно)} баров. Раздел 2 промта требует снижать "
            f"активность в такой фазе — движения хаотичны, паттерны ненадёжны"
        )
        return анализ

    if лимит_убытка_исчерпан:
        анализ.вывод = РИСК_ПРЕДУПРЕЖДЕНИЕ
        анализ.причины_отказа.append("лимит убытка исчерпан — новые входы запрещены")
        return анализ

    if серия_убытков >= cfg["риск"]["серия_убытков_до_паузы"]:
        анализ.вывод = РИСК_ПРЕДУПРЕЖДЕНИЕ
        анализ.причины_отказа.append(
            f"{серия_убытков} убытка подряд — рекомендована пауза и пересмотр стратегии человеком"
        )
        return анализ

    # --- Разрешён ли этот режим рынка ---
    # Замер показал: трендовые сделки теряют деньги на обеих половинах данных
    # (профит-фактор 0.90 и 0.37), а сделки в боковике зарабатывают (1.24 и 2.15).
    # Поэтому режим — это фильтр входа, а не только выбор стратегии.
    разрешённые = С.get("разрешённые_режимы")
    if разрешённые and режим.направление not in разрешённые:
        анализ.вывод = НЕТ_СИГНАЛА
        анализ.причины_отказа.append(
            f"режим «{режим.направление}» отключён: по замеру сделки в нём "
            f"убыточны. Торгуем только {', '.join(разрешённые)}"
        )
        return анализ

    # --- Подтверждения ---
    все = собрать_подтверждения(показ, свечи, режим, П)

    if режим.направление == "переходный":
        анализ.отягчающие.append("режим не определён (ADX между порогами)")

    # Раздел 2 промта: «никогда не применяй трендовую логику в боковике и наоборот».
    # Направление сделки обязано следовать из режима, а не спорить с ним. Лонг
    # в нисходящем тренде на основании моментума и объёма — это ровно тот случай,
    # который правило запрещает, каким бы убедительным ни выглядел импульс.
    if режим.направление == "тренд вверх":
        допустимые = [LONG]
    elif режим.направление == "тренд вниз":
        допустимые = [SHORT]
    elif режим.боковик:
        допустимые = [LONG, SHORT]
    else:  # переходный режим
        допустимые = [LONG, SHORT]

    # В тренде премиссой служит сам тренд: без подтверждения группы A сделка
    # опирается только на моментум, то есть на производные той же цены.
    требуется_A = режим.трендовый
    # В неопределённом режиме планка выше: нужны все доступные группы.
    нужно_групп = 3 if режим.направление == "переходный" else С["мин_подтверждений"]

    for напр in допустимые:
        за = [п for п in все if п.направление == напр]
        группы = {п.группа for п in за}
        if len(группы) < нужно_групп:
            continue
        if требуется_A and "A" not in группы:
            continue
        анализ.направление = напр
        анализ.подтверждения = за
        анализ.противоречия = [
            f"{п.название}: {п.факт}" for п in все if п.направление != напр
        ]
        break

    if not анализ.направление:
        анализ.вывод = НЕТ_СИГНАЛА
        по_группам = {}
        for п in все:
            по_группам.setdefault(п.направление, set()).add(п.группа)
        описание = ", ".join(
            f"{н}: группы {sorted(г)}" for н, г in по_группам.items()
        ) or "подтверждений нет вовсе"
        уточнение = ""
        if требуется_A:
            уточнение = "; в тренде обязательно подтверждение группы A"
        анализ.причины_отказа.append(
            f"недостаточно независимых подтверждений: нужно {нужно_групп} "
            f"из разных групп по направлению {'/'.join(допустимые)}, "
            f"найдено — {описание}{уточнение}"
        )
        return анализ

    # --- План сделки и обязательные проверки ---
    план, тег = построить_план(свечи.актив, анализ.направление, показ, свечи, режим,
                               П, рабочая_R=cfg["риск"]["рабочая_цель_R"])
    анализ.тег_стратегии = тег

    r = cfg["риск"]
    риск_пр = r["стартовый_риск_на_сделку_пр"]
    план = risk.рассчитать(план, депозит, риск_пр, r["макс_плечо"], cfg["издержки"])
    план = risk.проверить(
        план, cfg, депозит,
        риск_кластера_текущий_пр=риск_кластера_текущий_пр,
        открытых_позиций=открытых_позиций,
        лимит_убытка_исчерпан=лимит_убытка_исчерпан,
        серия_убытков=серия_убытков,
    )
    анализ.план = план
    анализ.инвалидация = (
        f"закрытие бара за уровнем {план.стоп:,.8g} — идея опровергнута; "
        f"либо истечение {С['срок_жизни_сигнала_баров']} баров без входа"
    )

    if not план.допущена:
        анализ.вывод = НЕТ_СИГНАЛА
        for пр in план.нарушения:
            анализ.причины_отказа.append(
                f"{пр.правило}: {пр.факт} — требуется {пр.требование}"
            )
        return анализ

    # --- Уверенность по рубрике 3.2 ---
    анализ.вывод = СИГНАЛ
    if режим.волатильность == "высокая":
        анализ.отягчающие.append("высокая волатильность")
    if len(анализ.противоречия) > 0:
        анализ.отягчающие.append("есть противоречащие факторы")
    if "D" not in анализ.группы:
        анализ.отягчающие.append("ончейн-данные не подключены")

    групп = len(анализ.группы)
    if групп >= 3 and not анализ.отягчающие:
        анализ.уверенность = ВЫСОКАЯ
    elif len(анализ.отягчающие) <= 1:
        анализ.уверенность = СРЕДНЯЯ
    else:
        анализ.уверенность = НИЗКАЯ

    # Порог уверенности — единственный фильтр, устоявший на обеих половинах
    # глубокой истории. Сигналы низкой уверенности набирают минимум формально,
    # но тянут за собой два и более отягчающих фактора, и в среднем теряют.
    порядок = {НИЗКАЯ: 0, СРЕДНЯЯ: 1, ВЫСОКАЯ: 2}
    минимум = С.get("мин_уверенность")
    if минимум and порядок.get(анализ.уверенность, 0) < порядок.get(минимум, 0):
        анализ.вывод = НЕТ_СИГНАЛА
        анализ.причины_отказа.append(
            f"уверенность {анализ.уверенность} ниже порога {минимум}: "
            + ", ".join(анализ.отягчающие)
        )
        return анализ

    return анализ
