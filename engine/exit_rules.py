"""
Правила выхода: часть прибыли забираем на цели, остаток едет дальше.

Зачем понадобилось. Короткая система закрывала сделку целиком на 1.5R,
и вопрос "зачем продавать, если цена идёт выше" был совершенно уместен:
лучшая сделка за всю историю давала ровно 1.5R, потолок стоял искусственно.

Но простое "убрать цель и вести стопом" замерилось ХУЖЕ, и заметно:
    цель 1.5R целиком        +0.145R на сделку, ПФ 1.35 (половины 1.48 и 1.23)
    цели нет, трейлинг 1.5   +0.082R,           ПФ 1.19 (1.11 и 1.26)
    цели нет, трейлинг 2.0   +0.069R,           ПФ 1.13 (0.96 и 1.33)
    цели нет, трейлинг 3.0   +0.049R,           ПФ 1.08 (0.71 и 1.51)
Чем свободнее стоп, тем хуже — и на первой половине истории трейлинг
уходит в убыток. Причина в природе входа: короткая система ставит
на ВОЗВРАТ цены к среднему. Когда цель достигнута, отклонение закрылось
и повода держать позицию больше нет. Это не трендовая сделка, её нельзя
"дать ехать" тем же способом, каким едут прорывы.

Работает середина — забрать большую часть на цели, а небольшой остаток
отпустить с ПЛОТНЫМ стопом:
    70% на 1.5R, остаток трейлинг 1.0 ATR   +0.151R, ПФ 1.36 (1.48 и 1.26)
    70% на 1.5R, остаток трейлинг 1.5 ATR   +0.145R, ПФ 1.35
    70% на 1.5R, остаток трейлинг 2.0 ATR   +0.132R, ПФ 1.32
    80% на 1.5R, остаток трейлинг 1.0 ATR   +0.149R, ПФ 1.36
Зависимость от расстояния стопа монотонна при обеих долях — это не
случайная удача одной клетки таблицы. Выигрыш в доходности мал и лежит
в пределах шума, но потолок сделки поднимается с 1.5R до 3.1R: система
перестаёт отказываться от крупных движений, ничего за это не платя.

Здесь только ЧИСТАЯ ЛОГИКА, без чтения файлов: одно состояние, один бар,
решение. Так её можно проверить тестом и одинаково применить во всех трёх
журналах — рекомендаций, тени и решений пользователя.
"""

from __future__ import annotations

from dataclasses import dataclass

ДЕРЖИМ = "держим"
ЗАКРЫТА = "закрыта"


@dataclass
class Состояние:
    """Всё, что нужно знать о позиции, чтобы провести её по одному бару."""
    направление: str            # "Long" или "Short"
    цена_входа: float
    стоп: float
    стоп_начальный: float
    цель: float
    atr: float = 0.0

    порог_безубытка: float = 0.0
    доля_на_цели: float = 0.0   # 0 = старое поведение, закрыть всё на цели
    трейлинг_atr: float = 1.0

    стоп_в_безубытке: bool = False
    часть_взята: bool = False
    взято_R: float = 0.0        # прибыль, уже зафиксированная на цели
    осталось: float = 1.0       # какая доля позиции ещё в рынке
    экстремум: float = 0.0      # лучшая цена с момента частичной фиксации

    @property
    def риск(self) -> float:
        return abs(self.цена_входа - self.стоп_начальный)


@dataclass
class Шаг:
    """Что случилось на этом баре."""
    состояние: str = ДЕРЖИМ
    исход: str | None = None
    цена_выхода: float | None = None
    результат_R: float | None = None
    событие: str | None = None


def провести_бар(с: Состояние, high: float, low: float) -> Шаг:
    """Двигает позицию по одному бару. Меняет `с` на месте.

    Порядок внутри бара важен и выбран пессимистично: сперва стоп, потом
    цель. Что случилось раньше на самом деле, из бара не видно, а журнал,
    добрее рынка, обманывает в свою пользу."""
    длинная = с.направление == "Long"
    риск = с.риск
    if риск <= 0:
        return Шаг()

    # --- 1. Стоп. Он же закрывает остаток после частичной фиксации.
    if (low <= с.стоп) if длинная else (high >= с.стоп):
        ход = ((с.стоп - с.цена_входа) if длинная
               else (с.цена_входа - с.стоп)) / риск
        исход = "стоп"
        if с.часть_взята:
            исход = "остаток закрыт"
        elif с.стоп_в_безубытке:
            исход = "безубыток"
        return Шаг(ЗАКРЫТА, исход, с.стоп, с.взято_R + с.осталось * ход)

    # --- 2. Цель.
    цель_задета = (high >= с.цель) if длинная else (low <= с.цель)
    if цель_задета and not с.часть_взята:
        цель_R = abs(с.цель - с.цена_входа) / риск
        if с.доля_на_цели <= 0 or с.доля_на_цели >= 1:
            return Шаг(ЗАКРЫТА, "цель", с.цель, с.взято_R + с.осталось * цель_R)

        # Забираем часть, остаток отпускаем с плотным стопом от входа.
        с.взято_R = с.доля_на_цели * цель_R
        с.осталось = 1.0 - с.доля_на_цели
        с.часть_взята = True
        с.стоп_в_безубытке = True
        с.стоп = с.цена_входа
        с.экстремум = high if длинная else low
        return Шаг(событие=f"{int(с.доля_на_цели * 100)}% зафиксировано на цели, "
                           f"остаток идёт дальше")

    # --- 3. Ведение остатка: стоп ползёт за экстремумом.
    if с.часть_взята and с.atr > 0:
        с.экстремум = max(с.экстремум, high) if длинная else min(с.экстремум, low)
        новый = ((с.экстремум - с.atr * с.трейлинг_atr) if длинная
                 else (с.экстремум + с.atr * с.трейлинг_atr))
        двинулся = новый > с.стоп if длинная else новый < с.стоп
        if двинулся:
            с.стоп = новый
            return Шаг(событие="стоп подтянут за ценой")
        return Шаг()

    # --- 4. До цели: разовый перенос стопа в безубыток.
    # Это НЕ трейлинг: стоп переносится один раз и дальше не двигается.
    # Подтягивать его вслед за ценой ДО цели на замерах оказалось вдвое хуже.
    if not с.стоп_в_безубытке and с.порог_безубытка > 0:
        прибыль = ((high - с.цена_входа) if длинная
                   else (с.цена_входа - low)) / риск
        if прибыль >= с.порог_безубытка:
            с.стоп = с.цена_входа
            с.стоп_в_безубытке = True
            return Шаг(событие="стоп перенесён в безубыток")

    return Шаг()
