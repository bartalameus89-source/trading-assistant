"""
Формат вывода — раздел 7 промта, включая обязательный блок «ПРОСТЫМ ЯЗЫКОМ».

Две функции: текст для консоли и текст для Telegram. Содержание одинаковое,
различается только оформление — пользователь должен видеть одно и то же
независимо от того, куда смотрит.
"""

from __future__ import annotations

from .signals import Анализ, СИГНАЛ, НЕТ_СИГНАЛА


def _деньги(x: float | None, знаков: int = 2) -> str:
    if x is None:
        return "—"
    return f"{x:,.{знаков}f}".replace(",", " ")


def консоль(а: Анализ, валидатор_есть: bool = True) -> str:
    """Полная карточка для терминала и для сайта."""
    л: list[str] = []
    ш = "═" * 60
    л.append(ш)
    л.append(f"  АКТИВ: {а.актив}    ТАЙМФРЕЙМ: {а.таймфрейм}    источник: {а.источник}")
    л.append(ш)
    л.append(f"ТЕКУЩАЯ ЦЕНА: {_деньги(а.цена)}  "
             f"(бар от {а.время_бара}, возраст {а.возраст_баров:.2f} бара)")
    л.append(f"РЕЖИМ РЫНКА: {а.режим.направление} | волатильность: {а.режим.волатильность}")
    л.append(f"  └ {а.режим.пояснение}; ширина Bollinger на "
             f"{а.режим.bbw_перцентиль:.0f}-м перцентиле")
    л.append(f"ВЫВОД: {а.вывод}")

    if а.вывод != СИГНАЛ:
        л.append("")
        л.append("Чего не хватает для сигнала:")
        for п in а.причины_отказа:
            л.append(f"  • {п}")
        if а.план:
            л.append("")
            л.append("Проверки риск-менеджмента (раздел 7.1):")
            for пр in а.план.проверки:
                л.append("  " + пр.строкой())
        л.append(ш)
        return "\n".join(л)

    p = а.план
    л.append(f"УВЕРЕННОСТЬ: {а.уверенность}"
             + (f" — отягчающие факторы: {', '.join(а.отягчающие)}" if а.отягчающие else ""))
    л.append(f"НАПРАВЛЕНИЕ: {а.направление}")
    л.append(f"ТЕГ СТРАТЕГИИ: {а.тег_стратегии}")
    л.append(f"СРОК ДЕЙСТВИЯ: {а.срок_жизни_баров} бара, дальше пересчёт")
    л.append("")
    л.append(f"ВХОД: {_деньги(p.вход)}   (тип ордера: {p.тип_ордера})")
    л.append(f"СТОП-ЛОСС: {_деньги(p.стоп)}")
    л.append(f"  Дистанция до стопа: {p.дистанция_пр:.2f}% от входа = {p.дистанция_atr:.2f} x ATR")
    л.append("")
    л.append("ЦЕЛИ:")
    for i, (ц, rr) in enumerate(zip(p.цели, p.rr_по_целям), 1):
        пометка = "  <- решение принимается по этой цели" if i == 1 else ""
        л.append(f"  TP{i}: {_деньги(ц)}   R:R = 1:{rr:.2f}{пометка}")
    л.append("")

    if p.размер is not None:
        л.append(f"РАЗМЕР ПОЗИЦИИ: {p.размер:.6f} ед.   объём {_деньги(p.notional)}")
        л.append(f"  Риск на депозит: {p.риск_пр_депозита:.2f}% = {_деньги(p.риск_валюта)}")
        if p.урезан_плечом:
            л.append("  ! объём урезан ограничением плеча — фактический риск ниже заданного")
        л.append(f"  Ожидаемые издержки: {_деньги(p.издержки)} "
                 f"({p.издержки_пр_риска:.1f}% от риска)")
    else:
        л.append("РАЗМЕР ПОЗИЦИИ: не рассчитан — депозит не задан (раздел 8.1)")
    л.append("")

    л.append("Что подтверждает вывод:")
    for п in а.подтверждения:
        л.append(f"  [{п.группа}] {п.название}")
        л.append(f"      факт: {п.факт}")
        л.append(f"      трактовка: {п.интерпретация}")
    л.append(f"  Задействовано групп подтверждений: {len(а.группы)} ({', '.join(sorted(а.группы))})")
    л.append("")

    if а.противоречия:
        л.append("Что противоречит:")
        for п in а.противоречия:
            л.append(f"  • {п}")
        л.append("")

    л.append("Точка отмены сигнала (invalidation):")
    л.append(f"  {а.инвалидация}")
    л.append("")

    л.append("Проверки риск-менеджмента (раздел 7.1):")
    for пр in p.проверки:
        л.append("  " + пр.строкой())
    л.append("")
    л.append(f"Проверка кодом: {'выполнена модулем risk.py' if валидатор_есть else 'ОТСУТСТВУЕТ'}")
    л.append("")

    л.append("━━━ ПРОСТЫМ ЯЗЫКОМ ━━━")
    л.extend(простым_языком(а))
    л.append(ш)
    return "\n".join(л)


def простым_языком(а: Анализ) -> list[str]:
    """Раздел 15 промта: перевод для человека, который не читает графики."""
    p = а.план
    если_прав = (
        abs(p.цели[0] - p.вход) * p.размер if p.размер is not None else None
    )
    действие = "купить" if а.направление == "Long" else "продать в шорт"

    строки = [
        f"Что предлагается: {действие} {а.актив} по цене {_деньги(p.вход)}. "
        f"Сейчас цена {_деньги(а.цена)}, "
        + ("то есть ждём, пока рынок дойдёт до нашего уровня."
           if p.тип_ордера != "Market" else "то есть входим прямо сейчас."),
    ]

    if p.размер is not None:
        строки.append(
            f"Сколько денег под риском: {_деньги(p.риск_валюта)} — это "
            f"{p.риск_пр_депозита:.2f}% вашего депозита. Больше этой суммы "
            f"потерять по этой сделке нельзя."
        )
        строки.append(
            f"Если я ошибаюсь: сделка закроется сама на цене {_деньги(p.стоп)}, "
            f"вы потеряете {_деньги(p.риск_валюта)}."
        )
        строки.append(
            f"Если я прав: на первой цели {_деньги(p.цели[0])} вы получите "
            f"примерно {_деньги(если_прав)} до вычета комиссий."
        )
    else:
        строки.append(
            "Сколько денег под риском: посчитать не могу — не задан размер депозита. "
            "Укажите его в config.json, и суммы появятся."
        )

    строки.append(
        f"Насколько я уверен: {а.уверенность}"
        + (f", потому что {', '.join(а.отягчающие)}." if а.отягчающие
           else f", подтверждений из {len(а.группы)} независимых групп.")
    )
    строки.append(
        "Что от вас требуется: решение. Система ничего не исполняет — "
        "она только считает и объясняет."
    )
    return строки


_ЧАСОВ_В_БАРЕ = {"1m": 1 / 60, "5m": 1 / 12, "15m": 0.25, "30m": 0.5,
                 "1h": 1, "2h": 2, "4h": 4, "6h": 6, "12h": 12, "1d": 24}


def _монета(тикер: str) -> str:
    """BTCUSDT -> BTC. В сообщении человеку не нужен биржевой суффикс."""
    for хвост in ("USDT", "USDC", "BUSD", "FDUSD"):
        if тикер.endswith(хвост):
            return тикер[:-len(хвост)]
    return тикер


def _как_сработает(тип: str, направление: str, цена: float) -> str:
    действие = "покупку" if направление == "Long" else "продажу"
    if тип == "Market":
        return f"Ордер на {действие} по текущей цене — сработает сразу."
    if тип == "Limit":
        куда = "опустится" if направление == "Long" else "поднимется"
        return (f"Отложенный ордер: сработает сам, когда цена {куда} "
                f"до {_деньги(цена)}. Если не дойдёт — сделки просто не будет.")
    куда = "поднимется" if направление == "Long" else "опустится"
    return (f"Отложенный ордер: сработает сам, когда цена {куда} "
            f"до {_деньги(цена)} и движение подтвердится.")


def телеграм(а: Анализ) -> str:
    """Сообщение для человека, который не читает графики.
    Правило: сначала что делать, потом сколько это стоит, и только потом почему."""

    монета = _монета(а.актив)

    # ---------- нет сделки ----------
    if а.вывод != СИГНАЛ:
        т = [f"⏸ <b>{монета}</b> — сейчас лучше подождать", "",
             "<b>Что делать: ничего.</b> Сделку открывать не нужно.", ""]
        т.append("Почему:")
        for п in а.причины_отказа:
            т.append(f"• {_попроще(п)}")
        т.append("")
        т.append(f"Цена сейчас: {_деньги(а.цена)}")
        часы = _ЧАСОВ_В_БАРЕ.get(а.таймфрейм, 4)
        т.append(f"<i>Проверю снова через {часы:g} ч.</i>")
        return "\n".join(т)

    # ---------- есть сделка ----------
    p = а.план
    покупка = а.направление == "Long"
    значок = "🟢" if покупка else "🔴"
    слово = "ПОКУПКА" if покупка else "ПРОДАЖА В ШОРТ"
    часы = _ЧАСОВ_В_БАРЕ.get(а.таймфрейм, 4) * а.срок_жизни_баров

    т = [f"{значок} <b>{слово} · {монета}</b>",
         f"Уверенность: {а.уверенность}", ""]

    # 1. Что делать — по шагам.
    т.append("<b>ЧТО СДЕЛАТЬ</b>")
    if p.размер is not None:
        т.append(f"1. Ордер на {'покупку' if покупка else 'продажу'} "
                 f"<b>{p.размер:.6f} {монета}</b> по цене <b>{_деньги(p.вход)}</b>")
    else:
        т.append(f"1. Ордер на {'покупку' if покупка else 'продажу'} {монета} "
                 f"по цене <b>{_деньги(p.вход)}</b> "
                 f"(размер посчитать не могу — не задан депозит)")
    т.append(f"2. Сразу же поставить стоп-лосс на <b>{_деньги(p.стоп)}</b> — "
             f"это обязательно")
    т.append(f"3. Закрыть сделку при достижении <b>{_деньги(p.цели[0])}</b>")
    т.append("")

    # 2. Сколько денег на кону.
    if p.размер is not None:
        прибыль = abs(p.цели[0] - p.вход) * p.размер
        т.append("<b>СКОЛЬКО НА КОНУ</b>")
        т.append(f"Потеряете, если не сработает: <b>{_деньги(p.риск_валюта)}</b> "
                 f"({p.риск_пр_депозита:.2f}% депозита)")
        т.append(f"Заработаете, если сработает: <b>{_деньги(прибыль)}</b> "
                 f"(до комиссий ~{_деньги(p.издержки)})")
        т.append(f"То есть возможная прибыль в {p.rr_по_целям[0]:.1f} раза больше риска.")
        т.append("")
    else:
        т.append("<b>Суммы не показаны:</b> впишите размер депозита в настройки, "
                 "и я буду считать риск и прибыль в деньгах.")
        т.append("")

    # 3. Пояснение механики — то, чего человек может не знать.
    т.append("<b>КАК ЭТО РАБОТАЕТ</b>")
    т.append(_как_сработает(p.тип_ордера, а.направление, p.вход))
    т.append(f"Стоп-лосс — цена, на которой биржа закроет сделку сама, чтобы вы "
             f"не потеряли больше "
             f"{_деньги(p.риск_валюта) if p.риск_валюта else 'запланированного'}. "
             f"Без него сделку не открывайте.")
    т.append("")

    # 4. Основания — коротко и без индикаторной латыни.
    т.append("<b>ПОЧЕМУ</b>")
    for п in а.подтверждения:
        т.append(f"• {п.название}: {п.интерпретация}")
    if а.противоречия:
        т.append(f"Против: {а.противоречия[0].split(':')[0]}")
    т.append("")

    # 5. Условия отмены и срок.
    т.append(f"<b>Отменить план, если</b> цена закроется за {_деньги(p.стоп)}.")
    т.append(f"<b>Действует</b> {часы:g} часов, потом пересчитаю заново.")
    т.append("")
    т.append("<i>Это расчёт, а не гарантия. Решение за вами — "
             "система ничего не исполняет сама.</i>")
    return "\n".join(т)


_ЗАМЕНЫ = [
    ("ширина Bollinger", "размах колебаний цены"),
    ("перцентиле", "месте по величине среди последних значений"),
    ("Раздел 2 промта требует снижать активность в такой фазе", "в такие периоды система намеренно не торгует"),
    ("паттерны ненадёжны", "закономерности перестают работать"),
    ("движения хаотичны", "цена скачет непредсказуемо"),
    ("независимых подтверждений", "независимых признаков"),
    ("ADX", "показатель силы тренда"),
    ("R:R", "соотношение прибыли к риску"),
    ("ATR", "обычный размах свечи"),
    ("invalidation", "отмена плана"),
]


def человеку(причины: list[str]) -> str:
    """Короткое объяснение для того, кто не читает графики.

    Подмена слов внутри готовой технической фразы даёт кривой результат
    («перцентиль» -> «место по величине среди последних значений»). Поэтому
    здесь по признаку в исходной причине выбирается заранее написанная
    человеческая формулировка, а не переводится слово за словом.
    """
    if not причины:
        return "—"
    п = причины[0]

    if "высокая волатильность" in п:
        return "Цена скачет сильнее обычного. В такие периоды закономерности не работают, и система намеренно не торгует"
    if "недостаточно независимых" in п:
        if "Long/Short" in п:
            return "Признаков за сделку не хватает, и направление неясно"
        if "направлению Long" in п:
            return "Тренд вверх, но подтверждений для покупки пока мало — ждём"
        if "направлению Short" in п:
            return "Тренд вниз, но подтверждений для продажи пока мало — ждём"
        return "Признаков за сделку меньше, чем нужно"
    if "Запас до сопротивления" in п:
        return "До ближайшего препятствия слишком мало места: прибыль не окупит риск"
    if "Близость входа к рынку" in п:
        return "Выгодная цена входа слишком далеко от текущей — ждать её нет смысла"
    if "Дистанция до стопа" in п:
        return "Стоп пришлось бы поставить внутри обычных колебаний — его выбьет случайно"
    if "Издержки" in п:
        return "Комиссии биржи съели бы слишком большую часть риска"
    if "Рабочая цель" in п:
        return "Возможная прибыль слишком мала по сравнению с риском"
    if "устарели" in п or "качество данных" in п:
        return "Данные с биржи выглядят ненадёжно — сигнал не выдаётся"
    if "лимит убытка" in п:
        return "Дневной лимит убытка исчерпан — новые сделки до сброса запрещены"
    if "убытка подряд" in п or "серия" in п:
        return "Несколько убытков подряд — система рекомендует паузу"
    if "Плечо" in п:
        return "Позиция не помещается в капитал без плеча"
    if "Минимальный объём" in п:
        return "Биржа не примет такую мелкую заявку — нужен капитал побольше"
    return _попроще(п)[:110]


def _попроще(текст: str) -> str:
    """Убирает из причины отказа профессиональный жаргон.
    Полная техническая версия остаётся в карточке на сайте и в логах."""
    for что, на_что in _ЗАМЕНЫ:
        текст = текст.replace(что, на_что)
    return текст
