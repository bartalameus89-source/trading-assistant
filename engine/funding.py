"""
Ставка фондирования — что делает толпа, а не что рисует цена.

Это единственный доступный на глубокой истории источник, не производный
от цены. Наша проблема весь проект в том, что RSI, MACD и скользящие
считает каждый второй, и преимущество на них давно съедено. Фондирование
описывает другое: позиционирование участников.

Как читать. На бессрочных фьючерсах каждые 8 часов одна сторона платит
другой, чтобы цена контракта держалась около спота:
  ставка положительная  -> платят лонги, значит толпа набрала лонгов;
  ставка отрицательная  -> платят шорты, значит толпа набрала шортов.

Гипотеза, которую проверяем: КРАЙНИЕ значения работают против толпы.
Когда все в лонге и платят за это дорого, топливо для роста кончилось,
и любое движение вниз вызывает каскад закрытий. Зеркально для шортов.

Проверять обязательно: гипотеза известная, а известное на рынке
обычно уже не работает.
"""

from __future__ import annotations

import json
import os
import time
import urllib.request

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
КЕШ = os.path.join(БАЗА, "cache")
ПЕРИОД_МС = 8 * 3600 * 1000        # выплата раз в 8 часов


def _запрос(url: str):
    req = urllib.request.Request(url, headers={"User-Agent": "trading-assistant/1.0"})
    with urllib.request.urlopen(req, timeout=25) as r:
        return json.loads(r.read())


def загрузить_историю(актив: str, точек: int = 3000) -> list[tuple[int, float]]:
    """История ставки фондирования, страницами назад. (время_мс, ставка)."""
    собрано: list[tuple[int, float]] = []
    конец: int | None = None

    while len(собрано) < точек:
        url = (f"https://fapi.binance.com/fapi/v1/fundingRate"
               f"?symbol={актив}&limit=1000")
        if конец is not None:
            url += f"&endTime={конец}"
        try:
            куски = _запрос(url)
        except Exception:
            break
        if not куски:
            break
        порция = [(int(k["fundingTime"]), float(k["fundingRate"])) for k in куски]
        собрано = порция + собрано
        конец = порция[0][0] - ПЕРИОД_МС
        if len(куски) < 1000:
            break
        time.sleep(0.15)           # не долбить биржу

    # Убираем дубли на стыках страниц и сортируем.
    видели: set[int] = set()
    чисто = []
    for т, с in sorted(собрано):
        if т in видели:
            continue
        видели.add(т)
        чисто.append((т, с))
    return чисто


def кеш_путь(актив: str) -> str:
    return os.path.join(КЕШ, f"funding_{актив}.json")


def получить(актив: str, точек: int = 3000, обновить: bool = False) -> list[tuple[int, float]]:
    """С диска, если есть и свежее суток; иначе с биржи."""
    os.makedirs(КЕШ, exist_ok=True)
    путь = кеш_путь(актив)
    свежий = (os.path.exists(путь)
              and time.time() - os.path.getmtime(путь) < 86400)
    if свежий and not обновить:
        with open(путь, encoding="utf-8") as f:
            return [(int(т), float(с)) for т, с in json.load(f)]

    данные = загрузить_историю(актив, точек)
    if данные:
        with open(путь, "w", encoding="utf-8") as f:
            json.dump(данные, f)
    return данные


class Фондирование:
    """Быстрый доступ к ставке на момент времени + её место в распределении."""

    def __init__(self, история: list[tuple[int, float]], окно: int = 90):
        self.времена = [т for т, _ in история]
        self.ставки = [с for _, с in история]
        self.окно = окно           # сколько прошлых выплат берём для сравнения

    def __len__(self) -> int:
        return len(self.ставки)

    def _индекс(self, время_мс: int) -> int:
        """Последняя выплата, случившаяся ДО указанного времени.
        Строго до — иначе в анализ попадёт информация из будущего."""
        низ, верх = 0, len(self.времена) - 1
        ответ = -1
        while низ <= верх:
            середина = (низ + верх) // 2
            if self.времена[середина] <= время_мс:
                ответ = середина
                низ = середина + 1
            else:
                верх = середина - 1
        return ответ

    def на_момент(self, время_мс: int) -> tuple[float, float] | None:
        """(ставка, её перцентиль в окне). None — если истории не хватает."""
        i = self._индекс(время_мс)
        if i < self.окно:
            return None
        ставка = self.ставки[i]
        окно = self.ставки[i - self.окно:i]
        ниже = sum(1 for с in окно if с < ставка)
        return ставка, ниже / len(окно) * 100
