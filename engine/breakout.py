"""
Прорывы: участие в резких движениях, которые пропускают обе прежние системы.

Зачем понадобилась третья система. Когда BTC вырос на 24% за неделю, короткая
система молчала все 20 баров подряд из-за фильтра высокой волатильности,
а долгосрочная ждала отката в растущем тренде, которого ещё не было —
MA50 оставалась ниже MA200 после долгого падения. Обе системы устроены так,
что взрывной выход из падения проходит мимо них.

Замер «в высокой волатильности торговать убыточно» проверял сигналы ВОЗВРАТА
К СРЕДНЕМУ в такой фазе. Прорыв — противоположный по смыслу вход, и он
не проверялся ни разу. Проверка на 610 сделках за 8 лет показала обратное:

  профит-фактор 3.44 и 1.88 на двух половинах истории
  +0.832R на сделку, 13 прибыльных монет из 15
  без 20 лучших сделок система всё ещё в плюсе

Правило старое и простое — система «черепах» 1983 года:
  вход  — цена закрылась выше максимума за 20 дней;
  стоп  — 2 ATR ниже входа, дальше подтягивается за минимумами;
  выход — цена ушла ниже минимума за 10 дней. ЦЕЛИ НЕТ.

Цели нет намеренно: смысл в том, чтобы поймать движение целиком. Отсюда
профиль результата — 37% побед, но прибыльные держатся 31 день против
9 дней у убыточных, а средний рост в удачной сделке +42%.

ТОЛЬКО ПОКУПКА. Зеркальный шорт проверен отдельно и дал профит-фактор 1.00 —
шорт идёт против общего дрейфа рынка вверх и вдобавок платит за удержание.
"""

from __future__ import annotations

from dataclasses import dataclass, field

from . import indicators as ind
from .render import формат_цены
from .data import Свечи

ЕСТЬ_ПРОРЫВ = "ЕСТЬ ПРОРЫВ"
БЛИЗКО = "БЛИЗКО К ПРОРЫВУ"
НЕТ = "НЕТ"


@dataclass
class Прорыв:
    актив: str
    цена: float
    вывод: str = НЕТ

    максимум_окна: float = 0.0        # уровень, который нужно пробить
    до_прорыва_проц: float = 0.0      # сколько осталось до него
    объём_к_среднему: float = 0.0

    вход: float | None = None
    стоп: float | None = None
    стоп_проц: float | None = None
    уровень_выхода: float | None = None   # где сейчас проходит выход
    типичный_срок: str = "около двух недель, прибыльные — около месяца"

    условия: list[tuple[str, bool, str]] = field(default_factory=list)
    причины: list[str] = field(default_factory=list)


def проанализировать_прорыв(свечи: Свечи, cfg: dict) -> Прорыв:
    """Свечи ДНЕВНЫЕ. Нужно минимум 40 баров."""
    п = cfg.get("прорывы", {})
    вход_окно = int(п.get("окно_входа", 20))
    выход_окно = int(п.get("окно_выхода", 10))
    стоп_atr = float(п.get("стоп_atr", 2.0))
    порог_объёма = float(п.get("мин_объём_к_среднему", 0.0))

    highs, lows, closes = свечи.highs, свечи.lows, свечи.closes
    цена = свечи.последняя_цена
    в = Прорыв(актив=свечи.актив, цена=цена)

    if len(свечи) < вход_окно + 25:
        в.причины.append("мало истории для расчёта")
        return в

    atr_, _ = ind.last_defined(ind.atr(highs, lows, closes, 14))
    объём_ср, _ = ind.last_defined(ind.sma(свечи.volumes, 20))
    if not atr_ or not объём_ср:
        в.причины.append("не хватает данных по волатильности или объёму")
        return в

    # Максимум предыдущих баров — сам текущий бар в расчёт не берём,
    # иначе цена «пробивает» собственный максимум и сигнал появляется всегда.
    в.максимум_окна = max(highs[-вход_окно - 1:-1])
    в.до_прорыва_проц = (в.максимум_окна / цена - 1) * 100
    в.объём_к_среднему = свечи.volumes[-1] / объём_ср if объём_ср else 0.0

    пробита = цена > в.максимум_окна
    объём_ок = в.объём_к_среднему >= порог_объёма if порог_объёма else True

    в.условия = [
        (f"Цена выше максимума за {вход_окно} дней", пробита,
         f"цена {формат_цены(цена)} против максимума {формат_цены(в.максимум_окна)}"),
        ("Объём подтверждает" if порог_объёма else "Объём (справочно)",
         объём_ок, f"{в.объём_к_среднему:.1f}x к среднему за 20 дней"),
    ]

    if пробита and объём_ок:
        в.вывод = ЕСТЬ_ПРОРЫВ
        в.вход = цена
        в.стоп = цена - atr_ * стоп_atr
        в.стоп_проц = (цена - в.стоп) / цена * 100
        в.уровень_выхода = min(lows[-выход_окно:])
    elif not пробита and в.до_прорыва_проц <= 3.0:
        в.вывод = БЛИЗКО
        в.причины.append(
            f"до прорыва {в.до_прорыва_проц:.1f}% — уровень {формат_цены(в.максимум_окна)}")
        в.уровень_выхода = min(lows[-выход_окно:])
    else:
        в.вывод = НЕТ
        if not пробита:
            в.причины.append(
                f"цена ниже максимума за {вход_окно} дней на {в.до_прорыва_проц:.1f}%")
        if not объём_ок:
            в.причины.append(f"объём {в.объём_к_среднему:.1f}x — ниже порога")
    return в


def обновить_стоп(текущий_стоп: float, свечи: Свечи, cfg: dict) -> float:
    """Подтягивание стопа за минимумами. Это НЕ трейлинг по ATR от цены,
    который на четырёхчасовых данных оказался вреден: здесь стоп идёт
    за структурой рынка, а не за самой ценой."""
    п = cfg.get("прорывы", {})
    выход_окно = int(п.get("окно_выхода", 10))
    atr_, _ = ind.last_defined(ind.atr(свечи.highs, свечи.lows, свечи.closes, 14))
    минимум = min(свечи.lows[-выход_окно:])
    новый = минимум - (atr_ or 0) * 0.2
    return max(текущий_стоп, новый)


def словами(в: Прорыв) -> str:
    if в.вывод == ЕСТЬ_ПРОРЫВ:
        return (f"Цена пробила максимум за месяц — движение началось. "
                f"Держать, пока не упадёт ниже {формат_цены(в.уровень_выхода)}, "
                f"цели нет. Обычно это {в.типичный_срок}.")
    if в.вывод == БЛИЗКО:
        return (f"До прорыва {в.до_прорыва_проц:.1f}%. Если цена закроется выше "
                f"{формат_цены(в.максимум_окна)}, появится сигнал на покупку.")
    return (f"Цена на {abs(в.до_прорыва_проц):.0f}% ниже своего месячного максимума — "
            f"прорывом здесь не пахнет.")
