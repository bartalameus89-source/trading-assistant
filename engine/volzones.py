"""
Зоны волатильности: окупается ли ослабленный фильтр короткой системы.

13.09.2026 порог высокой волатильности поднят с 80 до 90 по решению
владельца, хотя замер его не подтвердил. Значит, это опыт на живых данных,
и у опыта должен быть способ дать ответ. Ответ здесь.

Источник — теневой журнал: в нём лежат ВСЕ сигналы короткой системы,
и рекомендованные, и отсеянные, со своим результатом. Каждый сигнал
делится на зону по перцентилю ширины Боллинджера на момент сигнала:

  спокойная   до 80    — торговалась и раньше;
  новая       80–90    — открыта ослаблением фильтра;
  закрытая    от 90    — по-прежнему не рекомендуется, ведётся в тени.

Сигналы до 13.09 точного перцентиля не хранят. Для них известно только,
был ли он ниже 80 (волатильность «нормальная») или не ниже (≥80, зону 80–90
от 90+ уже не отличить). Они показываются отдельно и в вывод не идут.

Вывод правило даёт один: новая зона должна давать на сделку не меньше
спокойной. Пока закрытых сделок в ней меньше 20, вывода нет — только цифры.
"""

from __future__ import annotations

import json
import os

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ФАЙЛ = os.path.join(БАЗА, "state", "shadow.json")
ДОСТАТОЧНО = 20
НЕ_ИСПОЛНЕНЫ = ("не дошло", "истёк срок")


def зона(запись: dict) -> str:
    п = запись.get("перцентиль_bbw")
    if п is None:
        return ("до 13.09: ниже 80" if запись.get("волатильность") != "высокая"
                else "до 13.09: 80 и выше")
    if п < 80:
        return "спокойная (до 80)"
    if п < 90:
        return "новая (80–90)"
    return "закрытая (от 90)"


ПОРЯДОК = ["спокойная (до 80)", "новая (80–90)", "закрытая (от 90)",
           "до 13.09: ниже 80", "до 13.09: 80 и выше"]


def свод(записи: list[dict] | None = None) -> dict[str, dict]:
    if записи is None:
        try:
            with open(ФАЙЛ, encoding="utf-8") as f:
                записи = json.load(f).get("сделки", []) or []
        except (OSError, json.JSONDecodeError):
            записи = []
    из: dict[str, dict] = {з: {"сигналов": 0, "исполнено": 0, "закрыто": 0,
                              "сумма_R": 0.0, "побед": 0} for з in ПОРЯДОК}
    for з in записи:
        if з.get("система", "короткая") != "короткая":
            continue
        с = из[зона(з)]
        с["сигналов"] += 1
        исход = з.get("исход")
        if з.get("цена_входа") or з.get("вошли_в") or (исход and исход not in НЕ_ИСПОЛНЕНЫ):
            с["исполнено"] += 1
        r = з.get("результат_R")
        if з.get("состояние") == "закрыта" and исход not in НЕ_ИСПОЛНЕНЫ and isinstance(r, (int, float)):
            с["закрыто"] += 1
            с["сумма_R"] += r
            с["побед"] += r > 0
    for с in из.values():
        с["на_сделку_R"] = с["сумма_R"] / с["закрыто"] if с["закрыто"] else None
    return из


def вывод(с: dict[str, dict]) -> str:
    нов, спок = с["новая (80–90)"], с["спокойная (до 80)"]
    if нов["закрыто"] < ДОСТАТОЧНО or спок["закрыто"] < ДОСТАТОЧНО:
        return (f"Выводов пока нет: закрыто в новой зоне {нов['закрыто']}, "
                f"в спокойной {спок['закрыто']}, нужно по {ДОСТАТОЧНО}.")
    if нов["на_сделку_R"] >= спок["на_сделку_R"]:
        return (f"Новая зона окупается: {нов['на_сделку_R']:+.3f}R на сделку против "
                f"{спок['на_сделку_R']:+.3f}R в спокойной. Ослабление оправдано.")
    return (f"Новая зона хуже: {нов['на_сделку_R']:+.3f}R на сделку против "
            f"{спок['на_сделку_R']:+.3f}R в спокойной. Порог стоит вернуть к 80.")
