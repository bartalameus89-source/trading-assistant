"""
Все сделки всех систем одним списком.

Зачем. Сделки лежат в пяти журналах с разными именами полей: у прорывов
результат в «r» и риск в «риск_usd», у коротких — «результат_R» и
«риск_денег», вход у одних «вход», у других «цена_входа». Из-за этого
единственного списка «что мы вообще наторговали» нигде не было: кабинет
показывал сводки и последние десять закрытых, а раздел «Мои сделки» —
только личные решения владельца по рекомендациям. Их было одно, и раздел
выглядел пустым, хотя сделок к тому моменту было пятьдесят.

Здесь журналы сводятся к одному набору полей. Этим пользуются и выгрузка
в CSV, и кабинет — чтобы список на экране и файл для Excel не разъезжались.
"""

from __future__ import annotations

import json
import os

БАЗА = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ПАПКА = os.path.join(БАЗА, "state")

ЗАКРЫТЫЕ = ("закрыта", "завершена")
# Исходы, при которых ордер так и не исполнился (как в engine/pnl.py).
НЕ_ИСПОЛНЕНЫ = ("не дошло", "истёк срок")

# файл -> (ключ, система, поле результата, поле риска, поле входа, тень)
ИСТОЧНИКИ = (
    ("breakouts.json", "позиции", "прорывы", "r", "риск_usd", "вход", None),
    ("paper_long.json", "позиции", "долгосрочная", "r", "риск_usd", "вход", None),
    ("paper.json", "сделки", "короткая", "результат_R", "риск_денег",
     "цена_входа", None),
    ("shadow.json", "сделки", "короткая", "результат_R", "риск_денег",
     "цена_входа", True),
)


def _читать(файл: str, ключ: str) -> list[dict]:
    п = os.path.join(ПАПКА, файл)
    if not os.path.exists(п):
        return []
    try:
        with open(п, encoding="utf-8") as f:
            return json.load(f).get(ключ, []) or []
    except (json.JSONDecodeError, OSError):
        return []


def _число(x) -> float | None:
    return x if isinstance(x, (int, float)) else None


def все(цены: dict[str, float] | None = None) -> list[dict]:
    """Все сделки, новые сверху. `цены` — текущая цена по активу: без них
    открытые позиции оцениваются по подтянутому стопу, то есть по уже
    защищённой прибыли, а не по рынку."""
    цены = цены or {}
    из: list[dict] = []

    for файл, ключ, система, r_поле, риск_поле, вход_поле, тень in ИСТОЧНИКИ:
        for з in _читать(файл, ключ):
            вход = з.get(вход_поле) or з.get("вход")
            # Правила те же, что в engine/pnl.py, иначе итог наверху кабинета
            # и итог списка разойдутся. Риск без записи — 1 $, как там.
            риск_денег = _число(з.get(риск_поле)) or 1.0
            состояние = з.get("состояние", "")
            закрыта = состояние in ЗАКРЫТЫЕ
            # Ордер, который так и не исполнился, — не сделка: денег он
            # не заработал и не потерял. В списке он виден, в итог не идёт.
            # Без этого 26 неисполненных ордеров шли в итог «в ноль»,
            # и закрытых выходило 36 вместо 10.
            исполнена = not (закрыта and з.get("исход") in НЕ_ИСПОЛНЕНЫ)
            r = _число(з.get(r_поле))

            деньги = None
            цена_сейчас = None
            if закрыта and исполнена and r is not None:
                деньги = r * риск_денег
            elif состояние == "открыта" and вход:
                стоп_нач = з.get("стоп_начальный") or з.get("стоп")
                if стоп_нач and вход - стоп_нач > 0:
                    цена = цены.get(з.get("актив"), з.get("стоп", вход))
                    # Показываем только настоящую рыночную цену: подставной
                    # стоп в колонке «сейчас» читался бы как текущий курс.
                    цена_сейчас = цены.get(з.get("актив"))
                    r = (цена - вход) / (вход - стоп_нач)
                    деньги = r * риск_денег

            части = з.get("части") or []
            из.append({
                "система": система,
                "ветка": "тень" if (тень or з.get("тень")) else "рекомендация",
                "актив": (з.get("актив") or "").replace("USDT", ""),
                "направление": з.get("направление", "Long"),
                "состояние": состояние,
                "исход": з.get("исход") or "",
                "открыта": з.get("открыта_в") or з.get("создана") or з.get("когда"),
                "закрыта": з.get("закрыта_в"),
                "вход": вход,
                "стоп": з.get("стоп"),
                "стоп_начальный": з.get("стоп_начальный") or з.get("стоп"),
                "цель": з.get("цель"),
                "выход": з.get("выход") or з.get("цена_выхода"),
                "цена_сейчас": цена_сейчас,
                # Без округления: итог складывается из этих чисел, и если
                # округлять каждую строку, сумма уходит на цент от итога
                # наверху кабинета. Красиво показывает уже браузер.
                "r": r,
                "деньги": деньги,
                "риск_денег": round(риск_денег, 2),
                "дней": з.get("дней"),
                "частей": len(части) if части else 1,
                "настройки": з.get("настройки", ""),
                "закрыта_ли": закрыта,
                "исполнена": исполнена,
            })

    из.sort(key=lambda с: (с["закрыта"] or с["открыта"] or 0), reverse=True)
    return из


def свод(сделки: list[dict]) -> dict:
    """Итог по списку — тот же, что показан наверху кабинета, но по любой
    выборке: за период, по одной системе, только по рекомендациям."""
    закрытые = [с for с in сделки if с["закрыта_ли"] and с["деньги"] is not None]
    открытые = [с for с in сделки if not с["закрыта_ли"] and с["деньги"] is not None]
    плюс = [с for с in закрытые if с["деньги"] > 0]
    минус = [с for с in закрытые if с["деньги"] < 0]
    заработано = sum(с["деньги"] for с in плюс)
    потеряно = sum(с["деньги"] for с in минус)
    открыто = sum(с["деньги"] for с in открытые)
    return {
        "сделок": len(закрытые),
        "в_плюс": len(плюс),
        "в_минус": len(минус),
        "в_ноль": len(закрытые) - len(плюс) - len(минус),
        "заработано": round(заработано, 2),
        "потеряно": round(потеряно, 2),
        "закрыто_итог": round(заработано + потеряно, 2),
        "открыто_итог": round(открыто, 2),
        "итог": round(заработано + потеряно + открыто, 2),
        "в_работе": len(открытые),
        "доля_побед": (round(len(плюс) / len(закрытые) * 100, 1)
                       if закрытые else 0.0),
    }
