"""
Сравнение с «просто купил и держал»: зарабатывает система или едет на рынке.

Зачем это главный вопрос. Любая цифра прибыли за 2023-2026 годы выглядит
хорошо, потому что рынок за этот отрезок вырос сам по себе. Пока мы не
сравним себя с тем, кто ничего не делал, мы не знаем, чем гордимся:
работой системы или тем, что биткоин подорожал. Это единственная проверка,
которая отличает первое от второго.

С чем сравниваем. Три эталона на ОДНОМ окне и ОДНОМ капитале:
  1. «купил биткоин и держал» — самый привычный ориентир;
  2. «купил корзину из тех же монет поровну и держал» — самый честный:
     тот же набор активов, что торгует система;
  3. деньги в кармане — 0%, чтобы видеть, стоило ли вообще заходить.

Чем меряем. Не только итогом. Итог сам по себе обманчив: держать биткоин
означало пережить просадку, на которой большинство выходит и фиксирует
убыток. Поэтому главная строка — ДОХОД НА ЕДИНИЦУ ПРОСАДКИ: сколько
процентов прибыли пришлось на каждый процент худшего провала. Заодно всё
считается по половинам истории: по нашему правилу улучшение засчитывается,
только если оно есть в обеих.

Честная оговорка, которая работает ПРОТИВ нас. Кривая системы двигается
только на закрытии сделок, поэтому её просадка занижена: пока позиция
открыта и болтается в минусе, кривая этого не видит, а у «купил и держал»
видно каждый день. Чтобы не обманываться, просадка системы считается ДВУМЯ
способами — по закрытым сделкам и пессимистично (каждая открытая сделка
считается стоящей у стопа). Правда между ними.

    python benchmark.py
    python benchmark.py --дней 365      только последний год
"""

from __future__ import annotations

import json
import os
import sys
from datetime import datetime, timezone

from engine import portsim

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
КЕШ = os.path.join(БАЗА, "cache", "candles.json")


# --------------------------------------------------------------------------
#  Данные
# --------------------------------------------------------------------------

def _день(t: float) -> str:
    """Время свечи в кеше — миллисекунды; у сделок бывает и то и другое."""
    if t > 1e11:
        t /= 1000.0
    return datetime.fromtimestamp(t, timezone.utc).strftime("%Y-%m-%d")


def дневные_закрытия() -> dict[str, dict[str, float]]:
    """{монета: {день: закрытие}}. Из четырёхчасового кеша берётся последняя
    свеча каждых суток — дневная сетка нужна, чтобы все монеты и обе системы
    легли на один календарь."""
    if not os.path.exists(КЕШ):
        raise SystemExit("Нет cache/candles.json — сначала: python collect.py")
    сырое = json.load(open(КЕШ, encoding="utf-8"))
    из: dict[str, dict[str, float]] = {}
    for монета, с in сырое.items():
        по_дням: dict[str, float] = {}
        for t, close in zip(с["времена"], с["closes"]):
            по_дням[_день(t)] = close      # последняя свеча дня побеждает
        из[монета] = по_дням
    return из


def календарь(закрытия: dict[str, dict[str, float]]) -> list[str]:
    дни: set[str] = set()
    for по_дням in закрытия.values():
        дни |= set(по_дням)
    return sorted(дни)


# --------------------------------------------------------------------------
#  Кривые
# --------------------------------------------------------------------------

def кривая_монеты(по_дням: dict[str, float], дни: list[str],
                  капитал: float) -> list[float] | None:
    """Купил на весь капитал в первый день окна и не трогал."""
    есть = [д for д in дни if д in по_дням]
    if len(есть) < 30:
        return None
    старт = по_дням[есть[0]]
    из: list[float] = []
    последняя = капитал
    for д in дни:
        if д in по_дням:
            последняя = капитал * по_дням[д] / старт
        из.append(последняя)               # нет свечи — держим прежнюю оценку
    return из


def кривая_корзины(закрытия: dict[str, dict[str, float]], дни: list[str],
                   капитал: float) -> tuple[list[float], list[str]]:
    """Капитал делится поровну между монетами, у которых есть цена в первый
    день окна. Монеты, появившиеся позже, в корзину не берутся: покупать
    то, чего ещё нет, нельзя, и делать вид, что можно, — самообман."""
    в_корзине = [м for м in sorted(закрытия) if дни[0] in закрытия[м]]
    if not в_корзине:
        return [капитал] * len(дни), []
    доля = капитал / len(в_корзине)
    части = [кривая_монеты(закрытия[м], дни, доля) for м in в_корзине]
    части = [ч for ч in части if ч]
    return [sum(ч[i] for ч in части) for i in range(len(дни))], в_корзине


def _сделки(файл: str) -> list[dict]:
    п = os.path.join(БАЗА, файл)
    if not os.path.exists(п):
        return []
    try:
        return json.load(open(п, encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return []


def _все_сделки() -> list[dict]:
    """Сделки всех трёх систем в виде, понятном движку портфеля.

    Короткая система не торгует монеты из сигналы.исключить_из_короткой —
    их сделки из бэктеста сюда не берутся, иначе замер посчитал бы деньги,
    которых вживую не будет."""
    из: list[dict] = []
    исключить = set(CFG.get("сигналы", {}).get("исключить_из_короткой", []))
    for файл, система in (("trades.json", "короткая"),
                          ("trades_long.json", "долгосрочная"),
                          ("trades_breakout.json", "прорывы")):
        for i, с in enumerate(_сделки(файл)):
            вх, вых, r = с.get("время_входа"), с.get("время_выхода"), с.get("r")
            if вх is None or вых is None or not isinstance(r, (int, float)):
                continue                            # старый файл без дат
            актив = с.get("актив") or f"{система}-{i}"
            if система == "короткая" and актив in исключить:
                continue
            из.append({"система": система, "актив": актив, "когда": float(вх),
                       "вход": _день(вх), "выход": _день(вых), "r": float(r),
                       "путь": ({д: float(x) for д, x in с["путь"]}
                                if с.get("путь") else None)})
    из.sort(key=lambda с: (с["когда"], с["система"], с["актив"]))
    return из


def кривая_системы(дни: list[str], капитал: float
                   ) -> tuple[list[float], list[float], dict]:
    """(кривая по закрытым сделкам, пессимистичная кривая, что вышло).

    Здесь делается то, чего НЕ делают бэктесты по отдельности: соблюдаются
    портфельные пределы. Каждый бэктест гоняет свою монету в одиночку и
    спокойно держит 15 позиций одновременно на 45% счёта под риском —
    в семь с половиной раз выше нашего же предела в 6%. Прибыль от такого
    портфеля существует только в таблице: реальная система эти сделки
    отказалась бы открывать. Поэтому здесь мы идём по дням, набираем
    позиции по правилам и считаем итог по тем сделкам, которые ПРОШЛИ
    БЫ отбор.

    Считаем сложным процентом: риск берётся от счёта на день входа.
    Иначе мерили бы разными линейками — «купил и держал» растёт сложным
    процентом, а мы бы росли линейно.

    Пессимистичная кривая: пока сделка открыта, считаем её стоящей у стопа.
    Это заведомо хуже правды, но её просадку нельзя обвинить в том, что она
    нарисована задним числом по одним закрытиям.
    """
    # Сам отбор делает общий движок портфеля — тот же, на котором мерится
    # распределение ставок. Раньше здесь был свой, и он ошибался строже
    # жизни: складывал риск быстрой и медленных систем в один потолок 6%,
    # хотя живой портфель держит их раздельно (4% и 6%), и не знал, что
    # одну монету держит одна система.
    п = CFG["портфель"]
    пределы = {"медленных": float(п.get("макс_общий_риск_пр", 100.0)),
               "быстрых": float(п.get("макс_риск_быстрых_пр", 100.0)),
               "позиций": int(п.get("макс_всего_позиций", 99)),
               "в_день": int(п.get("макс_сделок_в_день", 0)),
               "прорывов": int(CFG.get("прорывы", {}).get("макс_позиций", 10))}
    ставки = {"короткая": CFG["риск"]["стартовый_риск_на_сделку_пр"],
              "долгосрочная": CFG["долгосрочная"]["риск_на_позицию_пр"],
              "прорывы": CFG.get("прорывы", {}).get("риск_на_позицию_пр", 0.25)}
    сделки = _все_сделки()
    итог = portsim.прогнать(сделки, дни, ставки, пределы, капитал)
    взято = sum(итог["взято"].values())
    отсеяно = sum(итог["отсеяно"].values())
    вышло = {"взято": взято, "отсеяно": отсеяно, "вне_окна": итог["вне_окна"],
             "всего": взято + отсеяно + итог["вне_окна"],
             "по_системам": итог["взято"], "вклад": итог["вклад"]}
    return итог["кривая"], итог["песс"], вышло


# --------------------------------------------------------------------------
#  Метрики
# --------------------------------------------------------------------------

def просадка(кривая: list[float]) -> float:
    """Худшее падение от достигнутого пика, в процентах от пика."""
    пик = кривая[0]
    худшая = 0.0
    for з in кривая:
        пик = max(пик, з)
        if пик > 0:
            худшая = min(худшая, (з - пик) / пик * 100)
    return худшая


def итог_проц(кривая: list[float]) -> float:
    return (кривая[-1] / кривая[0] - 1) * 100 if кривая[0] else 0.0


def на_единицу(кривая: list[float]) -> float:
    п = abs(просадка(кривая))
    return итог_проц(кривая) / п if п > 0.01 else float("inf")


def строка(имя: str, кривая: list[float]) -> str:
    е = на_единицу(кривая)
    е_текст = "  —" if е in (float("inf"), float("-inf")) else f"{е:+.2f}"
    return (f"  {имя:<32} {итог_проц(кривая):+9.1f}% "
            f"{просадка(кривая):9.1f}% {е_текст:>11}")


def половины(кривая: list[float]) -> tuple[list[float], list[float]]:
    г = len(кривая) // 2
    return кривая[:г], кривая[г:]


# --------------------------------------------------------------------------

def главное() -> int:
    капитал = float(CFG["риск"]["депозит"] or 100)
    закрытия = дневные_закрытия()
    дни = календарь(закрытия)

    if "--дней" in sys.argv:
        сколько = int(sys.argv[sys.argv.index("--дней") + 1])
        дни = дни[-сколько:]

    сист, песс, вышло = кривая_системы(дни, капитал)
    btc = кривая_монеты(закрытия.get("BTCUSDT", {}), дни, капитал)
    корзина, в_корзине = кривая_корзины(закрытия, дни, капитал)
    деньги = [капитал] * len(дни)

    черта = "=" * 74
    print(черта)
    print("  СРАВНЕНИЕ С «ПРОСТО КУПИЛ И ДЕРЖАЛ»")
    print(черта)
    print(f"  Окно: {дни[0]} — {дни[-1]}  ({len(дни)} дней)")
    print(f"  Капитал: {капитал:.0f} $")
    имена = ", ".join(м.replace("USDT", "") for м in в_корзине)
    print(f"  В корзине {len(в_корзине)} монет: {имена}")
    print(f"  Сделок в бэктестах {вышло['всего']}: взято {вышло['взято']}, "
          f"отсеяно пределами портфеля {вышло['отсеяно']}, "
          f"вне окна {вышло['вне_окна']}.")
    п = CFG["портфель"]
    print(f"  Пределы как в живом портфеле: не больше {п['макс_всего_позиций']} позиций, "
          f"риск медленных до {п['макс_общий_риск_пр']}%, быстрых отдельно "
          f"до {п['макс_риск_быстрых_пр']}%.")
    if вышло["взято"] == 0:
        print("\n  Сделок с датами нет. Пересчитайте бэктесты:")
        print("      python backtest.py")
        print("      python backtest_long.py")
        return 1

    ряды = [
        ("Наша система (по закрытым)", сист),
        ("Наша система (пессимистично)", песс),
        ("Купил биткоин и держал", btc),
        (f"Купил корзину из {len(в_корзине)} поровну", корзина),
        ("Деньги лежат в кармане", деньги),
    ]
    ряды = [(и, к) for и, к in ряды if к]

    print()
    print(f"  {'':<32} {'итог':>9} {'просадка':>9} {'доход/прос':>11}")
    print("  " + "-" * 70)
    for имя, к in ряды:
        print(строка(имя, к))

    print()
    print("  ПО ПОЛОВИНАМ ИСТОРИИ (правило: улучшение должно быть в обеих)")
    грань = дни[len(дни) // 2]
    for номер in (0, 1):
        если_первая = номер == 0
        подпись = ("первая половина" if если_первая else "вторая половина")
        от_до = (f"{дни[0]} — {грань}" if если_первая
                 else f"{грань} — {дни[-1]}")
        print(f"\n  {подпись} ({от_до})")
        print("  " + "-" * 70)
        for имя, к in ряды:
            print(строка(имя, половины(к)[номер]))

    # --- вывод словами ---
    эталоны = [(и, к) for и, к in ряды
               if "система" not in и and "кармане" not in и]
    print()
    print(черта)
    if эталоны:
        имя_их, лучший = max(эталоны, key=lambda пара: на_единицу(пара[1]))
        наш, их = на_единицу(песс), на_единицу(лучший)
        print(f"  Доход на единицу просадки: у нас {наш:+.2f}, "
              f"у «{имя_их}» {их:+.2f}.")
        if наш > их:
            print("  Система оправдывает себя: та же прибыль даётся дешевле")
            print("  по риску и по нервам, чем простое удержание.")
        else:
            print("  Система НЕ оправдывает себя на этом окне: удержание давало")
            print("  больше дохода на каждый процент просадки. Это повод чинить")
            print("  правила, а не радоваться абсолютной прибыли.")

        # Отдельно и вслух — где нас обошли по ЧИСТОМУ доходу. Владелец
        # хочет заработать больше, а не только просесть меньше; если на
        # каком-то отрезке простое удержание принесло больше денег, это
        # надо говорить прямо, а не прятать за удобной метрикой.
        обошли = []
        for номер, подпись in ((0, "первой половине"), (1, "второй половине")):
            наш_итог = итог_проц(половины(песс)[номер])
            for имя_э, к in эталоны:
                if итог_проц(половины(к)[номер]) > наш_итог:
                    обошли.append(f"в {подпись} «{имя_э}» дал "
                                  f"{итог_проц(половины(к)[номер]):+.1f}% "
                                  f"против наших {наш_итог:+.1f}%")
        if обошли:
            print()
            print("  По чистому доходу нас обошли:")
            for строчка in обошли:
                print(f"    • {строчка}")
            print("    Мы взяли своё меньшей просадкой, но денег там было больше.")
        else:
            print("  По чистому доходу мы впереди эталонов в обеих половинах.")
    print("  Обе цифры — про прошлый отрезок рынка, а не про будущее.")
    print(черта)
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
