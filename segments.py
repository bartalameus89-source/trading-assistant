"""
Где именно теряются деньги: разбор сделок по признакам.

Идея простая. Общий результат — среднее по всем сделкам сразу. Если часть
сигналов заведомо плохая, она тянет вниз и хорошую часть. Тогда решение —
не улучшать стратегию целиком, а перестать брать плохую часть.

Осторожность обязательна: при делении на группы выборка дробится, и в каждой
остаётся по 10-20 сделок. На таких числах разница почти всегда случайна.
Поэтому рядом с каждым срезом печатается размер выборки, а вывод делается
только там, где разница велика И группа достаточно большая.

Запуск:  python segments.py
"""

from __future__ import annotations

import json
import os
from collections import defaultdict

from experiments import Правила, СИГНАЛЫ, провести

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ПРАВИЛО = Правила("рабочая цель 1.5R", цель_R=CFG["риск"]["рабочая_цель_R"])
МИН_ВЫБОРКА = 15          # меньше — не обсуждаем, это шум


def результаты() -> list[tuple[dict, float]]:
    вышло = []
    for с in sorted(СИГНАЛЫ, key=lambda x: (x["бар"], x["актив"])):
        r = провести(с, ПРАВИЛО)
        if r is not None:
            вышло.append((с, r))
    return вышло


def срез(данные: list[tuple[dict, float]], имя: str, ключ) -> None:
    группы: dict[str, list[float]] = defaultdict(list)
    for с, r in данные:
        группы[str(ключ(с))].append(r)

    print(f"\n  {имя}")
    print(f"  {'значение':<26} {'сделок':>7} {'побед':>7} {'итог R':>9} {'на сделку':>11}")
    print("  " + "-" * 64)
    for знач, R in sorted(группы.items(), key=lambda kv: -sum(kv[1])):
        победы = sum(1 for r in R if r > 0)
        пометка = "" if len(R) >= МИН_ВЫБОРКА else "  ← мало данных"
        print(f"  {знач:<26} {len(R):7d} {победы / len(R) * 100:6.0f}% "
              f"{sum(R):+9.2f} {sum(R) / len(R):+11.3f}{пометка}")


def главное() -> None:
    данные = результаты()
    всего = sum(r for _, r in данные)
    print("=" * 72)
    print(f"  РАЗБОР {len(данные)} СДЕЛОК ПО ПРИЗНАКАМ")
    print("=" * 72)
    print(f"  Общий итог: {всего:+.2f}R, в среднем {всего / len(данные):+.3f}R на сделку")
    print(f"  Группы меньше {МИН_ВЫБОРКА} сделок помечены — им доверять нельзя.")

    срез(данные, "ПО УВЕРЕННОСТИ", lambda с: с["уверенность"])
    срез(данные, "ПО РЕЖИМУ РЫНКА", lambda с: с["режим"])
    срез(данные, "ПО НАПРАВЛЕНИЮ", lambda с: с["направление"])
    срез(данные, "ПО ЧИСЛУ ГРУПП ПОДТВЕРЖДЕНИЯ", lambda с: f"{с['групп']} группы")
    срез(данные, "ПО ТИПУ ОРДЕРА", lambda с: с["тип_ордера"])
    срез(данные, "ПО СТРАТЕГИИ", lambda с: с["тег"])
    срез(данные, "ПО МОНЕТЕ", lambda с: с["актив"].replace("USDT", ""))

    # Отдельно: зависит ли результат от того, насколько далеко стоял стоп.
    def корзина_стопа(с: dict) -> str:
        проц = abs(с["вход"] - с["стоп"]) / с["вход"] * 100
        if проц < 1.0:
            return "стоп ближе 1%"
        if проц < 2.0:
            return "стоп 1-2%"
        if проц < 3.0:
            return "стоп 2-3%"
        return "стоп дальше 3%"
    срез(данные, "ПО ДИСТАНЦИИ ДО СТОПА", корзина_стопа)

    print("\n" + "=" * 72)
    print("  КАК ЧИТАТЬ")
    print("=" * 72)
    print("  Ищем группу, которая явно хуже остальных И достаточно велика.")
    print("  Если такая есть — её можно перестать брать, и общий результат")
    print("  улучшится. Если разница только в мелких группах — это случайность,")
    print("  и отсечение по ней сделает хуже на новых данных.")


if __name__ == "__main__":
    главное()
