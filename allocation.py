"""
Сколько ставить на каждую систему: замер через общий портфель.

Повод. Прорывы в долях риска зарабатывают столько же, сколько долгосрочная
(вживую по +3.1R), но в деньгах их почти не видно: ставка на позицию 0.25%
счёта против 3%. Её понизили с 0.5% из-за доливок, когда портфель ещё не
умел считать текущий риск позиции. Вопрос — не перекошено ли теперь
распределение в сторону долгосрочной.

Решает только прогон всех систем ВМЕСТЕ через портфель по живым правилам
(engine/portsim.py): поднять ставку одной системе значит отнять место
у другой, ведь медленные делят один потолок риска.

Правило приёма, как везде: вариант лучше нынешнего, только если доход на
единицу просадки выше в ОБЕИХ половинах истории. Одна удачная половина —
не довод.

Два опыта:
  1. медленные системы (долгосрочная + прорывы) на всей дневной истории —
     именно они делят потолок, и истории у них больше всего;
  2. все три системы на окне, где есть короткая (четырёхчасовой кеш).

    python allocation.py
"""

from __future__ import annotations

import json
import os

from engine import portsim

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))

ПРОРЫВЫ = [0.25, 0.35, 0.5, 0.75]
ДОЛГОСРОЧНАЯ = [2.0, 2.5, 3.0]


def пределы() -> dict:
    п = CFG["портфель"]
    return {"медленных": п["макс_общий_риск_пр"], "быстрых": п["макс_риск_быстрых_пр"],
            "позиций": п["макс_всего_позиций"], "в_день": п.get("макс_сделок_в_день", 0),
            "прорывов": CFG["прорывы"].get("макс_позиций", 10)}


def нынешние() -> dict:
    return {"короткая": CFG["риск"]["стартовый_риск_на_сделку_пр"],
            "долгосрочная": CFG["долгосрочная"]["риск_на_позицию_пр"],
            "прорывы": CFG["прорывы"]["риск_на_позицию_пр"]}


def опыт(название: str, системы: set[str], дни: list[str], сделки: list[dict]) -> None:
    н = нынешние()
    print("=" * 96)
    print(f"  {название}")
    print(f"  окно {дни[0]} — {дни[-1]} ({len(дни)} дней)")
    print("=" * 96)
    print(f"  {'прорывы':>8} {'долгоср.':>8} {'годовых':>8} {'просадка':>9} {'доход/пр':>9}"
          f" {'1-я пол.':>9} {'2-я пол.':>9} {'риск разом':>10}  вклад в $ по системам")
    строки = []
    for б in ПРОРЫВЫ:
        for л in ДОЛГОСРОЧНАЯ:
            ставки = {с: v for с, v in (("короткая", н["короткая"]),
                                        ("долгосрочная", л), ("прорывы", б))
                      if с in системы}
            итог = portsim.прогнать(сделки, дни, ставки, пределы())
            весь = portsim.показатели(итог["кривая"], итог["песс"])
            п1, п2 = portsim.по_половинам(итог)
            строки.append((б, л, весь, п1, п2, итог))

    база = next(с for с in строки if с[0] == н["прорывы"] and с[1] == н["долгосрочная"])
    лучшие = []
    for б, л, весь, п1, п2, итог in строки:
        нынешний = (б, л) == (база[0], база[1])
        лучше = (п1["отношение"] > база[3]["отношение"] + 1e-9
                 and п2["отношение"] > база[4]["отношение"] + 1e-9)
        if лучше:
            лучшие.append((б, л, весь, п1, п2))
        метка = "  <- сейчас" if нынешний else ("  ЛУЧШЕ В ОБЕИХ" if лучше else "")
        вклад = ", ".join(f"{с[:5]} {v:+.0f}" for с, v in sorted(итог["вклад"].items()))
        print(f"  {б:8.2f} {л:8.1f} {весь['годовых_пр']:+7.1f}% {весь['просадка_пр']:8.1f}%"
              f" {весь['отношение']:9.2f} {п1['отношение']:9.2f} {п2['отношение']:9.2f}"
              f" {итог['макс_разом_пр']:9.1f}%  {вклад}{метка}")

    итог = база[5]
    print(f"\n  сейчас взято: {итог['взято']}, отсеяно: {итог['отсеяно']}")
    print(f"  причины отказов: {dict(sorted(итог['причины'].items(), key=lambda kv: -kv[1]))}")
    if лучшие:
        б, л, весь, п1, п2 = max(лучшие, key=lambda x: min(x[3]["отношение"], x[4]["отношение"]))
        print(f"\n  Лучший вариант, прошедший правило обеих половин: прорывы {б}%, "
              f"долгосрочная {л}% — годовых {весь['годовых_пр']:+.1f}%, "
              f"отношение {п1['отношение']:.2f} и {п2['отношение']:.2f} "
              f"против нынешних {база[3]['отношение']:.2f} и {база[4]['отношение']:.2f}.")
    else:
        print("\n  Ни один вариант не лучше нынешнего в обеих половинах сразу.")
    print()


def главное() -> int:
    # Монеты, которые короткая система вживую не торгует, в замер не идут.
    исключить = {"короткая": set(CFG["сигналы"].get("исключить_из_короткой", []))}
    медленные = {"долгосрочная", "прорывы"}
    сделки_м = portsim.загрузить(медленные, исключить=исключить)
    if not any(с["система"] == "прорывы" for с in сделки_м):
        print("Нет trades_breakout.json — сначала: python backtest_breakout.py")
        return 1
    опыт("ОПЫТ 1. Медленные системы на всей дневной истории", медленные,
         portsim.календарь(сделки_м), сделки_м)

    все = portsim.загрузить(исключить=исключить)
    короткие = [с for с in все if с["система"] == "короткая"]
    if короткие:
        дни = portsim.календарь(короткие)
        опыт("ОПЫТ 2. Все три системы на окне короткой", {"короткая", *медленные},
             дни, все)
    return 0


if __name__ == "__main__":
    raise SystemExit(главное())
