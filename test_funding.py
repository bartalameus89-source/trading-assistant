"""
Проверка гипотезы: даёт ли ставка фондирования преимущество.

Метод честный и простой. Берём каждый бар истории, смотрим, где находилась
ставка фондирования в своём распределении, и считаем, что происходило
с ценой ДАЛЬШЕ. Никакого отбора сигналов, никаких дополнительных условий —
чистая проверка одного фактора.

Если крайние значения фондирования действительно предсказывают разворот,
это будет видно сразу. Если нет — тоже.

Запуск:  python test_funding.py
"""

from __future__ import annotations

import json
import os
from collections import defaultdict

from engine import data, funding

БАЗА = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(БАЗА, "config.json"), encoding="utf-8"))
ГОРИЗОНТ = 6          # через сколько баров смотрим результат (6 x 4ч = сутки)


def корзина(перцентиль: float) -> str:
    if перцентиль >= 90:
        return "90-100 (толпа сильно в лонге)"
    if перцентиль >= 70:
        return "70-90"
    if перцентиль >= 30:
        return "30-70 (норма)"
    if перцентиль >= 10:
        return "10-30"
    return "0-10 (толпа сильно в шорте)"


def главное() -> None:
    по_корзинам: dict[str, list[float]] = defaultdict(list)
    всего_точек = 0

    for актив in CFG["активы"]:
        try:
            свечи = data.загрузить_глубоко(актив, "4h", баров=3000,
                                           источники=CFG["источник_данных"])
            ф = funding.Фондирование(funding.получить(актив, точек=2000))
        except Exception as e:
            print(f"  {актив:10s} ошибка: {type(e).__name__}")
            continue
        if len(ф) < 200:
            print(f"  {актив:10s} мало данных о фондировании ({len(ф)})")
            continue

        попало = 0
        for i in range(len(свечи) - ГОРИЗОНТ - 1):
            точка = ф.на_момент(свечи.времена[i])
            if точка is None:
                continue
            _, перц = точка
            # Что сделала цена за следующие ГОРИЗОНТ баров.
            цена_сейчас = свечи.closes[i]
            цена_потом = свечи.closes[i + ГОРИЗОНТ]
            изменение = (цена_потом / цена_сейчас - 1) * 100
            по_корзинам[корзина(перц)].append(изменение)
            попало += 1
        всего_точек += попало
        print(f"  {актив:10s} точек {попало}")

    print(f"\n{'=' * 74}")
    print(f"  ЧТО ДЕЛАЛА ЦЕНА ЧЕРЕЗ СУТКИ ПОСЛЕ РАЗНЫХ УРОВНЕЙ ФОНДИРОВАНИЯ")
    print(f"  Всего наблюдений: {всего_точек}")
    print(f"{'=' * 74}")
    print(f"  {'уровень ставки':<32}{'наблюдений':>12}{'средний ход':>14}{'вверх':>10}")
    print("  " + "-" * 70)

    порядок = ["0-10 (толпа сильно в шорте)", "10-30", "30-70 (норма)",
               "70-90", "90-100 (толпа сильно в лонге)"]
    for к in порядок:
        значения = по_корзинам.get(к, [])
        if not значения:
            continue
        средний = sum(значения) / len(значения)
        вверх = sum(1 for x in значения if x > 0) / len(значения) * 100
        print(f"  {к:<32}{len(значения):12d}{средний:+13.3f}%{вверх:9.1f}%")

    все = [x for v in по_корзинам.values() for x in v]
    базовый = sum(все) / len(все)
    print("  " + "-" * 70)
    print(f"  {'В СРЕДНЕМ ПО ВСЕМ БАРАМ':<32}{len(все):12d}{базовый:+13.3f}%")
    print()
    print("  Как читать: если гипотеза верна, крайние корзины должны заметно")
    print("  отличаться от средней строки. Разница в сотые доли процента —")
    print("  это шум, торговать на нём нельзя: комиссии съедят больше.")


if __name__ == "__main__":
    главное()
